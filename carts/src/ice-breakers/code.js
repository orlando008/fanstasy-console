function drawPause() {
  panel(64, 80, 128, 64);
  ctxt('PAUSED', 88, GOLD);
  ['RESUME', 'RESTART', 'QUIT TO TITLE'].forEach((s, i) => txt(`${i === pauseSel ? '>' : ' '} ${s}`, 76, 104 + i * 10, i === pauseSel ? WHITE : DIM));
}

/** A fringe of icicles hanging from y, across x to x + w (the level banner's top edge). */
function icicles(x, y, w) {
  for (let i = 0; i < w / 8; i++) {
    for (let r = 0; r < 7; r++) { const half = 3 - (r >> 1) - (i % 3 === 1 ? 1 : 0); if (half > 0) rectfill(x + i * 8 + 4 - half, y + r, 2 * half, 1, CYAN); }
  }
}
function panel(x, y, w, h) { rectfill(x, y, w, h, SHADOW); rect(x, y, w, h, PANEL); }
function txt(s, x, y, c) { print(s, x + 1, y + 1, SHADOW); print(s, x, y, c); }
const ctxt = (s, y, c) => txt(s, 128 - s.length * 4, y, c);
