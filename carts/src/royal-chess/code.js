function init() {
  if (dget(VERSION_SLOT) !== SAVE_VERSION) { for (let i = 0; i < 256; i++) dset(i, 0); dset(VERSION_SLOT, SAVE_VERSION); }
  const ch = dget(CHOICE_SLOT);
  setupLevel = ch & 1 << 4 ? ch & 3 : 1; setupColour = ch & 1 << 4 ? (ch >> 2) & 3 : 0;
  if (skipTitle) newGame(); else toTitle();
}

// --- The saves (spec 13): a move is 16 bits (from and to as 0 to 63, and the promotion), two to a slot ---

const sq64 = (s) => (s >> 4) * 8 + (s & 7), sq88 = (i) => (i >> 3) * 16 + (i & 7);
const packMove = (m) => sq64(mFrom(m)) | (sq64(mTo(m)) << 6) | ((mPromo(m) ? mPromo(m) - 1 : 0) << 12);
const hasSave = () => (dget(GAME_SLOT) & 1) !== 0;
let saving = false;   // this game is saved after each move (a game from the start position, not one a test set up)

function saveMove() {
  if (!saving) return;
  const n = pos.undo.length;
  if (n > MAX_SAVED) { if (n === MAX_SAVED + 1) say('TOO LONG TO SAVE NOW'); return; }
  const slot = MOVES_SLOT + ((n - 1) >> 1), v = packMove(lastMove);
  dset(slot, (n - 1) & 1 ? (dget(slot) & 0xffff) | (v << 16) : v);
  dset(PLIES_SLOT, n);
  dset(GAME_SLOT, 1 | (cpu ? 0 : 2) | ((cpu ? cpu.level : 0) << 3) | ((cpu ? cpu.side ^ 1 : 0) << 5));
}
const clearSave = () => dset(GAME_SLOT, 0);

/** CONTINUE: the saved game, replayed from the start (which rebuilds its history for the repetition rule). */
function continueGame() {
  const g = dget(GAME_SLOT), n = dget(PLIES_SLOT);
  cpu = g & 2 ? null : { level: (g >> 3) & 3, side: ((g >> 5) & 1) ^ 1 };
  newGame();
  for (let i = 0; i < n; i++) {
    const v = (dget(MOVES_SLOT + (i >> 1)) >> (i & 1 ? 16 : 0)) & 0xffff, from = sq88(v & 63), to = sq88((v >> 6) & 63), pr = (v >> 12) & 3;
    const m = legalMoves(pos).find((x) => mFrom(x) === from && mTo(x) === to && (!mPromo(x) || mPromo(x) === pr + 1));
    if (!m) { clearSave(); newGame(); return; }   // a save that does not replay: start afresh
    make(pos, m, true); lastMove = m;
  }
  cur = { f: 4, r: cpu && cpu.side === WHITE_SIDE ? 6 : 1 };
}

function toTitle() { state = 'title'; timer = 0; titleSel = 0; paused = false; play(SONG.title); }
const titleItems = () => [...(hasSave() ? ['CONTINUE'] : []), 'PLAY THE COMPUTER', 'TWO PLAYERS'];
let setupLevel = 1, setupColour = 0, setupRow = 0;   // the level and colour screen: BEGINNER .. STEADY; WHITE, BLACK, RANDOM
const COLOURS = ['WHITE', 'BLACK', 'RANDOM'];

/** A new game against the computer at the level and colour chosen (RANDOM picks one each game). */
function startCpuGame() {
  const mine = setupColour === 2 ? rndi(0, 1) : setupColour;
  cpu = { level: setupLevel, side: mine ^ 1 };
  newGame();
}

function newGame(fen = START_FEN) {
  thinking = null; thought = null; saving = fen === START_FEN;
  if (saving) { clearSave(); dset(PLIES_SLOT, 0); }
  pos = fromFen(fen); cur = { f: 4, r: (cpu ? cpu.side === WHITE_SIDE : pos.side) ? 6 : 1 }; liftedSq = -1; liftMoves = []; lastMove = 0; result = null; promo = null;
  state = 'game'; timer = 0; paused = false; play(SONG.game);
}

// --- Update ---

function update() {
  readPads(); clock++;
  if (!paused) timer++;
  if (noticeT) noticeT--;
  if (state === 'game' && !cpu && !pad2 && masks[1] && !prevMasks[1]) pad2 = true;   // pad 2 joins: it plays Black from now on
  if (paused) updatePause();
  else if (state === 'title') updateTitle();
  else if (state === 'game') updateGame();
  else if (state === 'over') updateOver();
  else if (state === 'setup') updateSetup();
}

function updateTitle() {
  const items = titleItems(), n = items.length;
  if (pressed(UP)) { titleSel = (titleSel + n - 1) % n; fx(SFX.move); }
  if (pressed(DOWN)) { titleSel = (titleSel + 1) % n; fx(SFX.move); }
  if (timer < 10 || !(pressed(A) || pressed(START))) return;
  fx(SFX.select);
  const item = items[titleSel];
  if (item === 'CONTINUE') continueGame();
  else if (item === 'TWO PLAYERS') { cpu = null; newGame(); }
  else { state = 'setup'; timer = 0; setupRow = 0; }
}

/** The level and colour (spec 10): UP and DOWN the row, LEFT and RIGHT its value, A starts, B goes back. */
function updateSetup() {
  if (pressed(UP) || pressed(DOWN)) { setupRow ^= 1; fx(SFX.move); }
  const d = (pressed(RIGHT) ? 1 : 0) - (pressed(LEFT) ? 1 : 0);
  if (d && setupRow === 0) { setupLevel = (setupLevel + d + 3) % 3; fx(SFX.move); }
  if (d && setupRow === 1) { setupColour = (setupColour + d + 3) % 3; fx(SFX.move); }
  if (pressed(B)) { fx(SFX.pause); toTitle(); return; }
  if (timer > 10 && (pressed(A) || pressed(START))) { fx(SFX.select); dset(CHOICE_SLOT, setupLevel | (setupColour << 2) | (1 << 4)); startCpuGame(); }
}

/** The pad of a side: with two pads, White's is `whitePad` and Black's the other; with one, pad 1 plays both. */
const padOf = (side) => (pad2 && !cpu ? (side === WHITE_SIDE ? whitePad : whitePad ^ 1) : 0);
const movePad = () => padOf(pos.side);
const cpuToMove = () => cpu && pos.side === cpu.side;

/** The computer's turn: step its search a frame's worth of positions; play its move once it has thought for at least
 * minT frames (so it does not snap down), and stop searching deeper at maxT. */
function updateCpu() {
  const L = LEVELS[cpu.level];
  if (!thinking && !thought) { thinking = think(pos, L); thinkT = 0; thinkBest = null; nodes = 0; }
  thinkT++;
  if (thinking) {
    const stop = nodes + FRAME_NODES;
    while (nodes < stop) { const r = thinking.next(); if (r.done) { thought = r.value; thinking = null; break; } }
    if (thinking && thinkT >= L.maxT && thinkBest) { thought = thinkBest; thinking = null; }   // out of time: the deepest search finished
  }
  if (thought && thinkT >= L.minT) { const m = thought.move; thought = null; playMove(m); }
}

function updateGame() {
  const p = movePad();
  for (const q of pad2 ? [0, 1] : [0]) if (pressed(START, q)) { paused = true; pausePad = q; pauseSel = 0; menu = 'main'; fx(SFX.pause); return; }
  if (promo) { updatePromo(p); return; }
  if (cpuToMove()) { moveCursor(p); updateCpu(); return; }   // the cursor still moves (to look), but nothing is picked up
  moveCursor(p);
  const s = cur.r * 16 + cur.f;
  if (pressed(B, p) && liftedSq >= 0) { liftedSq = -1; liftMoves = []; fx(SFX.place); return; }
  if (!pressed(A, p)) return;
  const piece = pos.b[s];
  if (liftedSq < 0 || (piece && sideOf(piece) === pos.side && s !== liftedSq)) {   // pick up (or change the piece held)
    if (piece && sideOf(piece) === pos.side) {
      liftMoves = legalMoves(pos).filter((m) => mFrom(m) === s);
      liftedSq = s; fx(liftMoves.length ? SFX.lift : SFX.no);
    } else fx(SFX.no);
    return;
  }
  if (s === liftedSq) { liftedSq = -1; liftMoves = []; fx(SFX.place); return; }   // put it back where it was
  const choices = liftMoves.filter((m) => mTo(m) === s);
  if (!choices.length) { fx(SFX.no); return; }
  if (mPromo(choices[0])) { promo = { moves: PROMOS.map((t) => choices.find((m) => mPromo(m) === t)), sel: 0 }; fx(SFX.select); return; }
  playMove(choices[0]);
}

function moveCursor(p) {
  const dx = (pressed(RIGHT, p) ? 1 : 0) - (pressed(LEFT, p) ? 1 : 0), dy = (pressed(UP, p) ? 1 : 0) - (pressed(DOWN, p) ? 1 : 0);
  if (dx || dy) { cur.f = (cur.f + dx + 8) % 8; cur.r = (cur.r + dy + 8) % 8; fx(SFX.move); }
}

/** Choosing a promotion's piece: UP and DOWN, A confirms, B goes back to the pawn held. */
function updatePromo(p) {
  if (pressed(UP, p)) { promo.sel = (promo.sel + 3) % 4; fx(SFX.move); }
  if (pressed(DOWN, p)) { promo.sel = (promo.sel + 1) % 4; fx(SFX.move); }
  if (pressed(B, p)) { promo = null; fx(SFX.move); return; }
  if (pressed(A, p)) { const m = promo.moves[promo.sel]; promo = null; playMove(m); }
}

/** A move into the game: made, remembered as the last move, with its sound; then the game may be over. */
function playMove(m) {
  make(pos, m, true);
  lastMove = m; liftedSq = -1; liftMoves = []; promo = null;
  saveMove();
  const end = gameResult(pos);
  if (end) { finish(end); return; }
  fx(inCheck(pos) ? SFX.check : mPromo(m) ? SFX.promote : mFlags(m) & F_CASTLE ? SFX.castle : mFlags(m) & F_CAPTURE ? SFX.capture : SFX.place);
}

/** The game is over: the result panel over the final position (spec 10). */
function finish(end) {
  result = end; state = 'over'; timer = 0; paused = false; clearSave();   // a finished game is not saved
  fx(end.winner < 0 ? SFX.draw : SFX.mate);
}

/** After the game: A a new game (two players with two pads swap colours), B the title. */
function updateOver() {
  if (timer < 30) return;
  if (pressed(A)) { fx(SFX.select); if (pad2) whitePad ^= 1; if (cpu) startCpuGame(); else newGame(); }   // the same mode, level and colour
  else if (pressed(B)) { fx(SFX.select); toTitle(); }
}

/** The menu, moved by the pad that opened it. RESIGN asks again; OFFER DRAW asks the other player (step 3: the computer
 * decides for itself). Who resigns or offers: the side of the pad that opened the menu (with one pad, the side to move). */
function updatePause() {
  const p = pausePad, side = pad2 ? (p === whitePad ? WHITE_SIDE : BLACK_SIDE) : pos.side;
  if (menu === 'resign') {
    if (pressed(A, p)) { fx(SFX.select); finish({ winner: side ^ 1, why: side ? 'BLACK RESIGNS' : 'WHITE RESIGNS' }); }
    else if (pressed(B, p)) { menu = 'main'; fx(SFX.move); }
    return;
  }
  if (menu === 'offer' && cpu) {   // the computer answers at once: yes if it is at most half a pawn ahead (spec 5)
    const Q = copyPos(pos); Q.side = cpu.side; const v = thinkNow(Q, LEVELS[1]).score;
    paused = false; menu = 'main';
    if (v <= 50) { fx(SFX.select); finish({ winner: -1, why: 'DRAW AGREED' }); } else { say('DRAW DECLINED'); fx(SFX.no); }
    return;
  }
  if (menu === 'offer') {   // the other player answers, on their pad (pad 1 if only one is used)
    const q = padOf(side ^ 1);
    if (pressed(A, q)) { fx(SFX.select); finish({ winner: -1, why: 'DRAW AGREED' }); }
    else if (pressed(B, q)) { paused = false; menu = 'main'; say('DRAW DECLINED'); fx(SFX.no); }
    return;
  }
  if (pressed(UP, p)) { pauseSel = (pauseSel + MENU.length - 1) % MENU.length; fx(SFX.move); }
  if (pressed(DOWN, p)) { pauseSel = (pauseSel + 1) % MENU.length; fx(SFX.move); }
  if (pressed(B, p) || (pressed(START, p) && pauseSel === 0)) { paused = false; fx(SFX.pause); }
  else if (pressed(A, p) || pressed(START, p)) {
    fx(SFX.select);
    const item = MENU[pauseSel];
    if (item === 'RESUME') paused = false;
    else if (item === 'OFFER DRAW') menu = 'offer';
    else if (item === 'RESIGN') menu = 'resign';
    else if (item === 'NEW GAME') { if (cpu) startCpuGame(); else newGame(); }
    else toTitle();
  }
}
function say(s) { notice = s; noticeT = 120; }

// --- Draw ---

function draw() {
  cls();
  if (state === 'game' || state === 'over') drawBoard();
  else if (state === 'title') drawTitle();
  else if (state === 'setup') drawSetup();
  if (state === 'over') drawResult();
  if (promo) drawPromo();
  if (paused) drawPause();
}

/** A piece, for now: a disc in its side's colour with its letter (the art pass, step 6, carves them). */
function drawPiece(p, x, y) {
  const white = sideOf(p) === WHITE_SIDE;
  circfill(x + 12, y + 12, 9, white ? ART.colors.IVORY : ART.colors.EBONY);
  circ(x + 12, y + 12, 9, white ? ART.colors.EBONY : ART.colors.IVORY);
  print(' PNBRQK'[typeOf(p)], x + 9, y + 9, white ? ART.colors.EBONY : ART.colors.IVORY);
}

function drawBoard() {
  const C = ART.colors;
  rectfill(BX - 6, BY - 6, 8 * SQ + 12, 8 * SQ + 12, C.FRAME);
  for (let s = 0; s < 128; s++) {
    if (s & 0x88) continue;
    const x = screenX(s), y = screenY(s);
    rectfill(x, y, SQ, SQ, ((s >> 4) + (s & 7)) % 2 ? C.LIGHT : C.DARK);
    if (lastMove && (s === mFrom(lastMove) || s === mTo(lastMove))) rect(x + 1, y + 1, SQ - 2, SQ - 2, C.LAST);
  }
  if (inCheck(pos)) { const k = pos.kings[pos.side]; rectfill(screenX(k), screenY(k), SQ, SQ, C.CHECK); }
  for (let s = 0; s < 128; s++) if (!(s & 0x88) && pos.b[s] && s !== liftedSq) drawPiece(pos.b[s], screenX(s), screenY(s));
  for (const m of liftMoves) {   // the legal squares: a dot on an empty one, a ring on a capture
    const x = screenX(mTo(m)) + 12, y = screenY(mTo(m)) + 12;
    if (pos.b[mTo(m)] || mFlags(m) & F_EP) circ(x, y, 10, C.MOVE); else circfill(x, y, 3, C.MOVE);
  }
  for (let f = 0; f < 8; f++) print('abcdefgh'[f], BX + f * SQ + 10, BY + 8 * SQ + 1, DIM);
  for (let r = 0; r < 8; r++) print(String(r + 1), BX - 6, BY + (7 - r) * SQ + 9, DIM);
  const cx = BX + cur.f * SQ, cy = BY + (7 - cur.r) * SQ;
  rect(cx, cy, SQ, SQ, C.CURSOR); rect(cx + 1, cy + 1, SQ - 2, SQ - 2, C.CURSOR);
  if (liftedSq >= 0) drawPiece(pos.b[liftedSq], cx, cy - 3);   // the piece held, raised over the cursor
  const status = state === 'over' ? (result.winner < 0 ? 'DRAWN' : result.winner ? 'BLACK WINS' : 'WHITE WINS')
    : noticeT ? notice : cpuToMove() ? `${LEVELS[cpu.level].name} IS THINKING${'...'.slice(0, (flr(clock / 15) % 3) + 1)}`
    : `${pos.side ? 'BLACK' : 'WHITE'} TO MOVE${inCheck(pos) ? ': CHECK!' : ''}`;
  txt(status, 16, 212, noticeT || inCheck(pos) ? GOLD : WHITE);
  if (pad2) txt(`P${padOf(pos.side) + 1}`, 228, 212, DIM);
}

/** The promotion's choice, beside the square: the four pieces, one lit. */
function drawPromo() {
  const x = Math.min(BX + cur.f * SQ + SQ + 2, 256 - 34), y = clamp(BY + (7 - cur.r) * SQ - 30, 2, 224 - 104);
  panel(x - 2, y - 2, 32, 104);
  PROMOS.forEach((t, i) => {
    if (i === promo.sel) rectfill(x, y + i * 25, 28, 25, ART.colors.CURSOR);
    drawPiece(t | (pos.side ? BLACK : 0), x + 2, y + i * 25);
  });
}

