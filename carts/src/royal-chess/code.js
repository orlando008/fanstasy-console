// --- Sound (SPEC 5). Songs use channels 0 to 5; effects take turns on 6 and 7, so they never cut into the music. ---

const SFX = { move: 0, select: 1, pause: 2, lift: 3, place: 4, capture: 5, no: 6 };
const SONG = { title: 0, game: 1 };
const SFX_CH = [7, 6];
let fxNext = 0;
function fx(n) { sfx(n, SFX_CH[fxNext]); fxNext ^= 1; }
let playing = -1;
function play(song) { if (song === playing) return; playing = song; music(song); }

// --- Save slots (spec 13) ---

const VERSION_SLOT = 0, SAVE_VERSION = 2;

// --- Input: each pad's buttons this frame and last, for presses that do not repeat (btnp does) ---

const BUTTONS = [UP, DOWN, LEFT, RIGHT, A, B, X, Y, L, R, START, SELECT];
const masks = [0, 0, 0, 0], prevMasks = [0, 0, 0, 0];
function readPads() {
  for (let p = 0; p < 4; p++) { let m = 0; for (const b of BUTTONS) if (btn(b, p)) m |= 1 << b; prevMasks[p] = masks[p]; masks[p] = m; }
}
const held = (b, p = 0) => (masks[p] & (1 << b)) !== 0;
const pressed = (b, p = 0) => held(b, p) && (prevMasks[p] & (1 << b)) === 0;

// ===================================================================================================================
// The rules (spec 5): a 0x88 board. A square is rank * 16 + file (a1 = 0, h1 = 7, a8 = 112); sq & 0x88 is off the
// board. A piece is its type (1 pawn, 2 knight, 3 bishop, 4 rook, 5 queen, 6 king) plus 8 for Black; 0 is empty.
// ===================================================================================================================

const PAWN = 1, KNIGHT = 2, BISHOP = 3, ROOK = 4, QUEEN = 5, KING = 6, BLACK = 8, WHITE_SIDE = 0, BLACK_SIDE = 1;
const W_OO = 1, W_OOO = 2, B_OO = 4, B_OOO = 8;
const N_STEPS = [33, 31, 18, 14, -14, -18, -31, -33], K_STEPS = [1, -1, 16, -16, 17, 15, -15, -17];
const B_STEPS = [17, 15, -15, -17], R_STEPS = [1, -1, 16, -16];
// A move: from | to << 7 | promotion type << 14 | flags << 17.
const F_CAPTURE = 1, F_DOUBLE = 2, F_EP = 4, F_CASTLE = 8;
const mFrom = (m) => m & 127, mTo = (m) => (m >> 7) & 127, mPromo = (m) => (m >> 14) & 7, mFlags = (m) => m >> 17;
const mk = (from, to, promo = 0, flags = 0) => from | (to << 7) | (promo << 14) | (flags << 17);

const sideOf = (p) => (p & BLACK ? BLACK_SIDE : WHITE_SIDE), typeOf = (p) => p & 7;
const sqName = (s) => 'abcdefgh'[s & 7] + ((s >> 4) + 1);
const sqOf = (name) => (name.charCodeAt(1) - 49) * 16 + (name.charCodeAt(0) - 97);

/** A new position from FEN (spec 6). */
function fromFen(fen) {
  const [placement, side, castle, ep, half, full] = fen.trim().split(/\s+/);
  const P = { b: new Int8Array(128), side: side === 'b' ? BLACK_SIDE : WHITE_SIDE, castle: 0, ep: -1, half: +half || 0, full: +full || 1, kings: [0, 0], undo: [], keys: [] };
  let r = 7, f = 0;
  for (const ch of placement) {
    if (ch === '/') { r--; f = 0; }
    else if (ch >= '1' && ch <= '8') f += +ch;
    else {
      const t = 'pnbrqk'.indexOf(ch.toLowerCase()) + 1, p = t | (ch === ch.toLowerCase() ? BLACK : 0);
      P.b[r * 16 + f] = p; if (t === KING) P.kings[sideOf(p)] = r * 16 + f; f++;
    }
  }
  for (const ch of castle || '-') P.castle |= { K: W_OO, Q: W_OOO, k: B_OO, q: B_OOO }[ch] || 0;
  P.ep = ep && ep !== '-' ? sqOf(ep) : -1;
  P.keys.push(posKey(P));
  return P;
}

/** A position as FEN. */
function toFen(P) {
  let s = '';
  for (let r = 7; r >= 0; r--) {
    let empty = 0;
    for (let f = 0; f < 8; f++) {
      const p = P.b[r * 16 + f];
      if (!p) { empty++; continue; }
      if (empty) { s += empty; empty = 0; }
      const ch = ' pnbrqk'[typeOf(p)];
      s += p & BLACK ? ch : ch.toUpperCase();
    }
    if (empty) s += empty;
    if (r) s += '/';
  }
  const c = (P.castle & W_OO ? 'K' : '') + (P.castle & W_OOO ? 'Q' : '') + (P.castle & B_OO ? 'k' : '') + (P.castle & B_OOO ? 'q' : '');
  return `${s} ${P.side ? 'b' : 'w'} ${c || '-'} ${P.ep >= 0 ? sqName(P.ep) : '-'} ${P.half} ${P.full}`;
}

/** The position for the repetition rule: the pieces, the side to move, the castling rights and the en passant square. */
function posKey(P) { let k = ''; for (let s = 0; s < 128; s++) if (!(s & 0x88)) k += ' pnbrqkXPNBRQK'[P.b[s]] || '.'; return k + P.side + P.castle + P.ep; }

/** Is square s attacked by side `by`? */
function attacked(P, s, by) {
  const b = P.b, own = by ? BLACK : 0;
  const pawnFrom = by ? [s + 15, s + 17] : [s - 15, s - 17];   // a pawn attacks diagonally forward
  for (const q of pawnFrom) if (!(q & 0x88) && b[q] === (PAWN | own)) return true;
  for (const d of N_STEPS) { const q = s + d; if (!(q & 0x88) && b[q] === (KNIGHT | own)) return true; }
  for (const d of K_STEPS) { const q = s + d; if (!(q & 0x88) && b[q] === (KING | own)) return true; }
  for (const d of B_STEPS) for (let q = s + d; !(q & 0x88); q += d) { const p = b[q]; if (p) { if (p === (BISHOP | own) || p === (QUEEN | own)) return true; break; } }
  for (const d of R_STEPS) for (let q = s + d; !(q & 0x88); q += d) { const p = b[q]; if (p) { if (p === (ROOK | own) || p === (QUEEN | own)) return true; break; } }
  return false;
}
const inCheck = (P, side = P.side) => attacked(P, P.kings[side], side ^ 1);

/** Every move for the side to move that obeys how the pieces move, not yet checked for leaving the king attacked. */
function pseudoMoves(P, capturesOnly = false) {
  const b = P.b, us = P.side, out = [], dir = us ? -16 : 16, start = us ? 6 : 1, last = us ? 0 : 7;
  for (let s = 0; s < 128; s++) {
    if (s & 0x88) { s += 7; continue; }
    const p = b[s];
    if (!p || sideOf(p) !== us) continue;
    const t = typeOf(p);
    if (t === PAWN) {
      const add = (to, flags) => { if ((to >> 4) === last) for (const pr of [QUEEN, ROOK, BISHOP, KNIGHT]) out.push(mk(s, to, pr, flags)); else out.push(mk(s, to, 0, flags)); };
      const one = s + dir;
      if (!capturesOnly && !(one & 0x88) && !b[one]) {
        add(one, 0);
        const two = one + dir;
        if ((s >> 4) === start && !b[two]) out.push(mk(s, two, 0, F_DOUBLE));
      }
      for (const to of [one - 1, one + 1]) {
        if (to & 0x88) continue;
        if (b[to] && sideOf(b[to]) !== us) add(to, F_CAPTURE);
        else if (to === P.ep) out.push(mk(s, to, 0, F_CAPTURE | F_EP));
      }
    } else if (t === KNIGHT || t === KING) {
      for (const d of t === KNIGHT ? N_STEPS : K_STEPS) {
        const to = s + d;
        if (to & 0x88) continue;
        if (!b[to]) { if (!capturesOnly) out.push(mk(s, to)); }
        else if (sideOf(b[to]) !== us) out.push(mk(s, to, 0, F_CAPTURE));
      }
    } else {
      for (const d of t === BISHOP ? B_STEPS : t === ROOK ? R_STEPS : K_STEPS) {
        for (let to = s + d; !(to & 0x88); to += d) {
          if (!b[to]) { if (!capturesOnly) out.push(mk(s, to)); continue; }
          if (sideOf(b[to]) !== us) out.push(mk(s, to, 0, F_CAPTURE));
          break;
        }
      }
    }
  }
  // Castling: the rights, empty squares between, and the king not in check nor passing through or onto an attack.
  if (!capturesOnly) {
    const k = us ? 116 : 4, them = us ^ 1;
    if (b[k] === (KING | (us ? BLACK : 0)) && !attacked(P, k, them)) {
      if (P.castle & (us ? B_OO : W_OO) && !b[k + 1] && !b[k + 2] && !attacked(P, k + 1, them) && !attacked(P, k + 2, them)) out.push(mk(k, k + 2, 0, F_CASTLE));
      if (P.castle & (us ? B_OOO : W_OOO) && !b[k - 1] && !b[k - 2] && !b[k - 3] && !attacked(P, k - 1, them) && !attacked(P, k - 2, them)) out.push(mk(k, k - 2, 0, F_CASTLE));
    }
  }
  return out;
}

// Castling rights lost when a piece moves from, or to, these squares (a king, or a rook's home).
const CASTLE_MASK = new Int8Array(128).fill(15);
CASTLE_MASK[4] = 15 & ~(W_OO | W_OOO); CASTLE_MASK[0] = 15 & ~W_OOO; CASTLE_MASK[7] = 15 & ~W_OO;
CASTLE_MASK[116] = 15 & ~(B_OO | B_OOO); CASTLE_MASK[112] = 15 & ~B_OOO; CASTLE_MASK[119] = 15 & ~B_OO;

/** Make a move (no legality check). unmake() takes it back. track: keep the position's key, for the repetition rule. */
function make(P, m, track = false) {
  const b = P.b, from = mFrom(m), to = mTo(m), fl = mFlags(m), p = b[from], us = P.side;
  let cap = b[to], capSq = to;
  if (fl & F_EP) { capSq = to + (us ? 16 : -16); cap = b[capSq]; b[capSq] = 0; }
  P.undo.push([m, cap, P.castle, P.ep, P.half]);
  b[to] = mPromo(m) ? mPromo(m) | (us ? BLACK : 0) : p; b[from] = 0;
  if (fl & F_CASTLE) { const rf = to > from ? from + 3 : from - 4, rt = to > from ? from + 1 : from - 1; b[rt] = b[rf]; b[rf] = 0; }
  if (typeOf(p) === KING) P.kings[us] = to;
  P.castle &= CASTLE_MASK[from] & CASTLE_MASK[to];
  P.ep = fl & F_DOUBLE ? (from + to) >> 1 : -1;
  P.half = typeOf(p) === PAWN || cap ? 0 : P.half + 1;
  if (us) P.full++;
  P.side ^= 1;
  if (track) P.keys.push(posKey(P));
}
function unmake(P, track = false) {
  const [m, cap, castle, ep, half] = P.undo.pop(), b = P.b, from = mFrom(m), to = mTo(m), fl = mFlags(m);
  P.side ^= 1;
  const us = P.side;
  if (us) P.full--;
  const p = mPromo(m) ? PAWN | (us ? BLACK : 0) : b[to];
  b[from] = p; b[to] = 0;
  if (fl & F_EP) b[to + (us ? 16 : -16)] = cap; else b[to] = cap;
  if (fl & F_CASTLE) { const rf = to > from ? from + 3 : from - 4, rt = to > from ? from + 1 : from - 1; b[rf] = b[rt]; b[rt] = 0; }
  if (typeOf(p) === KING) P.kings[us] = from;
  P.castle = castle; P.ep = ep; P.half = half;
  if (track) P.keys.pop();
}

/** The legal moves: the pseudo-legal ones that do not leave the mover's king attacked. */
function legalMoves(P, capturesOnly = false) {
  const out = [], us = P.side;
  for (const m of pseudoMoves(P, capturesOnly)) { make(P, m); if (!inCheck(P, us)) out.push(m); unmake(P); }
  return out;
}

/** The number of positions reached after `depth` half-moves: the standard test of a move generator. */
function perft(P, depth) {
  if (depth === 0) return 1;
  let n = 0;
  const us = P.side;
  for (const m of pseudoMoves(P)) {
    make(P, m);
    if (!inCheck(P, us)) n += depth === 1 ? 1 : perft(P, depth - 1);
    unmake(P);
  }
  return n;
}

const START_FEN = 'rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1';

// ===================================================================================================================
// The board on the screen (spec 3, 4).
// ===================================================================================================================

const SQ = 24, BX = 16, BY = 8;   // a square's size, and the board's top left on the screen
const screenX = (s) => BX + (s & 7) * SQ, screenY = (s) => BY + (7 - (s >> 4)) * SQ;

let skipTitle = false;
let state = 'title', paused = false, timer = 0, clock = 0;
let titleSel = 0, pauseSel = 0;
let pos = null;                 // the game's position
let cur = { f: 4, r: 1 };       // the cursor: file and rank
let liftedSq = -1, liftMoves = [];   // the square of the piece held, and its legal moves
let lastMove = 0;

function init() {
  if (dget(VERSION_SLOT) !== SAVE_VERSION) { for (let i = 0; i < 256; i++) dset(i, 0); dset(VERSION_SLOT, SAVE_VERSION); }
  if (skipTitle) newGame(); else toTitle();
}

function toTitle() { state = 'title'; timer = 0; titleSel = 0; paused = false; play(SONG.title); }

function newGame(fen = START_FEN) {
  pos = fromFen(fen); cur = { f: 4, r: pos.side ? 6 : 1 }; liftedSq = -1; liftMoves = []; lastMove = 0;
  state = 'game'; timer = 0; paused = false; play(SONG.game);
}

// --- Update ---

function update() {
  readPads(); clock++;
  if (!paused) timer++;
  if (paused) updatePause();
  else if (state === 'title') updateTitle();
  else if (state === 'game') updateGame();
}

function updateTitle() {
  if (pressed(UP) || pressed(DOWN)) { titleSel ^= 1; fx(SFX.move); }
  if (timer > 10 && (pressed(A) || pressed(START))) { fx(SFX.select); newGame(); }
}

/** The pad that moves now (step 1: pad 1 moves both sides; step 2 gives Black to pad 2 when it is used). */
const movePad = () => 0;

function updateGame() {
  const p = movePad();
  if (pressed(START, p)) { paused = true; pauseSel = 0; fx(SFX.pause); return; }
  const dx = (pressed(RIGHT, p) ? 1 : 0) - (pressed(LEFT, p) ? 1 : 0), dy = (pressed(UP, p) ? 1 : 0) - (pressed(DOWN, p) ? 1 : 0);
  if (dx || dy) { cur.f = (cur.f + dx + 8) % 8; cur.r = (cur.r + dy + 8) % 8; fx(SFX.move); }
  const s = cur.r * 16 + cur.f;
  if (pressed(B, p) && liftedSq >= 0) { liftedSq = -1; liftMoves = []; fx(SFX.place); return; }
  if (!pressed(A, p)) return;
  const piece = pos.b[s];
  if (liftedSq < 0 || (piece && sideOf(piece) === pos.side && s !== liftedSq)) {   // pick up (or change the piece held)
    if (piece && sideOf(piece) === pos.side) {
      liftMoves = legalMoves(pos).filter((m) => mFrom(m) === s);
      liftedSq = s; fx(liftMoves.length ? SFX.lift : SFX.no);
    } else fx(SFX.no);
    return;
  }
  if (s === liftedSq) { liftedSq = -1; liftMoves = []; fx(SFX.place); return; }   // put it back where it was
  const choices = liftMoves.filter((m) => mTo(m) === s);
  if (!choices.length) { fx(SFX.no); return; }
  // Step 1: a pawn reaching the last rank becomes a queen (step 2 asks which piece).
  playMove(choices.find((m) => mPromo(m) === QUEEN || !mPromo(m)));
}

/** A move into the game: made, remembered as the last move, with its sound. */
function playMove(m) {
  make(pos, m, true);
  lastMove = m; liftedSq = -1; liftMoves = [];
  fx(mFlags(m) & F_CAPTURE ? SFX.capture : SFX.place);
}

function updatePause() {
  if (pressed(UP)) { pauseSel = (pauseSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { pauseSel = (pauseSel + 1) % 3; fx(SFX.move); }
  if (pressed(B) || (pressed(START) && pauseSel === 0)) { paused = false; fx(SFX.pause); }
  else if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (pauseSel === 0) paused = false;
    else if (pauseSel === 1) newGame();
    else toTitle();
  }
}

// --- Draw ---

function draw() {
  cls();
  if (state === 'game') drawBoard();
  else if (state === 'title') drawTitle();
  if (paused) drawPause();
}

/** A piece, for now: a disc in its side's colour with its letter (the art pass, step 6, carves them). */
function drawPiece(p, x, y) {
  const white = sideOf(p) === WHITE_SIDE;
  circfill(x + 12, y + 12, 9, white ? ART.colors.IVORY : ART.colors.EBONY);
  circ(x + 12, y + 12, 9, white ? ART.colors.EBONY : ART.colors.IVORY);
  print(' PNBRQK'[typeOf(p)], x + 9, y + 9, white ? ART.colors.EBONY : ART.colors.IVORY);
}

function drawBoard() {
  const C = ART.colors;
  rectfill(BX - 6, BY - 6, 8 * SQ + 12, 8 * SQ + 12, C.FRAME);
  for (let s = 0; s < 128; s++) {
    if (s & 0x88) continue;
    const x = screenX(s), y = screenY(s);
    rectfill(x, y, SQ, SQ, ((s >> 4) + (s & 7)) % 2 ? C.LIGHT : C.DARK);
    if (lastMove && (s === mFrom(lastMove) || s === mTo(lastMove))) rect(x + 1, y + 1, SQ - 2, SQ - 2, C.LAST);
  }
  if (inCheck(pos)) { const k = pos.kings[pos.side]; rectfill(screenX(k), screenY(k), SQ, SQ, C.CHECK); }
  for (let s = 0; s < 128; s++) if (!(s & 0x88) && pos.b[s] && s !== liftedSq) drawPiece(pos.b[s], screenX(s), screenY(s));
  for (const m of liftMoves) {   // the legal squares: a dot on an empty one, a ring on a capture
    const x = screenX(mTo(m)) + 12, y = screenY(mTo(m)) + 12;
    if (pos.b[mTo(m)] || mFlags(m) & F_EP) circ(x, y, 10, C.MOVE); else circfill(x, y, 3, C.MOVE);
  }
  for (let f = 0; f < 8; f++) print('abcdefgh'[f], BX + f * SQ + 10, BY + 8 * SQ + 1, DIM);
  for (let r = 0; r < 8; r++) print(String(r + 1), BX - 6, BY + (7 - r) * SQ + 9, DIM);
  const cx = BX + cur.f * SQ, cy = BY + (7 - cur.r) * SQ;
  rect(cx, cy, SQ, SQ, C.CURSOR); rect(cx + 1, cy + 1, SQ - 2, SQ - 2, C.CURSOR);
  if (liftedSq >= 0) drawPiece(pos.b[liftedSq], cx, cy - 3);   // the piece held, raised over the cursor
  txt(pos.side ? 'BLACK TO MOVE' : 'WHITE TO MOVE', 16, 212, WHITE);
}

function drawTitle() {
  ctxt('ROYAL CHESS', 60, GOLD);
  ['PLAY', ''].forEach((s, i) => s && txt(`${i === titleSel ? '> ' : '  '}${s}`, 104, 110 + i * 14, WHITE));
  ctxt('STEP 1: THE BOARD AND THE MOVES', 190, DIM);
}

function drawPause() {
  panel(64, 80, 128, 64);
  ctxt('PAUSED', 88, GOLD);
  ['RESUME', 'NEW GAME', 'QUIT TO TITLE'].forEach((s, i) => txt(`${i === pauseSel ? '>' : ' '} ${s}`, 76, 104 + i * 10, i === pauseSel ? WHITE : DIM));
}

function panel(x, y, w, h) { rectfill(x, y, w, h, ART.colors.GLASS); rect(x, y, w, h, PANEL); }
function txt(s, x, y, c) { print(s, x + 1, y + 1, SHADOW); print(s, x, y, c); }
const ctxt = (s, y, c) => txt(s, 128 - s.length * 4, y, c);
