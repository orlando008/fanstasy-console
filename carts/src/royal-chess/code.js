// ===================================================================================================================
// The rules (spec 5): a 0x88 board. A square is rank * 16 + file (a1 = 0, h1 = 7, a8 = 112); sq & 0x88 is off the
// board. A piece is its type (1 pawn, 2 knight, 3 bishop, 4 rook, 5 queen, 6 king) plus 8 for Black; 0 is empty.
// ===================================================================================================================

const PAWN = 1, KNIGHT = 2, BISHOP = 3, ROOK = 4, QUEEN = 5, KING = 6, BLACK = 8, WHITE_SIDE = 0, BLACK_SIDE = 1;
const W_OO = 1, W_OOO = 2, B_OO = 4, B_OOO = 8;
const N_STEPS = [33, 31, 18, 14, -14, -18, -31, -33], K_STEPS = [1, -1, 16, -16, 17, 15, -15, -17];
const B_STEPS = [17, 15, -15, -17], R_STEPS = [1, -1, 16, -16];
// A move: from | to << 7 | promotion type << 14 | flags << 17.
const F_CAPTURE = 1, F_DOUBLE = 2, F_EP = 4, F_CASTLE = 8;
const mFrom = (m) => m & 127, mTo = (m) => (m >> 7) & 127, mPromo = (m) => (m >> 14) & 7, mFlags = (m) => m >> 17;
const mk = (from, to, promo = 0, flags = 0) => from | (to << 7) | (promo << 14) | (flags << 17);

const sideOf = (p) => (p & BLACK ? BLACK_SIDE : WHITE_SIDE), typeOf = (p) => p & 7;
const sqName = (s) => 'abcdefgh'[s & 7] + ((s >> 4) + 1);
const sqOf = (name) => (name.charCodeAt(1) - 49) * 16 + (name.charCodeAt(0) - 97);

/** A new position from FEN (spec 6). */
function fromFen(fen) {
  const [placement, side, castle, ep, half, full] = fen.trim().split(/\s+/);
  const P = { b: new Int8Array(128), side: side === 'b' ? BLACK_SIDE : WHITE_SIDE, castle: 0, ep: -1, half: +half || 0, full: +full || 1, kings: [0, 0], undo: [], keys: [] };
  let r = 7, f = 0;
  for (const ch of placement) {
    if (ch === '/') { r--; f = 0; }
    else if (ch >= '1' && ch <= '8') f += +ch;
    else {
      const t = 'pnbrqk'.indexOf(ch.toLowerCase()) + 1, p = t | (ch === ch.toLowerCase() ? BLACK : 0);
      P.b[r * 16 + f] = p; if (t === KING) P.kings[sideOf(p)] = r * 16 + f; f++;
    }
  }
  for (const ch of castle || '-') P.castle |= { K: W_OO, Q: W_OOO, k: B_OO, q: B_OOO }[ch] || 0;
  P.ep = ep && ep !== '-' ? sqOf(ep) : -1;
  P.keys.push(posKey(P));
  return P;
}

/** A position as FEN. */
function toFen(P) {
  let s = '';
  for (let r = 7; r >= 0; r--) {
    let empty = 0;
    for (let f = 0; f < 8; f++) {
      const p = P.b[r * 16 + f];
      if (!p) { empty++; continue; }
      if (empty) { s += empty; empty = 0; }
      const ch = ' pnbrqk'[typeOf(p)];
      s += p & BLACK ? ch : ch.toUpperCase();
    }
    if (empty) s += empty;
    if (r) s += '/';
  }
  const c = (P.castle & W_OO ? 'K' : '') + (P.castle & W_OOO ? 'Q' : '') + (P.castle & B_OO ? 'k' : '') + (P.castle & B_OOO ? 'q' : '');
  return `${s} ${P.side ? 'b' : 'w'} ${c || '-'} ${P.ep >= 0 ? sqName(P.ep) : '-'} ${P.half} ${P.full}`;
}

/** The position for the repetition rule: the pieces, the side to move, the castling rights and the en passant square. */
function posKey(P) { let k = ''; for (let s = 0; s < 128; s++) if (!(s & 0x88)) k += ' pnbrqkXPNBRQK'[P.b[s]] || '.'; return k + P.side + P.castle + P.ep; }

/** Is square s attacked by side `by`? */
function attacked(P, s, by) {
  const b = P.b, own = by ? BLACK : 0;
  const pawnFrom = by ? [s + 15, s + 17] : [s - 15, s - 17];   // a pawn attacks diagonally forward
  for (const q of pawnFrom) if (!(q & 0x88) && b[q] === (PAWN | own)) return true;
  for (const d of N_STEPS) { const q = s + d; if (!(q & 0x88) && b[q] === (KNIGHT | own)) return true; }
  for (const d of K_STEPS) { const q = s + d; if (!(q & 0x88) && b[q] === (KING | own)) return true; }
  for (const d of B_STEPS) for (let q = s + d; !(q & 0x88); q += d) { const p = b[q]; if (p) { if (p === (BISHOP | own) || p === (QUEEN | own)) return true; break; } }
  for (const d of R_STEPS) for (let q = s + d; !(q & 0x88); q += d) { const p = b[q]; if (p) { if (p === (ROOK | own) || p === (QUEEN | own)) return true; break; } }
  return false;
}
const inCheck = (P, side = P.side) => attacked(P, P.kings[side], side ^ 1);

/** Every move for the side to move that obeys how the pieces move, not yet checked for leaving the king attacked. */
function pseudoMoves(P, capturesOnly = false) {
  const b = P.b, us = P.side, out = [], dir = us ? -16 : 16, start = us ? 6 : 1, last = us ? 0 : 7;
  for (let s = 0; s < 128; s++) {
    if (s & 0x88) { s += 7; continue; }
    const p = b[s];
    if (!p || sideOf(p) !== us) continue;
    const t = typeOf(p);
    if (t === PAWN) {
      const add = (to, flags) => { if ((to >> 4) === last) for (const pr of [QUEEN, ROOK, BISHOP, KNIGHT]) out.push(mk(s, to, pr, flags)); else out.push(mk(s, to, 0, flags)); };
      const one = s + dir;
      if (!capturesOnly && !(one & 0x88) && !b[one]) {
        add(one, 0);
        const two = one + dir;
        if ((s >> 4) === start && !b[two]) out.push(mk(s, two, 0, F_DOUBLE));
      }
      for (const to of [one - 1, one + 1]) {
        if (to & 0x88) continue;
        if (b[to] && sideOf(b[to]) !== us) add(to, F_CAPTURE);
        else if (to === P.ep) out.push(mk(s, to, 0, F_CAPTURE | F_EP));
      }
    } else if (t === KNIGHT || t === KING) {
      for (const d of t === KNIGHT ? N_STEPS : K_STEPS) {
        const to = s + d;
        if (to & 0x88) continue;
        if (!b[to]) { if (!capturesOnly) out.push(mk(s, to)); }
        else if (sideOf(b[to]) !== us) out.push(mk(s, to, 0, F_CAPTURE));
      }
    } else {
      for (const d of t === BISHOP ? B_STEPS : t === ROOK ? R_STEPS : K_STEPS) {
        for (let to = s + d; !(to & 0x88); to += d) {
          if (!b[to]) { if (!capturesOnly) out.push(mk(s, to)); continue; }
          if (sideOf(b[to]) !== us) out.push(mk(s, to, 0, F_CAPTURE));
          break;
        }
      }
    }
  }
  // Castling: the rights, empty squares between, and the king not in check nor passing through or onto an attack.
  if (!capturesOnly) {
    const k = us ? 116 : 4, them = us ^ 1;
    if (b[k] === (KING | (us ? BLACK : 0)) && !attacked(P, k, them)) {
      if (P.castle & (us ? B_OO : W_OO) && !b[k + 1] && !b[k + 2] && !attacked(P, k + 1, them) && !attacked(P, k + 2, them)) out.push(mk(k, k + 2, 0, F_CASTLE));
      if (P.castle & (us ? B_OOO : W_OOO) && !b[k - 1] && !b[k - 2] && !b[k - 3] && !attacked(P, k - 1, them) && !attacked(P, k - 2, them)) out.push(mk(k, k - 2, 0, F_CASTLE));
    }
  }
  return out;
}

// Castling rights lost when a piece moves from, or to, these squares (a king, or a rook's home).
const CASTLE_MASK = new Int8Array(128).fill(15);
CASTLE_MASK[4] = 15 & ~(W_OO | W_OOO); CASTLE_MASK[0] = 15 & ~W_OOO; CASTLE_MASK[7] = 15 & ~W_OO;
CASTLE_MASK[116] = 15 & ~(B_OO | B_OOO); CASTLE_MASK[112] = 15 & ~B_OOO; CASTLE_MASK[119] = 15 & ~B_OO;

/** Make a move (no legality check). unmake() takes it back. track: keep the position's key, for the repetition rule. */
function make(P, m, track = false) {
  const b = P.b, from = mFrom(m), to = mTo(m), fl = mFlags(m), p = b[from], us = P.side;
  let cap = b[to], capSq = to;
  if (fl & F_EP) { capSq = to + (us ? 16 : -16); cap = b[capSq]; b[capSq] = 0; }
  P.undo.push([m, cap, P.castle, P.ep, P.half]);
  b[to] = mPromo(m) ? mPromo(m) | (us ? BLACK : 0) : p; b[from] = 0;
  if (fl & F_CASTLE) { const rf = to > from ? from + 3 : from - 4, rt = to > from ? from + 1 : from - 1; b[rt] = b[rf]; b[rf] = 0; }
  if (typeOf(p) === KING) P.kings[us] = to;
  P.castle &= CASTLE_MASK[from] & CASTLE_MASK[to];
  P.ep = fl & F_DOUBLE ? (from + to) >> 1 : -1;
  P.half = typeOf(p) === PAWN || cap ? 0 : P.half + 1;
  if (us) P.full++;
  P.side ^= 1;
  if (track) P.keys.push(posKey(P));
}
function unmake(P, track = false) {
  const [m, cap, castle, ep, half] = P.undo.pop(), b = P.b, from = mFrom(m), to = mTo(m), fl = mFlags(m);
  P.side ^= 1;
  const us = P.side;
  if (us) P.full--;
  const p = mPromo(m) ? PAWN | (us ? BLACK : 0) : b[to];
  b[from] = p; b[to] = 0;
  if (fl & F_EP) b[to + (us ? 16 : -16)] = cap; else b[to] = cap;
  if (fl & F_CASTLE) { const rf = to > from ? from + 3 : from - 4, rt = to > from ? from + 1 : from - 1; b[rf] = b[rt]; b[rt] = 0; }
  if (typeOf(p) === KING) P.kings[us] = from;
  P.castle = castle; P.ep = ep; P.half = half;
  if (track) P.keys.pop();
}

/** The legal moves: the pseudo-legal ones that do not leave the mover's king attacked. */
function legalMoves(P, capturesOnly = false) {
  const out = [], us = P.side;
  for (const m of pseudoMoves(P, capturesOnly)) { make(P, m); if (!inCheck(P, us)) out.push(m); unmake(P); }
  return out;
}

/** The number of positions reached after `depth` half-moves: the standard test of a move generator. */
function perft(P, depth) {
  if (depth === 0) return 1;
  let n = 0;
  const us = P.side;
  for (const m of pseudoMoves(P)) {
    make(P, m);
    if (!inCheck(P, us)) n += depth === 1 ? 1 : perft(P, depth - 1);
    unmake(P);
  }
  return n;
}

