/** Copy a 16 px stamp (2 x 2 Map RAM entries from the library at stamp column sc, row sr) to tile (tx, ty) of the room's layer at
 * column `base`, with palette `pal` (or as it is); `off` writes nothing there (an empty cell). */
function stamp(base, tx, ty, sc, sr, pal = -1, off = false) {
  for (let j = 0; j < 2; j++) for (let i = 0; i < 2; i++) {
    let e = off ? 0 : mget(STAMP.mx + sc * 2 + i, STAMP.my + sr * 2 + j);
    if (e && pal >= 0) e = (e & ~(7 << 10)) | (pal << 10);
    mset(base + tx + i, ty + j, e);
  }
}
const hash2 = (x, y) => ((x * 73856093) ^ (y * 19349663) ^ (roomNo * 83492791)) >>> 0;
/** A wall cell of the room's outer wall that is a window: every third along the walls, not at the corners. */
function isWindow(x, y) {
  const { w, h, wall } = room;
  if (wall[y * w + x] === 3) return true;
  if (wall[y * w + x] !== 1) return false;
  const edge = x === 0 || y === 0 || x === w - 1 || y === h - 1, corner = (x === 0 || x === w - 1) && (y === 0 || y === h - 1);
  const inward = [0, 1, 2, 3].some((d) => { const nx = x + DX[d], ny = y + DY[d]; return nx >= 0 && ny >= 0 && nx < w && ny < h && !room.wall[ny * w + nx]; });
  return edge && !corner && inward && (x + y) % 3 === 1;
}
/** The room's layers: the margins and outside the tower's dark stone; walls, windows, the floor (its shadowed cells under walls); then
 * paintRoom() lights the floor where the light is (palette 2) and, in a dark room, blanks what cannot be seen. */
function buildRoom() {
  const f = Math.floor(roomNo / FLOOR_ROOMS), X = ox() / 8, Y = oy() / 8, { w, h, wall } = room;
  loadTheme(f);
  for (let ty = 0; ty < 28; ty += 2) for (let tx = 0; tx < 32; tx += 2) { stamp(ROOM_BG1, tx, ty, 4 + ((tx + ty) & 2 ? 1 : 0), 4); stamp(ROOM_BG0, tx, ty, 0, 0, -1, true); }
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const v = wall[y * w + x], tx = X + 2 * x, ty = Y + 2 * y;
    if (v === 2) continue; // outside: the dark stone
    if (v) { stamp(ROOM_BG0, tx, ty, isWindow(x, y) ? 2 : hash2(x, y) % 5 ? 0 : 1, 4); stamp(ROOM_BG1, tx, ty, 0, 0, -1, true); }
  }
  paintRoom();
}
function paintRoom() {
  const f = Math.floor(roomNo / FLOOR_ROOMS), X = ox() / 8, Y = oy() / 8, { w, h, wall } = room, lit = light.lit;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const v = wall[y * w + x], tx = X + 2 * x, ty = Y + 2 * y, seen = seenCell(x, y);
    if (v === 2) continue;
    if (!seen) { stamp(ROOM_BG0, tx, ty, 0, 0, -1, true); stamp(ROOM_BG1, tx, ty, 6, 4); continue; } // (not seen: solid dark)
    if (v) { if (room.dark) { stamp(ROOM_BG0, tx, ty, isWindow(x, y) ? 2 : hash2(x, y) % 5 ? 0 : 1, 4); stamp(ROOM_BG1, tx, ty, 0, 0, -1, true); } continue; }
    const under = y > 0 && (wall[(y - 1) * w + x] === 1 || wall[(y - 1) * w + x] === 3);
    stamp(ROOM_BG1, tx, ty, (hash2(x, y) >>> 3) % 4 + (under ? 4 : 0), f, lit[y * w + x] ? 2 : 1); // (>>>: the hash is unsigned)
  }
}
/** In a dark room a cell shows only when light is on it or next to it, or it is next to the cursor (the keeper's hand lamp). */
const seenCell = (x, y) => !room.dark || light.lit[y * room.w + x] || (Math.abs(x - cx) <= 1 && Math.abs(y - cy) <= 1);

