    const k = flash ? (flash > LIGHTNING / 2 ? 22 : 12) : 0;
    for (const base of [64, 112]) for (let i = 1; i < 16; i++) { const v = PALETTE0[base + i]; color(base + i, lift(v & 31, k), lift((v >> 5) & 31, k), lift(v >> 10, k)); }
