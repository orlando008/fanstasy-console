const packSpot = (c) => (c ? (c.who | (c.items[0] << 4) | ((c.items[1] || 0) << 9) | ((c.got[0] ? 1 : 0) << 14) | ((c.got[1] ? 1 : 0) << 15) | ((c.special ? 1 : 0) << 16) | (1 << 17)) : 0);
