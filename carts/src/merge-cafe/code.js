  coins = dget(COINS_SLOT); stars = dget(STARS_SLOT); found = dget(FOUND_SLOT); cratesOpened = dget(CRATES_SLOT);
  tasks = dget(TASKS_SLOT); styles = [dget(STYLE_SLOT), dget(STYLE_SLOT + 1)]; served = dget(SERVED_SLOT);
  const st = dget(STORY_SLOT); story = [0, 1, 2, 3, 4].map((k) => (st >> (3 * k)) & 7);
