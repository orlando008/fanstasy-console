/** Queue one of ART.sprites at (x, y); opts as for spr. */
function sprite(s, x, y, opts = {}) { spr(s.tile, x, y, { size: s.size, pal: s.pal, prio: 3, ...opts }); }

// --- Pictures (art.py): items, generators, the crate and the customers are 32 x 32 pictures in the ROM (rom/pics.bin), copied into a pool of
// sprite slots as the screen needs them, the least recently used slot first (spec 14). picSlot(p) returns the slot, -1 if every slot is
// already showing another picture this frame (then the picture is not drawn this frame).

const POOL = 36, PIC_CRATE = 35, PIC_MABEL = 36;
const SLOT_TILE = Array.from({ length: POOL }, (_, k) => ART.sprites['slot' + k].tile);
let slotPic = new Array(POOL).fill(-1), slotAt = new Array(POOL).fill(-1), drawNo = 0, picLoads = 0;
const picPal = (p) => rom('pics')[1 + p * 513];
function picSlot(p) {
  let k = slotPic.indexOf(p);
  if (k < 0) {
    for (let i = 0; i < POOL; i++) if (slotAt[i] !== drawNo && (k < 0 || slotAt[i] < slotAt[k])) k = i;
    if (k < 0) return -1;
    const b = rom('pics'), off = 2 + p * 513, t = SLOT_TILE[k], x0 = (t % 16) * 8, y0 = (t >> 4) * 8;
    for (let y = 0; y < 32; y++) for (let x = 0; x < 32; x += 2) { const v = b[off + y * 16 + (x >> 1)]; sset(x0 + x, y0 + y, v & 15); sset(x0 + x + 1, y0 + y, v >> 4); }
    slotPic[k] = p; picLoads++;
  }
  slotAt[k] = drawNo;
  return k;
}
function drawPic(p, x, y, opts = {}) { const k = picSlot(p); if (k >= 0) spr(SLOT_TILE[k], x, y, { size: 32, pal: picPal(p), prio: 3, ...opts }); }

// --- Sound (SPEC 5): songs on channels 0 to 5, effects take turns on 6 and 7 ---

const SFX = { move: 0, select: 1, pause: 2, knock: 3, pick: 4, drop: 5, pop: 6, merge: 7, sell: 12, crate: 13, find: 14, serve: 15, stars: 16, fanfare: 17 };
const SONG = { title: 0, play: 1 };
const SFX_CH = [7, 6];
let fxNext = 0;
function fx(n) { sfx(n, SFX_CH[fxNext]); fxNext ^= 1; }
let playing = -1;
function play(song) { if (song === playing) return; playing = song; music(song); }

// --- The board and the items (spec 5.1 to 5.3) ---

const COLS = 7, ROWS = 5, CELLS = 35, CW = 32, CH = 28, BX = 16, BY = 84;
const EMPTY = 0, GEN0 = 31, CRATE = 40;                             // a cell: 0 empty, 1 to 30 an item (line x 6 + tier), 31 to 35 a generator, 40 a crate
const LINES = ['BAKERY', 'COFFEE', 'DAIRY', 'FRUIT', 'TABLEWARE'];
const NAMES = [
  ['WHEAT', 'FLOUR', 'DOUGH', 'ROLL', 'LOAF', 'LAYER CAKE'],
  ['BEANS', 'GROUND COFFEE', 'ESPRESSO', 'CAPPUCCINO', 'LATTE', 'COFFEE POT SET'],
  ['MILK', 'CREAM', 'WHIPPED CREAM', 'ICE CREAM', 'SUNDAE', 'PARFAIT'],
  ['CHERRY', 'STRAWBERRIES', 'BERRY BOWL', 'JAM JAR', 'FRUIT TART', 'FRUIT PIE'],
  ['SPOON', 'CUP', 'TEAPOT', 'TRAY', 'CAKE STAND', 'TEA SERVICE'],
];
const GEN_NAMES = ['GRAIN SACK', 'COFFEE GRINDER', 'MILK CHURN', 'FRUIT BASKET', 'CUPBOARD'];
const TIER2_CHANCE = 0.1, CRATE_BASE = 10, CRATE_STEP = 5, START_COINS = 10;
const item = (line, tier) => line * 6 + tier;
const isItem = (v) => v >= 1 && v <= 30, isGen = (v) => v >= GEN0 && v < GEN0 + 5;
const lineOf = (v) => ((v - 1) / 6) | 0, tierOf = (v) => ((v - 1) % 6) + 1;
const nameOf = (v) => (isItem(v) ? NAMES[lineOf(v)][tierOf(v) - 1] : isGen(v) ? GEN_NAMES[v - GEN0] : v === CRATE ? 'CRATE' : '');
const valueOf = (v) => (isItem(v) ? tierOf(v) * tierOf(v) : 0);  // what an item sells for (5.1)
const picOf = (v) => (isItem(v) ? v - 1 : isGen(v) ? 30 + v - GEN0 : v === CRATE ? PIC_CRATE : -1);
const colOf = (i) => i % COLS, rowOf = (i) => (i / COLS) | 0, cellX = (i) => BX + colOf(i) * CW, cellY = (i) => BY + rowOf(i) * CH;
const crateCost = () => CRATE_BASE + CRATE_STEP * cratesOpened;

/** A new café's board: rows 0 and 1 open, the grain sack and the grinder on row 1, two wheat to start; the rest under crates (5.3). */
function newBoard() {
  const b = new Array(CELLS).fill(CRATE);
  for (let i = 0; i < 14; i++) b[i] = EMPTY;
  b[7 + 1] = GEN0; b[7 + 5] = GEN0 + 1; b[2] = item(0, 1); b[4] = item(0, 1);
  return b;
}
/** The empty cell nearest cell i (the fewest steps across cells; ties: the higher row, then the left), or -1. */
function nearestEmpty(b, i) {
  let best = -1, bd = 99;
  for (let j = 0; j < CELLS; j++) {
    if (b[j] !== EMPTY) continue;
    const d = Math.abs(colOf(j) - colOf(i)) + Math.abs(rowOf(j) - rowOf(i));
    if (d < bd) { bd = d; best = j; }                               // j runs row by row, left to right: the first at a distance wins the tie
  }
  return best;
}
/** What dropping the item from cell a onto cell b does: 'back', 'move', 'merge', 'swap' or 'no' (a crate, or two of the top tier). */
function dropKind(b, a, t) {
  if (a === t) return 'back';
  const u = b[t], v = b[a];
  if (u === CRATE) return 'no';
  if (u === EMPTY) return 'move';
  if (u === v) return tierOf(v) < 6 ? 'merge' : 'no';
  return 'swap';
}
/** A crate can be opened when a cell beside it (up, down, left or right) is open. */
const crateOpenable = (b, i) => b[i] === CRATE && [[-1, 0], [1, 0], [0, -1], [0, 1]].some(([dc, dr]) => {
  const c = colOf(i) + dc, r = rowOf(i) + dr;
  return c >= 0 && c < COLS && r >= 0 && r < ROWS && b[r * COLS + c] !== CRATE;
});

// --- Save slots (spec section 13) ---

const VERSION_SLOT = 0, SAVE_VERSION = 1, BOARD_SLOT = 1, COINS_SLOT = 10, STARS_SLOT = 11, FOUND_SLOT = 15, CRATES_SLOT = 17;
function saveGame() {
  for (let k = 0; k < 9; k++) {
    let v = 0;
    for (let q = 0; q < 4; q++) v |= (board[k * 4 + q] ?? 0) << (8 * q);
    dset(BOARD_SLOT + k, v);
  }
  dset(COINS_SLOT, coins); dset(STARS_SLOT, stars); dset(FOUND_SLOT, found); dset(CRATES_SLOT, cratesOpened);
}
function loadGame() {
  board = [];
  for (let i = 0; i < CELLS; i++) board.push((dget(BOARD_SLOT + (i >> 2)) >>> (8 * (i & 3))) & 255);
  coins = dget(COINS_SLOT); stars = dget(STARS_SLOT); found = dget(FOUND_SLOT); cratesOpened = dget(CRATES_SLOT);
}
const hasSave = () => dget(VERSION_SLOT) === SAVE_VERSION && dget(BOARD_SLOT + 2) !== 0;

// --- Input: edge-triggered presses, and a held d-pad that repeats ---

let inputMask = 0, prevMask = 0;
const BUTTONS = [UP, DOWN, LEFT, RIGHT, A, B, X, Y, L, R, START, SELECT];
function readPad() { let m = 0; for (const b of BUTTONS) if (btn(b)) m |= 1 << b; return m; }
const pressed = (b) => (inputMask & (1 << b)) !== 0 && (prevMask & (1 << b)) === 0;
const stepped = (b) => pressed(b) || (btnp(b) && (inputMask & (1 << b)) !== 0);

// --- State ---

let skipTitle = false;                                              // tests set this to land straight on the board
let state = 'title', paused = false, timer = 0, clock = 0, titleSel = 0, pauseSel = 0, confirm = null;
let board = [], coins = 0, stars = 0, found = 0, cratesOpened = 0;
let cur = 17, held = -1, card = -1, ask = null, msg = '', msgAt = -999, msgC = WHITE;
let anims = [], sparks = [];

function init() {
  if (dget(VERSION_SLOT) !== SAVE_VERSION) { for (let i = 0; i < 256; i++) dset(i, 0); dset(VERSION_SLOT, SAVE_VERSION); }
  const bd = ART.scenes.board, cf = ART.scenes.cafe, lg = ART.scenes.logo;
  bg(0, { mx: bd.mx, my: bd.my, mw: bd.w, mh: bd.h, x: 0, y: 0, wrap: false, show: true });
  bg(1, { mx: cf.mx, my: cf.my, mw: cf.w, mh: 11, x: 0, y: 0, wrap: false, show: true });
  bg(2, { mx: lg.mx, my: lg.my, mw: lg.w, mh: lg.h, x: 0, y: -96, wrap: false, show: false });
  color(CREAM, 30, 28, 24); color(SOLID, 6, 3, 2); color(0, 7, 4, 3);   // the backdrop: dark wood, for the title
  const bb = ART.scenes.bubble;                                     // an order bubble beside the customer (orders: step 4)
  for (let y = 0; y < bb.h; y++) for (let x = 0; x < bb.w; x++) mset(bd.mx + BUBBLE_TX + x, bd.my + y, mget(bb.mx + x, bb.my + y));
  blend({ layers: ['overlay'], half: true });                       // overlay colours from 192 up (GLASS) are see-through panels
  if (skipTitle) { if (hasSave()) loadGame(); else newCafe(); toPlay(); } else toTitle();
}

function newCafe() {
  board = newBoard(); coins = START_COINS; stars = 0; found = 0; cratesOpened = 0;
  markFound(item(0, 1), true); markFound(GEN0, true);
  saveGame();
}
function toTitle() { state = 'title'; timer = 0; titleSel = 0; paused = false; confirm = null; play(SONG.title); }
function toPlay() { state = 'play'; timer = 0; paused = false; held = -1; card = -1; ask = null; anims = []; play(SONG.play); }
function say(text, c = WHITE) { msg = text; msgAt = clock; msgC = c; }
/** The first time an item is made: a star and a card (5.6). quiet: at the start of a café, no star. */
function markFound(v, quiet = false) {
  if (!isItem(v)) return;
  const bit = 1 << (v - 1);
  if (found & bit) return;
  found |= bit;
  if (!quiet) { stars++; say('NEW: ' + nameOf(v) + '  +1 STAR', GOLD); fx(SFX.find); }
}

// --- Update ---

function update() {
  inputMask = readPad(); clock++;
  if (!paused) timer++;
  if (paused) updatePause();
  else if (state === 'title') updateTitle();
  else if (state === 'play') updatePlay();
  prevMask = inputMask;
}

function updateTitle() {
  if (confirm) {                                                    // NEW CAFE over a saved one asks first
    if (pressed(A)) { fx(SFX.select); newCafe(); toPlay(); } else if (pressed(B)) { fx(SFX.move); confirm = null; }
    return;
  }
  if (pressed(UP) || pressed(DOWN)) { titleSel ^= 1; fx(SFX.move); }
  if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    const cont = hasSave();
    if (titleSel === 0) { if (cont) loadGame(); else newCafe(); toPlay(); }
    else if (cont) confirm = 'new'; else { newCafe(); toPlay(); }
  }
}

/** A on the cell under the cursor: make, pick up, drop, open (spec section 3). */
function press(i) {
  const v = board[i];
  if (held >= 0) { drop(held, i); return; }
  if (isGen(v)) { generate(i); return; }
  if (isItem(v)) { held = i; fx(SFX.pick); return; }
  if (v === CRATE) {
    if (!crateOpenable(board, i)) { say('OPEN THE CRATES NEXT TO YOUR SPACE FIRST', ORANGE); fx(SFX.knock); return; }
    if (ask && ask.kind === 'crate' && ask.i === i) {
      ask = null;
      if (coins < crateCost()) { say(`A CRATE COSTS ${crateCost()} COINS`, ORANGE); fx(SFX.knock); return; }
      coins -= crateCost(); cratesOpened++; board[i] = EMPTY; fx(SFX.crate); burst(i); saveGame();
    } else ask = { kind: 'crate', i };
  }
}
function generate(g) {
  const to = nearestEmpty(board, g);
  if (to < 0) { say('NO ROOM ON THE BOARD', ORANGE); fx(SFX.knock); return -1; }
  const line = board[g] - GEN0, v = item(line, rnd(1) < TIER2_CHANCE ? 2 : 1);
  board[to] = v; markFound(v); fx(SFX.pop);
  anims.push({ i: to, from: g, at: clock });
  saveGame();
  return to;
}
function drop(a, t) {
  const k = dropKind(board, a, t), v = board[a];
  held = -1;
  if (k === 'back') { fx(SFX.drop); return k; }
  if (k === 'no') { held = a; fx(SFX.knock); return k; }
  if (k === 'move') { board[t] = v; board[a] = EMPTY; fx(SFX.drop); }
  else if (k === 'swap') { board[a] = board[t]; board[t] = v; fx(SFX.drop); }
  else { board[t] = v + 1; board[a] = EMPTY; fx(SFX.merge + tierOf(v + 1) - 2); burst(t); markFound(v + 1); }
  saveGame();
  return k;
}
function sell(i) {
  const v = board[i];
  if (!isItem(v)) return 0;
  coins += valueOf(v); board[i] = EMPTY; fx(SFX.sell); say(`SOLD ${nameOf(v)}: +${valueOf(v)} COIN${valueOf(v) > 1 ? 'S' : ''}`, GOLD); saveGame();
  return valueOf(v);
}
function burst(i) { for (let k = 0; k < 6; k++) sparks.push({ x: cellX(i) + 16, y: cellY(i) + 13, a: k * Math.PI / 3 + clock * 0.3, at: clock }); }

function updatePlay() {
  if (pressed(START)) { paused = true; pauseSel = 0; fx(SFX.pause); return; }
  if (ask) {                                                        // a question waiting: A yes, anything else no
    if (pressed(A)) { const q = ask; if (q.kind === 'sell') { ask = null; sell(q.i); } else press(q.i); return; }
    if (pressed(B) || stepped(UP) || stepped(DOWN) || stepped(LEFT) || stepped(RIGHT) || pressed(SELECT)) { ask = null; fx(SFX.move); }
    return;
  }
  if (card >= 0) { if (pressed(A) || pressed(B) || pressed(SELECT)) card = -1; return; }
  const c = colOf(cur), r = rowOf(cur);
  if (stepped(LEFT) && c > 0) { cur--; fx(SFX.move); }
  if (stepped(RIGHT) && c < COLS - 1) { cur++; fx(SFX.move); }
  if (stepped(UP) && r > 0) { cur -= COLS; fx(SFX.move); }
  if (stepped(DOWN) && r < ROWS - 1) { cur += COLS; fx(SFX.move); }
  if (pressed(A)) press(cur);
  else if (pressed(B)) { if (held >= 0) { held = -1; fx(SFX.drop); } else if (board[cur] !== EMPTY) card = cur; }
  else if (pressed(SELECT) && held < 0) { if (isItem(board[cur])) ask = { kind: 'sell', i: cur }; else fx(SFX.knock); }
}

function updatePause() {
  if (confirm) { if (pressed(A)) { fx(SFX.select); newCafe(); toPlay(); } else if (pressed(B)) confirm = null; return; }
  if (pressed(UP)) { pauseSel = (pauseSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { pauseSel = (pauseSel + 1) % 3; fx(SFX.move); }
  if (pressed(B) || (pressed(START) && pauseSel === 0)) { paused = false; fx(SFX.pause); }
  else if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (pauseSel === 0) paused = false;
    else if (pauseSel === 1) confirm = 'new';
    else { saveGame(); toTitle(); }
  }
}

// --- Draw ---

function draw() {
  cls(); drawNo++;
  const inGame = state === 'play';
  bg(0, { show: inGame }); bg(2, { show: state === 'title' });
  drawCafe();
  if (inGame) { drawBoard(); drawHud(); }
  else drawTitle();
  if (paused) drawPause();
}

const BUBBLE_TX = 18;                                               // the bubble's tile column in BG0's map (x 144)
/** The café: Mabel at the counter with her order (customers and orders come in step 4). */
function drawCafe() {
  const blink = (clock % 240) < 8;
  drawPic(PIC_MABEL + (blink ? 1 : 0), 112, 26, { prio: 1 });     // behind the counter's high-priority tiles
  if (state === 'play') drawPic(picOf(item(0, 4)), BUBBLE_TX * 8, -2);   // her order: a roll
}

function drawBoard() {
  const now = clock;
  for (let i = 0; i < CELLS; i++) {
    const v = board[i];
    if (v === EMPTY || i === held) continue;
    const an = anims.find((a) => a.i === i && now - a.at < 10);
    let x = cellX(i), y = cellY(i) - 1;
    if (an) { const k = (now - an.at) / 10; x = lerp(cellX(an.from), x, k); y = lerp(cellY(an.from), y, k) - Math.sin(k * Math.PI) * 10; }
    drawPic(picOf(v), flr(x), flr(y), { prio: 2 });
  }
  anims = anims.filter((a) => now - a.at < 10);
  const bob = (clock >> 4) & 1;
  sprite(ART.sprites[bob ? 'cursor1' : 'cursor0'], cellX(cur), cellY(cur) - 2, { prio: 3 });
  if (held >= 0) drawPic(picOf(board[held]), cellX(cur), cellY(cur) - 9 - bob, { prio: 3 });
  sparks = sparks.filter((s) => clock - s.at < 14);
  for (const s of sparks) { const d = 4 + (clock - s.at) * 1.5; sprite(ART.sprites.spark, flr(s.x + d * Math.cos(s.a) - 4), flr(s.y + d * Math.sin(s.a) - 4)); }
}

function drawHud() {
  txt(`COINS ${coins}`, 4, 2, GOLD);
  const st = `STARS ${stars}`; txt(st, 252 - st.length * 8, 2, CREAM);
  if (ask) {
    const v = board[ask.i];
    panel(24, 120, 208, 40);
    ctxt(ask.kind === 'sell' ? `SELL ${nameOf(v)} FOR ${valueOf(v)}?` : `OPEN THIS CRATE FOR ${crateCost()}?`, 130, WHITE);
    ctxt('A: YES   B: NO', 144, DIM);
  } else if (card >= 0) drawCard(board[card]);
  else if (clock - msgAt < 100) { const w = msg.length * 8 + 12; rectfill(128 - w / 2, 70, w, 12, 200); ctxt(msg, 72, msgC); }
}

/** B on a cell: what it is (spec section 3). */
function drawCard(v) {
  panel(24, 96, 208, 72);
  ctxt(nameOf(v), 104, GOLD);
  if (isItem(v)) {
    ctxt(`${LINES[lineOf(v)]}, TIER ${tierOf(v)} OF 6`, 118, DIM);
    ctxt(tierOf(v) < 6 ? `TWO MAKE ${NAMES[lineOf(v)][tierOf(v)]}` : 'THE BEST OF ITS LINE', 132, WHITE);
    ctxt(`SELLS FOR ${valueOf(v)} (SELECT)`, 146, DIM);
  } else if (isGen(v)) { ctxt(`A: MAKE ${NAMES[v - GEN0][0]}`, 122, WHITE); ctxt('NO LIMIT: MIND THE SPACE', 138, DIM); }
  else if (v === CRATE) { ctxt(`A: OPEN IT FOR ${crateCost()} COINS`, 122, WHITE); ctxt('ONLY NEXT TO OPEN SPACE', 138, DIM); }
}

function drawTitle() {
  drawCafe();
  if (confirm) { panel(32, 150, 192, 40); ctxt('START A NEW CAFE?', 158, WHITE); ctxt('YOUR SAVED ONE IS LOST.  A: YES  B: NO', 172, ORANGE); return; }
  const cont = hasSave();
  [cont ? 'CONTINUE' : 'NEW CAFE', cont ? 'NEW CAFE' : 'NEW CAFE'].slice(0, cont ? 2 : 1).forEach((s, i) => txt(`${i === titleSel ? '> ' : '  '}${s}`, 92, 162 + i * 14, i === titleSel ? WHITE : DIM));
  ctxt('A: PICK UP, DROP   B: WHAT IS IT', 206, DIM);
}

function drawPause() {
  panel(56, 80, 144, 64);
  if (confirm) { ctxt('START A NEW CAFE?', 92, WHITE); ctxt('A: YES   B: NO', 112, ORANGE); return; }
  ctxt('PAUSED', 88, GOLD);
  ['RESUME', 'NEW CAFE', 'QUIT TO TITLE'].forEach((s, i) => txt(`${i === pauseSel ? '>' : ' '} ${s}`, 68, 104 + i * 10, i === pauseSel ? WHITE : DIM));
}

