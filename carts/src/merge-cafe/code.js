const POOL = 36, PIC_CRATE = 35, PIC_PEOPLE = 36, PIC_PROP = 52;   // the pictures in rom/pics.bin: items 0-29, generators 30-34, the crate, people (two frames each), props
const SLOT_TILE = Array.from({ length: POOL }, (_, k) => ART.sprites['slot' + k].tile);
let slotPic = new Array(POOL).fill(-1), slotAt = new Array(POOL).fill(-1), drawNo = 0, picLoads = 0;
const picPal = (p) => rom('pics')[1 + p * 513];
function picSlot(p) {
  let k = slotPic.indexOf(p);
  if (k < 0) {
    for (let i = 0; i < POOL; i++) if (slotAt[i] !== drawNo && (k < 0 || slotAt[i] < slotAt[k])) k = i;
    if (k < 0) return -1;
    const b = rom('pics'), off = 2 + p * 513, t = SLOT_TILE[k], x0 = (t % 16) * 8, y0 = (t >> 4) * 8;
    for (let y = 0; y < 32; y++) for (let x = 0; x < 32; x += 2) { const v = b[off + y * 16 + (x >> 1)]; sset(x0 + x, y0 + y, v & 15); sset(x0 + x + 1, y0 + y, v >> 4); }
    slotPic[k] = p; picLoads++;
  }
  slotAt[k] = drawNo;
  return k;
}
