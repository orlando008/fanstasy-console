/** A panel: solid over the busy board (seeThrough for a light one over the picture). */
function panel(x, y, w, h, seeThrough = false) { rectfill(x, y, w, h, seeThrough ? ART.colors.GLASS : SOLID); rect(x, y, w, h, GOLD); rect(x + 2, y + 2, w - 4, h - 4, CHALK); }
function txt(s, x, y, c) { print(s, x + 1, y + 1, SHADOW); print(s, x, y, c); }
const ctxt = (s, y, c) => txt(s, 128 - s.length * 4, y, c);

/** Each line: on the title, the backdrop under the café is a warm gradient (one colour there read as a flat picture). */
