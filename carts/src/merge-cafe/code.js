function panel(x, y, w, h, seeThrough = false) { rectfill(x, y, w, h, seeThrough ? ART.colors.GLASS : SOLID); rect(x, y, w, h, GOLD); rect(x + 1, y + 1, w - 2, h - 2, SHADOW); }
function txt(s, x, y, c) { print(s, x + 1, y + 1, SHADOW); print(s, x, y, c); }
