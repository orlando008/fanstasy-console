/** A new café's board: rows 0 and 1 open, the grain sack and the grinder on row 1, two wheat to start; the rest under crates (5.3). */
function newBoard() {
  const b = new Array(CELLS).fill(CRATE);
  for (let i = 0; i < 14; i++) b[i] = EMPTY;
  b[7 + 1] = GEN0; b[7 + 5] = GEN0 + 1; b[2] = item(0, 1); b[4] = item(0, 1);
  return b;
}
/** The empty cell nearest cell i (the fewest steps across cells; ties: the higher row, then the left), or -1. */
function nearestEmpty(b, i) {
  let best = -1, bd = 99;
  for (let j = 0; j < CELLS; j++) {
    if (b[j] !== EMPTY) continue;
    const d = Math.abs(colOf(j) - colOf(i)) + Math.abs(rowOf(j) - rowOf(i));
    if (d < bd) { bd = d; best = j; }                               // j runs row by row, left to right: the first at a distance wins the tie
  }
  return best;
}
/** What dropping the item from cell a onto cell b does: 'back', 'move', 'merge', 'swap' or 'no' (a crate, or two of the top tier). */
function dropKind(b, a, t) {
  if (a === t) return 'back';
  const u = b[t], v = b[a];
  if (u === CRATE) return 'no';
  if (u === EMPTY) return 'move';
  if (u === v) return tierOf(v) < 6 ? 'merge' : 'no';
  return 'swap';
}
/** A crate can be opened when a cell beside it (up, down, left or right) is open. */
const crateOpenable = (b, i) => b[i] === CRATE && [[-1, 0], [1, 0], [0, -1], [0, 1]].some(([dc, dr]) => {
  const c = colOf(i) + dc, r = rowOf(i) + dr;
  return c >= 0 && c < COLS && r >= 0 && r < ROWS && b[r * COLS + c] !== CRATE;
});

