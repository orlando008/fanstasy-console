// The river is a floor seen in perspective (BG2, affine: a new matrix on every line, SPEC 4.5): the line y shows the water z world
// pixels ahead of the camera, z = HEIGHT * FOCAL / (y - HORIZON + 1); a pad z ahead is drawn on the same line, so it sits on the water.
// The frog is at Z0. The river flows V world pixels a frame, so a pad shows LOOKAHEAD frames before it reaches the hit line, ZH, a little
// ahead of the frog: a pad on the line is a perfect tap (the glowing bar marks the windows); the frog jumps onto it as it floats on to him.
const HORIZON = 64, FOCAL = 128, HEIGHT = 123, Z0 = 128, ZH = 185, V = 5, FROG_Y = 186, LANE = 45, HOPF = 14;
const lineY = (z) => HORIZON - 1 + HEIGHT * FOCAL / z;                                       // the screen line of the water z ahead
let frogX = 128, frogY = FROG_Y, hopFrom = 128, hopFromY = FROG_Y, hopTo = 128, hopZ = Z0, pieceEnd = 1, camY = 0;

/** A lane from -2 to 2 for each pad, from its pitch (the lowest tenth of the notes to the highest tenth), so the frog's hops draw the melody. */
function setLanes() {
  const ps = notes.map((n) => n.pitch).sort((a, b) => a - b), lo = ps[flr(ps.length * 0.1)] ?? 0, hi = ps[Math.max(0, Math.ceil(ps.length * 0.9) - 1)] ?? 0;
  for (const n of notes) n.lane = clamp(Math.round((n.pitch - lo) / Math.max(hi - lo, 4) * 4) - 2, -2, 2);
}

// The five times of day (dawn, morning, noon, dusk, night) are tints of the noon palettes, and a sky: [red, green, blue multipliers, red,
// green, blue added, the sky at the top, in the middle and at the horizon (3 numbers each), the stars' brightness 0 to 1, the sun or moon's
// place (x, y) and colour]. A piece goes from one to another over its length (the Moonlight, from dusk to night).
const TOD = [
  [1, 0.9, 0.85, 5, 2, 0, 10, 12, 22, 26, 16, 20, 31, 24, 16, 0.2, 40, 44, 31, 24, 12],
  [0.95, 1, 1.05, 1, 2, 3, 14, 21, 27, 20, 26, 30, 26, 29, 30, 0, 70, 24, 31, 30, 20],
  [1, 1, 1, 0, 0, 0, 7, 15, 25, 13, 21, 28, 22, 27, 30, 0, 112, 6, 31, 31, 24],
  [1, 0.78, 0.74, 4, 0, 2, 6, 7, 13, 22, 9, 13, 31, 17, 9, 0.35, 190, 40, 31, 16, 8],
  [0.34, 0.42, 0.62, 0, 0, 2, 1, 2, 6, 3, 4, 10, 5, 7, 13, 1, 176, 14, 24, 26, 31]];
const PIECE_TOD = [[2, 2], [0, 0], [1, 1], [2, 2], [3, 4], [4, 4]], TITLE_TOD = [3, 3];
const TINTED = [[17, 31], [33, 47], [49, 63], [129, 143], [145, 159], [161, 175]];       // the CGRAM entries of the river, the far bank, the reeds, the pads, the frog, the orb
const STAR = 39, ORB = [161, 162, 163];                                                   // the stars' entry and the sun's three (art.json says where)
const STAMP = [177, 183];                                                                  // the lettering's palette: an ink, a gold ramp of five, a shade (the logo, the count-in, the grade)
const STAMP_COLOURS = [[17, 19, 26], [24, 15, 8], [8, 22, 29], [10, 28, 12], [31, 25, 6]];   // for the grades D to S
let baseColours = [], tintedNow = [], tod = TOD[2], todKey = '';
function initTint() { for (const [a, b] of TINTED.concat([STAMP])) for (let e = a; e <= b; e++) baseColours[e] = color(e); }
/** The big letters of a grade in its colour (the gold of the logo is the palette as made). */
function setStamp(g) { const c = STAMP_COLOURS[g]; [0.4, 0.62, 0.82, 1, 1.22].forEach((k, i) => color(STAMP[0] + 1 + i, clamp(c[0] * k, 0, 31), clamp(c[1] * k, 0, 31), clamp(c[2] * k, 0, 31))); }
function resetStamp() { for (let e = STAMP[0]; e <= STAMP[1]; e++) if (baseColours[e]) color(e, baseColours[e][0], baseColours[e][1], baseColours[e][2]); }
const mixTod = (a, b, k) => TOD[a].map((v, i) => lerp(v, TOD[b][i], k));
/** The palettes in the light of `v` (a row of TOD); sprites take half of it. */
function applyTod(v) {
  tod = v;
  TINTED.forEach(([a, b], g) => {
    const h = g > 2 ? 0.55 : 1, r = g > 2 ? 1 : 1 + 0.2 * look, d = g > 2 ? 0 : 2.5 * look;      // in flow the colours grow richer and brighter: the river, the bank and the reeds
    for (let e = a; e <= b; e++) {
      const c = baseColours[e];
      const t = tintedNow[e] = [clamp((c[0] * (1 + (v[0] - 1) * h) + v[3] * h) * r + d, 0, 31), clamp((c[1] * (1 + (v[1] - 1) * h) + v[4] * h) * r + d, 0, 31), clamp((c[2] * (1 + (v[2] - 1) * h) + v[5] * h) * r + d, 0, 31)];
      color(e, t[0], t[1], t[2]);
    }
  });
  const m = v.slice(18), s = clamp(v[15], 0, 1);
  color(STAR, lerp(v[9], 31, s), lerp(v[10], 31, s), lerp(v[11], 31, s));                // a star is the sky's colour until the night
  color(ORB[0], m[0] * 0.85, m[1] * 0.85, m[2] * 0.85); color(ORB[1], m[0], m[1], m[2]); color(ORB[2], Math.min(31, m[0] + 6), Math.min(31, m[1] + 6), Math.min(31, m[2] + 6));
}
/** Each frame: the time of day from the piece's progress (or the title's), and the palettes when it has changed enough to see. */
function updateTod() {
  if (state === 'map') {                                                                      // the light of the stretch the frog is on, eased from the one before
    const tgt = TOD[PIECE_TOD[mapSel][0]]; let moved = 0;
    mapTod = mapTod.map((v, i) => { const n = v + (tgt[i] - v) * 0.12; moved += Math.abs(tgt[i] - n); return n; });
    if (moved > 0.02 || todKey !== 'map') { applyTod(mapTod); todKey = moved > 0.02 ? 'map~' : 'map'; }
    return;
  }
  if (state === 'calib') { if (todKey !== 'calib') { todKey = 'calib'; applyTod(TOD[2]); } return; }
  const [a, b] = state === 'title' || state === 'pick' || state === 'records' ? TITLE_TOD : PIECE_TOD[piece] || [2, 2];
  const k = state === 'play' ? clamp(tm / pieceEnd, 0, 1) : state === 'results' ? 1 : 0, key = `${a}${b}${flr(k * 40)}.${flr(look * 20)}`;
  if (key !== todKey) { todKey = key; applyTod(mixTod(a, b, k)); }
}
const skyAt = (y) => {
  const t = y / HORIZON, v = tod, k = t < 0.5 ? t * 2 : t * 2 - 1, o = t < 0.5 ? 6 : 9;
  const b = 3 * look;                                                                      // and the sky brighter
  return [lerp(v[o], v[o + 3], k) + b, lerp(v[o + 1], v[o + 4], k) + b, lerp(v[o + 2], v[o + 5], k) + b];
};

function draw() {
  cls();
  camY = state === 'play' ? -tm * V : -clock * 1.5;                                          // the river flows with the song
  bg(1, { show: true, x: flr(clock * 0.15) }); bg(2, { show: false }); affine({ a: 1, b: 0, c: 0, d: 1, cx: 0, cy: 0 });
  look += ((state === 'play' && !paused ? (multiplier() - 1) / 3 : 0) - look) * 0.04;
  blend((state === 'play' || state === 'calib') && !paused ? { layers: ['overlay', 'spr'], op: 'add' } : { layers: ['overlay'], half: true });   // in play the glows add their light; in the menus the panels mix
  updateTod();
  sprite({ tile: ART.sprites.orb.tile, size: 32, pal: ART.sprites.orb.pal }, tod[16] - 16, tod[17] - 16, { prio: 0 });
  if (state === 'map') drawMapSprites(); else if (state !== 'records') drawFrogAndPads();
  drawFireflies();
  if (state === 'play') drawPlay();
  else if (state === 'map') drawMap();
  else if (state === 'calib') drawCalib();
  else if (state === 'title') drawTitle();
  else if (state === 'results') drawResults();
  else if (state === 'records') drawRecords();
  if (paused) drawPause();
}

/** The sprites of the river: the frog (first, so it is on top of the pad under it), its halo in flow state, a ripple where it landed, the pad under it, and the pads on their way. */
function drawFrogAndPads() {
  const age = clock - hopAt, a = age / HOPF;
  let fx = hopTo, fy = FROG_Y, up = 0;
  if (age < HOPF) {                                                                          // the hop: to the pad as it floats on towards the frog (a stray tap hops in place)
    const e = 0.5 - Math.cos(Math.PI * a) / 2, z = Math.max(Z0, hopZ - V * age), k = FOCAL / z;
    fx = lerp(hopFrom, 128 + (hopTo - 128) * k, e); fy = lerp(hopFromY, Math.min(FROG_Y, lineY(z)), e);
    up = Math.sin(Math.PI * a) * (hopZ === Z0 ? 10 : 16 + 8 * look);                          // higher hops in flow state
  }
  if (state === 'results') {                                                                   // the frog waits beside the grade, and hops for joy after an A or an S
    const j = gradeOf(accuracy()) >= 3 ? Math.abs(Math.sin(timer * 0.07)) * 12 : 0;
    sprite(ART.sprites[j > 3 ? 'frog_air' : 'frog_sit'], 42, 112 - 26 - j); sprite(ART.sprites.pad32, 42, 112 - 18);
    return;
  }
  frogX = fx; frogY = fy;
  const pose = age < 3 ? 'crouch' : age < HOPF - 3 ? 'air' : age < HOPF + 4 ? 'land' : 'sit', home = age < HOPF - 3 ? hopFrom : hopTo;
  sprite(ART.sprites['frog_' + pose], fx - 16, fy - 26 - up);
  if (look > 0.8 && state === 'play') bigSprite(ART.big.halo, fx - 24, fy - 12 - up - 24);   // the frog glows
  const rp = age - HOPF;
  if ((state === 'play' || state === 'calib') && lastG >= 0 && rp >= 0 && rp < 18) {                                // a ripple on the water where the frog landed, in the colour of the judgement
    const S = rp < 6 ? 8 : rp < 12 ? 16 : 32, r = ART.sprites['ripple' + S + (S === 32 && rp > 14 ? 'b' : '')];
    sprite(r, hopTo - S / 2, FROG_Y + 6 - S * 0.62, { pal: [5, 6, 4][lastG] });
  }
  sprite(ART.sprites.pad32, home - 16, FROG_Y + 2 - 20);
  if (state === 'title') {                                                                     // on the title a few pads drift down the river towards the frog
    for (let i = 0; i < 5; i++) {
      const z = lerp(720, 100, ((i * 72 + clock) % 360) / 360), k = FOCAL / z, S = k >= 0.75 ? 32 : k >= 0.38 ? 16 : 8;
      sprite(ART.sprites['pad' + S], 128 + [-2, 1, -1, 2, 0][i] * LANE * k - S / 2, HORIZON - 1 + HEIGHT * k - S * 0.62);
    }
  }
  if (state !== 'play' && state !== 'calib') return;
  for (const n of notes) {
    const z = ZH + V * (n.f - st());
    if (z > ZH + V * LOOKAHEAD) break;
    if (z < (n.r && n.r !== 4 ? Z0 : 98) || n.r === 5) continue;                               // a pad that was hit goes under the frog; one missed floats on and off the screen
    const k = FOCAL / z, S = k >= 0.75 ? 32 : k >= 0.38 ? 16 : 8;
    sprite(ART.sprites['pad' + S], 128 + n.lane * LANE * k - S / 2, HORIZON - 1 + HEIGHT * k - S * 0.62);
  }
}

/** Fireflies come out as the flow deepens (a few in DEEP, many in FLOW STATE), drifting over the water and blinking. */
function drawFireflies() {
  if (state !== 'play' || paused) return;
  const n = look > 0.9 ? 9 : look > 0.6 ? 5 : look > 0.3 ? 2 : 0;
  for (let i = 0; i < n; i++) {
    if ((clock + i * 23) % 90 > 70) continue;
    sprite(ART.sprites.fly, 128 + Math.sin(clock * 0.011 * (1 + i % 3) + i * 2.4) * 108 - 4, 92 + (i % 4) * 17 + Math.sin(clock * 0.017 + i) * 9);
  }
}

/** The hit line: a glowing bar across the river where a pad is a perfect tap, with the good and ok windows fainter around it (the windows' real size in frames). */
function drawHitBar() {
  const half = 92, bands = [[WIN[2], ART.colors.GLOW_OK], [WIN[1], ART.colors.GLOW_GOOD], [WIN[0], ART.colors.GLOW_PERFECT]];
  for (const [w, c] of bands) { const y0 = lineY(ZH + V * w), y1 = lineY(ZH - V * w); rectfill(128 - half, y0, half * 2, y1 - y0, c); }
}

/** The pond: the flow meter, a tall basin that fills; its top is a wave, its colour the level, with the levels' marks (x2, x3 and x4 at 40, 70 and 90). */
function drawPond() {
  const x = 8, y = 44, w = 16, h = 118, top = y + h - (h - 2) * flow / 100, m = multiplier(), c = LEVEL_COLOURS[m - 1];
  rectfill(x - 2, y - 2, w + 4, h + 4, SHADOW); rect(x - 2, y - 2, w + 4, h + 4, PANEL); rectfill(x, y, w, h, PANEL + 0);
  rectfill(x, y, w, h, SHADOW);
  for (let i = 0; i < w; i++) { const yy = flr(top + Math.sin(clock * 0.15 + i * 0.7) * 1.5); rectfill(x + i, yy, 1, y + h - yy, c); }
  if (flow > 2) rectfill(x, flr(top) + 3, 2, y + h - flr(top) - 5, WHITE);                      // a glint down the left edge
  [[40, 2], [70, 3], [90, 4]].forEach(([v, k]) => { const yy = y + h - (h - 2) * v / 100; rectfill(x - 2, yy, w + 4, 1, PANEL); txt(`x${k}`, x + w + 4, yy - 4, k === m ? c : DIM); });
  txt(flowName(), x - 2, y - 14, c);
}

