// Flow State: a frog on a river of lily pads, a one-button rhythm game to Bach and Beethoven (docs/carts/flow-state.md).
// The music is the clock: a song's row lasts `speed` frames, so a chart (rom/charts.bin, made from the same notes as the song) is in
// time with it to the frame. `tm` counts frames of song time from the start of the piece; the music starts when it reaches `musicAt`.

// --- Colours: the default palette (DawnBringer 16). The overlay's index 0 is transparent. ---

const SHADOW = 1, PANEL = 3, RED = 6, ORANGE = 9, DIM = 10, GREEN = 11, CYAN = 13, GOLD = 14, WHITE = 15;

// --- Art: made by art.py (tiles.txt, palette.txt, map.txt). The block below is rewritten each time it runs. ---

// ART (generated by art.py: do not edit)
const ART = {
  tiles: {},
  sprites: {"frog_air": {"pal": 1, "size": 32, "tile": 704}, "frog_crouch": {"pal": 1, "size": 32, "tile": 652}, "frog_land": {"pal": 1, "size": 32, "tile": 708}, "frog_sit": {"pal": 1, "size": 32, "tile": 648}, "orb": {"pal": 2, "size": 32, "tile": 712}, "pad16": {"pal": 0, "size": 16, "tile": 644}, "pad32": {"pal": 0, "size": 32, "tile": 640}, "pad8": {"pal": 0, "size": 8, "tile": 646}},
  scenes: {"far": {"h": 8, "mx": 0, "my": 0, "pal": 2, "w": 32}, "reeds": {"h": 28, "mx": 0, "my": 64, "pal": 3, "w": 32}, "river": {"h": 128, "mx": 128, "my": 0, "pal": 1, "w": 128}},
  colors: {"DIM": 10, "GLASS": 200, "GLOW_GOOD": 202, "GLOW_OK": 201, "GLOW_PERFECT": 203, "PANEL": 3, "SHADOW": 1},
};
// END ART
/** Queue one of ART.sprites at (x, y), above the background; opts as for spr (fx, fy ...). */
function sprite(s, x, y, opts = {}) { spr(s.tile, x, y, { size: s.size, pal: s.pal, prio: 3, ...opts }); }

// --- Sound (SPEC 5). Any channel plays any instrument. Songs use channels 0 to 5; effects take turns on 6 and 7, ---
// so they never cut into the music and two can sound at once.

const SFX = { move: 0, select: 1, pause: 2, hit: 3, over: 4, point: 5, record: 6 };
const SONG = { title: 0 };                                           // the pieces are songs 1 and on
const SFX_CH = [7, 6];
let fxNext = 0;
function fx(n) { sfx(n, SFX_CH[fxNext]); fxNext ^= 1; }

// A song is only started if it is not already playing.
let playing = -1;
function play(song) {
  if (song === playing) return;
  playing = song; music(song);
}

// --- Save slots (SPEC 13) ---

const VERSION_SLOT = 0, SAVE_VERSION = 2, LAG_SLOT = 1, OPEN_SLOT = 2, BEST_SLOT = 10;
const DIFF_NAMES = ['EASY', 'NORMAL', 'HARD'];
const bestSlot = (piece, diff) => BEST_SLOT + (piece * 3 + diff) * 2;            // the score; the grade (0 none, 1 D to 5 S) and the best combo

// --- Input: edge-triggered presses (btnp repeats; menus want one press) ---

let inputMask = 0, prevMask = 0;
const BUTTONS = [UP, DOWN, LEFT, RIGHT, A, B, X, Y, L, R, START, SELECT];
function readPad() { let m = 0; for (const b of BUTTONS) if (btn(b)) m |= 1 << b; return m; }
const pressed = (b) => (inputMask & (1 << b)) !== 0 && (prevMask & (1 << b)) === 0;
const tapped = () => pressed(A) || pressed(B) || pressed(X) || pressed(Y) || pressed(L) || pressed(R);

// --- The rules (spec section 5) ---

const LOOKAHEAD = 110, LEAD = 120, RESUME_LEAD = 90, WIN = [3, 6, 10], FLOW_START = 30;     // frames: how far ahead a pad shows, the count-in, the count-in after a pause, the windows
const JUDGE = [{ name: 'PERFECT', flow: 5, pts: 100 }, { name: 'GOOD', flow: 3, pts: 70 }, { name: 'OK', flow: 1, pts: 40 }];
const MISS_FLOW = -12, STRAY_FLOW = -2, GRADES = ['D', 'C', 'B', 'A', 'S'];

/** The chart of a piece for a difficulty, from the ROM: { speed, notes: [{ f (the frame), pitch, dur (rows), r (0 waiting, 1 to 3 the judgement, 4 missed, 5 skipped) }] }. */
function loadChart(i, diff) {
  const b = rom('charts'), off = b[1 + 2 * i] | (b[2 + 2 * i] << 8), n = b[off + 2] | (b[off + 3] << 8), notes = [];
  for (let k = 0; k < n; k++) {
    const o = off + 4 + 4 * k, fl = b[o + 3];
    if (fl & (1 << diff)) notes.push({ f: b[o] | (b[o + 1] << 8), pitch: b[o + 2], dur: fl >> 3, r: 0 });
  }
  return { speed: b[off], notes };
}
const multiplier = () => (inFlow ? 4 : flow >= 70 ? 3 : flow >= 40 ? 2 : 1);
const flowName = () => ['CALM', 'FLOWING', 'DEEP', 'FLOW STATE'][multiplier() - 1];

/** A pad hit with judgement g (0 perfect, 1 good, 2 ok): the points at the multiplier the flow gives now, then the flow moves. */
function hit(n, g) {
  n.r = g + 1; combo++; bestCombo = Math.max(bestCombo, combo); counts[g]++;
  score += JUDGE[g].pts * multiplier();
  setFlow(flow + JUDGE[g].flow);
  show(JUDGE[g].name, g === 0 ? GOLD : g === 1 ? GREEN : CYAN); fx(SFX.point);
}
function miss(n) { n.r = 4; combo = 0; counts[3]++; setFlow(flow + MISS_FLOW); show('MISS', RED); }                       // the word in red says it: no sound, it would cut into the music's flow
function setFlow(v) { flow = clamp(v, 0, 100); if (flow >= 90) inFlow = true; else if (flow < 80) inFlow = false; }
function show(text, c) { judgeText = text; judgeColour = c; judgeAt = clock; }

/** A tap at song time st: the nearest pad not hit yet within the widest window is judged; a tap with no pad near is a stray. */
function tap(st) {
  let best = null;
  for (const n of notes) if (!n.r && Math.abs(n.f - st) <= WIN[2] && (!best || Math.abs(n.f - st) < Math.abs(best.f - st))) best = n;
  hopFrom = frogX; hopFromY = frogY; hopTo = best ? 128 + best.lane * LANE : frogX; hopZ = best ? ZH + V * (best.f - st) : Z0; hopAt = clock;
  if (!best) { setFlow(flow + STRAY_FLOW); return; }
  const d = Math.abs(best.f - st);
  hit(best, d <= WIN[0] ? 0 : d <= WIN[1] ? 1 : 2);
}
const accuracy = () => { const n = counts[0] + counts[1] + counts[2] + counts[3]; return n ? (counts[0] + 0.7 * counts[1] + 0.4 * counts[2]) / n : 0; };
const gradeOf = (acc) => (acc >= 0.95 ? 4 : acc >= 0.85 ? 3 : acc >= 0.7 ? 2 : acc >= 0.5 ? 1 : 0);

// --- State ---

let skipTitle = false; // tests set this to land straight in the game
let state = 'title', paused = false, timer = 0, clock = 0;
let titleSel = 0, pauseSel = 0, pickPiece = 1, pickDiff = 1;
const PIECES = ['PRACTICE: SCALE RUN', 'MINUET IN G', 'AIR ON THE G STRING', 'FUR ELISE', 'MOONLIGHT SONATA', 'BADINERIE'], DIFFS = ['EASY', 'NORMAL', 'HARD'];
let piece = 0, diff = 1, notes = [], speed = 8, tm = 0, musicAt = 0, started = false, lag = 0;
let score = 0, combo = 0, bestCombo = 0, flow = FLOW_START, inFlow = false, counts = [0, 0, 0, 0], hopAt = -99, judgeText = '', judgeColour = WHITE, judgeAt = -99, endAt = 0, newBest = false;
const st = () => tm - lag;                                          // the song time the player hears now

function init() {
  if (dget(VERSION_SLOT) !== SAVE_VERSION) { // a new or older save: start clean
    for (let i = 0; i < 256; i++) dset(i, 0);
    dset(VERSION_SLOT, SAVE_VERSION);
  }
  lag = dget(LAG_SLOT) ? dget(LAG_SLOT) - 16 : 0;
  const r = ART.scenes.reeds, fb = ART.scenes.far, rv = ART.scenes.river;
  bg(0, { mx: r.mx, my: r.my, mw: r.w, mh: r.h, x: 0, y: 0, wrap: false, show: true });
  bg(1, { mx: fb.mx, my: fb.my, mw: fb.w, mh: fb.h, x: 0, y: 0, wrap: true, show: true });
  bg(2, { mx: rv.mx, my: rv.my, mw: rv.w, mh: rv.h, wrap: true, show: false });
  blend({ layers: ['overlay'], half: true }); // overlay colours from 192 up (ART.colors.GLASS) are see-through
  initTint();
  if (skipTitle) startPiece(0, 1); else toTitle();
}

function toTitle() { state = 'title'; timer = 0; titleSel = 0; paused = false; play(SONG.title); }

/** A piece from its start: the count-in, then the music when song time reaches 0. */
function startPiece(i, d) {
  piece = i; diff = d; const c = loadChart(i, d); notes = c.notes; speed = c.speed; setLanes();
  frogX = hopFrom = hopTo = 128; hopAt = -99; pieceEnd = (notes.length ? notes[notes.length - 1].f : 0) + 120;
  score = 0; combo = 0; bestCombo = 0; flow = FLOW_START; inFlow = false; counts = [0, 0, 0, 0]; judgeAt = -99; newBest = false;
  tm = -LEAD; musicAt = 0; started = false; endAt = 0; paused = false; timer = 0; state = 'play'; play(-1);
}

// --- Update ---

function update() {
  inputMask = readPad(); clock++;
  if (!paused) timer++; // a state's clock: it stands still while paused
  if (paused) updatePause();
  else if (state === 'title') updateTitle();
  else if (state === 'play') updatePlay();
  else if (state === 'pick') updatePick();
  else if (state === 'results') updateResults();
  else if (state === 'records') updateRecords();
  prevMask = inputMask;
}

function updateTitle() {
  if (pressed(UP) || pressed(DOWN)) { titleSel ^= 1; fx(SFX.move); }
  if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (titleSel === 0) { state = 'pick'; timer = 0; } else { state = 'records'; timer = 0; }
  }
}

/** Choose a piece (UP and DOWN) and a difficulty (LEFT and RIGHT); the journey's map takes this place in step 5. */
function updatePick() {
  if (pressed(UP)) { pickPiece = (pickPiece + PIECES.length - 1) % PIECES.length; fx(SFX.move); }
  if (pressed(DOWN)) { pickPiece = (pickPiece + 1) % PIECES.length; fx(SFX.move); }
  if (pressed(LEFT)) { pickDiff = (pickDiff + 2) % 3; fx(SFX.move); }
  if (pressed(RIGHT)) { pickDiff = (pickDiff + 1) % 3; fx(SFX.move); }
  if (pressed(B)) { state = 'title'; timer = 0; fx(SFX.move); }
  else if (pressed(A) || pressed(START)) { fx(SFX.select); startPiece(pickPiece, pickDiff); }
}

/** One frame of a piece: the clock, the music's start, the taps, the pads that were missed, the end. */
function updatePlay() {
  if (pressed(START)) { paused = true; pauseSel = 0; fx(SFX.pause); music(-1); playing = -1; return; }
  tm++;
  if (!started && tm >= musicAt) { started = true; playing = piece + 1; music(piece + 1, musicAt / (64 * speed)); }
  if (tapped()) tap(st());
  for (const n of notes) if (!n.r && n.f + WIN[2] < st()) miss(n);
  const last = notes.length ? notes[notes.length - 1].f : 0;
  if (!endAt && st() > last + WIN[2] && notes.every((n) => n.r)) endAt = clock;
  if (endAt && clock > endAt + 90) finish();
}

function finish() {
  endAt = 0; state = 'results'; timer = 0;
  const g = gradeOf(accuracy()), s = bestSlot(piece, diff);
  newBest = score > dget(s);
  if (newBest) { dset(s, score); dset(s + 1, (g + 1) | (bestCombo << 4)); }
  if (dget(OPEN_SLOT) < piece + 2) dset(OPEN_SLOT, piece + 2);
  fx(SFX.record);
}

function updateResults() {
  if (timer > 30 && (pressed(A) || pressed(START))) { fx(SFX.select); toTitle(); }
}

function updateRecords() {
  if ((pressed(START) || pressed(A) || pressed(B)) && timer > 20) { fx(SFX.select); toTitle(); }
}

/** Resume starts the music again at the start of the pattern the piece was in, after a count-in: pads whose time went by stay as they were. */
function resume() {
  paused = false;
  const pat = Math.max(0, Math.floor(Math.max(0, tm) / (64 * speed)));
  musicAt = pat * 64 * speed; tm = musicAt - RESUME_LEAD; started = false;
  for (const n of notes) if (!n.r && n.f < musicAt) n.r = 5;            // too near the cut to play: skipped
}

function updatePause() {
  if (pressed(UP)) { pauseSel = (pauseSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { pauseSel = (pauseSel + 1) % 3; fx(SFX.move); }
  if (pressed(B) || (pressed(START) && pauseSel === 0)) { fx(SFX.pause); resume(); }
  else if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (pauseSel === 0) resume();
    else if (pauseSel === 1) startPiece(piece, diff); // restart
    else toTitle(); // quitting abandons the piece: nothing is recorded
  }
}

// --- Draw ---

// The river is a floor seen in perspective (BG2, affine: a new matrix on every line, SPEC 4.5): the line y shows the water z world
// pixels ahead of the camera, z = HEIGHT * FOCAL / (y - HORIZON + 1); a pad z ahead is drawn on the same line, so it sits on the water.
// The frog is at Z0. The river flows V world pixels a frame, so a pad shows LOOKAHEAD frames before it reaches the hit line, ZH, a little
// ahead of the frog: a pad on the line is a perfect tap (the glowing bar marks the windows); the frog jumps onto it as it floats on to him.
const HORIZON = 64, FOCAL = 128, HEIGHT = 123, Z0 = 128, ZH = 185, V = 5, FROG_Y = 186, LANE = 45, HOPF = 14;
const lineY = (z) => HORIZON - 1 + HEIGHT * FOCAL / z;                                       // the screen line of the water z ahead
const BAR_TOP = flr(lineY(ZH + V * 10)), BAR_END = flr(lineY(ZH - V * 10)) + 1;           // the lines of the hit bar (the ok window's edges)
let frogX = 128, frogY = FROG_Y, hopFrom = 128, hopFromY = FROG_Y, hopTo = 128, hopZ = Z0, pieceEnd = 1, camY = 0;

/** A lane from -2 to 2 for each pad, from its pitch (the lowest tenth of the notes to the highest tenth), so the frog's hops draw the melody. */
function setLanes() {
  const ps = notes.map((n) => n.pitch).sort((a, b) => a - b), lo = ps[flr(ps.length * 0.1)] ?? 0, hi = ps[Math.max(0, Math.ceil(ps.length * 0.9) - 1)] ?? 0;
  for (const n of notes) n.lane = clamp(Math.round((n.pitch - lo) / Math.max(hi - lo, 4) * 4) - 2, -2, 2);
}

// The five times of day (dawn, morning, noon, dusk, night) are tints of the noon palettes, and a sky: [red, green, blue multipliers, red,
// green, blue added, the sky at the top, in the middle and at the horizon (3 numbers each), the stars' brightness 0 to 1, the sun or moon's
// place (x, y) and colour]. A piece goes from one to another over its length (the Moonlight, from dusk to night).
const TOD = [
  [1, 0.9, 0.85, 5, 2, 0, 10, 12, 22, 26, 16, 20, 31, 24, 16, 0.2, 40, 44, 31, 24, 12],
  [0.95, 1, 1.05, 1, 2, 3, 14, 21, 27, 20, 26, 30, 26, 29, 30, 0, 70, 24, 31, 30, 20],
  [1, 1, 1, 0, 0, 0, 7, 15, 25, 13, 21, 28, 22, 27, 30, 0, 112, 6, 31, 31, 24],
  [1, 0.78, 0.74, 4, 0, 2, 6, 7, 13, 22, 9, 13, 31, 17, 9, 0.35, 190, 40, 31, 16, 8],
  [0.34, 0.42, 0.62, 0, 0, 2, 1, 2, 6, 3, 4, 10, 5, 7, 13, 1, 176, 14, 24, 26, 31]];
const PIECE_TOD = [[2, 2], [0, 0], [1, 1], [2, 2], [3, 4], [4, 4]], TITLE_TOD = [3, 3];
const TINTED = [[17, 31], [33, 47], [49, 63], [129, 143], [145, 159], [161, 175]];       // the CGRAM entries of the river, the far bank, the reeds, the pads, the frog, the orb
const STAR = 39, ORB = [161, 162, 163];                                                   // the stars' entry and the sun's three (art.json says where)
let baseColours = [], tintedNow = [], tod = TOD[2], todKey = '';
function initTint() { for (const [a, b] of TINTED) for (let e = a; e <= b; e++) baseColours[e] = color(e); }
const mixTod = (a, b, k) => TOD[a].map((v, i) => lerp(v, TOD[b][i], k));
/** The palettes in the light of `v` (a row of TOD); sprites take half of it. */
function applyTod(v) {
  tod = v;
  TINTED.forEach(([a, b], g) => {
    const h = g > 2 ? 0.55 : 1;
    for (let e = a; e <= b; e++) {
      const c = baseColours[e];
      const t = tintedNow[e] = [clamp(c[0] * (1 + (v[0] - 1) * h) + v[3] * h, 0, 31), clamp(c[1] * (1 + (v[1] - 1) * h) + v[4] * h, 0, 31), clamp(c[2] * (1 + (v[2] - 1) * h) + v[5] * h, 0, 31)];
      color(e, t[0], t[1], t[2]);
    }
  });
  const m = v.slice(18), s = clamp(v[15], 0, 1);
  color(STAR, lerp(v[9], 31, s), lerp(v[10], 31, s), lerp(v[11], 31, s));                // a star is the sky's colour until the night
  color(ORB[0], m[0] * 0.85, m[1] * 0.85, m[2] * 0.85); color(ORB[1], m[0], m[1], m[2]); color(ORB[2], Math.min(31, m[0] + 6), Math.min(31, m[1] + 6), Math.min(31, m[2] + 6));
}
/** Each frame: the time of day from the piece's progress (or the title's), and the palettes when it has changed enough to see. */
function updateTod() {
  const [a, b] = state === 'title' || state === 'pick' || state === 'records' ? TITLE_TOD : PIECE_TOD[piece] || [2, 2];
  const k = state === 'play' ? clamp(tm / pieceEnd, 0, 1) : state === 'results' ? 1 : 0, key = `${a}${b}${flr(k * 40)}`;
  if (key !== todKey) { todKey = key; applyTod(mixTod(a, b, k)); }
}
const skyAt = (y) => {
  const t = y / HORIZON, v = tod, k = t < 0.5 ? t * 2 : t * 2 - 1, o = t < 0.5 ? 6 : 9;
  return [lerp(v[o], v[o + 3], k), lerp(v[o + 1], v[o + 4], k), lerp(v[o + 2], v[o + 5], k)];
};

function draw() {
  cls();
  camY = state === 'play' ? -tm * V : -clock * 1.5;                                          // the river flows with the song
  bg(1, { show: true, x: flr(clock * 0.15) }); bg(2, { show: false }); affine({ a: 1, b: 0, c: 0, d: 1, cx: 0, cy: 0 });
  updateTod();
  sprite({ tile: ART.sprites.orb.tile, size: 32, pal: ART.sprites.orb.pal }, tod[16] - 16, tod[17] - 16, { prio: 0 });
  drawFrogAndPads();
  if (state === 'play') drawPlay();
  else if (state === 'title') drawTitle();
  else if (state === 'pick') drawPick();
  else if (state === 'results') drawResults();
  else if (state === 'records') drawRecords();
  if (paused) drawPause();
}

/** The sprites of the river: the frog (first, so it is on top of the pad under it), that pad, and the pads on their way. */
function drawFrogAndPads() {
  const age = clock - hopAt, a = age / HOPF;
  let fx = hopTo, fy = FROG_Y, up = 0;
  if (age < HOPF) {                                                                          // the hop: to the pad as it floats on towards the frog (a stray tap hops in place)
    const e = 0.5 - Math.cos(Math.PI * a) / 2, z = Math.max(Z0, hopZ - V * age), k = FOCAL / z;
    fx = lerp(hopFrom, 128 + (hopTo - 128) * k, e); fy = lerp(hopFromY, Math.min(FROG_Y, lineY(z)), e);
    up = Math.sin(Math.PI * a) * (hopZ === Z0 ? 10 : 16);
  }
  frogX = fx; frogY = fy;
  const pose = age < 3 ? 'crouch' : age < HOPF - 3 ? 'air' : age < HOPF + 4 ? 'land' : 'sit', home = age < HOPF - 3 ? hopFrom : hopTo;
  sprite(ART.sprites['frog_' + pose], fx - 16, fy - 26 - up);
  sprite(ART.sprites.pad32, home - 16, FROG_Y + 2 - 20);
  if (state !== 'play') return;
  for (const n of notes) {
    const z = ZH + V * (n.f - st());
    if (z > ZH + V * LOOKAHEAD) break;
    if (z < (n.r && n.r !== 4 ? Z0 : 98) || n.r === 5) continue;                               // a pad that was hit goes under the frog; one missed floats on and off the screen
    const k = FOCAL / z, S = k >= 0.75 ? 32 : k >= 0.38 ? 16 : 8;
    sprite(ART.sprites['pad' + S], 128 + n.lane * LANE * k - S / 2, HORIZON - 1 + HEIGHT * k - S * 0.62);
  }
}

/** The hit line: a glowing bar across the river where a pad is a perfect tap, with the good and ok windows fainter around it (the windows' real size in frames). */
function drawHitBar() {
  const half = 92, bands = [[WIN[2], ART.colors.GLOW_OK], [WIN[1], ART.colors.GLOW_GOOD], [WIN[0], ART.colors.GLOW_PERFECT]];
  for (const [w, c] of bands) { const y0 = lineY(ZH + V * w), y1 = lineY(ZH - V * w); rectfill(128 - half, y0, half * 2, y1 - y0, c); }
}

function drawPlay() {
  drawHitBar();
  rectfill(10, 40, 12, 124, PANEL); rectfill(11, 41 + 122 - flow * 1.22, 10, flow * 1.22, inFlow ? GOLD : flow >= 70 ? GREEN : flow >= 40 ? CYAN : DIM);
  txt(`${flowName()} x${multiplier()}`, 28, 40, inFlow ? GOLD : WHITE);
  txt(`SCORE ${score}`, 8, 6, WHITE); txt(`COMBO ${combo}`, 168, 6, WHITE);
  if (clock - judgeAt < 30) ctxt(judgeText, 118, judgeColour);
  if (tm < 0) ctxt(String(Math.ceil(-tm / 40)), 100, GOLD);
}

function drawTitle() {
  ctxt('FLOW STATE', 50, GOLD);
  ['PLAY', 'RECORDS'].forEach((s, i) => txt(`${i === titleSel ? '> ' : '  '}${s}`, 96, 100 + i * 14, i === titleSel ? WHITE : DIM));
}

function drawPick() {
  panel(24, 36, 208, 150);
  ctxt('CHOOSE A PIECE', 46, GOLD);
  PIECES.forEach((s, i) => txt(`${i === pickPiece ? '> ' : '  '}${s}`, 40, 70 + i * 14, i === pickPiece ? WHITE : DIM));
  DIFFS.forEach((s, i) => txt(s, 56 + i * 52, 164, i === pickDiff ? GOLD : DIM));
  ctxt('A PLAY   B BACK', 180, DIM);
}

function drawResults() {
  panel(40, 40, 176, 140);
  ctxt(newBest ? 'NEW BEST!' : 'DONE', 50, GOLD);
  ctxt(`GRADE ${GRADES[gradeOf(accuracy())]}`, 70, WHITE);
  ctxt(`SCORE ${score}`, 88, WHITE);
  ctxt(`ACCURACY ${Math.round(accuracy() * 100)}%`, 104, DIM);
  ctxt(`PERFECT ${counts[0]} GOOD ${counts[1]}`, 120, DIM); ctxt(`OK ${counts[2]} MISS ${counts[3]}`, 132, DIM);
  ctxt(`BEST COMBO ${bestCombo}`, 148, DIM);
  if (timer > 30 && timer % 60 < 40) ctxt('A: CONTINUE', 164, WHITE);
}

function drawRecords() {
  panel(24, 16, 208, 192);
  ctxt('BEST SCORES', 24, GOLD);
  for (let d = 0; d < 3; d++) {
    const s = bestSlot(0, d), g = dget(s + 1) & 15;
    txt(DIFF_NAMES[d], 40, 56 + d * 16, WHITE); txt(String(dget(s)).padStart(8), 120, 56 + d * 16, GOLD); txt(g ? GRADES[g - 1] : '-', 200, 56 + d * 16, WHITE);
  }
  if (timer % 60 < 40) ctxt('A: BACK', 192, DIM);
}

function drawPause() {
  panel(64, 80, 128, 64);
  ctxt('PAUSED', 88, GOLD);
  ['RESUME', 'RESTART', 'QUIT TO TITLE'].forEach((s, i) => txt(`${i === pauseSel ? '>' : ' '} ${s}`, 76, 104 + i * 10, i === pauseSel ? WHITE : DIM));
}

function panel(x, y, w, h) { rectfill(x, y, w, h, ART.colors.GLASS); rect(x, y, w, h, PANEL); }
function txt(s, x, y, c) { print(s, x + 1, y + 1, SHADOW); print(s, x, y, c); }
const ctxt = (s, y, c) => txt(s, 128 - s.length * 4, y, c);

/** Each line of the screen: the sky above the horizon (the SNES did its skies with HDMA); below it the river in perspective, hazier towards the horizon. */
function scanline(y) {
  if (y < HORIZON) { const c = skyAt(y); color(0, c[0], c[1], c[2]); return; }
  if (y === HORIZON) { bg(1, { show: false }); bg(2, { show: true }); }
  if (state === 'play') { if (y === BAR_TOP) blend({ layers: ['overlay'], op: 'add' }); else if (y === BAR_END) blend({ layers: ['overlay'], half: true }); }   // the bar adds its light to the water; the panels mix
  const z = HEIGHT * FOCAL / (y - HORIZON + 1), s = z / FOCAL;
  affine({ a: s, b: 512 - 128, c: 0, d: ((camY - z) % 1024 + 1024) % 1024, cx: 128, cy: 0 });
  bgscroll(2, 0, 1 - y);
  const h = y - HORIZON < 60 ? Math.pow(1 - (y - HORIZON) / 60, 1.6) * 0.8 : 0;               // haze: the far water takes the colour of the sky at the horizon
  if (h > 0) { const c = skyAt(HORIZON - 1); for (let e = 17; e <= 31; e++) { const b = tintedNow[e]; color(e, lerp(b[0], c[0], h), lerp(b[1], c[1], h), lerp(b[2], c[2], h)); } }
}
