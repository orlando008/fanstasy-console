// --- Physics: a balloon is a point with a radius, under gravity, stepped SUBSTEPS times a frame ---

function launch(p, angle, power) {
  const v = CFG.VMIN + (CFG.VMAX - CFG.VMIN) * power / 100, a = angle * Math.PI / 180, dir = p ? -1 : 1;
  return { x: CFG.SLING[p].x, y: CFG.SLING[p].y, vx: dir * v * Math.cos(a), vy: v * Math.sin(a), alive: true, age: 0 };
}
/** One substep of one balloon (no collisions): the only motion rule, used by the flight, the aiming dots and the bot. */
function move(b) { const dt = 1 / CFG.SUBSTEPS; b.vx += wind * CFG.WIND_STEP * dt; b.vy -= CFG.GRAVITY * dt; b.x += b.vx * dt; b.y += b.vy * dt; }
/** The points of a flight with nothing in the way, one a frame (for the aiming dots and the bot). */
function arc(p, angle, power, frames) {
  const b = launch(p, angle, power), out = [];
  for (let f = 0; f < frames && b.y > -40; f++) { for (let s = 0; s < CFG.SUBSTEPS; s++) move(b); out.push([b.x, b.y]); }
  return out;
}
/** What the balloon is in, at its present place: a wall (and which side), the ground, or out of the courtyard. */
function contact(b, py) {
  const R = CFG.BALLOON_R;
  for (let w = 0; w < 2; w++) {
    const x0 = w ? CFG.WORLD_W - CFG.WALL_W : 0, x1 = x0 + CFG.WALL_W;
    if (b.x + R >= x0 && b.x - R < x1 && b.y - R < CFG.WALL_H) return { kind: 'wall', w, top: py >= CFG.WALL_H + R - 0.01, x: b.x - x0, y: b.y };
  }
  if (b.y - R <= 0) return { kind: 'ground' };
  if (b.x < -24 || b.x > CFG.WORLD_W + 24) return { kind: 'out' };
  return null;
}

// --- Coverage: each wall's paint is a mask of cells; the wall's tiles are drawn from it ---
// walls[w].mask[j * COLS + i]: cell i across, j up from the ground. Wall 0 is teal's (painted magenta), wall 1 magenta's.

const COLS = CFG.WALL_W / CFG.CELL, ROWS = CFG.WALL_H / CFG.CELL, CELLS = COLS * ROWS;
const PAINT_TILE = 512, WALL_PAL = 3, PAINT_BASE = [11, 6]; // wall 0 takes the magenta ramp, wall 1 the teal
let walls = [];
const covered = (w) => walls[w].count;
/** Percent of the opponent's wall that player p has painted (whole percent, rounded down: what the HUD shows). */
const percent = (p) => flr(covered(1 - p) * 100 / CELLS);
function newWalls() {
  walls = [0, 1].map(() => ({ mask: new Uint8Array(CELLS), count: 0, dirty: true }));
}
function setCell(w, i, j, v) {
  if (i < 0 || j < 0 || i >= COLS || j >= ROWS) return 0;
  const W = walls[w], k = j * COLS + i;
  if (W.mask[k] === v) return 0;
  W.mask[k] = v; W.count += v ? 1 : -1; W.dirty = true;
  return v ? 1 : -1;
}
/** A splash on wall w at (u, v) of its face (px from its left and from the ground): cells inside an uneven blob of
 *  radius r (SPLASH_WIDE times that across the wall) are painted. Returns the cells newly painted (a cell painted twice counts once). */
function splash(w, u, v, r) {
  const lobes = rndi(4, 7), phase = rnd(6.283);
  let added = 0;
  for (let j = 0; j < ROWS; j++) for (let i = 0; i < COLS; i++) {
    const dx = (i * CFG.CELL + 1 - u) / CFG.SPLASH_WIDE, dy = j * CFG.CELL + 1 - v, d = Math.hypot(dx, dy);
    if (d > r * 1.1) continue;
    // ragged top and bottom (up to 16% in), but a clean reach sideways: where it lands across the wall is not aimed
    const edge = r * (1 - 0.16 * (Math.abs(dy) / (d || 1)) * (0.5 + 0.5 * Math.sin(lobes * Math.atan2(dy, dx) + phase)));
    if (d <= edge) added += setCell(w, i, j, 1);
  }
  return added;
}
/** Paint Roller: a band ROLLER_H tall across wall w, where the band is barest. Returns [cells added, band's v]. */
function roll(w) {
  const h = CFG.ROLLER_H / CFG.CELL; let best = 0, bestBare = -1;
  for (let j = 0; j + h <= ROWS; j++) {
    let bare = 0;
    for (let jj = j; jj < j + h; jj++) for (let i = 0; i < COLS; i++) bare += 1 - walls[w].mask[jj * COLS + i];
    if (bare > bestBare) { bestBare = bare; best = j; }
  }
  let added = 0;
  for (let jj = best; jj < best + h; jj++) for (let i = 0; i < COLS; i++) added += setCell(w, i, jj, 1);
  return [added, best * CFG.CELL];
}
/** Sponge: clear a disc of SPONGE_R from wall w where it holds the most paint. Returns [-cells cleared, v]. */
function sponge(w) {
  const r = CFG.SPONGE_R, cells = (u, v, f) => {
    let n = 0;
    for (let j = 0; j < ROWS; j++) for (let i = 0; i < COLS; i++)
      if (Math.hypot(i * CFG.CELL + 1 - u, j * CFG.CELL + 1 - v) <= r) n += f(i, j);
    return n;
  };
  let bu = 16, bv = 48, most = -1;
  for (let v = 0; v <= CFG.WALL_H; v += 4) {
    const n = cells(16, v, (i, j) => walls[w].mask[j * COLS + i]);
    if (n > most) { most = n; bv = v; }
  }
  return [cells(bu, bv, (i, j) => setCell(w, i, j, 0)), bv]; // cells cleared, as a negative number
}

// The walls' tiles: at init each cell of a wall in the map gets a tile of its own (PAINT_TILE on), a copy of its
// brick; a wall that changed is drawn again from the brick and its mask.
let brick = [];
function initWallTiles() {
  const s = ART.scenes.walls;
  brick = [0, 1].map((w) => {
    const px = new Uint8Array(CFG.WALL_W * CFG.WALL_H);
    for (let ty = 0; ty < CFG.WALL_H / 8; ty++) for (let tx = 0; tx < CFG.WALL_W / 8; tx++) {
      const mx = s.mx + (w ? 28 : 0) + tx, my = s.my + 1 + ty, e = mget(mx, my);
      const t = e & 1023, hf = e & 0x2000, vf = e & 0x4000;
      for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++)
        px[(ty * 8 + y) * CFG.WALL_W + tx * 8 + x] = sget((t % 16) * 8 + (hf ? 7 - x : x), flr(t / 16) * 8 + (vf ? 7 - y : y));
      mset(mx, my, tile(PAINT_TILE + w * 48 + ty * 4 + tx, WALL_PAL));
    }
    return px;
  });
}
function drawWallTiles(w) {
  const W = walls[w], base = brick[w], paint = PAINT_BASE[w];
  for (let y = 0; y < CFG.WALL_H; y++) {
    const j = (CFG.WALL_H - 1 - y) >> 1;
    for (let x = 0; x < CFG.WALL_W; x++) {
      const b = base[y * CFG.WALL_W + x], n = PAINT_TILE + w * 48 + (y >> 3) * 4 + (x >> 3);
      sset((n % 16) * 8 + (x & 7), flr(n / 16) * 8 + (y & 7), W.mask[j * COLS + (x >> 1)] ? paint + b - 1 : b);
    }
  }
  W.dirty = false;
}

// --- The power-up: exactly one in the courtyard; hidden until a balloon passes near; collected by a direct hit ---

let pu = null; // { kind, x, y, revealed } or null after collection (a new one comes at the start of the next turn)
function spawnPowerup() {
  const span = CFG.PU_X[rndi(0, 1)];
  let k = rnd(CFG.PU_WEIGHTS.reduce((a, b) => a + b, 0)), i = 0;
  while (k >= CFG.PU_WEIGHTS[i]) k -= CFG.PU_WEIGHTS[i++];
  pu = { kind: CFG.PU_KINDS[i], x: rndi(span[0], span[1]), y: rndi(CFG.PU_Y[0], CFG.PU_Y[1]), revealed: false };
}

