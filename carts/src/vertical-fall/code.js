let skipTitle = false; // tests set this to land straight in the game
let state = 'title', paused = false, timer = 0, clock = 0;
let titleSel = 0, pauseSel = 0, rank = -1, hl = -1, initials = null;
let score = 0, best = 0, camY = 0, clearT = 0;
let me = null, bullets = [];

function newFaller() {
  return {
    x: (CELLS * CELL - BOX_W) / 2, y: CELL, vx: 0, vy: 0, face: 1, ground: false, onLedge: false, air: 0, jumping: false,
    trig: false, cd: 0, drop: 0, flash: 0, inv: 0, hp: HP, maxHp: HP, ammo: AMMO, maxAmmo: AMMO, walk: 0,
  };
}

function init() {
  if (dget(VERSION_SLOT) !== SAVE_VERSION) { // a new or older save: start clean
    for (let i = 0; i < 256; i++) dset(i, 0);
    dset(VERSION_SLOT, SAVE_VERSION);
  }
  loadCells();
  // BG0 is the strip of the well, BG1 the back wall; both start at the well's left edge (x 56). Window 0 is the well:
  // outside it the picture is black (the gutters, where the HUD goes), but for the overlay.
  const w = ART.scenes.wall;
  bg(0, { mx: 0, my: 0, mw: CELLS * 2, mh: STRIP * 2, x: -WELL_X, y: 0, wrap: true, show: true });
  bg(1, { mx: w.mx, my: w.my, mw: w.w, mh: w.h, x: -WELL_X, y: 0, wrap: true, show: true });
  bg(2, { show: false });
  winpos(0, WELL_X, WELL_X + CELLS * CELL - 1);
  winmask('screen', { w0: 'out' });
  blend({ layers: ['overlay'], half: true }); // overlay colours from 192 up (ART.colors.GLASS) are see-through
  runSeed = rndi(1, 999999); makeLevel(1); me = newFaller();
  if (skipTitle) startGame(); else toTitle();
}

function toTitle() { state = 'title'; timer = 0; titleSel = 0; paused = false; play(SONG.title); }

function startGame() {
  runSeed = rndi(1, 999999); level = 1; depthBase = 0; makeLevel(level);
  me = newFaller(); bullets = []; score = 0; best = 0; camY = 0; clearT = 0;
  paused = false; timer = 0; state = 'play';
  play(SONG.play);
}

function nextLevel() {
  depthBase += rows; level++; makeLevel(level);
  me.x = (CELLS * CELL - BOX_W) / 2; me.y = CELL; me.vx = me.vy = 0; me.ground = false;
  bullets = []; camY = 0; clearT = 0;
}

// --- Update ---

function update() {
  inputMask = readPad(); clock++;
  if (!paused) timer++; // a state's clock: it stands still while paused
  if (paused) updatePause();
  else if (state === 'title') updateTitle();
  else if (state === 'play') updatePlay();
  else if (state === 'over') updateOver();
  else if (state === 'initials') updateInitials();
  else if (state === 'records') updateRecords();
  prevMask = inputMask;
}

function updateTitle() {
  if (pressed(UP) || pressed(DOWN)) { titleSel ^= 1; fx(SFX.move); }
  if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (titleSel === 0) startGame(); else { state = 'records'; hl = -1; timer = 0; }
  }
}

function updatePlay() {
  if (pressed(START)) { paused = true; pauseSel = 0; fx(SFX.pause); return; }
  moveFaller();
  updateBullets();
  if (state !== 'play') return;
  const depth = depthBase + flr((me.y + BOX_H) / METRE);
  if (depth > best) best = depth;
  score = best;
  if (clearT) { if (++clearT > CLEAR_WAIT) nextLevel(); }
  else if (me.ground && flr((me.y + BOX_H) / CELL) >= rows - 1) { clearT = 1; fx(SFX.clear); }
  camera();
}

/** Run, jump, fire, fall: section 5. A press on the ground (or within COYOTE frames of leaving it, unless jumping) jumps;
 * a new press in the air fires, and holding it fires again every RATE frames. */
function moveFaller() {
  const f = me, push = pressed(A) || pressed(B), hold = held(A) || held(B);
  const dir = (held(RIGHT) ? 1 : 0) - (held(LEFT) ? 1 : 0);
  if (dir) { f.vx = clamp(f.vx + dir * ACCEL, -RUN, RUN); f.face = dir; }
  else { const fr = f.ground ? FRICTION : AIR_FRICTION; f.vx = abs(f.vx) <= fr + 1e-6 ? 0 : f.vx - sgn(f.vx) * fr; }

  if (push && (f.ground || (f.air < COYOTE && !f.jumping))) { f.vy = -JUMP; f.jumping = true; f.ground = false; f.air = COYOTE; fx(SFX.jump); }
  else if (!f.ground) {
    if (push) { f.trig = true; f.cd = RATE; shoot(); }
    else if (f.trig && hold && --f.cd <= 0) { f.cd = RATE; shoot(); }
  }
  if (!hold) f.trig = false;
  if (f.jumping && f.vy < 0 && !hold) { f.vy *= 0.5; f.jumping = false; } // a short hop
  if (f.vy >= 0) f.jumping = false;
  if (f.ground && f.onLedge && pressed(DOWN)) { f.drop = 8; f.ground = false; }

  const was = f.ground;
  f.vy = Math.min(f.vy + GRAVITY, MAX_FALL);
  moveX(f); moveY(f);
  if (f.drop) f.drop--;
  if (f.flash) f.flash--;
  if (f.inv) f.inv--;
  if (f.ground) {
    if (!was) { if (f.ammo < f.maxAmmo || f.air > 20) fx(SFX.land); f.trig = false; }
    f.ammo = f.maxAmmo; f.air = 0;
    f.walk = f.vx ? f.walk + 1 : 0;
  } else f.air++;
}

const solidAt = (x, y) => cellAt(flr(x / CELL), flr(y / CELL)) === STONE;

function moveX(f) {
  f.x += f.vx;
  const t = f.y, m = f.y + BOX_H / 2, b = f.y + BOX_H - 1;
  if (f.vx > 0) {
    const e = f.x + BOX_W - 1;
    if (solidAt(e, t) || solidAt(e, m) || solidAt(e, b)) { f.x = flr(e / CELL) * CELL - BOX_W; f.vx = 0; }
  } else if (f.vx < 0) {
    if (solidAt(f.x, t) || solidAt(f.x, m) || solidAt(f.x, b)) { f.x = (flr(f.x / CELL) + 1) * CELL; f.vx = 0; }
  }
}

/** Fall (or rise) and stop on stone; a ledge stops a fall only if the feet were above its top before the move. */
function moveY(f) {
  const oldBot = f.y + BOX_H;
  f.y += f.vy; f.ground = false; f.onLedge = false;
  const l = f.x, r = f.x + BOX_W - 1;
  if (f.vy >= 0) {
    const row = flr((f.y + BOX_H) / CELL), top = row * CELL;   // the row the feet touch (touching counts: standing)
    const kl = cellAt(flr(l / CELL), row), kr = cellAt(flr(r / CELL), row);
    if (kl === STONE || kr === STONE) { f.y = top - BOX_H; f.vy = 0; f.ground = true; }
    else if ((kl === LEDGE || kr === LEDGE) && !f.drop && oldBot <= top) { f.y = top - BOX_H; f.vy = 0; f.ground = true; f.onLedge = true; }
  } else if (solidAt(l, f.y) || solidAt(r, f.y)) { f.y = (flr(f.y / CELL) + 1) * CELL; f.vy = 0; }
}

function shoot() {
  const f = me;
  if (f.ammo <= 0) { fx(SFX.click); return; }
  f.ammo--;
  bullets.push({ x: f.x + BOX_W / 2, y: f.y + BOX_H });
  if (bullets.length > MAX_BULLETS) bullets.shift();
  f.vy = Math.min(f.vy, LIFT); f.flash = 3;
  fx(SFX.shot);
}

/** Bullets fly straight down and stop at stone (they pass ledges) or below the screen. */
function updateBullets() {
  for (const b of bullets) {
    b.y += BULLET_SPEED;
    if (solidAt(b.x, b.y + 5) || b.y > camY + VIEW_H + 16) b.dead = true;
  }
  bullets = bullets.filter((b) => !b.dead);
}

/** A hit (step 2 brings the enemies): 1 HP, a knock up, HURT_SAFE frames without harm. */
function hurt() {
  const f = me;
  if (f.inv > 0 || state !== 'play') return false;
  f.hp--; f.inv = HURT_SAFE; f.vy = -HURT_KNOCK; fx(SFX.hit);
  if (f.hp <= 0) gameOver();
  return true;
}

/** Keep the faller's middle near y CAM_Y, looking further ahead the faster they fall; never past the level's ends. */
function camera() {
  const mid = me.y + BOX_H / 2, target = mid - CAM_Y + Math.max(0, me.vy) * CAM_LEAD;
  camY += (target - camY) * CAM_EASE;
  camY = clamp(camY, mid - 136, mid - 40);
  camY = clamp(camY, 0, rows * CELL - VIEW_H);
}

function gameOver() {
  state = 'over'; timer = 0; play(-1); fx(SFX.over);
  rank = insertTop({ score, initials: lastInitials(), level });
}

function updateOver() {
  if (timer < 60 || !(pressed(A) || pressed(START))) return;
  fx(SFX.select);
  if (rank >= 0) { state = 'initials'; timer = 0; initials = { chars: lastInitials().split(''), pos: 0 }; fx(SFX.record); }
  else toTitle();
}

/** UP/DOWN pick a letter, LEFT/RIGHT (or A and B) move, START saves (as does A on the last letter). */
function updateInitials() {
  const ini = initials, k = LETTERS.indexOf(ini.chars[ini.pos]);
  if (pressed(UP)) { ini.chars[ini.pos] = LETTERS[(k + 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(DOWN)) { ini.chars[ini.pos] = LETTERS[(k + LETTERS.length - 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(LEFT) || pressed(B)) ini.pos = Math.max(0, ini.pos - 1);
  if (pressed(RIGHT)) ini.pos = Math.min(2, ini.pos + 1);
  const done = pressed(START) || (pressed(A) && ini.pos === 2);
  if (pressed(A) && ini.pos < 2) ini.pos++;
  if (!done || timer < 20) return;
  const v = packInitials(ini.chars.join(''));
  dset(INITIALS_SLOT, v); dset(TOP_SLOT + rank * ENTRY + 1, v);
  fx(SFX.select);
  state = 'records'; hl = rank; timer = 0;
}

function updateRecords() {
  if ((pressed(START) || pressed(A) || pressed(B)) && timer > 20) { fx(SFX.select); toTitle(); }
}

function updatePause() {
  if (pressed(UP)) { pauseSel = (pauseSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { pauseSel = (pauseSel + 1) % 3; fx(SFX.move); }
  if (pressed(B) || (pressed(START) && pauseSel === 0)) { paused = false; fx(SFX.pause); }
  else if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (pauseSel === 0) paused = false;
    else if (pauseSel === 1) startGame(); // restart
    else toTitle(); // quitting abandons the game: nothing is recorded
  }
}

// --- Draw ---

function draw() {
  cls();
  stream();
  const y = flr(camY);
  bgscroll(0, -WELL_X, y % (STRIP * CELL));
  bgscroll(1, -WELL_X, flr(y / 2) % (ART.scenes.wall.h * 8));
  if (state === 'play' || state === 'over') drawPlay();
  else if (state === 'title') drawTitle();
  else if (state === 'initials') drawInitials();
  else if (state === 'records') drawRecords();
  if (state === 'over') {
    panel(60, 72, 136, 72); ctxt('GAME OVER', 82, RED);
    ctxt(`LEVEL ${level}  ${best}M`, 98, WHITE); ctxt(`SCORE ${score}`, 110, WHITE);
    if (timer > 60 && timer % 60 < 40) ctxt('START: CONTINUE', 128, DIM);
  }
  if (paused) drawPause();
}

function drawPlay() {
  const f = me, sx = WELL_X + flr(f.x) - 3, sy = flr(f.y - camY) - 2;
  if (!(f.inv && f.inv % 8 < 4)) {
    const s = !f.ground ? ART.sprites.air : f.walk && (f.walk >> 3) & 1 ? ART.sprites.run : ART.sprites.stand;
    sprite(s, sx, sy, { fx: f.face < 0 });
  }
  if (f.flash) sprite(ART.sprites.flash, sx + 4, sy + 15);
  for (const b of bullets) sprite(ART.sprites.bullet, WELL_X + flr(b.x) - 4, flr(b.y - camY));
  hud();
}

/** The HUD in the gutters: HP on the left; depth and level on the right, the ammo gauge beside the well's right edge. */
function hud() {
  const f = me;
  txt('HP', 8, 12, DIM);
  for (let i = 0; i < f.maxHp; i++) {
    const x = 8 + (i % 4) * 11, y = 24 + flr(i / 4) * 11;
    rectfill(x, y, 9, 8, i < f.hp ? RED : SHADOW); rect(x, y, 9, 8, i < f.hp ? WHITE : PANEL);
  }
  const depth = depthBase + flr((f.y + BOX_H) / METRE);
  txt(`${depth}M`, 214, 12, WHITE);
  txt(`LV ${level}`, 214, 24, DIM);
  for (let i = 0; i < f.maxAmmo; i++) rectfill(203, 210 - i * 8, 6, 6, i < f.ammo ? WHITE : PANEL);
  if (clearT) { panel(80, 92, 96, 24); ctxt(`LEVEL ${level} CLEAR`, 100, GOLD); }
}

