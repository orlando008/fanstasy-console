function drawEnemy(e) {
  const x = WELL_X + flr(e.x) - 8, y = flr(e.y - camY) - 8, S = ART.sprites;
  if (e.flash && e.flash % 4 < 2) return;
  if (e.kind === 'bat') sprite(e.hang ? S.bat0 : (e.t >> 3) & 1 ? S.bat1 : S.bat2, x, e.hang ? y + 2 : y);
  else if (crawls(e.kind)) {
    const [gx, gy] = e.fall ? [0, 1] : e.g, [dx, dy] = e.d, sp = e.kind === 'spiky';
    if (gy) sprite(sp ? S.spiky : S.snail, x, y, { fx: dx < 0, fy: gy < 0 });
    else sprite(sp ? S.spikyw : S.snailw, x, y, { fx: gx > 0, fy: dy < 0 });
  } else if (e.kind === 'turtle') sprite((e.t >> 4) & 1 ? S.turtle1 : S.turtle0, x, y, { fx: e.dir < 0 });
  else if (e.kind === 'frog') sprite(e.ground ? S.frog0 : S.frog1, x, y, { fx: e.dir < 0 });
  else if (e.kind === 'blob') sprite(S.blob, x, y + ((e.t >> 4) & 1));
  else if (e.kind === 'blobling') sprite(S.blobling, x + 4, y + 4);
  else if (e.kind === 'jelly') sprite((e.t >> 3) & 1 ? S.jelly1 : S.jelly0, x, y + 2);
  else if (e.kind === 'turret') sprite(S.turret, x, y - 3, { fx: e.dir < 0 });
  else if (e.kind === 'ghost' && !(fading(e) && e.t % 4 < 2)) sprite((e.t >> 4) & 1 ? S.ghost1 : S.ghost0, x, y);
}

/** The HUD in the gutters: HP on the left; depth and level on the right, the ammo gauge beside the well's right edge. */
function hud() {
  const f = me;
  txt('HP', 8, 12, DIM);
  for (let i = 0; i < f.maxHp; i++) {
    const x = 8 + (i % 4) * 11, y = 24 + flr(i / 4) * 11;
    rectfill(x, y, 9, 8, i < f.hp ? RED : SHADOW); rect(x, y, 9, 8, i < f.hp ? WHITE : PANEL);
  }
  txt('GEMS', 8, 60, DIM); txt(String(wallet), 8, 72, RED);
  txt(MODULES[f.mod].s, 8, 200, f.mod === 'boots' ? DIM : WHITE);
  rectfill(8, 84, 42, 4, SHADOW); rectfill(8, 84, flr((meter * 42) / HIGH_AT), 4, high ? WHITE : RED);
  if (high && timer % 30 < 20) txt('GEM HIGH', 4, 92, WHITE);
  const depth = depthBase + flr((f.y + BOX_H) / METRE);
  txt(`${depth}M`, 214, 12, WHITE);
  txt(`LV ${level}`, 214, 24, DIM);
  if (combo > 1) { txt('COMBO', 214, 52, combo >= 8 ? GOLD : DIM); txt(String(combo), 214, 64, combo >= 8 ? GOLD : WHITE); }
  if (payMsg) {
    txt(`${payMsg.n} COMBO`, 4, 120, GOLD); txt(`+${payMsg.g} GEMS`, 4, 132, RED);
    if (payMsg.hp) txt('+1 HP', 4, 144, WHITE);
    if (payMsg.ammo) txt('+1 AMMO', 4, 156, WHITE);
  }
  for (let i = 0; i < f.maxAmmo; i++) rectfill(203, 210 - i * 8, 6, 6, i < f.ammo ? WHITE : PANEL);
  if (room) return;
  if (clearT) { panel(80, 92, 96, 24); ctxt(`LEVEL ${level} CLEAR`, 100, GOLD); }
  else if (banner && banner.t > 30 || (banner && banner.t % 8 < 4)) { panel(68, 56, 120, 34); ctxt(banner.text, 62, GOLD); ctxt(loopOf(level) ? `LOOP ${loopOf(level) + 1}  LEVEL ${level}` : `LEVEL ${level}`, 76, DIM); }
}

