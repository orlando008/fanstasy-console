function draw() {
  cls();
  stream();
  const inRoom = !!room && state === 'play';
  bg(0, { show: !inRoom }); bg(1, { show: !inRoom }); bg(2, { show: inRoom });
  const y = flr(camY);
  bgscroll(0, -WELL_X, y % (STRIP * CELL));
  bgscroll(1, -WELL_X, flr(y / 2) % (ART.scenes.wall.h * 8));
  if (state === 'play' || state === 'over') drawPlay();
  else if (state === 'title') drawTitle();
  else if (state === 'initials') drawInitials();
  else if (state === 'records') drawRecords();
  if (state === 'over') {
    panel(36, 60, 184, 104); ctxt(daily ? 'THE DAILY WELL' : 'GAME OVER', 70, RED);
    ctxt(`LEVEL ${level}   ${best} M`, 88, WHITE); ctxt(`${collected} GEMS   ${kills} KILLS`, 100, WHITE);
    ctxt(`BEST COMBO ${bestCombo}`, 112, WHITE); ctxt(`SCORE ${score}`, 128, GOLD);
    if (newDaily) ctxt("TODAY'S BEST!", 140, GOLD);
    if (timer > 60 && timer % 60 < 40) ctxt('START: CONTINUE', 152, DIM);
  }
  if (paused) drawPause();
}

function drawPlay() {
  if (room) return drawRoom();
  const f = me, sx = WELL_X + flr(f.x) - 3, sy = flr(f.y - camY) - 2;
  if (has('drone')) sprite(ART.sprites.dronesm, WELL_X + flr(droneX()) - 4, sy - 2 + ((timer >> 4) & 1));
  if (beam) { rectfill(WELL_X + flr(beam.x) - 2, flr(beam.y - camY), 5, VIEW_H, RED); rectfill(WELL_X + flr(beam.x) - 1, flr(beam.y - camY), 3, VIEW_H, WHITE); }
  if (fist) sprite(ART.sprites.fist, WELL_X + flr(fist.x) - 8, flr(fist.y - camY) + 4);
  if (!(f.inv && f.inv % 8 < 4)) {
    const s = !f.ground ? ART.sprites.air : f.walk && (f.walk >> 3) & 1 ? ART.sprites.run : ART.sprites.stand;
    sprite(s, sx, sy, { fx: f.face < 0 });
  }
  if (f.flash) sprite(ART.sprites.flash, sx + 4, sy + 15);
  for (const b of bullets) sprite(b.big ? ART.sprites.bigshot : ART.sprites.bullet, WELL_X + flr(b.x) - 4, flr(b.y - camY));
  for (const e of enemies) if (e.awake && !e.dead && e.y > camY - 16 && e.y < camY + VIEW_H + 16) drawEnemy(e);
  for (const g of gems) if (!(g.t > GEM_LIFE - GEM_BLINK && g.t % 8 < 4)) sprite(g.v >= BIG ? ART.sprites.biggem : ART.sprites.gem, WELL_X + flr(g.x) - 4, flr(g.y - camY) - 4, { prio: 2 });
  for (const s of shots) sprite(ART.sprites.ball, WELL_X + flr(s.x) - 4, flr(s.y - camY) - 4);
  for (const p of puffs) sprite(ART.sprites.puff, WELL_X + flr(p.x) - 4, flr(p.y - camY) - 4);
  hud();
}

