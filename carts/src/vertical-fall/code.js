const held = (b) => (inputMask & (1 << b)) !== 0;

// --- The rules (spec section 5): units are pixels and frames; a cell is 16 px, and a metre is a cell ---

const WELL_X = 56, CELLS = 9, CELL = 16, METRE = 16, VIEW_H = 224;
const BOX_W = 10, BOX_H = 14;                       // the faller's box
const RUN = 1.6, ACCEL = 0.3, FRICTION = 0.4, AIR_FRICTION = 0.15;
const GRAVITY = 0.22, MAX_FALL = 4.5, JUMP = 4.0, COYOTE = 4;
const AMMO = 8, BULLET_SPEED = 7, RATE = 8, LIFT = 0.3, MAX_BULLETS = 16;
const HP = 4, HURT_SAFE = 90, HURT_KNOCK = 2.5;
const CAM_Y = 80, CAM_LEAD = 5, CAM_EASE = 0.25;   // the faller's middle at y 80, the camera looking ahead when falling
const CLEAR_WAIT = 60;                              // frames on a level's floor before the next level
const EMPTY = 0, STONE = 1, LEDGE = 2;
const levelRows = (n) => Math.min(140 + 10 * (n - 1), 220);

// --- The well: a grid of cells, CELLS wide, `rows` deep ---

let cells = null, rows = 0, level = 1, depthBase = 0, runSeed = 1;

/** A small seeded generator (mulberry32) for the level layouts, apart from the console's PRNG, so a layout depends only
 * on the run's seed and the level (the Daily well, step 4). */
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), a | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const edge = (c) => c <= 0 || c >= CELLS - 1;
/** The cell at column c, row r: stone beyond the sides and below the floor; open above the top (but the side walls). */
const cellAt = (c, r) => (c < 0 || c >= CELLS || r >= rows ? STONE : r < 0 ? (edge(c) ? STONE : EMPTY) : cells[r * CELLS + c]);
function setCell(c, r, v) { cells[r * CELLS + c] = v; }

/** Step 1's test layout (the chunks of step 4 replace it): the side walls, outcrops from either wall of 1 to 3 cells,
 * ledges of 2 to 4, a pair of blocks in the middle, every 4 to 7 rows; a quiet top and the floor at the bottom. Every
 * row leaves at least 4 of the 7 inner cells open, so there is always a way down. */
function makeLevel(n) {
  rows = levelRows(n); cells = new Uint8Array(rows * CELLS);
  const R = rng(runSeed * 977 + n), ri = (a, b) => a + Math.floor(R() * (b - a + 1));
  for (let r = 0; r < rows; r++) { setCell(0, r, STONE); setCell(CELLS - 1, r, STONE); }
  for (let c = 0; c < CELLS; c++) setCell(c, rows - 1, STONE);
  for (let r = 8; r < rows - 8; r += ri(4, 7)) {
    const k = ri(0, 3);
    if (k < 2) {
      const w = ri(1, 3);
      for (let i = 0; i < w; i++) setCell(k ? CELLS - 2 - i : 1 + i, r, STONE);
      if (R() < 0.5) setCell(k ? CELLS - 2 : 1, r + 1, STONE);
    } else if (k === 2) {
      const w = ri(2, 4), c0 = ri(1, CELLS - 1 - w);
      for (let i = 0; i < w; i++) setCell(c0 + i, r, LEDGE);
    } else { const c0 = ri(3, 4); setCell(c0, r, STONE); setCell(c0 + 1, r, STONE); }
  }
  restream();
}

// --- The strip of Map RAM: STRIP rows of cells (2 x 2 tiles each) that wrap; the rows near the camera are written as
// it moves, so a level of any depth costs no more map. A cell's four entries are copied from the catalogue art.py
// placed in Map RAM (the stone has four, chosen by column and row, so the texture is seamless). ---

const STRIP = 32;
const slotRow = new Int32Array(STRIP);
let cellMap = null;
function loadCells() {
  const s = ART.scenes, ent = (sc) => [mget(sc.mx, sc.my), mget(sc.mx + 1, sc.my), mget(sc.mx, sc.my + 1), mget(sc.mx + 1, sc.my + 1)];
  cellMap = [[[0, 0, 0, 0]], [0, 1, 2, 3].map((i) => ent(s['stone' + i])), [ent(s.ledge)]];
}
const slotOf = (r) => ((r % STRIP) + STRIP) % STRIP;
function restream() { slotRow.fill(-999999); }
function writeRow(r) {
  const slot = slotOf(r);
  slotRow[slot] = r;
  for (let c = 0; c < CELLS; c++) {
    const v = cellMap[cellAt(c, r)], e = v[v.length > 1 ? (c & 1) + (r & 1) * 2 : 0];
    mset(2 * c, 2 * slot, e[0]); mset(2 * c + 1, 2 * slot, e[1]);
    mset(2 * c, 2 * slot + 1, e[2]); mset(2 * c + 1, 2 * slot + 1, e[3]);
  }
}
function stream() {
  const r0 = flr(camY / CELL) - 1;
  for (let r = r0; r < r0 + VIEW_H / CELL + 3; r++) if (slotRow[slotOf(r)] !== r) writeRow(r);
}

