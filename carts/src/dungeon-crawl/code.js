/** Take a ball into a kickout's hole (a slot or a cubby): it is held, then thrown out. */
function capture(b, h) { b.hold = { h, t: HOLD * SUB }; b.vx = b.vy = 0; b.x = h.x; b.y = h.y; b.ride = null; b.zone = null; } // (held in substeps)
