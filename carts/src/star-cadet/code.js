/** The light of the table follows the rank: a dim cool blue for a cadet, a warm bright gold for a fleet admiral (the floor's palette is rewritten). */
function applyRankLight() {
  const t = (career ? 8 : rk) / 8;
  for (let i = 17; i < 32; i++) {
    const [r, g, b] = floorBase[i] || [0, 0, 0], lum = 0.3 * r + 0.59 * g + 0.11 * b;
    const k = 0.8 * t, f = 0.9 + 0.8 * t, ch = (v, gold) => clamp(Math.round((v * (1 - k) + gold * k) * f), 0, 31);
    color(i, ch(r, lum * 3), ch(g, lum * 2.3), ch(b, lum * 0.7));
  }
}

const flash = (a, b) => { banner = { a, b, t: 150 }; };

/** What the ball did this frame, in order: the lamps, the missions and the jackpots. */
function processEvents() {
  for (const k of evq) {
    if (mission) {
      if (k === 'jackpot') { if (MISSIONS[mission.r].multi) { award(JACKPOT); fx(SFX.jackpot); } else continue; }
      if (MISSIONS[mission.r].on(mission, k)) completeMission();
      continue;
    }
    if (k === 'standupSet') setLamp(0); else if (k === 'bank') setLamp(1);
    else if (k === 'standup' && ++lampN[0] >= LAMP_STANDUPS) setLamp(0);          // three standup targets lit light the first lamp, two drop targets the second
    else if (k === 'drop' && ++lampN[1] >= LAMP_DROPS) setLamp(1);
    else if (k === 'rampL' || k === 'rampR') setLamp(2);
    else if (k === 'gate' && lamps.every(Boolean)) startMission();
  }
  evq.length = 0;
}

/** A mission lamp: lit by a full set of standup targets, by the drop bank and by a ramp; all three light the gate. */
function setLamp(i) {
  if (lamps[i]) return;
  lamps[i] = true; lampN[i] = 0; fx(SFX.lamp);
  say(lamps.every(Boolean) ? 'GATE LIT' : `LAMP ${i + 1}`);
}

/** The gate was shot with all three lamps lit: this rank's mission begins (after the last rank, a jackpot instead). */
function startMission() {
  lamps = [false, false, false];
  if (career) { award(RANK_PRIZE * 10); say('JACKPOT'); flash('MOTHERSHIP', 'JACKPOT 5000000'); fx(SFX.jackpot); return; }
  const d = MISSIONS[rk];
  mission = { r: rk, left: d.time * 60, n: 0, step: 0, set: {} };
  flash(d.name, d.text(mission)); fx(SFX.mission);
  if (d.multi) { // two more balls come out of the gate behind the one that is in it, and there is no save
    saved = true; saveT = 0;
    for (let i = 1; i <= 2; i++) bs.push(newBall(GATE.x, GATE.y, (GATE_HOLD + 25 * i) * SUB));
  }
}

function tickMission() {
  if (--mission.left <= 0) failMission('TIME UP');
  else if (MISSIONS[mission.r].multi && bs.length < 2) failMission('MULTIBALL OVER');
}

function failMission(why) { mission = null; lamps = [true, true, true]; flash('MISSION FAILED', why); fx(SFX.fail); }

/** Done: the prize (500,000 times the new rank's number), the new rank, an extra ball at some, and the lamps start again. */
function completeMission() {
  const r = mission.r; mission = null;
  award(RANK_PRIZE * (r + 2));
  if (r < 8) rk = r + 1; else career = true;
  if (EXTRA_AT_RANK.includes(r)) { extraBalls++; say('EXTRA BALL'); } else say('RANK UP');
  lamps = [false, false, false]; lampN = [0, 0, 0]; applyRankLight();
  flash('RANK UP', RANK_NAMES[rk] + (career ? ' *' : '')); fx(SFX.rankUp);
}

/** A shove of the table: the ball is pushed (L left, R right, SELECT up); the third in a ball is a warning, the fourth a tilt. */
function nudge(side, up) {
  nudges++;
  if (nudges >= NUDGE_TILT) { tilted = true; say('TILT'); fx(SFX.tilt); return; }
  if (nudges === NUDGE_WARN) { say('WARNING'); fx(SFX.warn); }
  for (const b of bs) if (!b.ramp && !b.hold) { b.vx += side * NUDGE_V; if (up) b.vy -= NUDGE_V; }
  shake = 8; fx(SFX.nudge);
}

/** The ball is lost: a saved ball goes back to the plunger; otherwise the ball is over. */
function drain() {
  if (saveT > 0 && !saved) { saved = true; saveT = 0; say('BALL SAVED'); fx(SFX.save); serve(); return; }
  fx(SFX.drain); if (mission && MISSIONS[mission.r].multi) failMission('BALL LOST'); // a mission is put on hold by a lost ball; a multiball is over
  const base = bonus + rk * RANK_BONUS, b = tilted ? 0 : base * mult;
  if (b > 0) { // the bonus is counted on its own screen: the shots of the ball (and 10,000 for each rank) times the multiplier
    bonusRes = { base, mult, total: b }; award(b); state = 'bonus'; timer = 0;
  } else afterBall();
}

const BONUS_COUNT = 90, BONUS_HOLD = 45; // frames the bonus counts up, and waits when done
const bonusShown = () => Math.ceil(bonusRes.total * Math.min(1, timer / BONUS_COUNT));
function updateBonus() {
  if (demo && timer > 30) { afterBall(); return; }
  const done = timer >= BONUS_COUNT;
  if (!done && timer % 5 === 0) fx(SFX.tick);
  if (pressed(A) || pressed(START)) { // a press skips the counting; another goes on
    if (!done && timer > 10) timer = BONUS_COUNT; else if (done && timer > BONUS_COUNT + 10) afterBall();
  } else if (timer > BONUS_COUNT + BONUS_HOLD) afterBall();
}

/** After a ball's bonus: an extra ball plays the same player again; otherwise the next player with a ball left; or the game is over. */
function afterBall() {
  if (extraBalls > 0) { extraBalls--; beginBall(); say('SHOOT AGAIN'); state = 'play'; return; }
  balls--; savePlayer();
  for (let i = 1; i <= nPlayers; i++) {
    const j = (cur + i) % nPlayers;
    if (players[j].balls > 0) {
      loadPlayer(j); beginBall(); timer = 0;
      state = nPlayers > 1 ? 'turn' : 'play';
      return;
    }
  }
  gameOver();
}

/** A turn's splash: whose ball it is. */
function updateTurn() { if (demo) { state = 'play'; return; } if (timer > 90 || (timer > 15 && (pressed(A) || pressed(START)))) { state = 'play'; timer = 0; } }

function gameOver() {
  if (demo) { toTitle(); return; }
  state = 'over'; timer = 0; play(-1); fx(SFX.over);
  dset(GAMES_SLOT, dget(GAMES_SLOT) + 1); // the games played, and the best rank reached by anyone
  newBest = Math.max(...players.map(rankNo)) > dget(BEST_SLOT) ? Math.max(...players.map(rankNo)) : 0;
  if (newBest) dset(BEST_SLOT, newBest);
  initQueue = players.map((q, i) => i).sort((a, b) => players[b].score - players[a].score); firstRank = -1;
}

/** The next score that makes the top 10 asks for initials (best score first); true if there was one. */
function nextInitials() {
  while (initQueue.length) {
    const i = initQueue.shift(), r = insertTop({ score: players[i].score, initials: lastInitials(), rn: rankNo(players[i]) });
    if (r < 0) continue;
    rank = r; if (firstRank < 0) firstRank = r;
    state = 'initials'; timer = 0; initials = { chars: lastInitials().split(''), pos: 0, who: i }; fx(SFX.record);
    return true;
  }
  return false;
}

function updateOver() {
  if (timer < 60 || !(pressed(A) || pressed(START))) return;
  fx(SFX.select);
  if (!nextInitials()) toTitle();
}

/** UP/DOWN pick a letter, LEFT/RIGHT (or A and B) move, START saves (as does A on the last letter). */
function updateInitials() {
  const ini = initials, k = LETTERS.indexOf(ini.chars[ini.pos]);
  if (pressed(UP)) { ini.chars[ini.pos] = LETTERS[(k + 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(DOWN)) { ini.chars[ini.pos] = LETTERS[(k + LETTERS.length - 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(LEFT) || pressed(B)) ini.pos = Math.max(0, ini.pos - 1);
  if (pressed(RIGHT)) ini.pos = Math.min(2, ini.pos + 1);
  const done = pressed(START) || (pressed(A) && ini.pos === 2);
  if (pressed(A) && ini.pos < 2) ini.pos++;
  if (!done || timer < 20) return;
  const v = packInitials(ini.chars.join(''));
  dset(INITIALS_SLOT, v); dset(TOP_SLOT + rank * ENTRY + 1, v);
  fx(SFX.select);
  if (!nextInitials()) { state = 'records'; hl = firstRank; timer = 0; }
}

function updateRecords() {
  if ((pressed(START) || pressed(A) || pressed(B)) && timer > 20) { fx(SFX.select); toTitle(); }
}

function updatePause() {
  if (pressed(UP)) { pauseSel = (pauseSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { pauseSel = (pauseSel + 1) % 3; fx(SFX.move); }
  if (pressed(B) || (pressed(START) && pauseSel === 0)) { paused = false; fx(SFX.pause); }
  else if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (pauseSel === 0) paused = false;
    else if (pauseSel === 1) startGame(); // restart
    else toTitle(); // quitting abandons the game: nothing is recorded
  }
}

// --- Draw ---

function draw() {
  cls();
  const inPlay = state === 'play' || state === 'over' || state === 'turn' || state === 'bonus', menu = state === 'title' || state === 'players';
  if (!inPlay && !menu) { bg(0, { show: false }); bg(1, { show: false }); }
  bg(2, { y: Math.round(clock * 0.25) });
  if (inPlay) drawPlay();
  else if (menu) { drawTable(Math.round(96 + 96 * Math.sin(clock / 300))); drawMenuPanel(); if (state === 'title') drawTitle(); else drawPlayers(); }
  else if (state === 'initials') drawInitials();
  else if (state === 'records') drawRecords();
  if (state === 'turn') drawTurn();
  else if (state === 'bonus') drawBonus();
  else if (state === 'over') drawOver();
  if (paused) drawPause();
}

/** The picture of the table: sprites over the two background layers, which scroll with the camera; the panel on the overlay. */
function drawPlay() {
  const cy = Math.round(camY) + (shake > 0 ? (shake & 1 ? 2 : -2) : 0);
  drawTable(cy);
  if (mission || (banner && banner.t > 0)) drawBanner();
  drawPanel(cy);
  if (demo && clock % 60 < 40) ctab('DEMO: PRESS ANY BUTTON', 196, WHITE);
}

/** A ball in an orbit lane runs along a ramp's ribbon (the ramps share the lanes): it is drawn over it. */
const inOrbit = (b) => b.y > ORBIT_Y - 10 && b.y < ORBIT_IN + 10 && (b.x < ORBIT_X[0] || (b.x > ORBIT_X[1] && b.x < LANE_X));

/** The table: both background layers scrolled to cy, and every part of it as a sprite. */
function drawTable(cy) {
  const sy = (y) => Math.round(y - cy), R = Math.round, S = ART.sprites, B = ART.big;
  bg(0, { y: cy, show: true }); bg(1, { y: cy, show: true });
  const P = { prio: 2 }; // the table's parts: over the rails, under a ramp
  // lamps and their glow: under the decor (priority 1)
  const lamp = (x, y, on) => {
    if (on) sprite(S.glow, R(x) - 8, sy(y) - 8, { pal: 4, prio: 1 });
    sprite(on ? S.lamp_on : S.lamp, R(x) - 4, sy(y) - 4, { prio: 1 });
  };
  LANE_XS.forEach((x, i) => lamp(x, LANE_Y, laneLit[i]));
  RAMPS.forEach((r) => lamp(r.ex, r.ey + 14, r.lit));
  lamp(8, 588, kickback);
  lamps.forEach((on, i) => lamp(76 + i * 12, 124, on)); // the three mission lamps, under the gate
  if (lamps.every(Boolean) && !mission && clock % 30 < 20) sprite(S.glow, GATE.x - 8, sy(GATE.y) - 8, { pal: 4, prio: 1 }); // the gate is lit
  for (const e of BUMPERS) sprite(e.flash ? S.bump_hit : S.bump, e.x - 16, sy(e.y) - 16, P);
  SLINGS.forEach((e, k) => bigSprite(B[e.flash ? 'sling_hit' : 'sling'], k ? 123 : 22, sy(476), { ...P, fx: !!k }));
  STANDUPS.forEach((e, k) => sprite(e.lit ? S.stand_hit : S.stand, k < 2 ? e.x0 - 3 : e.x0 - 28, sy(e.y0 - 5.5), { ...P, fx: k >= 2 }));
  for (const e of DROPS) sprite(e.down ? S.drop_down : S.drop, R(e.x0 - 3), sy(e.y0 - 6), P);
  sprite(S['spin' + (flr(spinPhase) & 3)], 4, sy(240) - 8, P);
  const pull = inLane() && plunge > 0 ? plunge * 12 : 0;
  sprite(S.plunger, LANE_X, sy(LANE_FLOOR - 1 + pull), P);
  for (let i = 0; i < 3; i++) sprite(S.spring, LANE_X + 4, sy(LANE_FLOOR + 6 + pull + i * 8), P);
  flips.forEach((f, k) => {
    const n = clamp(R((REST_A - f.a) / (REST_A - UP_A) * 8), 0, 8);
    bigSprite(B['flip' + n], R(k ? f.x - 38 : f.x - 10), sy(f.y) - 24, { ...P, fx: !!k });
  });
  for (const b of bs) sprite(S.ball, R(b.x) - 8, sy(b.y + (b === ball && inLane() && plunge > 0 ? plunge * 12 : 0)) - 8, { prio: b.ramp || inOrbit(b) ? 3 : 2 });
}

/** Short scores for the list of players: 12345, 151K, 1.2M. */
const short = (n) => (n >= 1e6 ? (n / 1e6).toFixed(1) + 'M' : n >= 1e5 ? Math.floor(n / 1000) + 'K' : String(n));

/** The panel: glass over the starfield with the player, the score, the ball, the multiplier, a message, a map of the table and every player's score. */
function drawPanel(cy) {
  const R = Math.round;
  rectfill(TABLE_W, 0, 256 - TABLE_W, 224, ART.colors.GLASS); line(TABLE_W, 0, TABLE_W, 223, PANEL);
  txt(nPlayers > 1 ? `P${cur + 1}` : 'SCORE', 198, 6, GOLD);
  txt(String(score), 252 - String(score).length * 8, 16, WHITE);
  txt(`BALL ${Math.min(BALLS, BALLS + 1 - balls)}`, 198, 28, balls > 1 ? DIM : RED);
  txt(RANK_SHORT[rk], 198, 40, career ? GOLD : CYAN);
  if (mult > 1) txt(`MULT X${mult}`, 198, 52, CYAN);
  if (saveT > 0 && clock % 40 < 28) txt('SAVE', 198, 62, GREEN);
  if (msgT > 0 && (msgT > 30 || msgT % 8 < 5)) msg.split(' ').forEach((w, i) => txt(w, 198, 74 + i * 10, tilted ? RED : GOLD));
  // a map of the table: the balls and what the screen shows
  const mx = 208, my = 104;
  rect(mx - 1, my - 1, TABLE_W / 8 + 2, TABLE_H / 8 + 2, PANEL);
  rect(mx, my + R(cy / 8), TABLE_W / 8, VIEW_H / 8, DIM);
  for (const b of bs) rectfill(mx + R(b.x / 8) - 1, my + R(b.y / 8) - 1, 2, 2, WHITE);
  if (nPlayers > 1) players.forEach((q, i) => {
    const v = short(i === cur ? score : q.score);
    txt(`${i + 1}`, 194, 189 + i * 9, i === cur ? GOLD : DIM); txt(v, 252 - v.length * 8, 189 + i * 9, i === cur ? WHITE : DIM);
  });
}

/** At the top of the table: the mission and what is left to do and its time, or the last announcement (rank up, failed ...). */
