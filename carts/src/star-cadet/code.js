/** Queue one of ART.sprites at (x, y), above the background; opts as for spr (fx, fy ...). */
function sprite(s, x, y, opts = {}) { spr(s.tile, x, y, { size: s.size, pal: s.pal, prio: 3, ...opts }); }

// --- Sound (SPEC 5). Any channel plays any instrument. Songs use channels 0 to 5; effects take turns on 6 and 7, ---
// so they never cut into the music and two can sound at once.

const SFX = { move: 0, select: 1, pause: 2, hit: 3, over: 4, point: 5, record: 6 };
const SONG = { title: 0, play: 1 };
const SFX_CH = [7, 6];
let fxNext = 0;
function fx(n) { sfx(n, SFX_CH[fxNext]); fxNext ^= 1; }

// A song is only started if it is not already playing.
let playing = -1;
function play(song) {
  if (song === playing) return;
  playing = song; music(song);
}

// --- Save slots (SPEC 13) ---

const VERSION_SLOT = 0, SAVE_VERSION = 1, INITIALS_SLOT = 1;
const TOP_SLOT = 10, TOP_N = 10, ENTRY = 3; // the top 10, best first: score, initials, a spare (slots 10 to 39)
const LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';

function readEntry(i) { const s = TOP_SLOT + i * ENTRY; return { score: dget(s), initials: unpackInitials(dget(s + 1)) }; }
function writeEntry(i, e) { const s = TOP_SLOT + i * ENTRY; dset(s, e.score); dset(s + 1, packInitials(e.initials)); }
const topTen = () => Array.from({ length: TOP_N }, (_, i) => readEntry(i));

/** Put a score into the top 10 if it makes it. Returns its row, or -1. */
function insertTop(e) {
  if (!e.score) return -1;
  const list = topTen(), at = list.findIndex((x) => e.score > x.score);
  if (at < 0) return -1;
  list.splice(at, 0, e);
  for (let i = at; i < TOP_N; i++) writeEntry(i, list[i]);
  return at;
}
/** Three characters, 8 bits each. */
const packInitials = (str) => (str.charCodeAt(0) << 16) | (str.charCodeAt(1) << 8) | str.charCodeAt(2);
const unpackInitials = (v) => (v ? String.fromCharCode((v >> 16) & 255, (v >> 8) & 255, v & 255) : '---');
const lastInitials = () => (dget(INITIALS_SLOT) ? unpackInitials(dget(INITIALS_SLOT)) : 'AAA');

// --- The table and its physics (SPEC 4, 5). World pixels: x 0 to 192 across, y 0 to 640 down; the ball is 5 px in radius. ---
// All the numbers are here, in one place, because only playing can say how the ball should feel.

const TABLE_W = 192, TABLE_H = 640, VIEW_H = 224;
const BR = 5, SUB = 4; // ball radius; substeps a frame (a substep moves the ball at most 3.5 px, under its radius)
const GRAV = 0.12, VMAX = 14; // px per frame squared; px per frame
const WALL_E = 0.45, FLIP_E = 0.7, REST_CUT = 0.3; // bounce of a wall and of a flipper; below this normal speed a hit does not bounce
const FLEN = 34, FR = 4; // a flipper is a capsule: length, radius
const REST_A = 30 * Math.PI / 180, UP_A = -28 * Math.PI / 180; // its angle (down is positive), at rest and held up
const W_UP = (REST_A - UP_A) / 4, W_DOWN = (REST_A - UP_A) / 6; // radians a frame: up in 4 frames, down in 6
const LANE_X = 176, LANE_FLOOR = 612, BALL_HOME = { x: 184, y: LANE_FLOOR - BR };
const PLUNGE_FRAMES = 60; // held this long is full power; the launch speed is 4 + 10 x power
const DRAIN_Y = 632;

/** The walls: segments [x0, y0, x1, y1]. A top arch of radius 96 over the table, the plunger lane on the right, and the
 *  guides that feed the flippers. */
const WALLS = (() => {
  const w = [];
  for (let i = 0; i < 16; i++) { // the arch: a half circle of 16 segments
    const a0 = Math.PI + (Math.PI * i) / 16, a1 = Math.PI + (Math.PI * (i + 1)) / 16;
    w.push([96 + 96 * Math.cos(a0), 96 + 96 * Math.sin(a0), 96 + 96 * Math.cos(a1), 96 + 96 * Math.sin(a1)]);
  }
  w.push([0, 96, 0, 512]); // the left wall
  w.push([0, 512, 48, 588]); // the left guide, into the left flipper's pivot
  w.push([TABLE_W, 96, TABLE_W, LANE_FLOOR]); // the right wall of the lane
  w.push([LANE_X, 120, LANE_X, 512]); // the lane's inner wall
  w.push([LANE_X, 512, 128, 588]); // the right guide
  w.push([LANE_X, LANE_FLOOR, TABLE_W, LANE_FLOOR]); // the lane's floor
  return w;
})();
/** Flippers: pivot, side (+1 points right), angle, and the last swing (radians a frame, for the ball). */
const makeFlippers = () => [{ x: 48, y: 588, s: 1, a: REST_A, w: 0 }, { x: 128, y: 588, s: -1, a: REST_A, w: 0 }];
const flipTip = (f) => ({ x: f.x + f.s * FLEN * Math.cos(f.a), y: f.y + FLEN * Math.sin(f.a) });

/** Push the ball out of a capsule (or a segment, r 0) and bounce it. vs: the surface's velocity at the contact. */
function collide(b, x0, y0, x1, y1, r, e, vsAt) {
  const dx = x1 - x0, dy = y1 - y0, len2 = dx * dx + dy * dy;
  const t = len2 ? clamp(((b.x - x0) * dx + (b.y - y0) * dy) / len2, 0, 1) : 0;
  const cx = x0 + dx * t, cy = y0 + dy * t, ox = b.x - cx, oy = b.y - cy, d2 = ox * ox + oy * oy, reach = BR + r;
  if (d2 >= reach * reach) return false;
  const d = Math.sqrt(d2), nx = d ? ox / d : 0, ny = d ? oy / d : -1;
  b.x = cx + nx * reach; b.y = cy + ny * reach;
  const vs = vsAt ? vsAt(t) : [0, 0];
  const vn = (b.vx - vs[0]) * nx + (b.vy - vs[1]) * ny;
  if (vn < 0) {
    const k = -(1 + (vn > -REST_CUT ? 0 : e)) * vn;
    b.vx += k * nx; b.vy += k * ny;
  }
  return true;
}

/** One frame of the table: the flippers swing, the ball moves in SUB substeps. hold: the flippers' buttons [left, right]. */
function stepTable(b, flips, hold) {
  for (let i = 0; i < SUB; i++) {
    flips.forEach((f, k) => {
      const a0 = f.a;
      f.a = hold[k] ? Math.max(UP_A, f.a - W_UP / SUB) : Math.min(REST_A, f.a + W_DOWN / SUB);
      f.w = (f.a - a0) * SUB;
    });
    b.vy += GRAV / SUB;
    const sp = Math.hypot(b.vx, b.vy);
    if (sp > VMAX) { b.vx *= VMAX / sp; b.vy *= VMAX / sp; }
    b.x += b.vx / SUB; b.y += b.vy / SUB;
    for (const w of WALLS) collide(b, w[0], w[1], w[2], w[3], 0, WALL_E);
    for (const f of flips) {
      const tip = flipTip(f);
      collide(b, f.x, f.y, tip.x, tip.y, FR, FLIP_E, (t) => {
        const r = t * FLEN; // the contact's speed: its distance from the pivot times the turn
        return [-f.s * Math.sin(f.a) * r * f.w, Math.cos(f.a) * r * f.w];
      });
    }
  }
}

// --- Input: edge-triggered presses (btnp repeats; menus want one press) ---

let inputMask = 0, prevMask = 0;
// The flippers: one hand each. Anything on the D-pad is the left flipper, any of the four buttons on the right is the right one.
const PAD_LEFT = [UP, DOWN, LEFT, RIGHT], PAD_RIGHT = [A, B, X, Y];
const BUTTONS = [UP, DOWN, LEFT, RIGHT, A, B, X, Y, L, R, START, SELECT];
function readPad() { let m = 0; for (const b of BUTTONS) if (btn(b)) m |= 1 << b; return m; }
const pressed = (b) => (inputMask & (1 << b)) !== 0 && (prevMask & (1 << b)) === 0;

// --- State ---

let skipTitle = false; // tests set this to land straight in the game
let state = 'title', paused = false, timer = 0, clock = 0;
let titleSel = 0, pauseSel = 0, rank = -1, hl = -1, initials = null;
let score = 0, balls = 3, ball = null, flips = [], plunge = 0, camY = 0, held = [false, false];

function init() {
  if (dget(VERSION_SLOT) !== SAVE_VERSION) { // a new or older save: start clean
    for (let i = 0; i < 256; i++) dset(i, 0);
    dset(VERSION_SLOT, SAVE_VERSION);
  }
  // The background: the ground on layer 0 along the bottom of the screen, the hills behind it on layer 1 (each its
  // region of Map RAM, placed with a negative scroll and not repeated), the sky a gradient in scanline() below.
  const f = ART.scenes.field, h = ART.scenes.hills;
  bg(0, { mx: f.mx, my: f.my, mw: f.w, mh: f.h, x: 0, y: -(224 - f.h * 8), wrap: false, show: true });
  bg(1, { mx: h.mx, my: h.my, mw: h.w, mh: h.h, x: 0, y: -(224 - f.h * 8 - h.h * 8 + 8), wrap: false, show: true });
  blend({ layers: ['overlay'], half: true }); // overlay colours from 192 up (ART.colors.GLASS) are see-through
  if (skipTitle) startGame(); else toTitle();
}

function toTitle() { state = 'title'; timer = 0; titleSel = 0; paused = false; play(SONG.title); }

function startGame() {
  score = 0; balls = 3; flips = makeFlippers(); serve(); paused = false; timer = 0; state = 'play';
  play(SONG.play);
}

/** A new ball in the plunger lane. */
function serve() {
  ball = { x: BALL_HOME.x, y: BALL_HOME.y, vx: 0, vy: 0 }; plunge = 0;
  camY = clamp(ball.y - 150, 0, TABLE_H - VIEW_H);
}
const inLane = () => ball.x > LANE_X && ball.y > LANE_FLOOR - 40;

// --- Update ---

function update() {
  inputMask = readPad(); clock++;
  if (!paused) timer++; // a state's clock: it stands still while paused
  if (paused) updatePause();
  else if (state === 'title') updateTitle();
  else if (state === 'play') updatePlay();
  else if (state === 'over') updateOver();
  else if (state === 'initials') updateInitials();
  else if (state === 'records') updateRecords();
  prevMask = inputMask;
}

function updateTitle() {
  if (pressed(UP) || pressed(DOWN)) { titleSel ^= 1; fx(SFX.move); }
  if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (titleSel === 0) startGame(); else { state = 'records'; hl = -1; timer = 0; }
  }
}

/** The game: the flippers, the plunger and the ball. */
function updatePlay() {
  if (pressed(START)) { paused = true; pauseSel = 0; fx(SFX.pause); return; }
  held = [PAD_LEFT.some((k) => btn(k)), PAD_RIGHT.some((k) => btn(k))];
  if (!inLane() && PAD_LEFT.concat(PAD_RIGHT).some((k) => pressed(k))) fx(SFX.move);
  const waiting = inLane() && ball.vy >= 0 && ball.y >= BALL_HOME.y - 1;
  if (waiting && (held[0] || held[1])) plunge = Math.min(1, plunge + 1 / PLUNGE_FRAMES);
  else if (waiting && plunge > 0.04) { ball.vy = -(4 + 10 * plunge); plunge = 0; fx(SFX.point); }
  else if (!waiting) plunge = 0;
  stepTable(ball, flips, held);
  const want = clamp(ball.y - 150, 0, TABLE_H - VIEW_H);
  camY += (want - camY) * 0.12;
  if (ball.y > DRAIN_Y && ball.x < LANE_X) drain();
}

function drain() {
  fx(SFX.hit); balls--;
  if (balls <= 0) gameOver(); else serve();
}

function gameOver() {
  state = 'over'; timer = 0; play(-1); fx(SFX.over);
  rank = insertTop({ score, initials: lastInitials() });
}

function updateOver() {
  if (timer < 60 || !(pressed(A) || pressed(START))) return;
  fx(SFX.select);
  if (rank >= 0) { state = 'initials'; timer = 0; initials = { chars: lastInitials().split(''), pos: 0 }; fx(SFX.record); }
  else toTitle();
}

/** UP/DOWN pick a letter, LEFT/RIGHT (or A and B) move, START saves (as does A on the last letter). */
function updateInitials() {
  const ini = initials, k = LETTERS.indexOf(ini.chars[ini.pos]);
  if (pressed(UP)) { ini.chars[ini.pos] = LETTERS[(k + 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(DOWN)) { ini.chars[ini.pos] = LETTERS[(k + LETTERS.length - 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(LEFT) || pressed(B)) ini.pos = Math.max(0, ini.pos - 1);
  if (pressed(RIGHT)) ini.pos = Math.min(2, ini.pos + 1);
  const done = pressed(START) || (pressed(A) && ini.pos === 2);
  if (pressed(A) && ini.pos < 2) ini.pos++;
  if (!done || timer < 20) return;
  const v = packInitials(ini.chars.join(''));
  dset(INITIALS_SLOT, v); dset(TOP_SLOT + rank * ENTRY + 1, v);
  fx(SFX.select);
  state = 'records'; hl = rank; timer = 0;
}

function updateRecords() {
  if ((pressed(START) || pressed(A) || pressed(B)) && timer > 20) { fx(SFX.select); toTitle(); }
}

function updatePause() {
  if (pressed(UP)) { pauseSel = (pauseSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { pauseSel = (pauseSel + 1) % 3; fx(SFX.move); }
  if (pressed(B) || (pressed(START) && pauseSel === 0)) { paused = false; fx(SFX.pause); }
  else if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (pauseSel === 0) paused = false;
    else if (pauseSel === 1) startGame(); // restart
    else toTitle(); // quitting abandons the game: nothing is recorded
  }
}

// --- Draw ---

function draw() {
  cls();
  if (state === 'play' || state === 'over') drawPlay();
  else if (state === 'title') drawTitle();
  else if (state === 'initials') drawInitials();
  else if (state === 'records') drawRecords();
  if (state === 'over') { panel(48, 80, 160, 64); ctxt('GAME OVER', 92, RED); ctxt(`SCORE ${score}`, 108, WHITE); if (timer > 60 && timer % 60 < 40) ctxt('START: CONTINUE', 126, DIM); }
  if (paused) drawPause();
}

function drawPlay() {
  rectfill(0, 0, 256, 224, 2);
  const cy = Math.round(camY), sy = (y) => Math.round(y - cy);
  for (const w of WALLS) line(Math.round(w[0]), sy(w[1]), Math.round(w[2]), sy(w[3]), WHITE);
  for (const f of flips) {
    const tip = flipTip(f);
    for (let i = 0; i <= 8; i++) circfill(Math.round(f.x + (tip.x - f.x) * i / 8), sy(f.y + (tip.y - f.y) * i / 8), FR, GOLD);
  }
  if (inLane()) rectfill(LANE_X + 6, sy(LANE_FLOOR - 4 + plunge * 14), 8, 4, DIM); // the plunger, pulled back
  circfill(Math.round(ball.x), sy(ball.y), BR, WHITE);
  rectfill(TABLE_W, 0, 256 - TABLE_W, 224, SHADOW);
  txt('SCORE', 198, 8, DIM); txt(String(score), 252 - String(score).length * 8, 18, WHITE);
  txt('BALL', 198, 40, DIM); txt(String(4 - balls), 198, 50, balls > 1 ? WHITE : RED);
}

function drawTitle() {
  ctxt('STAR CADET PINBALL', 50, GOLD);
  ['PLAY', 'RECORDS'].forEach((s, i) => txt(`${i === titleSel ? '> ' : '  '}${s}`, 96, 100 + i * 14, i === titleSel ? WHITE : DIM));
}

function drawRecords() {
  panel(24, 16, 208, 192);
  ctxt('TOP 10', 24, GOLD);
  topTen().forEach((e, i) => {
    const y = 48 + i * 14, on = i === hl;
    if (on && timer % 40 < 30) rectfill(28, y - 2, 200, 12, PANEL);
    txt(String(i + 1).padStart(2), 40, y, i === 0 ? GOLD : DIM);
    txt(e.score ? e.initials : '---', 72, y, on ? GOLD : WHITE);
    txt(e.score ? String(e.score).padStart(8) : '', 128, y, i === 0 ? GOLD : WHITE);
  });
  if (timer % 60 < 40) ctxt('START: BACK', 192, DIM);
}

function drawInitials() {
  const ini = initials;
  panel(24, 40, 208, 144);
  ctxt(rank === 0 ? 'NEW HIGH SCORE!' : `TOP 10: #${rank + 1}`, 52, GOLD);
  ctxt(String(score), 68, WHITE);
  ctxt('ENTER YOUR INITIALS', 90, DIM);
  for (let i = 0; i < 3; i++) {
    const on = i === ini.pos, x = 84 + i * 32;
    rect(x - 2, 106, 28, 20, on ? GOLD : PANEL);
    txt(ini.chars[i], x + 10, 112, on ? GOLD : WHITE);
  }
  if (timer % 60 < 40) ctxt('START: SAVE', 160, WHITE);
}

function drawPause() {
  panel(64, 80, 128, 64);
  ctxt('PAUSED', 88, GOLD);
  ['RESUME', 'RESTART', 'QUIT TO TITLE'].forEach((s, i) => txt(`${i === pauseSel ? '>' : ' '} ${s}`, 76, 104 + i * 10, i === pauseSel ? WHITE : DIM));
}

function panel(x, y, w, h) { rectfill(x, y, w, h, ART.colors.GLASS); rect(x, y, w, h, PANEL); }
function txt(s, x, y, c) { print(s, x + 1, y + 1, SHADOW); print(s, x, y, c); }
const ctxt = (s, y, c) => txt(s, 128 - s.length * 4, y, c);

/** Each line of the screen: the sky's colour for that line (the SNES did its skies this way, with HDMA). */
function scanline(y) { gradientLine(ART.gradients.sky, y); }
