// The Ivory Tower
// Scaffolded by tools/new-cart.js. A tiny working game (dodge the falling blocks) around everything every cart
// needs: a title, play, pause, game over, a saved top 10 with initials, a records screen, sound and music cues,
// a skipTitle hook and save slots. Replace the play part, keep the frame. See docs/dev/playbook.md.

// --- Colours: the default palette (DawnBringer 16). The overlay's index 0 is transparent. ---

const SHADOW = 1, PANEL = 3, RED = 6, DIM = 10, GREEN = 11, CYAN = 13, GOLD = 14, WHITE = 15;

// --- Art: made by art.py (tiles.txt, palette.txt, map.txt). The block below is rewritten each time it runs. ---

// ART (generated by art.py: do not edit)
const ART = {
  tiles: {},
  sprites: {},
  scenes: {"clouds": {"h": 24, "mx": 32, "my": 0, "pal": 2, "w": 32}, "landmarks": {"h": 77, "mx": 0, "my": 0, "pal": 1, "w": 32}, "stars": {"h": 28, "mx": 64, "my": 0, "pal": 3, "w": 32}},
  colors: {"GLASS": 200},
};
// END ART
/** Queue one of ART.sprites at (x, y), above the background; opts as for spr (fx, fy ...). */
function sprite(s, x, y, opts = {}) { spr(s.tile, x, y, { size: s.size, pal: s.pal, prio: 3, ...opts }); }

// --- Sound (SPEC 5). Any channel plays any instrument. Songs use channels 0 to 5; effects take turns on 6 and 7, ---
// so they never cut into the music and two can sound at once.

const SFX = { move: 0, select: 1, pause: 2, miss: 3, over: 4, tick: 5, record: 6, thudNarrow: 7, thudMid: 8, thudWide: 9, slice: 10, regrow: 11, landmark: 12, best: 13, chime: 14 };   // chime: 20 of them, 14 to 33 (the ladder, then an octave up)
const SONG = { title: 0, floors0: 1, floors20: 2, floors40: 3 };   // the climb's music gains a layer at floors 20 and 40 (a landmark)
const songFor = (n) => (n >= 40 ? SONG.floors40 : n >= 20 ? SONG.floors20 : SONG.floors0);
const SFX_CH = [7, 6];
let fxNext = 0;
function fx(n) { sfx(n, SFX_CH[fxNext]); fxNext ^= 1; }

// A song is only started if it is not already playing.
let playing = -1;
function play(song) {
  if (song === playing) return;
  playing = song; music(song);
}

// --- Save slots (SPEC 13) ---

const VERSION_SLOT = 0, SAVE_VERSION = 2, BEST_SLOT = 1, GAMES_SLOT = 2, INITIALS_SLOT = 3; // the best height (floors), games played, the last initials
const TOP_SLOT = 10, TOP_N = 10, ENTRY = 3; // the top 10, best first: floors, initials, points (slots 10 to 39)
const LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';

function readEntry(i) { const s = TOP_SLOT + i * ENTRY; return { floors: dget(s), initials: unpackInitials(dget(s + 1)), points: dget(s + 2) }; }
function writeEntry(i, e) { const s = TOP_SLOT + i * ENTRY; dset(s, e.floors); dset(s + 1, packInitials(e.initials)); dset(s + 2, e.points); }
const topTen = () => Array.from({ length: TOP_N }, (_, i) => readEntry(i));

/** Put a run into the top 10 if it makes it (more floors, then more points). Returns its row, or -1. */
function insertTop(e) {
  if (!e.floors) return -1;
  const list = topTen(), at = list.findIndex((x) => e.floors > x.floors || (e.floors === x.floors && e.points > x.points));
  if (at < 0) return -1;
  list.splice(at, 0, e);
  for (let i = at; i < TOP_N; i++) writeEntry(i, list[i]);
  return at;
}
/** Three characters, 8 bits each. */
const packInitials = (str) => (str.charCodeAt(0) << 16) | (str.charCodeAt(1) << 8) | str.charCodeAt(2);
const unpackInitials = (v) => (v ? String.fromCharCode((v >> 16) & 255, (v >> 8) & 255, v & 255) : '---');
const lastInitials = () => (dget(INITIALS_SLOT) ? unpackInitials(dget(INITIALS_SLOT)) : 'AAA');

// --- Input: edge-triggered presses (btnp repeats; menus want one press) ---

let inputMask = 0, prevMask = 0;
const BUTTONS = [UP, DOWN, LEFT, RIGHT, A, B, X, Y, L, R, START, SELECT];
function readPad() { let m = 0; for (const b of BUTTONS) if (btn(b)) m |= 1 << b; return m; }
const pressed = (b) => (inputMask & (1 << b)) !== 0 && (prevMask & (1 << b)) === 0;

// --- State ---

let demo = false, idle = 0, titleTower = [], demoAim = null; // the demo: the game playing itself on the title's idle; the title's own tower
let skipTitle = false; // tests set this to land straight in the game
let state = 'title', paused = false, timer = 0, clock = 0;
let titleSel = 0, pauseSel = 0, rank = -1, hl = -1, initials = null;
// --- The tower and its rules (SPEC 5). Pixels and pixels a frame; the numbers are here, in one place, because only playing can set them. ---

const SLAB_H = 8, BASE_W = 96, CENTRE = 128, REACH = 110; // a slab is 8 px thick; the first is 96 wide; a slab's centre slides over CENTRE +- REACH
const PERFECT = 4, MIN_OVERLAP = 2, REGROW = 4, REGROW_FROM = 3; // a drop within 4 px is perfect; the third perfect in a row starts to give width back, 4 px each
const SPEED0 = 1.6, SPEED_STEP = 0.04, SPEED_MAX = 4.8; // the slide's speed at floor 0, how much each floor adds, and its limit
const BASE_Y = 176, TOP_Y = 140; // the screen y of the base slab's top at the start, and of the top slab's top once the tower is tall
const COUNT_IN = 60, FALL_FRAMES = 50, GRAVITY = 0.25; // frames before the first slab; a missed slab falls this long before the game is over
const POINTS_FLOOR = 10, POINTS_PERFECT = 10, PERFECT_CAP = 10, POINTS_LANDMARK = 100; // a floor, each perfect (times the run, up to the cap), a landmark
const METRES = 3, LADDER = 10; // a floor is 3 m; the perfect chime climbs a ladder of 10 notes, then repeats an octave higher
let bestAtStart = 0;

let floors = 0, tower = [], slab = null, slices = [], run = 0, bestRun = 0, perfects = 0, cam = 0, points = 0, newBest = false;
let rings = [], sparks = []; // the perfect's ring (one for each perfect, a few frames) and its sparkles
const speed = (n = floors) => Math.min(SPEED_MAX, SPEED0 + SPEED_STEP * n);
/** The perfect's chime for a run of n: the note on a ladder of 10 (a pentatonic scale), and 1 for the repeat an octave higher after the tenth. */
const chimeNote = (n) => (n - 1) % LADDER, chimeOctave = (n) => Math.min(1, Math.floor((n - 1) / LADDER));
const DROP_BUTTONS = [UP, DOWN, LEFT, RIGHT, A, B, X, Y];
const dropped = () => DROP_BUTTONS.some((b) => pressed(b)); // a drop is a new press of any of these (a held button does not drop the next slab)

function init() {
  if (dget(VERSION_SLOT) !== SAVE_VERSION) { // a new or older save: start clean
    for (let i = 0; i < 256; i++) dset(i, 0);
    dset(VERSION_SLOT, SAVE_VERSION);
  }
  // The sky is a gradient set in scanline() from the camera's height; the landmarks, clouds and stars are layers 0, 1 and 2; the tower is drawn on the overlay.
  marbleColors();
  blend({ layers: ['overlay', 'bg1'], half: true });                   // the clouds are see-through, and so is the glass // overlay colours from 192 up (ART.colors.GLASS) are see-through
  if (skipTitle) startGame(); else toTitle();
}

const TITLE_LIFT = 40, IDLE_FRAMES = 20 * 60; // the demo starts after 20 seconds without a button on the title

function toTitle() {
  state = 'title'; timer = 0; titleSel = 0; paused = false; demo = false; idle = 0; slab = null; slices = []; rings = []; sparks = []; banner = null;
  cam = -TITLE_LIFT;                                       // the title has the tower higher up the screen, with room for the menu below
  play(SONG.title);
  const n = Math.max(5, Math.min(9, dget(BEST_SLOT)));  // the title shows a tower as high as the best (5 to 9 floors), a little off true like a person's
  titleTower = [{ x: CENTRE - BASE_W / 2, w: BASE_W, ox: CENTRE - BASE_W / 2 }];
  for (let k = 1; k <= n; k++) {
    const t = titleTower[k - 1], d = Math.round((hash(k, 77) - 0.5) * 16), cut = Math.abs(d) <= PERFECT ? 0 : Math.abs(d);
    titleTower.push(cut ? { x: Math.max(t.x, t.x + d), w: Math.max(40, t.w - cut), ox: t.x + d } : { x: t.x, w: Math.min(BASE_W, t.w + 3), ox: t.x });
  }
}

function startGame(isDemo = false) {
  demo = isDemo; demoAim = null;
  floors = 0; points = 0; run = 0; bestRun = 0; perfects = 0; slices = []; cam = 0; newBest = false; bestAtStart = dget(BEST_SLOT);
  tower = [{ x: CENTRE - BASE_W / 2, w: BASE_W, ox: CENTRE - BASE_W / 2 }];       // the base slab, centred
  rings = []; sparks = []; banner = null;
  slab = null; paused = false; timer = 0; state = 'play';
  if (!demo) play(SONG.floors0);
}

/** The next slab: as wide as the top of the tower, from the left side on even floors and the right on odd ones. */
function nextSlab() {
  const w = tower[tower.length - 1].w, left = floors % 2 === 0;
  slab = { x: (left ? CENTRE - REACH : CENTRE + REACH) - w / 2, w, dir: left ? 1 : -1 };
}

/** Put the slab down where it is: the overlap with the top of the tower stays (and a perfect keeps the whole), the rest is sliced off; no overlap is a miss. */
function drop() {
  const top = tower[tower.length - 1], sy = screenY(floors + 1);
  const L = Math.max(slab.x, top.x), R = Math.min(slab.x + slab.w, top.x + top.w), ov = R - L;
  if (ov < MIN_OVERLAP) { slab.fall = 0; slab.vy = 0; state = 'fall'; timer = 0; fx(SFX.miss); return false; }
  let nx, nw, perfect = false, grew = false;
  if (Math.abs(slab.x - top.x) <= PERFECT) {              // dead on: the slab takes the place of the one below
    perfect = true; nx = top.x; nw = top.w; run++; perfects++; bestRun = Math.max(bestRun, run);
    if (run >= REGROW_FROM && nw < BASE_W) { const g = Math.min(REGROW, BASE_W - nw); nx -= g / 2; nw += g; grew = true; }
    points += POINTS_PERFECT * Math.min(run, PERFECT_CAP);
    fx(SFX.chime + 10 * chimeOctave(run) + chimeNote(run));
    if (grew) fx(SFX.regrow);
  } else {                                                // sliced: what overhangs falls away
    nx = L; nw = ov; run = 0;
    const piece = (x, w, side) => slices.push({ k: floors + 1, x, w, ox: slab.x, y: sy, vx: slab.dir * speed() * 0.5, vy: 0, rot: 0, spin: side * (0.03 + 0.02 * hash(floors, 9)) });
    if (slab.x < L) piece(slab.x, L - slab.x, -1);
    if (slab.x + slab.w > R) piece(R, slab.x + slab.w - R, 1);
    fx(ov >= 64 ? SFX.thudWide : ov >= 32 ? SFX.thudMid : SFX.thudNarrow); fx(SFX.slice);
  }
  tower.push({ x: nx, w: nw, ox: slab.x }); floors++; points += POINTS_FLOOR;
  if (perfect) shine(floors, nx, nw);
  if (floors % 10 === 0 && floors <= 60) reach(floors / 10);
  else if (!newBest && bestAtStart > 0 && floors > bestAtStart) beatBest();
  slab = null;
  nextSlab();
  return true;
}

/** The screen y of the top of floor k (floor 0 is the base slab): the camera scrolls once the tower is tall enough. */
function screenY(k) { return BASE_Y - (k * SLAB_H - cam); }

// --- Update ---

function update() {
  inputMask = readPad(); clock++;
  if (!paused) timer++; // a state's clock: it stands still while paused
  if (paused) updatePause();
  else if (state === 'title') updateTitle();
  else if (state === 'play' || state === 'fall') updatePlay();
  else if (state === 'over') updateOver();
  else if (state === 'initials') updateInitials();
  else if (state === 'records') updateRecords();
  skyUpdate();
  prevMask = inputMask;
}

function updateTitle() {
  if (inputMask !== prevMask) idle = 0; else if (++idle >= IDLE_FRAMES) { startGame(true); return; }
  if (pressed(SELECT)) { fx(SFX.select); state = 'records'; hl = -1; timer = 0; return; }
  if (pressed(UP) || pressed(DOWN)) { titleSel ^= 1; fx(SFX.move); }
  if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (titleSel === 0) startGame(); else { state = 'records'; hl = -1; timer = 0; }
  }
}

/** The game: wait a second, then a slab slides and is dropped with a press; a miss lets the slab fall. */
function updatePlay() {
  if (demo && (inputMask & ~prevMask)) { toTitle(); return; }   // any new press ends the demo
  if (!demo && pressed(START)) { paused = true; pauseSel = 0; fx(SFX.pause); return; }
  if (state === 'fall') { updateFall(); return; }
  if (!slab && !demo && floors === 0 && timer < COUNT_IN && timer % 20 === 1) fx(SFX.tick);   // the count-in ticks 3, 2, 1
  if (!slab && timer >= (demo ? 20 : COUNT_IN)) nextSlab();
  if (slab) {
    slab.x += slab.dir * speed();                           // slides across and turns at the end of its reach
    const c = slab.x + slab.w / 2;
    if (c > CENTRE + REACH) { slab.x = CENTRE + REACH - slab.w / 2; slab.dir = -1; } else if (c < CENTRE - REACH) { slab.x = CENTRE - REACH - slab.w / 2; slab.dir = 1; }
    if (demo ? demoWants() : dropped()) drop();
  }
  updateSlices(); updateShine();
  const want = Math.max(0, floors * SLAB_H - (BASE_Y - TOP_Y));
  cam += (want - cam) * 0.15;                               // the camera follows, eased
}

/** The demo's player: aims at the top of the tower with an error of a few pixels (so it fumbles and ends in a while), and drops when the slab gets there. */
function demoWants() {
  const t = tower[tower.length - 1];
  if (!demoAim || demoAim.of !== slab) demoAim = { of: slab, err: (rnd() + rnd() + rnd() - 1.5) * 9 };
  return Math.abs(slab.x - (t.x + demoAim.err)) <= speed() / 2 + 0.5;
}

/** The slab that missed falls past the tower; then the game is over. */
function updateFall() {
  const s = slab; s.vy += GRAVITY; s.x += s.dir * speed() * 0.5; s.fall += s.vy;
  updateSlices(); updateShine();
  if (++timer > FALL_FRAMES) gameOver();
}

function updateSlices() {
  for (const p of slices) { p.vy += GRAVITY; p.x += p.vx; p.y += p.vy; p.rot += p.spin; }
  slices = slices.filter((p) => p.y < 260);
}

function gameOver() {
  if (demo) { toTitle(); return; }                           // the demo records nothing
  state = 'over'; timer = 0; slab = null; banner = null; play(-1); fx(SFX.over);
  rank = insertTop({ floors, points, initials: lastInitials() });
  dset(GAMES_SLOT, dget(GAMES_SLOT) + 1);
  if (floors > dget(BEST_SLOT)) { dset(BEST_SLOT, floors); newBest = true; }
}

/** The camera flies back down the tower to the courtyard (the sky and the landmarks go by), then the result shows. */
function updateOver() {
  updateSlices(); updateShine();
  if (timer > 20 && cam > 0) cam = Math.max(0, cam - Math.max(3, cam * 0.05));
  if (timer < 60 || cam > 0 || !(pressed(A) || pressed(START))) return;
  fx(SFX.select);
  if (rank >= 0) { state = 'initials'; timer = 0; initials = { chars: lastInitials().split(''), pos: 0 }; fx(SFX.record); }
  else toTitle();
}

/** UP/DOWN pick a letter, LEFT/RIGHT (or A and B) move, START saves (as does A on the last letter). */
function updateInitials() {
  const ini = initials, k = LETTERS.indexOf(ini.chars[ini.pos]);
  if (pressed(UP)) { ini.chars[ini.pos] = LETTERS[(k + 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(DOWN)) { ini.chars[ini.pos] = LETTERS[(k + LETTERS.length - 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(LEFT) || pressed(B)) ini.pos = Math.max(0, ini.pos - 1);
  if (pressed(RIGHT)) ini.pos = Math.min(2, ini.pos + 1);
  const done = pressed(START) || (pressed(A) && ini.pos === 2);
  if (pressed(A) && ini.pos < 2) ini.pos++;
  if (!done || timer < 20) return;
  const v = packInitials(ini.chars.join(''));
  dset(INITIALS_SLOT, v); dset(TOP_SLOT + rank * ENTRY + 1, v);
  fx(SFX.select);
  state = 'records'; hl = rank; timer = 0;
}

function updateRecords() {
  if ((pressed(START) || pressed(A) || pressed(B)) && timer > 20) { fx(SFX.select); toTitle(); }
}

function updatePause() {
  if (pressed(UP)) { pauseSel = (pauseSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { pauseSel = (pauseSel + 1) % 3; fx(SFX.move); }
  if (pressed(B) || (pressed(START) && pauseSel === 0)) { paused = false; fx(SFX.pause); }
  else if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (pauseSel === 0) paused = false;
    else if (pauseSel === 1) startGame(); // restart
    else toTitle(); // quitting abandons the game: nothing is recorded
  }
}

// --- Draw ---

function draw() {
  cls();
  if (state === 'play' || state === 'fall' || state === 'over') drawPlay();
  else if (state === 'title') drawTitle();
  else if (state === 'initials') drawInitials();
  else if (state === 'records') drawRecords();
  if (state === 'over' && cam <= 0 && timer >= 60) {
    panel(40, 60, 176, 104); ctxt('GAME OVER', 70, RED); ctxt(`${floors} FLOORS  ${floors * METRES} M`, 88, WHITE); ctxt(`${points} POINTS`, 102, DIM);
    ctxt(newBest ? 'NEW BEST!' : `BEST ${dget(BEST_SLOT)}`, 118, newBest ? GOLD : DIM);
    if (timer % 60 < 40) ctxt('START: CONTINUE', 144, WHITE);
  }
  if (paused) drawPause();
}

// --- The sky and the landmarks (SPEC 5, 12) ---

// Seven skies, one for each stretch of ten floors: [the top of the screen, the horizon], as 0-31 colours. A sky holds for the first five
// floors of its stretch and blends into the next over the last five.
const SKIES = [
  [[12, 18, 28], [31, 22, 19]],   // 0 The Courtyard: dawn, a pink horizon under a pale blue
  [[7, 15, 28], [19, 26, 31]],    // 1 The Balcony: morning blue
  [[4, 12, 27], [13, 23, 31]],    // 2 The Colonnade: bright day
  [[2, 6, 20], [8, 17, 29]],      // 3 The Dome: deep blue above
  [[7, 5, 17], [31, 17, 7]],      // 4 The Belfry: sunset, orange into purple
  [[2, 2, 10], [20, 9, 17]],      // 5 The Spire: dusk
  [[0, 0, 4], [3, 3, 13]],        // 6 The Stars: night
];
const LANDMARKS = ['THE COURTYARD', 'THE BALCONY', 'THE COLONNADE', 'THE DOME', 'THE BELFRY', 'THE SPIRE', 'THE STARS'];
const BANNER_FRAMES = 120;
const SIL = 17, CLOUD = 33, STAR = 49, MOON = 52;   // CGRAM entries of art.py's BG palettes 1 (the landmarks), 2 (clouds) and 3 (stars, moon)
const INK = [4, 5, 12], GOLDEN = [31, 26, 10], WHITE3 = [31, 31, 31];

let skyLines = new Int16Array(224 * 3), banner = null;
const mix = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];
const setColor = (i, c) => color(i, Math.round(c[0]), Math.round(c[1]), Math.round(c[2]));
const clamp01 = (v) => Math.max(0, Math.min(1, v));
/** The camera's height in floors (0 at the start; the top slab is 4.5 floors above the camera's bottom edge once it has scrolled). */
const climb = () => (state === 'title' ? 7 : cam / SLAB_H + 4.5 * Math.min(1, cam / (BASE_Y - TOP_Y)));   // the title looks at a morning sky with clouds

/** The sky at height h (in floors): its top and horizon colours, how dark it is (stars), how bright (clouds). */
function skyAt(h) {
  const i = Math.max(0, Math.min(6, Math.floor(h / 10))), b = i < 6 ? clamp01((h - 10 * i - 5) / 5) : 0, n = SKIES[Math.min(6, i + 1)];
  return {
    top: mix(SKIES[i][0], n[0], b), bot: mix(SKIES[i][1], n[1], b),
    stars: clamp01((h - 48) / 12),                            // the first stars at dusk, all of them by floor 60
    day: Math.max(0.12, Math.min(1, 1 - (h - 38) / 14)),      // how bright the clouds are: dim from the sunset on
    clouds: clamp01((h - 4) / 6),                             // clouds come in from floor 4
  };
}

/** Each frame, from the camera: the gradient of the sky line by line, the colours of the landmarks, clouds and stars, and the three layers. */
function skyUpdate() {
  const h = climb(), k = skyAt(h);
  for (let y = 0; y < 224; y++) {
    const t = Math.pow(y / 223, 1.35);
    skyLines[y * 3] = Math.round(k.top[0] + (k.bot[0] - k.top[0]) * t); skyLines[y * 3 + 1] = Math.round(k.top[1] + (k.bot[1] - k.top[1]) * t); skyLines[y * 3 + 2] = Math.round(k.top[2] + (k.bot[2] - k.top[2]) * t);
  }
  const haze = mix(k.bot, k.top, 0.25);                       // the landmarks are the horizon's colour, darker the nearer they are
  setColor(SIL, mix(haze, INK, 0.28)); setColor(SIL + 1, mix(haze, INK, 0.52)); setColor(SIL + 2, mix(haze, INK, 0.78));
  setColor(SIL + 3, mix(haze, WHITE3, 0.45)); setColor(SIL + 4, mix(mix(haze, INK, 0.52), GOLDEN, 0.25 + 0.75 * k.stars));
  const cl = (w) => mix(k.bot, WHITE3, w * k.day);            // the clouds take the light of the sky: white by day, rosy at sunset, dim at night
  [0.5, 0.7, 0.88, 1].forEach((w, j) => setColor(CLOUD + j, mix(k.bot, cl(w), clamp01(k.clouds))));
  const tw = 0.7 + 0.3 * Math.sin(clock * 0.09);              // the stars twinkle together, a little
  setColor(STAR, mix(k.top, WHITE3, 0.35 * k.stars)); setColor(STAR + 1, mix(k.top, WHITE3, 0.7 * k.stars * tw)); setColor(STAR + 2, mix(k.top, WHITE3, k.stars));
  [0.2, 0.45, 0.7, 0.9, 1].forEach((w, j) => setColor(MOON + j, mix(k.top, WHITE3, w * Math.max(k.stars, 0.001) * 0.95)));
  bg(0, { mx: 0, my: 0, mw: 32, mh: 77, x: 0, y: 352 - Math.round(cam), wrap: false, show: true });
  bg(1, { mx: 32, my: 0, mw: 32, mh: 24, x: Math.round(clock * 0.12), y: -Math.round(cam * 0.5), wrap: true, show: k.clouds > 0.02 });
  bg(2, { mx: 64, my: 0, mw: 32, mh: 28, x: 0, y: -Math.round((1 - k.stars) * 170), wrap: false, show: k.stars > 0.02 });   // the moon rises with the dark
}

/** A landmark is reached: the banner for two seconds and a chime. */
function reach(k) { banner = { k, top: `FLOOR ${k * 10}`, name: LANDMARKS[k], t: 0 }; points += POINTS_LANDMARK; fx(SFX.landmark); play(songFor(floors)); }
/** Past the best height of the games before: said once. */
function beatBest() { newBest = true; banner = { k: -1, top: `${floors} FLOORS`, name: 'NEW BEST!', t: 0 }; fx(SFX.best); }
function drawBanner() {
  if (!banner) return;
  const t = banner.t++, slide = Math.round(40 * (1 - clamp01(t / 12))) + Math.round(40 * clamp01((t - BANNER_FRAMES + 12) / 12));
  if (t >= BANNER_FRAMES) { banner = null; return; }
  panel(36, 46 - slide, 184, 34); ctxt(banner.top, 52 - slide, DIM); ctxt(banner.name, 64 - slide, GOLD);
}

// --- The marble (SPEC 5, 12): a slab is drawn from its floor number each frame, so no picture is stored and any width is cheap. ---

// Five marbles, a new one every 10 floors. Each has 8 colours in CGRAM from MARBLE_BASE (the overlay addresses CGRAM directly):
// 0 shadow, 1 stone, 2 light stone, 3 highlight, 4 faint vein, 5 strong vein, 6 gloss, 7 spare.
const MARBLE_BASE = 144, RING = 208;
const MARBLES = [
  [[17, 17, 19], [26, 26, 25], [29, 29, 28], [31, 31, 30], [21, 21, 23], [13, 13, 17], [31, 31, 31]],     // Carrara: white, grey veins
  [[3, 8, 6], [6, 15, 10], [9, 20, 14], [13, 24, 17], [14, 23, 17], [24, 30, 24], [26, 31, 27]],         // Verde: deep green, pale veins
  [[1, 1, 2], [4, 4, 5], [8, 8, 9], [13, 13, 14], [14, 11, 4], [28, 22, 6], [20, 20, 22]],               // Nero: black, gold veins
  [[19, 11, 13], [27, 19, 20], [30, 23, 23], [31, 27, 26], [29, 24, 24], [31, 30, 29], [31, 31, 30]],    // Rosa: pink, white veins
  [[4, 8, 16], [8, 13, 24], [12, 18, 28], [17, 23, 30], [18, 22, 29], [26, 29, 31], [29, 31, 31]],       // Azul: blue, silver veins
];
function marbleColors() {
  MARBLES.forEach((m, i) => m.forEach((c, j) => color(MARBLE_BASE + i * 8 + j, c[0], c[1], c[2])));
  color(RING, 31, 28, 12);                                       // the ring: gold, see-through (an overlay colour from 192 up)
}
const marbleOf = (k) => Math.floor(k / 10) % MARBLES.length;

/** A number from 0 up to 1 from two integers: the same every time (the veins of a floor never change). */
function hash(a, b) {
  let h = Math.imul(a + 1, 374761393) + Math.imul(b + 7, 668265263) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}

/** Floor k's slab with its left edge at x, w wide, top at y. The veins and the gloss hang on ox (where the slab was
 * before any slicing), so a cut slab keeps its pattern; rows r0 to r1 only (a sheared slice draws it row by row). */
function drawSlab(k, x, y, w, ox, r0 = 0, r1 = SLAB_H) {
  x = Math.round(x); y = Math.round(y); w = Math.round(w); ox = Math.round(ox);
  if (w < 1) return;
  const c = MARBLE_BASE + marbleOf(k) * 8;
  clip(x, y + r0, w, r1 - r0);
  rectfill(x, y, w, SLAB_H, c + 1);                              // the stone
  rectfill(x, y + 1, w, 2, c + 2);                               // lit from above
  const n = 3 + Math.floor(hash(k, 1) * 3);
  for (let j = 0; j < n; j++) {                                  // veins: a few slanted lines, some strong, some faint
    const u = hash(k, 10 + j) * (BASE_W + 20) - 10, dx = Math.round((hash(k, 20 + j) - 0.5) * 12), strong = hash(k, 30 + j) > 0.5;
    line(ox + u, y + 1, ox + u + dx, y + SLAB_H - 2, strong ? c + 5 : c + 4);
    if (strong) line(ox + u + 1, y + 1, ox + u + dx + 1, y + SLAB_H - 2, c + 4);
  }
  rectfill(x, y, w, 1, c + 3);                                   // the bevel: a bright top edge, a shadow below, a bright left end, a dark right end
  rectfill(x, y + SLAB_H - 1, w, 1, c);
  rectfill(x, y, 1, SLAB_H, c + 3); rectfill(x + w - 1, y + 1, 1, SLAB_H - 1, c);
  const g = ox + hash(k, 50) * (BASE_W - 24) + 8;                // a streak of gloss
  line(g, y + 5, g + 4, y + 1, c + 6);
  clip();
}

/** A slice tumbling: sheared, a row at a time. */
function drawSlice(p) {
  const sh = Math.max(-1.2, Math.min(1.2, p.rot));
  for (let r = 0; r < SLAB_H; r++) { const d = Math.round(sh * (r - 3.5)); drawSlab(p.k, p.x + d, p.y, p.w, p.ox + d, r, r + 1); }
}

/** The perfect's ring, spreading from the slab, and the sparkles that rise from it. */
function shine(k, x, w) {
  rings.push({ k, x, w, t: 0 });
  for (let i = 0; i < 5; i++) sparks.push({ k, x: x + (0.1 + 0.8 * hash(k * 5 + i, run)) * w, dy: -2, vy: -0.6 - hash(i, k) * 0.6, vx: (hash(i, k + 3) - 0.5) * 0.8, t: 0 });
}
function updateShine() {
  for (const r of rings) r.t++;
  rings = rings.filter((r) => r.t < 18);
  for (const s of sparks) { s.t++; s.x += s.vx; s.dy += s.vy; s.vy += 0.02; }
  sparks = sparks.filter((s) => s.t < 34);
}
function drawShine() {
  for (const r of rings) { const e = Math.round(r.t * 0.6), y = Math.round(screenY(r.k)); rect(Math.round(r.x) - e - 1, y - e - 1, Math.round(r.w) + 2 * e + 2, SLAB_H + 2 * e + 2, RING); }
  for (const s of sparks) {
    const x = Math.round(s.x), y = Math.round(screenY(s.k) + s.dy), c = s.t > 22 && s.t % 4 < 2 ? GOLD : WHITE;
    rectfill(x - 1, y, 3, 1, c); rectfill(x, y - 1, 1, 3, c);
  }
}

/** The steps the tower stands on (the courtyard is layer 0), and its floors. */
function drawTower(list) {
  const by = screenY(0) + SLAB_H;
  if (by < 224) { drawSlab(0, CENTRE - 60, by, 120, CENTRE - 60); drawSlab(0, CENTRE - 76, by + SLAB_H, 152, CENTRE - 76); }
  list.forEach((t, k) => { const y = screenY(k); if (y > -SLAB_H && y < 224) drawSlab(k, t.x, y, t.w, t.ox); });
}

// The count-in's digits: 3 x 5 blocks, 6 px each.
const DIGITS = { 3: ['111', '001', '011', '001', '111'], 2: ['111', '001', '111', '100', '111'], 1: ['010', '110', '010', '010', '111'] };
