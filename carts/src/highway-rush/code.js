function drawPart(p, z) {
  const sx = projX(p.x, z), sy = projY(z) - p.h * FOCAL / z, a = p.life / p.max;
  if (p.k === 'smoke') { const f = Math.min(3, flr((1 - a) * 4)), s = ART.sprites['puff' + f]; if (s) sprite(s, Math.round(sx - s.size / 2), Math.round(sy - s.size / 2), { prio: 1 }); }
  else if (p.k === 'sparkle') { const f = Math.min(3, flr((1 - a) * 4)), s = ART.sprites['spark' + f]; if (s) sprite(s, Math.round(sx - s.size / 2), Math.round(sy - s.size / 2), { prio: 1 }); }
  else { const c = a > 0.5 ? GOLD : 9; rectfill(Math.round(sx), Math.round(sy), 2, 2, c); }
}
/** The finish gantry: two posts and a chequered banner, projected on the overlay (it is above the cars, as the real one is above the road). */
function drawGantry() {
  const z = FINISH_D - camD;
  if (z < 20 || z > 900) return;
  const yb = (h) => HORIZON - 1 + (HEIGHT - h) * FOCAL / z, xs = (x) => projX(x, z), k = FOCAL / z;
  const xl = xs(-58), xr = xs(58), top = yb(86), bot = yb(62), gnd = yb(0), w = Math.max(1, Math.round(4 * k));
  rectfill(Math.round(xl - w / 2), Math.round(top), w, Math.round(gnd - top), DIM); rectfill(Math.round(xr - w / 2), Math.round(top), w, Math.round(gnd - top), DIM);
  const n = 12, cw = (xr - xl) / n, ch = (bot - top) / 2;
  for (let i = 0; i < n; i++) for (let j = 0; j < 2; j++) rectfill(Math.round(xl + i * cw), Math.round(top + j * ch), Math.ceil(cw), Math.ceil(ch), (i + j) & 1 ? WHITE : SHADOW);
  rect(Math.round(xl), Math.round(top), Math.round(xr - xl), Math.round(bot - top), DIM);
}
function speedLines() {
  const n = P.boost > 0 ? 14 : 7;
  for (let i = 0; i < n; i++) {
    const a = (hash2(i, 5) % 1000) / 1000 * 6.2832, ph = ((clock * 0.045 + i * 0.37) % 1);
    const ca = Math.cos(a), sa = Math.sin(a);
    if (sa < 0.15 && Math.abs(ca) < 0.5) continue;
    const r0 = 40 + ph * 150, r1 = r0 + 14 + ph * 22, y0 = HORIZON + sa * r0 * 0.7, y1 = HORIZON + sa * r1 * 0.7;
    if (y0 < HORIZON + 8) continue;
    const x0 = 128 + ca * r0 * 1.2, x1 = 128 + ca * r1 * 1.2;
    if (Math.abs(x0 - 128) < 78 && y0 > 170) continue; // keep clear of the car and the middle of the road
    line(Math.round(x0), Math.round(y0), Math.round(x1), Math.round(y1), ph > 0.5 ? WHITE : DIM);
  }
}

