/** Write world row r (distance 8r to 8r + 8) into the ring: grass, rail, shoulder, kerb and road in the two bands, then the stamps of any pad or oil on it. */
function floorRow(r) {
  const ty = (-r - 1) & 127, band = (r >> 2) & 1, B = band ? 'B' : 'A', dash = r % 6 < 3, finish = r === Math.floor(FINISH_D / 8) || r === Math.floor(FINISH_D / 8) + 1;
  for (let tx = 0; tx < 128; tx++) {
    const u = tx - 64;
    let e;
    if (u >= -6 && u <= 5) {
      if (finish) e = T1(TL[((tx + r) & 1) ? 'chkA' : 'chkB']);
      else if (u === -6) e = T1(TL['edgeL' + B]);
      else if (u === 5) e = T1(TL['edgeR' + B]);
      else if (dash && (u === -3 || u === 1)) e = T1(TL['dashR' + B]);
      else if (dash && (u === -2 || u === 2)) e = T1(TL['dashL' + B]);
      else e = T1(TL['asph' + B + hash2(tx, r) % 3]);
    } else if (u === -7 || u === 6) e = T1(TL[(r & 1) ? 'kerbR' : 'kerbW']);
    else if (u === -8 || u === 7) e = T1(TL['sh' + B + (hash2(tx, r) & 1)]);
    else if (u === -9 || u === 8) e = T1(TL[(r % 6 === 0 ? 'post' : 'rail') + B], u > 0);
    else e = T1(TL['gr' + B + hash2(tx, r) % 4]);
    mset(tx, ty, e);
  }
  const ds = decals.get(r);
  if (ds) for (const [k, lane, j] of ds) stamp(k, lane, ty, j);
  for (const o of oils) if (o.rows && o.rows.has(r)) stamp('o', o.lane, ty, o.rows.get(r));
}
/** Copy one tile row of a stamp (the pad or oil scene) onto the floor at a lane. */
