/** One frame of the world: the player's controls, every car, what they hit, the camera and the floor. */
function stepWorld(still) {
  for (const r of racers) {
    r.prev = r.d;
    if (r === P && !P.auto && !still) playerDrive(P); else if (still) { r.sv = 0; r.brake = true; } else aiDrive(r);
    if (!still) moveRacer(r);
  }
  if (!still) {
    for (const r of racers) touchObjects(r);
    carHits();
    for (const o of oils) o.ttl--;
    const gone = oils.filter((o) => o.ttl <= 0);
    if (gone.length) { oils = oils.filter((o) => o.ttl > 0); for (const o of gone) wipeOil(o); }
    followRank();
  }
  for (const r of racers) {
    if (r.fin < 0 && r.d >= FINISH_D && !still) { r.fin = rt; finishOrder.push(r); }
    if (r.inv > 0) r.inv--; if (r.slow > 0) r.slow--; if (r.spin > 0) r.spin--; if (r.boost > 0) r.boost--; if (r.cool > 0) r.cool--;
    if (r.boost <= 0) { r.boostAdd = 0; r.turbo = false; }
  }
  updateParts();
  if (msgT > 0) msgT--;
  if (shake > 0) shake--;
  const want = P.x * 0.62; camX += (want - camX) * 0.25;
  camD = P.d - CAMD;
  ensureRows();
}

// --- Driving ---
function targetSpeed(r) {
  let s = TUNE.cruise * r.rv;
  if (r.id && r.d < P.d - 700) s *= 1 + TUNE.rubber * Math.min(1, (P.d - r.d - 700) / 2500);   // a rival far behind you catches up a little
  else if (r.id && r.d > P.d + 900) s *= 1 - TUNE.rubber * 0.6 * Math.min(1, (r.d - P.d - 900) / 2500);
  if (r.boost > 0) s += r.boostAdd;
  if (r.slow > 0) s *= TUNE.coneMul;
  if (r.spin > 0) s *= TUNE.oilMul;
  return s;
}
function moveRacer(r) {
  const tgt = targetSpeed(r);
  if (r.brake) r.v = Math.max(0, r.v - TUNE.brake);
  else if (r.v < tgt) r.v = Math.min(tgt, r.v + TUNE.accel * (r.boost > 0 ? 2.2 : 1));
  else r.v = Math.max(tgt, r.v - TUNE.drag);
  r.d += r.v;
  r.x += r.sv;
  if (r.spin > 0) r.x += Math.sin((rt + r.id * 7) * 0.45) * 0.9 * Math.min(1, r.spin / 20);
  if (r.x > 40) { r.x = 40; scrape(r); } else if (r.x < -40) { r.x = -40; scrape(r); }
}
function scrape(r) {
  r.v *= 0.985;
  if (r === P && rt % 14 === 0) { fx(SFX.scrape); emit('spark', P.x + (P.x > 0 ? 12 : -12), P.d, 4, 0.3, 0.2, 10); }
}
function playerDrive(r) {
  const dir = (held(RIGHT) ? 1 : 0) - (held(LEFT) ? 1 : 0), grip = r.spin > 0 ? TUNE.oilGrip : 1;
  r.sv += (dir * TUNE.steer - r.sv) * TUNE.steerLerp * grip;
  r.brake = held(B);
  if (pressed(A)) useItem(r);
  if (r.brake && r.v > 2) skid(r, 3);
  if (r.spin > 0 && rt % 4 === 0) skid(r, 1);
}
function skid(r, every) { if (rt % every === 0) { emit('smoke', r.x - 10, r.d - 6, 1, -0.2, 0.15, 22); emit('smoke', r.x + 10, r.d - 6, 1, 0.2, 0.15, 22); } }

/** The computer's driving, for rivals and for the player's car when it drives itself (the title's demo and after the line):
 *  look ahead for hazards and slower cars, move to a free lane, and use the item it holds. */
function aiDrive(r) {
  r.brake = false;
  if (r.fin >= 0) { if (r.id === 0) r.tx = 0; r.sv = clamp((r.tx - r.x) * 0.1, -1, 1); if (r.d > FINISH_D + 400 + r.id * 40) r.brake = true; return; }
  if (r.cool <= 0 || r.spin > 0) {
    const ahead = lookAhead(r);
    if (ahead.block) {
      const lane = bestLane(r);
      if (lane !== laneOf(r.tx) && r.spin <= 0) { r.tx = LANES[lane] + rndi(-5, 5); r.cool = 28; }
      else if (ahead.slow !== null && ahead.dist < 40) { r.brake = ahead.dist < 22 && r.v > ahead.slow; }
    }
  }
  const dx = r.tx - r.x;
  r.sv = clamp(dx * 0.12, -0.9, 0.9) * (r.spin > 0 ? TUNE.oilGrip : 1);
  // a car that cannot get past one in front keeps its distance
  const f = nearestAhead(r, 30, 20);
  if (f && r.v > f.v) { r.v = Math.max(f.v * 0.97, r.v - 0.12); }
  if (r.item && r.itemT-- <= 0) useItem(r);
}
/** What is in the way: a hazard or a slower car within `near` of this car's lane, and how far off. */
function lookAhead(r) {
  const reach = 150 + r.v * 6;
  for (let i = lowerBound(r.d + 4); i < objs.length && objs[i].d < r.d + reach; i++) {
    const o = objs[i];
    if (!o.on || o.k === 'c' || o.k === 'g') continue;
    if (Math.abs(o.x - r.tx) < o.hw + 8 && (r.skill >= 1 || hash2(o.i, r.id) % 100 < r.skill * 100)) return { block: true, dist: o.d - r.d, slow: null };
  }
  for (const o of oils) if (o.d > r.d + 4 && o.d < r.d + reach && Math.abs(o.x - r.tx) < 26 && o.owner !== r.id) return { block: true, dist: o.d - r.d, slow: null };
  const f = nearestAhead(r, reach * 0.6, 22);
  if (f && f.v < r.v + 0.2) return { block: true, dist: f.d - r.d, slow: f.v };
  return { block: false };
}
function nearestAhead(r, reach, width) {
  let best = null;
  for (const o of racers) if (o !== r && o.d > r.d && o.d - r.d < reach && Math.abs(o.x - r.x) < width && (!best || o.d < best.d)) best = o;
  return best;
}
/** The lane with nothing in it for a stretch ahead, nearest the current one (cubes break a tie). */
function bestLane(r) {
  let best = laneOf(r.tx), bestScore = -1e9;
  for (let l = 0; l < 3; l++) {
    let s = -Math.abs(LANES[l] - r.x) * 0.5, clear = 0;
    for (let i = lowerBound(r.d + 4); i < objs.length && objs[i].d < r.d + 190; i++) {
      const o = objs[i];
      if (!o.on || Math.abs(o.x - LANES[l]) > o.hw + 12) continue;
      if (o.k === 'k' || o.k === 'o' || o.k === 'r') s -= 400; else if (o.k === 'c') s += 30; else s += 40;
    }
    for (const o of oils) if (o.d > r.d && o.d < r.d + 190 && o.lane === l) s -= 400;
    for (const o of racers) if (o !== r && o.d > r.d - 26 && o.d < r.d + 120 && Math.abs(o.x - LANES[l]) < 24) s -= 220 - (o.d - r.d) * 0.5;
    if (s > bestScore) { bestScore = s; best = l; }
  }
  return best;
}

// --- Items ---
/** Hand out an item from a cube: worse positions get the better ones. */
function pickItem(r) {
  const p = place(r), roll = rndi(0, 99);
  const turbo = 38 + p * 3, shield = 30;
  return roll < turbo ? 1 : roll < turbo + shield ? 2 : 3;
}
function useItem(r) {
  const it = r.item; if (!it) return;
  r.item = 0;
  if (it === 1) { r.boost = TUNE.turboFrames; r.boostAdd = TUNE.turboAdd; r.turbo = true; if (r === P) { fx(SFX.boost); shake = 12; } }
  else if (it === 2) { r.shield = true; if (r === P) fx(SFX.shield); }
  else dropOil(r);
}
function dropOil(r) {
  const lane = laneOf(r.x), d = r.d - 36, o = { x: LANES[lane], d, lane, ttl: TUNE.oilLife, owner: r.id, on: true, hw: 18, hl: 14, k: 'o', rows: new Map() };
  const r0 = Math.floor(d / 8) - 2;
  for (let j = 0; j < 4; j++) o.rows.set(r0 + 3 - j, j);
  oils.push(o);
  for (const [row, j] of o.rows) if (row > camD / 8 && row < nextRow) stamp('o', lane, (-row - 1) & 127, j);
  if (r === P) { fx(SFX.drop); msg = 'OIL DROPPED'; msgT = 40; }
}
function wipeOil(o) { for (const row of o.rows.keys()) if (row > camD / 8 && row < nextRow) floorRow(row); }

// --- What cars touch ---
function hit(r, kind, o) {
  if (r.inv > 0) return false;
  if (r.shield) { r.shield = false; r.inv = TUNE.protect; if (r === P) { fx(SFX.pop); msg = 'SHIELD!'; msgT = 40; } emit('spark', r.x, r.d, 8, 0, 0.3, 14); return false; }
  r.inv = kind === 'car' ? TUNE.protect : 30;
  return true;
}
function touchObjects(r) {
  for (let i = lowerBound(r.prev - 30); i < objs.length && objs[i].d < r.d + 30; i++) {
    const o = objs[i];
    if (!o.on || r.last.includes(o) || Math.abs(o.x - r.x) >= o.hw || r.d < o.d - o.hl || r.prev > o.d + o.hl) continue;
    remember(r, o);
    if (o.k === 'c') { o.on = false; collect(r, o); }
    else if (o.k === 'g') { r.boost = Math.max(r.boost, TUNE.greenBoost); r.boostAdd = Math.max(r.boostAdd, TUNE.greenAdd); if (r === P) { fx(SFX.pad); shake = 6; } }
    else if (o.k === 'r') { if (hit(r, 'red', o)) { r.slow = TUNE.redSlow; r.v *= 0.85; if (r === P) fx(SFX.slow); } }
    else if (o.k === 'k') { if (hit(r, 'cone', o)) { r.slow = TUNE.coneSlow; r.v *= TUNE.coneKeep; if (r === P) { fx(SFX.cone); shake = 10; } } o.on = false; emit('spark', o.x, o.d, 6, 0, 0.4, 16); }
    else if (o.k === 'o') { if (hit(r, 'oil', o)) { r.spin = TUNE.oilSpin; r.slow = 20; if (r === P) { fx(SFX.oil); msg = 'OIL!'; msgT = 40; } } }
  }
  for (const o of oils) {
    if (r.last.includes(o) || o.owner === r.id && r.id === P.id || Math.abs(o.x - r.x) >= o.hw || r.d < o.d - o.hl || r.prev > o.d + o.hl) continue;
    remember(r, o);
    if (hit(r, 'oil', o)) { r.spin = TUNE.oilSpin; r.slow = 20; if (r === P) { fx(SFX.oil); msg = 'OIL!'; msgT = 40; } else if (o.owner === P.id) { msg = r.name + ' SPUN OUT!'; msgT = 60; fx(SFX.pass); } }
  }
}
function remember(r, o) { r.last.push(o); if (r.last.length > 4) r.last.shift(); }
function collect(r, o) {
  if (r === P) { cubes++; fx(SFX.cube); emit('sparkle', o.x, o.d, 6, 0, 0.1, 24); if (!P.item) { P.item = pickItem(P); P.itemT = rndi(60, 200); } else { msg = 'ITEM FULL'; msgT = 30; } }
  else if (!r.item && r.id) { r.item = rndi(0, 1) ? 1 : 3; r.itemT = rndi(90, 300); }
}
function carHits() {
  for (let i = 0; i < racers.length; i++) for (let j = i + 1; j < racers.length; j++) {
    const a = racers[i], b = racers[j];
    if (Math.abs(a.d - b.d) > 18 || Math.abs(a.x - b.x) > 20) continue;
    const back = a.d < b.d ? a : b, front = back === a ? b : a;
    if (back.inv > 0 || front.inv > 0) continue;
    const protectedBack = back.shield, protectedFront = front.shield;
    if (protectedBack) { hit(back, 'car'); front.inv = 20; }
    else if (protectedFront) { hit(front, 'car'); back.inv = 20; }
    else {
      back.v = Math.min(back.v, front.v * 0.82); back.slow = 25; back.inv = TUNE.protect; front.inv = 20; front.v += 0.3;
      if (back === P || front === P) { fx(SFX.crash); shake = 14; emit('spark', (a.x + b.x) / 2, front.d - 8, 8, 0, 0.5, 16); }
    }
    const push = Math.sign(back.x - front.x) || (back.id & 1 ? 1 : -1);
    back.x = clamp(back.x + push * 5, -40, 40); front.x = clamp(front.x - push * 5, -40, 40);
    back.tx = front.tx = clamp(back.tx, -32, 32);
  }
}

// --- Standing ---
const order = () => racers.slice().sort((a, b) => (a.fin >= 0 && b.fin >= 0 ? a.fin - b.fin : a.fin >= 0 ? -1 : b.fin >= 0 ? 1 : b.d - a.d));
const place = (r) => order().indexOf(r) + 1;
function followRank() {
  const p = place(P);
  if (p < lastRank && state === 'race' && !P.auto) { passes += lastRank - p; fx(SFX.pass); msg = p === 1 ? 'IN THE LEAD!' : `PASSED! ${ord(p)}`; msgT = 50; }
  lastRank = p;
}
const ord = (n) => n + (n === 1 ? 'ST' : n === 2 ? 'ND' : n === 3 ? 'RD' : 'TH');

// --- Particles: smoke, sparks and sparkles in world coordinates (lateral, distance, height) ---
function emit(k, x, d, n, vx, vd, life) {
  for (let i = 0; i < n && parts.length < 28; i++) parts.push({ k, x: x + (n > 1 ? rndi(-4, 4) : 0), d, h: k === 'smoke' ? 1 : 4, vx: vx + (rndi(-3, 3) / 8), vd: P.v * (k === 'sparkle' ? 0 : 0.8) + vd * rndi(0, 4), vh: k === 'smoke' ? 0.2 : 0.5, life, max: life });
}
function updateParts() {
  for (const p of parts) { p.x += p.vx; p.d += p.vd; p.h += p.vh; p.vh -= p.k === 'spark' ? 0.06 : 0; p.life--; }
  parts = parts.filter((p) => p.life > 0);
}

