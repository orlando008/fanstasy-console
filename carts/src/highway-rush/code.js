// A 5 x 7 pixel font for the big words (countdown, GO, FINISH): rows of five bits.
const FONT = { 0: '01110 10001 10011 10101 11001 10001 01110', 1: '00100 01100 00100 00100 00100 00100 01110', 2: '01110 10001 00001 00110 01000 10000 11111', 3: '11110 00001 00001 01110 00001 00001 11110',
  G: '01110 10001 10000 10111 10001 10001 01111', O: '01110 10001 10001 10001 10001 10001 01110', F: '11111 10000 10000 11110 10000 10000 10000', I: '01110 00100 00100 00100 00100 00100 01110',
  N: '10001 11001 10101 10101 10011 10001 10001', S: '01111 10000 10000 01110 00001 00001 11110', H: '10001 10001 10001 11111 10001 10001 10001' };
function bigText(s, cx, y, k, col, shadow) {
  const w = s.length * 6 * k - k; let x = Math.round(cx - w / 2);
  for (const ch of s) {
    const g = FONT[ch];
    if (g) g.split(' ').forEach((row, j) => { for (let i = 0; i < 5; i++) if (row[i] === '1') { if (shadow) rectfill(x + i * k + (k >> 2) + 1, y + j * k + (k >> 2) + 1, k, k, SHADOW); } });
    if (g) g.split(' ').forEach((row, j) => { for (let i = 0; i < 5; i++) if (row[i] === '1') rectfill(x + i * k, y + j * k, k, k, col); });
    x += 6 * k;
  }
}

// --- Each line of the screen: the sky above the horizon, the Mode 7 road below it ---
function scanline(y) {
  if (y < HORIZON) { gradientLine(ART.gradients.sky, y); return; }
  if (y === HORIZON) {
    bg(1, { show: false });
    bg(2, { mx: 0, my: 0, mw: 128, mh: 128, x: 0, y: 0, wrap: true, show: false });
    color(0, HAZE[0], HAZE[1], HAZE[2]);
  }
  if (y < FLOOR_TOP) return;
  if (y === FLOOR_TOP) bg(2, { show: true });
  const z = HEIGHT * FOCAL / (y - HORIZON + 1), s = z / FOCAL;
  const py = ((-camD - z) % 1024 + 1024) % 1024;
  affine({ a: s, b: CX + camX - 128, c: 0, d: py, cx: 128, cy: 0 });
  bgscroll(2, 0, 1 - y);
  if (y <= FOG_END + 1) {   // the road's colours fade into the haze with distance; one line past the last faded one they are put back
    const k = y > FOG_END ? 0 : Math.pow(clamp((z - 160) / 840, 0, 1), 0.7);
    for (const i of FOG_ENTRIES) { const c = FOG[i]; color(i, flr(lerp(c[0], HAZE[0], k)), flr(lerp(c[1], HAZE[1], k)), flr(lerp(c[2], HAZE[2], k))); }
  }
}
