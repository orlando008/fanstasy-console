const tname = (t) => `${team(t).city} ${team(t).nick}`;
const pad = (v, n) => String(v).padStart(n);

/** A scrolling list: rows of [text, colour], the selected one on a panel; max rows from y0. */
function drawList(list, sel, y0, max, rh = 10) {
  const top = clamp(sel - (max >> 1), 0, Math.max(0, list.length - max));
  for (let i = 0; i < max && top + i < list.length; i++) {
    const y = y0 + i * rh, on = top + i === sel;
    if (on) rectfill(4, y - 1, 248, rh, PANEL);
    txt(list[top + i][0], 8, y, on ? WHITE : list[top + i][1]);
  }
  if (top > 0) txt('^', 244, y0, GOLD);
  if (top + max < list.length) txt('v', 244, y0 + (max - 1) * rh, GOLD);
}
function header(left, right) { txt(left, 8, 6, GOLD); txt(right, 248 - right.length * 8, 6, WHITE); rectfill(4, 18, 248, 1, PANEL); }
function footer(s) { rectfill(4, 210, 248, 1, PANEL); txt(s, 8, 214, DIM); }

