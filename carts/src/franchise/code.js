const menuMove = (n, v) => { if (pressed(UP)) { fx(SFX.move); return (v + n - 1) % n; } if (pressed(DOWN)) { fx(SFX.move); return (v + 1) % n; } return v; };
/** UP and DOWN move a selection down a list of n rows; LEFT and RIGHT jump a page. */
function listMove(n) {
  let v = sel;
  if (btnp(UP)) v = Math.max(0, v - 1);
  if (btnp(DOWN)) v = Math.min(n - 1, v + 1);
  if (v !== sel) { sel = v; fx(SFX.move); }
}

