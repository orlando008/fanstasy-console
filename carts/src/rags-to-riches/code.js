// --- The economy: pure functions (no state, no random numbers: the roll is an argument) ---

/** The six multipliers of the crowd. */
function factors(city, price, ad, pop, fresh, fatigue) {
  return {
    pop: TUNE.popBase + TUNE.popSlope * pop / 100,
    fresh: TUNE.freshBase + TUNE.freshSlope * fresh / 100,
    price: clamp(TUNE.priceBase - price / city.priceScale, TUNE.priceLow, TUNE.priceHigh),
    ad: 1 + TUNE.adBoost * (ad / (ad + TUNE.adHalf)),
    fatigue: clamp(1 - fatigue / TUNE.fatigueSpan, TUNE.fatigueFloor, 1),
    comp: 1 - city.competition,
  };
}
/** The crowd the band can expect, before the venue's size and the roll. */
function expectedCrowd(city, price, ad, pop, fresh, fatigue) {
  const f = factors(city, price, ad, pop, fresh, fatigue);
  return city.pool * f.pop * f.fresh * f.price * f.ad * f.fatigue * f.comp;
}
/** The tickets sold: a whole number from 0 to the venue's capacity. roll is a percentage, TUNE.rollMin to rollMax. */
function attendance(city, venue, price, ad, pop, fresh, fatigue, roll) {
  return clamp(Math.round(expectedCrowd(city, price, ad, pop, fresh, fatigue) * roll / 100), 0, venue.capacity);
}
/** Popularity won or lost by a show of this size in this room (spec 5.3). */
function popularityChange(att, capacity) {
  const occ = Math.floor(att * 100 / capacity);
  if (occ < 30) return occ < 10 ? -3 : occ < 20 ? -2 : -1;
  return 1 + (occ >= 100 ? 5 : occ >= 90 ? 4 : occ >= 75 ? 3 : occ >= 60 ? 2 : occ >= 45 ? 1 : 0);
}
/** LOW, FAIR or STRONG: the expected crowd (roll 100) against the room, never the number itself. */
function forecast(city, venue, price, ad, pop, fresh, fatigue) {
  const r = expectedCrowd(city, price, ad, pop, fresh, fatigue) / venue.capacity;
  return r < 0.4 ? 'LOW' : r < 0.75 ? 'FAIR' : 'STRONG';
}
/** The one line that says why the crowd was what it was (spec 5.5). */
function mainFactor(f, full) {
  if (full) return 'FULL HOUSE! BIGGER ROOM?';
  const worst = [[f.pop, 'LOW POPULARITY'], [f.fresh, 'STALE SONGS'], [f.price, 'PRICE TOO HIGH'], [f.fatigue, 'TIRED MARKET']]
    .reduce((a, b) => (b[0] < a[0] ? b : a));
  return worst[0] >= 0.9 ? 'GOOD MIX OF PRICE AND BUZZ' : worst[1];
}
/** How the fans of a market feel, from its fatigue: the word the hub shows. */
const fansWord = (fatigue) => (fatigue < 20 ? 'EAGER' : fatigue < 45 ? 'WARM' : fatigue < 70 ? 'TIRED' : 'WORN OUT');
/** Songwriting (spec 5.3): freshness and popularity up, no money, no fatigue. s = { pop, fresh }. */
function writeSongs(s) {
  const pop = clamp(s.pop + TUNE.songPop, 0, 100);
  return { popBefore: s.pop, pop, popChange: pop - s.pop, freshBefore: s.fresh, fresh: clamp(s.fresh + TUNE.songFresh, 0, 100) };
}
const canTravel = (cash) => cash >= TUNE.fare;
/** The tour is won with the goal or more in cash at the end of week 10. */
const isWin = (cash) => cash >= TUNE.goal;
/** Can the cash pay for a show in at least one venue of this city? */
const canConcert = (cash, c) => cash >= Math.min(...c.venues.map((v) => v.rent));
/** The words under a concert's cutscene, from how full the room was (percent). */
const crowdVerdict = (occ) => (occ >= 100 ? 'SOLD OUT! THE ROOM ERUPTS!' : occ >= 75 ? 'WHAT A NIGHT!' : occ >= 45 ? 'A GOOD, LOUD CROWD' : occ >= 20 ? 'A THIN BUT KIND CROWD' : 'CRICKETS... AND ONE DOG');
/** The most advertising the cash allows after the rent. */
const maxAd = (cash, rent) => clamp(Math.floor((cash - rent) / TUNE.adStep) * TUNE.adStep, 0, TUNE.adMax);
const canAfford = (cash, venue, ad) => venue.rent + ad <= cash;
/** A whole concert, settled: s = { cash, pop, fresh, fatigue } before it. Returns every figure the result screen shows. */
function settle(s, city, venue, price, ad, roll) {
  const f = factors(city, price, ad, s.pop, s.fresh, s.fatigue);
  const att = attendance(city, venue, price, ad, s.pop, s.fresh, s.fatigue, roll);
  const revenue = att * price, net = revenue - venue.rent - ad, dp = popularityChange(att, venue.capacity);
  return {
    att, capacity: venue.capacity, price, revenue, rent: venue.rent, ad, net, roll,
    cashBefore: s.cash, cash: s.cash + net,
    popBefore: s.pop, pop: clamp(s.pop + dp, 0, 100), popChange: dp,
    freshBefore: s.fresh, fresh: clamp(s.fresh - TUNE.freshCost, 0, 100),
    fatigue: clamp(s.fatigue + TUNE.fatigueGain, 0, 100),
    note: mainFactor(f, att >= venue.capacity),
  };
}

