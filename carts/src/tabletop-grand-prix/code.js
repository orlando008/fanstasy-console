/** Queue one of ART.sprites at (x, y), above the background; opts as for spr (fx, fy ...). */
function sprite(s, x, y, opts = {}) { spr(s.tile, x, y, { size: s.size, pal: s.pal, prio: 3, ...opts }); }

// --- Sound (SPEC 5). Songs use channels 0 to 5; effects take turns on 6 and 7, so they never cut into the music. ---

const SFX = { move: 0, select: 1, pause: 2, bump: 3, fall: 4, land: 5 };
const SONG = { title: 0, race: 1 };
const SFX_CH = [7, 6];
let fxNext = 0;
function fx(n) { sfx(n, SFX_CH[fxNext]); fxNext ^= 1; }

// A song is only started if it is not already playing.
let playing = -1;
function play(song) {
  if (song === playing) return;
  playing = song; music(song);
}

// --- Save slots (spec 13) ---

const VERSION_SLOT = 0, SAVE_VERSION = 2;

// --- Input: each pad's buttons this frame and last, for presses that do not repeat (btnp does) ---

const BUTTONS = [UP, DOWN, LEFT, RIGHT, A, B, X, Y, L, R, START, SELECT];
const masks = [0, 0, 0, 0], prevMasks = [0, 0, 0, 0];
function readPads() {
  for (let p = 0; p < 4; p++) { let m = 0; for (const b of BUTTONS) if (btn(b, p)) m |= 1 << b; prevMasks[p] = masks[p]; masks[p] = m; }
}
const held = (b, p = 0) => (masks[p] & (1 << b)) !== 0;
const pressed = (b, p = 0) => held(b, p) && (prevMasks[p] & (1 << b)) === 0;

// --- Driving (spec 5.1 and 5.2): speeds in px a frame ---

const TOP = 2.0, ACC = 0.045, BRAKE = 0.09, REV = 0.7, ROLL = 0.985, TURN = 0.065, STEER_RAMP = 6, R_CAR = 5;
const SLIDE_KEEP = 0.55;      // the sideways speed kept while turning with A let go (the slide)
const BOUNCE = 0.5, SCRAPE = 0.8;  // into a wall: the speed into it comes back halved; along it, a fifth is lost
const FALL_T = 30;            // frames a falling car takes to drop out of sight

// The surfaces of the track's grid (one 8 px cell each): sideways speed kept, top speed, and the tile drawn.
const S_OFF = 0, S_ROAD = 1, S_ROUGH = 2, S_SLICK = 3, S_STICKY = 4, S_RAMP = 5, S_HOLE = 6, S_WALL = 7;
const SURF = [
  { name: 'OFF', keep: 0.30, top: 1.3, tile: 'off' },
  { name: 'ROAD', keep: 0.20, top: TOP, tile: 'road' },
  { name: 'ROUGH', keep: 0.30, top: 1.1, tile: 'rough' },
  { name: 'SLICK', keep: 0.85, top: TOP, tile: 'slick' },
  { name: 'STICKY', keep: 0.20, top: 0.8, tile: 'sticky' },
  { name: 'RAMP', keep: 0.20, top: TOP, tile: 'ramp' },
  { name: 'HOLE', keep: 0.30, top: TOP, tile: null },
  { name: 'WALL', keep: 0.30, top: TOP, tile: 'wall' },
];

// --- Tracks (spec 6). pts: the centreline's control points in px (a closed loop, smoothed); width: the road in px;
// table: [x, y, w, h] in px (outside it is the floor); prims: [surface, 'r', x, y, w, h] or [surface, 'c', x, y, r]
// painted over the road in order. The map is w x h cells of 8 px (at most 128 x 96). ---

const TRACKS = [
  { name: 'TEST TABLE', w: 128, h: 96, width: 48, table: [16, 16, 992, 736],
    pts: [200, 130, 820, 130, 900, 190, 900, 330, 820, 400, 620, 400, 560, 460, 620, 540, 860, 560, 900, 620, 840, 680, 200, 680, 130, 620, 130, 200],
    prims: [[S_ROUGH, 'c', 500, 130, 22], [S_SLICK, 'c', 900, 260, 30], [S_STICKY, 'r', 300, 655, 60, 50],
      [S_WALL, 'r', 400, 250, 120, 80], [S_HOLE, 'c', 700, 290, 36]] },
];
const SPACING = 16;           // px between the centreline's waypoints after smoothing

let track = null;             // the track being raced: its data, waypoints (wx, wy) and their count n
let grid = null;              // Uint8Array of the surface of each cell

/** A closed Catmull-Rom curve through the control points, resampled to a waypoint every SPACING px. */
function centreline(pts) {
  const n = pts.length / 2, P = (i) => [pts[((i + n) % n) * 2], pts[((i + n) % n) * 2 + 1]], dense = [];
  for (let i = 0; i < n; i++) {
    const [p0, p1, p2, p3] = [P(i - 1), P(i), P(i + 1), P(i + 2)];
    for (let k = 0; k < 16; k++) {
      const t = k / 16, t2 = t * t, t3 = t2 * t;
      const f = (a, b, c, d) => 0.5 * (2 * b + (c - a) * t + (2 * a - 5 * b + 4 * c - d) * t2 + (3 * b - a - 3 * c + d) * t3);
      dense.push([f(p0[0], p1[0], p2[0], p3[0]), f(p0[1], p1[1], p2[1], p3[1])]);
    }
  }
  const lens = dense.map(([ax, ay], i) => Math.hypot(dense[(i + 1) % dense.length][0] - ax, dense[(i + 1) % dense.length][1] - ay));
  const total = lens.reduce((s, l) => s + l, 0), n2 = Math.round(total / SPACING), step = total / n2; // evenly spaced, the loop closing too
  const wx = [], wy = [];
  let carry = 0;
  for (let i = 0; i < dense.length && wx.length < n2; i++) {
    const [ax, ay] = dense[i], [bx, by] = dense[(i + 1) % dense.length], len = lens[i];
    while (carry <= len && wx.length < n2) { const t = carry / len; wx.push(ax + (bx - ax) * t); wy.push(ay + (by - ay) * t); carry += step; }
    carry -= len;
  }
  return { wx, wy, n: wx.length };
}

/** Build a track: its waypoints, its grid of surfaces (spec 6), and its tiles in Map RAM (BG1, from cell 0, 0). */
function buildTrack(i) {
  const T = TRACKS[i], W = T.w, H = T.h, c = centreline(T.pts);
  track = { ...T, i, ...c };
  grid = new Uint8Array(W * H).fill(S_HOLE);
  const paint = (s, x0, y0, x1, y1, inside) => {
    for (let cy = Math.max(0, flr(y0 / 8)); cy <= Math.min(H - 1, flr(y1 / 8)); cy++)
      for (let cx = Math.max(0, flr(x0 / 8)); cx <= Math.min(W - 1, flr(x1 / 8)); cx++)
        if (inside(cx * 8 + 4, cy * 8 + 4)) grid[cy * W + cx] = s;
  };
  const [tx, ty, tw, th] = T.table;
  paint(S_OFF, tx, ty, tx + tw - 1, ty + th - 1, () => true);
  const r = T.width / 2;
  for (let k = 0; k < c.n; k++) {     // the road: every cell within r of a segment of the centreline
    const ax = c.wx[k], ay = c.wy[k], bx = c.wx[(k + 1) % c.n], by = c.wy[(k + 1) % c.n];
    paint(S_ROAD, Math.min(ax, bx) - r, Math.min(ay, by) - r, Math.max(ax, bx) + r, Math.max(ay, by) + r, (x, y) => segDist(x, y, ax, ay, bx, by) < r);
  }
  for (const [s, shape, x, y, a, b] of T.prims) {
    if (shape === 'r') paint(s, x, y, x + a - 1, y + b - 1, () => true);
    else paint(s, x - a, y - a, x + a, y + a, (px, py) => (px - x) ** 2 + (py - y) ** 2 < a * a);
  }
  for (let cy = 0; cy < 128; cy++) for (let cx = 0; cx < 128; cx++) {
    const s = cx < W && cy < H ? grid[cy * W + cx] : S_HOLE, t = SURF[s].tile;
    mset(cx, cy, t ? tile(ART.tiles[t], 1) : 0);
  }
}

/** Distance from (x, y) to the segment from (ax, ay) to (bx, by). */
function segDist(x, y, ax, ay, bx, by) {
  const dx = bx - ax, dy = by - ay, L = dx * dx + dy * dy, t = L ? clamp(((x - ax) * dx + (y - ay) * dy) / L, 0, 1) : 0;
  return Math.hypot(x - ax - dx * t, y - ay - dy * t);
}

/** The surface under a point (outside the map is the floor). */
function surfAt(x, y) {
  const cx = flr(x / 8), cy = flr(y / 8);
  return cx < 0 || cy < 0 || cx >= track.w || cy >= track.h ? S_HOLE : grid[cy * track.w + cx];
}

/** Does a car's body at (x, y) overlap a wall cell? (Its box of R_CAR - 1 against the cells under it.) */
function hitsWall(x, y) {
  const r = R_CAR - 1;
  for (const [px, py] of [[x - r, y - r], [x + r, y - r], [x - r, y + r], [x + r, y + r]]) if (surfAt(px, py) === S_WALL) return true;
  return false;
}

// --- Cars ---

/** A car on waypoint k of the track, facing along it. */
function newCar(seat, k) {
  const c = { seat, x: 0, y: 0, a: 0, vx: 0, vy: 0, st: 0, fall: 0, wp: k, lap: 0, sliding: false, surf: S_ROAD };
  placeAt(c, k, 0, 0);
  return c;
}

/** Put a car on waypoint k, `back` px behind it and `side` px to its left or right, facing along the track, stopped. */
function placeAt(c, k, back, side) {
  const n = track.n, k1 = (k + 1) % n, dx = track.wx[k1] - track.wx[k], dy = track.wy[k1] - track.wy[k], L = Math.hypot(dx, dy) || 1;
  const ux = dx / L, uy = dy / L;
  c.x = track.wx[k] - ux * back - uy * side; c.y = track.wy[k] - uy * back + ux * side;
  c.a = Math.atan2(uy, ux); c.vx = c.vy = 0; c.st = 0; c.fall = 0; c.wp = k;
}

/** One frame of a car, from its controls: steer -1, 0 or 1; gas and brake true or false (spec 5.1 to 5.3). */
function drive(c, steer, gas, brake) {
  if (c.fall) { if (--c.fall === 0) respawn(c); return; }
  // The steering builds over STEER_RAMP frames to its full value (the pad is digital).
  c.st = steer ? clamp(c.st + steer / STEER_RAMP, -1, 1) : c.st - sgn(c.st) * Math.min(Math.abs(c.st), 1 / STEER_RAMP);
  const S = SURF[c.surf];
  let ca = Math.cos(c.a), sa = Math.sin(c.a), f = c.vx * ca + c.vy * sa;
  // The turn: full rate from a speed of 1 up, less below it (a car at a standstill cannot spin); backwards it turns the other way.
  c.a += TURN * c.st * clamp(f, -1, 1);
  ca = Math.cos(c.a); sa = Math.sin(c.a);
  f = c.vx * ca + c.vy * sa;
  let side = -c.vx * sa + c.vy * ca;   // the velocity split along the new heading and across it: the grip works on `side`
  if (gas) f = Math.min(f + ACC, Math.max(f, S.top));
  else if (brake) f = f > 0.05 ? Math.max(0, f - BRAKE) : Math.max(f - ACC * 0.6, -REV);
  else f *= ROLL;
  if (f > S.top) f -= (f - S.top) * 0.1;   // a slow surface drags a fast car down to its top speed
  c.sliding = !gas && Math.abs(c.st) > 0.3 && f > 1;
  side *= Math.max(S.keep, c.sliding ? SLIDE_KEEP : 0);
  c.vx = f * ca - side * sa; c.vy = f * sa + side * ca;
  // Move, one axis at a time, bouncing off walls.
  if (hitsWall(c.x + c.vx, c.y)) { c.vx *= -BOUNCE; c.vy *= SCRAPE; bump(c); } else c.x += c.vx;
  if (hitsWall(c.x, c.y + c.vy)) { c.vy *= -BOUNCE; c.vx *= SCRAPE; bump(c); } else c.y += c.vy;
  c.surf = surfAt(c.x, c.y);
  if (c.surf === S_HOLE) { c.fall = FALL_T; fx(SFX.fall); }
  follow(c);
}

let lastBump = -99;
function bump(c) { if (clock - lastBump > 8) { fx(SFX.bump); lastBump = clock; } }

/** Step 1: a fallen car comes back on its waypoint (from step 2 it is out of the round instead). */
function respawn(c) { placeAt(c, c.wp, 0, 0); c.surf = surfAt(c.x, c.y); fx(SFX.land); }

/** Keep a car's waypoint up to date: move it on (or back) along the centreline as the car passes, counting laps. A car
 * only moves one waypoint at a time, so it cannot jump to a part of the track that lies close by on the table. */
function follow(c) {
  const n = track.n;
  for (let i = 0; i < 4; i++) {
    const k = c.wp, k1 = (k + 1) % n, dx = track.wx[k1] - track.wx[k], dy = track.wy[k1] - track.wy[k];
    const t = ((c.x - track.wx[k]) * dx + (c.y - track.wy[k]) * dy) / (dx * dx + dy * dy);
    if (t >= 1) { c.wp = k1; if (k1 === 0) c.lap++; }
    else if (t < 0 && i === 0) { if (k === 0) c.lap--; c.wp = (k + n - 1) % n; break; }
    else break;
  }
}

/** How far a car is along the race: laps and waypoints (the leader is the car with the most; spec 5.4). */
function progress(c) {
  const n = track.n, k = c.wp, k1 = (k + 1) % n, dx = track.wx[k1] - track.wx[k], dy = track.wy[k1] - track.wy[k];
  const t = clamp(((c.x - track.wx[k]) * dx + (c.y - track.wy[k]) * dy) / (dx * dx + dy * dy), 0, 1);
  return c.lap * n + k + t;
}

// --- The camera (spec 5.5): it looks 40 px ahead of the car it follows, moving 12 % of the way a frame, at most 4 px ---

const LOOK = 40, CAM_K = 0.12, CAM_MAX = 4, HUD_H = 12;
let cam = { x: 0, y: 0 };
function camTarget(c) {
  const tx = c.x + Math.cos(c.a) * LOOK - 128, ty = c.y + Math.sin(c.a) * LOOK - (HUD_H + (224 - HUD_H) / 2);
  return [clamp(tx, 0, track.w * 8 - 256), clamp(ty, -HUD_H, track.h * 8 - 224)];
}
function moveCam(c, cut) {
  const [tx, ty] = camTarget(c);
  if (cut) { cam.x = tx; cam.y = ty; return; }
  cam.x += clamp((tx - cam.x) * CAM_K, -CAM_MAX, CAM_MAX);
  cam.y += clamp((ty - cam.y) * CAM_K, -CAM_MAX, CAM_MAX);
}

// --- State ---

let skipTitle = false; // tests set this to land straight in a race
let state = 'title', paused = false, timer = 0, clock = 0;
let titleSel = 0, pauseSel = 0;
let cars = [];

function init() {
  if (dget(VERSION_SLOT) !== SAVE_VERSION) { // a new or older save: start clean
    for (let i = 0; i < 256; i++) dset(i, 0);
    dset(VERSION_SLOT, SAVE_VERSION);
  }
  const f = ART.scenes.floor;
  bg(0, { show: false });
  bg(1, { mx: 0, my: 0, mw: 128, mh: 96, wrap: false, show: true });          // the table and the track
  bg(2, { mx: f.mx, my: f.my, mw: f.w, mh: f.h, wrap: true, show: true });   // the floor far below, repeated
  blend({ layers: ['overlay'], half: true }); // overlay colours from 192 up (ART.colors.GLASS) are see-through
  if (skipTitle) startRace(0); else toTitle();
}

function toTitle() { state = 'title'; timer = 0; titleSel = 0; paused = false; play(SONG.title); }

function startRace(i) {
  buildTrack(i);
  cars = [newCar(0, 0)];
  moveCam(cars[0], true);
  paused = false; timer = 0; state = 'race';
  play(SONG.race);
}

// --- Update ---

function update() {
  readPads(); clock++;
  if (!paused) timer++; // a state's clock: it stands still while paused
  if (paused) updatePause();
  else if (state === 'title') updateTitle();
  else if (state === 'race') updateRace();
}

function updateTitle() {
  if (pressed(UP) || pressed(DOWN)) { titleSel ^= 1; fx(SFX.move); }
  if (pressed(A) || pressed(START)) { fx(SFX.select); startRace(0); }
}

function updateRace() {
  if (pressed(START)) { paused = true; pauseSel = 0; fx(SFX.pause); return; }
  for (const c of cars) {
    const p = c.seat;
    drive(c, (held(RIGHT, p) ? 1 : 0) - (held(LEFT, p) ? 1 : 0), held(A, p), held(B, p));
  }
  moveCam(cars[0], false);
}

function updatePause() {
  if (pressed(UP)) { pauseSel = (pauseSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { pauseSel = (pauseSel + 1) % 3; fx(SFX.move); }
  if (pressed(B) || (pressed(START) && pauseSel === 0)) { paused = false; fx(SFX.pause); }
  else if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (pauseSel === 0) paused = false;
    else if (pauseSel === 1) startRace(track.i); // restart
    else toTitle();
  }
}

// --- Draw ---

function draw() {
  cls();
  if (state === 'race') drawRace();
  else if (state === 'title') drawTitle();
  if (paused) drawPause();
}

/** The car's sprite for its heading: 16 directions from 5 drawings (0 to 90 degrees), the rest flipped. */
function drawCar(c) {
  if (c.fall && (c.fall & 2)) return;   // a falling car blinks out of sight (the art pass, step 6, shrinks it)
  const d = ((Math.round(c.a / (Math.PI / 8)) % 16) + 16) % 16;
  let f = d, fxx = false, fyy = false;
  if (d > 4 && d <= 8) { f = 8 - d; fxx = true; }
  else if (d > 8 && d <= 12) { f = d - 8; fxx = fyy = true; }
  else if (d > 12) { f = 16 - d; fyy = true; }
  sprite(ART.sprites['car' + f], flr(c.x - cam.x) - 8, flr(c.y - cam.y) - 8, { fx: fxx, fy: fyy });
}

function drawRace() {
  bgscroll(1, flr(cam.x), flr(cam.y));
  bgscroll(2, flr(cam.x / 2), flr(cam.y / 2));
  for (const c of cars) drawCar(c);
  const c = cars[0];
  rectfill(0, 0, 256, HUD_H, ART.colors.GLASS);
  txt(track.name, 4, 2, GOLD);
  txt(`LAP ${Math.max(0, c.lap) + 1}`, 120, 2, WHITE);
  txt(`${SURF[c.surf].name}`, 200, 2, c.sliding ? CYAN : DIM);
}

function drawTitle() {
  ctxt('TABLETOP GRAND PRIX', 50, GOLD);
  ['CUP', 'QUICK RACE'].forEach((s, i) => txt(`${i === titleSel ? '> ' : '  '}${s}`, 96, 100 + i * 14, i === titleSel ? WHITE : DIM));
  ctxt('STEP 1: A TEST TABLE', 180, DIM);
}

function drawPause() {
  panel(64, 80, 128, 64);
  ctxt('PAUSED', 88, GOLD);
  ['RESUME', 'RESTART RACE', 'QUIT TO TITLE'].forEach((s, i) => txt(`${i === pauseSel ? '>' : ' '} ${s}`, 76, 104 + i * 10, i === pauseSel ? WHITE : DIM));
}

function panel(x, y, w, h) { rectfill(x, y, w, h, ART.colors.GLASS); rect(x, y, w, h, PANEL); }
function txt(s, x, y, c) { print(s, x + 1, y + 1, SHADOW); print(s, x, y, c); }
const ctxt = (s, y, c) => txt(s, 128 - s.length * 4, y, c);
