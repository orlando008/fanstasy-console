/** A car on waypoint k of the track, facing along it. */
function newCar(seat, k) {
  const c = { seat, x: 0, y: 0, a: 0, vx: 0, vy: 0, st: 0, fall: 0, air: 0, airT: 0, wp: k, lap: 0, sliding: false, surf: S_ROAD, out: false, points: 0 };
  placeAt(c, k, 0, 0);
  return c;
}

/** Put a car on waypoint k, `back` px behind it and `side` px to one side, facing along the track, stopped. */
function placeAt(c, k, back, side) {
  const n = track.n, k1 = (k + 1) % n, dx = track.wx[k1] - track.wx[k], dy = track.wy[k1] - track.wy[k], L = Math.hypot(dx, dy) || 1;
  const ux = dx / L, uy = dy / L;
  c.x = track.wx[k] - ux * back - uy * side; c.y = track.wy[k] - uy * back + ux * side;
  c.a = Math.atan2(uy, ux); c.vx = c.vy = 0; c.st = 0; c.fall = 0; c.air = 0; c.wp = k; c.surf = surfAt(c.x, c.y);
}

/** One frame of a car, from its controls: steer -1, 0 or 1; gas and brake true or false (spec 5.1 to 5.3). */
function drive(c, steer, gas, brake) {
  if (c.fall) { if (--c.fall === 0) knockOut(c); return; }
  if (c.air) { c.air--; moveCar(c); if (!c.air) land(c); follow(c); return; }   // in the air: a straight line, no control
  // The steering builds over STEER_RAMP frames to its full value (the pad is digital).
  c.st = steer ? clamp(c.st + steer / STEER_RAMP, -1, 1) : c.st - sgn(c.st) * Math.min(Math.abs(c.st), 1 / STEER_RAMP);
  const S = SURF[c.surf];
  let ca = Math.cos(c.a), sa = Math.sin(c.a), f = c.vx * ca + c.vy * sa;
  // The turn: full rate from a speed of 1 up, less below it (a car at a standstill cannot spin); backwards it turns the other way.
  c.a += TURN * c.st * clamp(f, -1, 1);
  ca = Math.cos(c.a); sa = Math.sin(c.a);
  f = c.vx * ca + c.vy * sa;
  let side = -c.vx * sa + c.vy * ca;   // the velocity split along the new heading and across it: the grip works on `side`
  if (gas) f = Math.min(f + ACC, Math.max(f, S.top));
  else if (brake) f = f > 0.05 ? Math.max(0, f - BRAKE) : Math.max(f - ACC * 0.6, -REV);
  else f *= ROLL;
  if (f > S.top) f -= (f - S.top) * 0.1;   // a slow surface drags a fast car down to its top speed
  c.sliding = !gas && Math.abs(c.st) > 0.3 && f > 1;
  side *= Math.max(S.keep, c.sliding ? SLIDE_KEEP : 0);
  c.vx = f * ca - side * sa; c.vy = f * sa + side * ca;
  for (const o of track.fans) {   // a fan blows a car away from it (spec 5.6)
    const dx = c.x - o.x, dy = c.y - o.y, d = Math.hypot(dx, dy);
    if (d < FAN_R && d > 0) { const k = FAN_PUSH * (2 - d / FAN_R); c.vx += (dx / d) * k; c.vy += (dy / d) * k; }
  }
  moveCar(c);
  c.surf = surfAt(c.x, c.y);
  if (c.surf === S_RAMP && f >= JUMP_MIN) { c.air = c.airT = flr(16 + 10 * f); fx(SFX.jump); }   // launched: 31 to 36 frames
  else if (c.surf === S_HOLE) startFall(c);
  follow(c);
}

/** Move, one axis at a time, bouncing off walls (spec 5.3). */
function moveCar(c) {
  if (hitsWall(c.x + c.vx, c.y)) { c.vx *= -BOUNCE; c.vy *= SCRAPE; bump(); } else c.x += c.vx;
  if (hitsWall(c.x, c.y + c.vy)) { c.vy *= -BOUNCE; c.vx *= SCRAPE; bump(); } else c.y += c.vy;
}
function land(c) { c.surf = surfAt(c.x, c.y); if (c.surf === S_HOLE) startFall(c); else fx(SFX.land); }
function startFall(c) { c.fall = FALL_T; c.vx = c.vy = 0; fx(SFX.fall); }

let lastBump = -99;
function bump(crash) { if (clock - lastBump > 8) { fx(crash ? SFX.crash : SFX.bump); lastBump = clock; } }

/** Cars that touch are pushed apart and swap their speeds along the line between them, damped (spec 5.3). Cars in the
 * air, falling or out touch nothing. */
function collide() {
  const live = cars.filter((c) => !c.out && !c.fall && !c.air);
  for (const c of live) hitRollers(c);
  for (let i = 0; i < live.length; i++) for (let j = i + 1; j < live.length; j++) {
    const a = live[i], b = live[j], dx = b.x - a.x, dy = b.y - a.y, d = Math.hypot(dx, dy);
    if (d >= 2 * R_CAR) continue;
    const nx = d ? dx / d : 1, ny = d ? dy / d : 0, o = (2 * R_CAR - d) / 2;
    shove(a, -nx * o, -ny * o); shove(b, nx * o, ny * o);
    const an = a.vx * nx + a.vy * ny, bn = b.vx * nx + b.vy * ny;
    if (an - bn > 0) {   // closing: swap the parts along the line
      a.vx += (bn * CAR_DAMP - an) * nx; a.vy += (bn * CAR_DAMP - an) * ny;
      b.vx += (an * CAR_DAMP - bn) * nx; b.vy += (an * CAR_DAMP - bn) * ny;
      bump(true);
    }
  }
}
/** A car that touches a roller bounces off it as off a wall; the roller rolls on (spec 5.6). */
function hitRollers(c) {
  for (const o of track.rollers) {
    const dx = c.x - o.x, dy = c.y - o.y, d = Math.hypot(dx, dy), r = R_CAR + o.r;
    if (d >= r) continue;
    const nx = d ? dx / d : 1, ny = d ? dy / d : 0, vn = c.vx * nx + c.vy * ny;
    shove(c, nx * (r - d), ny * (r - d));
    if (vn < 0) { c.vx -= (1 + BOUNCE) * vn * nx; c.vy -= (1 + BOUNCE) * vn * ny; bump(); }
  }
}
function shove(c, dx, dy) { if (!hitsWall(c.x + dx, c.y + dy)) { c.x += dx; c.y += dy; } }

/** Keep a car's waypoint up to date: move it on (or back) along the centreline as the car passes, counting laps. A car
 * only moves one waypoint at a time, so it cannot jump to a part of the track that lies close by on the table. */
function follow(c) {
  const n = track.n;
  for (let i = 0; i < 4; i++) {
    const k = c.wp, k1 = (k + 1) % n, dx = track.wx[k1] - track.wx[k], dy = track.wy[k1] - track.wy[k];
    const t = ((c.x - track.wx[k]) * dx + (c.y - track.wy[k]) * dy) / (dx * dx + dy * dy);
    if (t >= 1) { c.wp = k1; if (k1 === 0) c.lap++; }
    else if (t < 0 && i === 0) { if (k === 0) c.lap--; c.wp = (k + n - 1) % n; break; }
    else break;
  }
}

/** How far a car is along the race: laps and waypoints (the leader is the car with the most; spec 5.4). */
function progress(c) {
  const n = track.n, k = c.wp, k1 = (k + 1) % n, dx = track.wx[k1] - track.wx[k], dy = track.wy[k1] - track.wy[k];
  const t = clamp(((c.x - track.wx[k]) * dx + (c.y - track.wy[k]) * dy) / (dx * dx + dy * dy), 0, 1);
  return c.lap * n + k + t;
}
/** The car furthest along of those still in the round (and not falling). */
function leader() {
  let best = null;
  for (const c of cars) if (!c.out && !c.fall && (!best || progress(c) > progress(best))) best = c;
  return best;
}

const AI_SAFE = 0.9;      // a bend's speed: TURN x its radius (the speed at which the car's turn just follows it), x this
const STUCK_T = 45, BACK_T = 30;   // a driver that makes no headway for this long reverses out for BACK_T frames
const AVOID_D = 64, AVOID_SIDE = 20;   // a car up to AVOID_D px ahead and in the way: aim AVOID_SIDE px to the side of it

/** A computer driver's controls: [steer, gas, brake] (spec 7). It drives the same physics as a person, with a level `L`
 * and a character `ch`. The bot of the tests calls it for P1's seat with a level of its own. */
function aiControls(c, L = LEVELS[level], ch = CHARS[Math.max(0, seats[c.seat].ch)]) {
  const ai = c.ai || (c.ai = { err: 0, errTo: 0, errT: 0, steer: 0, stuck: 0, back: 0 });
  const t = track, n = t.n, v = Math.hypot(c.vx, c.vy), f = c.vx * Math.cos(c.a) + c.vy * Math.sin(c.a);
  // Stuck against something: back out, steering the other way.
  if (ai.back) { ai.back--; return [-ai.steer, false, true]; }
  ai.stuck = f < 0.25 ? ai.stuck + 1 : 0;
  if (ai.stuck > STUCK_T) { ai.stuck = 0; ai.back = BACK_T; return [0, false, true]; }
  // Its error: a sideways offset from the line that drifts to a new value now and then.
  if (--ai.errT <= 0) { ai.errTo = (rnd(2) - 1) * L.err * ch.err; ai.errT = rndi(60, 120); }
  ai.err += clamp(ai.errTo - ai.err, -0.2, 0.2);
  // The point it steers for: on the line, 3 waypoints ahead and more at speed, moved by the error and round a car ahead.
  const k = (c.wp + 3 + flr(v)) % n, k1 = (k + 1) % n, ux = t.wx[k1] - t.wx[k], uy = t.wy[k1] - t.wy[k], ul = Math.hypot(ux, uy) || 1;
  const rx = -uy / ul, ry = ux / ul;   // to the right
  let side = ai.err;
  for (const o of [...cars, ...track.rollers]) {
    if (o === c || o.out || o.fall) continue;
    const roller = o.r !== undefined;
    const dx = o.x - c.x, dy = o.y - c.y, along = dx * Math.cos(c.a) + dy * Math.sin(c.a), across = -dx * Math.sin(c.a) + dy * Math.cos(c.a);
    if ((ch.avoid || roller) && along > 0 && along < AVOID_D && Math.abs(across) < 16) side += across > 0 ? -AVOID_SIDE : AVOID_SIDE;   // round a car (or a roller) ahead
    if (ch.lean && !roller && Math.abs(along) < 10 && Math.abs(across) < 18) side += sgn(across) * ch.lean;    // MAX leans on the one beside him
  }
  // A wall straight ahead (a nail, a post): aim to the side of it that is clear.
  const ca = Math.cos(c.a), sa = Math.sin(c.a);
  for (const d of [10, 18, 26]) {
    if (!hitsWall(c.x + ca * d, c.y + sa * d)) continue;
    const clearR = !hitsWall(c.x + ca * d - sa * 14, c.y + sa * d + ca * 14), clearL = !hitsWall(c.x + ca * d + sa * 14, c.y + sa * d - ca * 14);
    side += clearR && !clearL ? AVOID_SIDE : clearL && !clearR ? -AVOID_SIDE : (side >= 0 ? AVOID_SIDE : -AVOID_SIDE);
    break;
  }
  const tx = t.lx[k] + rx * side, ty = t.ly[k] + ry * side;
  if (flr(clock + c.seat) % Math.max(1, flr(L.react / 4)) === 0) {
    const d = Math.atan2(Math.sin(Math.atan2(ty - c.y, tx - c.x) - c.a), Math.cos(Math.atan2(ty - c.y, tx - c.x) - c.a));
    ai.steer = d > 0.05 ? 1 : d < -0.05 ? -1 : 0;
  }
  // Its speed: the top speed at its level, less for each bend (and slick patch in a bend) in braking distance ahead.
  let target = TOP * L.throttle * ch.throttle;
  const late = flr((v * L.react) / SPACING);
  for (let j = 1 + late; j <= 12; j++) {
    const q = (c.wp + j) % n;
    let safe = TURN * t.rad[q] * AI_SAFE * L.corner * ch.corner;
    if (Math.abs(t.bend[q]) > 0.5 && surfAt(t.wx[q], t.wy[q]) === S_SLICK) safe = Math.min(safe, ch.slick * L.corner);
    const dist = (j - late) * SPACING;
    target = Math.min(target, Math.sqrt(safe * safe + 2 * BRAKE * dist));
  }
  return [ai.steer, f < target - 0.02, f > target + 0.15];
}
function controls(c) {
  const p = c.seat;
  if (!seats[p].human) return aiControls(c);
  return [(held(RIGHT, p) ? 1 : 0) - (held(LEFT, p) ? 1 : 0), held(A, p), held(B, p)];
}

// --- The camera (spec 5.5): it looks 40 px ahead of the leader, moving 12 % of the way a frame, at most 4 px ---

const LOOK = 40, CAM_K = 0.12, CAM_MAX = 4, HUD_H = 12;
// The squeeze: from SQUEEZE_T frames into a round the camera looks further ahead, SQUEEZE_RATE px a frame more, up to
// LOOK_MAX, so the leader drifts towards the back of the screen and the cars behind it drop off (a pack of equal cars
// would otherwise never split). The look is held to SQUEEZE_X and SQUEEZE_Y px across and down, so the leader stays at
// least 16 px inside the screen.
const SQUEEZE_T = 480, SQUEEZE_RATE = 6 / 60, LOOK_MAX = 112, SQUEEZE_X = 112, SQUEEZE_Y = 90;
let cam = { x: 0, y: 0 };
const lookAhead = () => (phase === 'go' && cars.length > 1 ? Math.min(LOOK_MAX, LOOK + Math.max(0, rtime - SQUEEZE_T) * SQUEEZE_RATE) : LOOK);
function camTarget(c) {
  const look = lookAhead(), tx = c.x + clamp(Math.cos(c.a) * look, -SQUEEZE_X, SQUEEZE_X) - 128;
  const ty = c.y + clamp(Math.sin(c.a) * look, -SQUEEZE_Y, SQUEEZE_Y) - (HUD_H + (224 - HUD_H) / 2);
  return [clamp(tx, 0, track.w * 8 - 256), clamp(ty, -HUD_H, track.h * 8 - 224)];
}
function moveCam(c, cut) {
  const [tx, ty] = camTarget(c);
  if (cut) { cam.x = tx; cam.y = ty; return; }
  cam.x += clamp((tx - cam.x) * CAM_K, -CAM_MAX, CAM_MAX);
  cam.y += clamp((ty - cam.y) * CAM_K, -CAM_MAX, CAM_MAX);
}
const offScreen = (c) => { const x = c.x - cam.x, y = c.y - cam.y; return x < -OUT_MARGIN || x > 256 + OUT_MARGIN || y < -OUT_MARGIN || y > 224 + OUT_MARGIN; };

