/** A car's sprite for its heading, raised in a jump over its shadow on the ground; a falling car shrinks and spins. */
function drawCar(c) {
  if (c.out) return;
  const x = flr(c.x - cam.x) - 8, y = flr(c.y - cam.y) - 8;
  if (c.fall) {   // three sizes, smaller as it drops, turned a quarter every 4 frames
    const k = Math.min(2, flr((FALL_T - c.fall) / (FALL_T / 3))), spin = flr(c.fall / 4) & 3;
    sprite(ART.sprites['fall' + k], x, y, { pal: c.seat, fx: spin === 1 || spin === 2, fy: spin >= 2 });
    return;
  }
  const lift = c.air ? flr(LIFT * Math.sin(Math.PI * (1 - c.air / c.airT))) : 0;
  carSprite(c.seat, c.a, x + 2 + lift, y + 3 + lift, 'shadow', 7);   // the shadow, further off the higher the car
  carSprite(c.seat, c.a, x, y - lift, 'car', c.seat);
}
/** One of the 16 directions: 5 drawings (0 to 90 degrees), the rest flipped. */
function carSprite(seat, a, x, y, name = 'car', pal = seat) {
  const d = ((Math.round(a / (Math.PI / 8)) % 16) + 16) % 16;
  let f = d, fxx = false, fyy = false;
  if (d > 4 && d <= 8) { f = 8 - d; fxx = true; }
  else if (d > 8 && d <= 12) { f = d - 8; fxx = fyy = true; }
  else if (d > 12) { f = 16 - d; fyy = true; }
  sprite(ART.sprites[name + f], x, y, { fx: fxx, fy: fyy, pal, prio: name === 'car' ? 3 : 2 });
}

/** The table, the things on it and the cars (the floor below scrolls at half the camera's speed). */
