  ctxt('TABLETOP GRAND PRIX', 50, GOLD);
  ['CUP', 'QUICK RACE'].forEach((s, i) => txt(`${i === titleSel ? '> ' : '  '}${s}`, 96, 100 + i * 14, i === titleSel ? WHITE : DIM));
