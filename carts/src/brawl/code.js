/** Set sprite palette p to 15 packed colours (r | g << 5 | b << 10): a stage's thug, a wave's Fire-breather or Brute. */
function setPal(p, c) { if (p === 6) bossPal = -1; for (let i = 0; i < 15; i++) color(129 + p * 16 + i, c[i] & 31, (c[i] >> 5) & 31, c[i] >> 10); }

// --- The fighters: drawn frames streamed from the cart's ROM (ART.streams.f) into seven slots of 64 tiles, one for each
// fighter on the screen, picked by animation name (clips h_ for a hero, t_ for a thug; art.py says which exist). ---
const FSLOTS = 7, PRE = { knife: 'k_', chucker: 'c_', lasher: 'l_', fire: 'f_', brute: 'b_' };
const slots = new Map();                                             // a fighter on the screen -> his slot
function slotFor(f) {
  let s = slots.get(f);
  if (s === undefined) {
    const used = [...slots.values()];
    const lim = bossOn ? FSLOTS - 2 : FSLOTS;
    for (s = 0; s < lim && used.includes(s); s++);
    if (s === lim) return -1;
    slots.set(f, s);
  }
  return s;
}
const onScreen = (f) => abs(f.x - cam - 128) < 180;
/** The frame of a fighter's animation to show: a clip by the animation's name, a frame of it by how far the animation has got. */
function frameIndex(f, c = ART.streams.f.clips, pre = f.kind === 'hero' ? 'h_' : PRE[f.type] || 't_', n = f.anim) {
  const hero = f.kind === 'hero', a = animOf(f);
  if (n === 'down') n = f.h > 0 || f.vz !== 0 ? 'fly' : 'lie';
  else if (n === 'tpunch2' || n === 'tpunch3') n = 'tpunch';
  if (hero) n = { wknife: 'punch1', wthrow: 'punch1', pick: 'land', throw: 'grab' }[n] || n;   // the hero's few frames serve more than one animation
  const cl = c[pre + n] || (!hero && f.kind !== 'boss' && c['t_' + n]) || (a.length === 3 && c[pre + 'tpunch']) || c[pre + 'idle'], cnt = cl[1];
  let i;
  if (n === 'idle') i = flr(clock / 24) % cnt;
  else if (n === 'walk') i = (flr((f.x * f.face + f.y) / 5) % cnt + cnt) % cnt;
  else if (a.length > 1) i = Math.min(f.fi, cnt - 1);
  else i = Math.min(cnt - 1, flr(f.ft * cnt / a[0][0]));
  return cl[0] + i;
}

/** Where the near hand and the head are in the frame being shown, from his feet (the hand's x and y, then the head's): ROM 'hands'. */
function anchors(f, i, blob = 'hands') {
  const b = rom(blob), d = f.face;
  return [d * (b[i * 4] - 128), b[i * 4 + 1] - 128, d * (b[i * 4 + 2] - 128), b[i * 4 + 3] - 128];
}

/** THE ART LAYER: a fighter as the frame of his animation, with the effects of the special attacks drawn over it. */
function drawFighter(f) {
  if (f.inv > 0 && flr(clock / 3) % 2 === 0) return;                 // flashes while invulnerable
  if (f.dying && f.anim === 'down' && f.h === 0 && f.lie < 20 && flr(clock / 2) % 2 === 0) return;
  if (!onScreen(f)) return;
  const s = slotFor(f);
  if (s < 0) return;
  const st = ART.streams.f, sx = flr(f.x - cam), by = flr(f.y - f.h), d = f.face, fr = frameOf(f);
  const pal = f.kind === 'hero' ? f.pad : { '': 2, knife: 3, chucker: 4, lasher: 5 }[f.type] ?? 6;
  const fi = frameIndex(f), [hx, hy, ex, ey] = anchors(f, fi);
  streamSprite(st, fi, sx - st.w / 2, by - st.h, { fx: d < 0, slot: s, pal });
  if (f.anim === 'dash' && fr[2] && !f.hits.length) { line(sx - d * 24, by - 52, sx - d * 52, by - 52, WHITE); line(sx - d * 20, by - 38, sx - d * 46, by - 38, WHITE); }
  else if (f.anim === 'fbreath' && f.fi === 1) for (let k = 0; k < 7; k++) circfill(sx + ex + d * (6 + k * 13), by + ey + 4 + flr(Math.sin((clock + k * 3) / 2) * 3), 3 + k * 1.1, [RED, ORANGE, GOLD][(k + flr(clock / 3)) % 3]);   // a stream of flame from his mouth along the hit box
  else if (f.anim === 'cthrow' && f.fi === 0) { rf(sx + hx - 3, by + hy - 14, 6, 12, GREEN); rf(sx + hx - 1, by + hy - 18, 2, 5, GREEN); }   // the Chucker: the bottle in his raised hand
  else if (f.anim === 'wlash') {                                      // the Lasher: the whip drawn back, then a crack along the hit box with a spark at its tip
    if (f.fi === 1) { line(sx + hx, by + hy, sx + hx + d * 46, by + hy - 4, BROWN); line(sx + hx + d * 46, by + hy - 4, sx + d * 116, by + hy + 2, BROWN); line(sx + hx, by + hy + 1, sx + hx + d * 46, by + hy - 3, BROWN); rf(sx + d * 116 - 3, by + hy - 1, 6, 6, WHITE); }
    else { line(sx + hx, by + hy, sx + hx - d * 30, by + hy - 18, BROWN); line(sx + hx - d * 30, by + hy - 18, sx + hx - d * 46, by + hy, BROWN); }
  } else if (f.anim === 'sstab' && f.fi === 1) { line(sx + hx, by + hy, sx + d * fr[2][2], by + hy, WHITE); line(sx + hx, by + hy - 1, sx + d * fr[2][2], by + hy - 1, WHITE); }   // the knife's blade, out to the end of the hit box
  if (f.weapon) {
    drawWeapon(f, sx, by, fr, hx, hy);
    const tag = `${ITEM[f.weapon.kind].name} ${f.weapon.uses}`;
    txt(tag, clamp(sx - tag.length * 4, 2, 254 - tag.length * 8), by - 86, f.weapon.kind === 'knife' ? WHITE : DIM);
  }
}

