/** The weapon in a hero's hand: held up, drawn back for the swing, out along the hit box when it is active. */
function drawWeapon(f, sx, by, fr, ax, ay) {
  const d = f.face, knife = f.weapon.kind === 'knife', len = knife ? 20 : 34, hx = sx + ax, hy = by + ay;
  let tx = hx + d * 6, ty = hy - len;                                // held up
  const swing = f.anim === 'wpipe' || f.anim === 'wknife';
  if (swing && fr[2]) { tx = sx + d * (knife ? 62 : 80); ty = hy; } else if (swing) { tx = hx - d * 8; ty = hy - len; }
  for (let k = -1; k <= (knife ? 0 : 1); k++) line(hx, hy + k, tx, ty + k, knife ? WHITE : DIM);
  if (knife) rf(hx - 3, hy - 3, 7, 7, BROWN);
}

/** The boss as shapes: bigger than a thug, orange, a red headband and a gold belt; he crouches before a charge and sees stars when stunned. */
/** A boss: a frame of stream b (a bigger frame, laid over the fighters' last two slots while he is on), and his effects. */
const BPRE = { bull: 'u_', king: 'u_', razor: 'z_' };
let bossOn = false, bossPal = -1;
function drawBoss(f) {
  if (f.inv > 0 && flr(clock / 3) % 2 === 0) return;
  if (f.dying && f.anim === 'down' && f.h === 0 && f.lie < 20 && flr(clock / 2) % 2 === 0) return;
  const st = ART.streams.b, pre = BPRE[f.type], sx = flr(f.x - cam), by = flr(f.y - f.h), d = f.face, fr = frameOf(f);
  const want = f.type === 'king' && kingRage(f) ? 3 : { bull: 0, razor: 1, king: 2 }[f.type];
  if (bossPal !== want) { setPal(6, SWAP.boss[want]); bossPal = want; }
  let n = f.anim;
  if (n === 'down') n = f.h > 0 || f.vz !== 0 ? 'fly' : 'lie';
  else if (n === 'rslash2') n = 'rslash1';
  const i = frameIndex(f, st.clips, pre, n), [hx, hy, ex, ey] = anchors(f, i, 'bhands');
  streamSprite(st, i, sx - st.w / 2, by - st.h, { fx: d < 0, slot: 0, pal: 6 });
  if (f.anim === 'bcharge') {
    if (f.fi === 0 && flr(clock / 4) % 2 === 0) txt('!', sx + ex - 4, by + ey - 24, RED);          // the warning: he is about to charge
    else if (f.fi === 1) { line(sx - d * 34, by - 62, sx - d * 62, by - 62, WHITE); line(sx - d * 30, by - 46, sx - d * 58, by - 46, WHITE); }
  } else if (f.anim === 'kslam' && fr[2]) { rf(sx - 96, by - 8, 192, 8, flr(clock / 2) % 2 ? WHITE : GOLD); rf(sx - 96, by - 14, 192, 3, WHITE); }   // the wave along the floor
  else if (f.anim === 'bstun') for (let k = 0; k < 3; k++) { const a = clock / 8 + k * 2.1; circfill(sx + ex + flr(Math.cos(a) * 16), by + ey - 18 + flr(Math.sin(a) * 4), 3, GOLD); }
  else if (f.anim === 'rcrouch' && flr(clock / 4) % 2 === 0) txt('!', sx + ex - 4, by + ey - 24, RED);
  else if (/^rslash/.test(f.anim) && fr[2]) { line(sx + hx, by + hy, sx + d * fr[2][2], by + (fr[2][1] + fr[2][3]) / 2, WHITE); line(sx + hx, by + hy - 1, sx + d * fr[2][2], by + (fr[2][1] + fr[2][3]) / 2 - 1, WHITE); }   // the blade out to the end of the hit box
}

function drawBoxes(f) {
  if (f.prop) { rect(flr(f.x + f.box[0] - cam), flr(f.y + f.box[1]), f.box[2] - f.box[0], f.box[3] - f.box[1], GREEN); return; }
  const hb = worldBox(f, frameOf(f)[1]);
  rect(flr(hb[0] - cam), flr(hb[1]), hb[2] - hb[0], hb[3] - hb[1], GREEN);
  const ht = frameOf(f)[2];
  if (ht) { const b = worldBox(f, ht); rect(flr(b[0] - cam), flr(b[1]), b[2] - b[0], b[3] - b[1], RED); }
}

function bar(x, y, w, v, max, c) {
  rf(x, y, w, 6, SHADOW); rf(x + 1, y + 1, clamp(flr((w - 2) * v / max), 0, w - 2), 4, c); rect(x, y, w, 6, DIM);
}

function drawHud() {
  for (const h of players) {                                         // each hero: a bar, his lives and his score
    const x = h.pad ? 136 : 8;
    txt(h.pad ? 'P2' : 'P1', x, 6, h.pad ? GREEN : CYAN); bar(x + 18, 6, 70, h.out ? 0 : h.hp, HERO_HP, h.hp > 20 ? GREEN : RED);
    txt(`x${h.lives}`, x + 94, 6, h.lives > 1 ? WHITE : RED);
    txt(`${h.score}`.padStart(7, '0'), x, 18, h.out ? DIM : WHITE);
  }
  if (players.length < 2 && state === 'play' && clock % 60 < 40) txt('P2 PRESS A', 160, 6, DIM);   // the second player can join
  const boss = enemies.find((e) => e.kind === 'boss');
  if (boss) { const nm = BOSS[boss.type].name, nx = 12 + nm.length * 8; txt(nm, 8, 209, GOLD); bar(nx, 210, 248 - nx, Math.max(0, boss.hp), boss.maxhp, RED); }
  if (warnT > 0 && warnT % 24 < 16) ctxt('WARNING', 40, RED);
  if (bannerT > 0 && state === 'play') { ctxt(`STAGE ${stage + 1}`, 60, GOLD); ctxt(ST.name, 74, WHITE); }
  if (lastHit && lastHitT > 0 && lastHit.kind === 'thug') bar(players.length > 1 ? 72 : 80, 18, 52, Math.max(0, lastHit.hp), lastHit.maxhp, 6);
  if (!locked && wave < LEVEL.length + 1 && wave > 0 && goT % 40 < 26 && state === 'play') txt('GO >', 214, 96, GOLD);
}

