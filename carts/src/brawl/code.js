/** Queue one of ART.sprites at (x, y), above the background; opts as for spr (fx, fy ...). */
function sprite(s, x, y, opts = {}) { spr(s.tile, x, y, { size: s.size, pal: s.pal, prio: 3, ...opts }); }

// --- Sound (SPEC 5). Any channel plays any instrument. Songs use channels 0 to 5; effects take turns on 6 and 7, ---
// so they never cut into the music and two can sound at once.

const SFX = { move: 0, select: 1, pause: 2, hit: 3, over: 4, point: 5, record: 6 };
const SONG = { title: 0, play: 1 };
const SFX_CH = [7, 6];
let fxNext = 0;
function fx(n) { sfx(n, SFX_CH[fxNext]); fxNext ^= 1; }

// A song is only started if it is not already playing.
let playing = -1;
function play(song) {
  if (song === playing) return;
  playing = song; music(song);
}

// --- Save slots (SPEC 13) ---

const VERSION_SLOT = 0, SAVE_VERSION = 1, INITIALS_SLOT = 1;
const TOP_SLOT = 10, TOP_N = 10, ENTRY = 3; // the top 10, best first: score, initials, a spare (slots 10 to 39)
const LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';

function readEntry(i) { const s = TOP_SLOT + i * ENTRY; return { score: dget(s), initials: unpackInitials(dget(s + 1)) }; }
function writeEntry(i, e) { const s = TOP_SLOT + i * ENTRY; dset(s, e.score); dset(s + 1, packInitials(e.initials)); }
const topTen = () => Array.from({ length: TOP_N }, (_, i) => readEntry(i));

/** Put a score into the top 10 if it makes it. Returns its row, or -1. */
function insertTop(e) {
  if (!e.score) return -1;
  const list = topTen(), at = list.findIndex((x) => e.score > x.score);
  if (at < 0) return -1;
  list.splice(at, 0, e);
  for (let i = at; i < TOP_N; i++) writeEntry(i, list[i]);
  return at;
}
/** Three characters, 8 bits each. */
const packInitials = (str) => (str.charCodeAt(0) << 16) | (str.charCodeAt(1) << 8) | str.charCodeAt(2);
const unpackInitials = (v) => (v ? String.fromCharCode((v >> 16) & 255, (v >> 8) & 255, v & 255) : '---');
const lastInitials = () => (dget(INITIALS_SLOT) ? unpackInitials(dget(INITIALS_SLOT)) : 'AAA');

// --- Input: edge-triggered presses (btnp repeats; menus want one press) ---

let inputMask = 0, prevMask = 0;
const BUTTONS = [UP, DOWN, LEFT, RIGHT, A, B, X, Y, L, R, START, SELECT];
function readPad() { let m = 0; for (const b of BUTTONS) if (btn(b)) m |= 1 << b; return m; }
const pressed = (b) => (inputMask & (1 << b)) !== 0 && (prevMask & (1 << b)) === 0;

// --- The street: lanes, the camera, and the frame table (docs/carts/brawl.md, section 5) ---

const LANE_TOP = 150, LANE_BOT = 208, LANE_TOL = 12;        // a fighter's feet are at y, the lane is the pavement
const LEVEL_W = 1024, GRAV = 0.3, HITSTOP = 5;
const HERO_HP = 60, THUG_HP = 20;
// The waves: the camera stops at x, n thugs come in from the sides, and it holds until they are all down.
const LEVEL = [{ x: 0, n: 2 }, { x: 300, n: 3 }, { x: 560, n: 3 }, { x: 768, n: 4 }];

// Every animation is a list of frames [duration, hurt box, hit box or null]. Boxes are [x0, y0, x1, y1] from the feet,
// facing right, up is negative. Real art must have its feet at the same pivot and fit these (or the boxes are tuned).
const STAND = [-14, -92, 14, 0], LYING = [-40, -18, 40, 0];
const ANIM = {
  idle: [[30, STAND, null]],
  walk: [[30, STAND, null]],
  punch1: [[4, STAND, null], [3, STAND, [14, -72, 50, -58]], [7, STAND, null]],
  punch2: [[4, STAND, null], [3, STAND, [14, -72, 50, -58]], [7, STAND, null]],
  hook: [[6, STAND, null], [4, STAND, [14, -78, 58, -56]], [12, STAND, null]],
  jump: [[999, STAND, null]],
  jkick: [[4, STAND, null], [999, STAND, [10, -44, 50, -20]]],
  land: [[6, STAND, null]],
  hurt: [[16, STAND, null]],
  down: [[999, LYING, null]],
  getup: [[20, STAND, null]],
  tpunch: [[18, STAND, null], [4, STAND, [14, -74, 52, -60]], [22, STAND, null]],
};
// What an attack does: damage, hit stun (frames, with a knock back of 6 px over them) or a knockdown.
const MOVE = {
  punch1: { dmg: 4, stun: 16 }, punch2: { dmg: 4, stun: 16 }, hook: { dmg: 6, down: 1 }, jkick: { dmg: 6, down: 1 },
  tpunch: { dmg: 5, stun: 16 },
};
const COMBO = { punch1: 'punch2', punch2: 'hook' };

// --- State ---

let skipTitle = false; // tests set this to land straight in the game
let state = 'title', paused = false, timer = 0, clock = 0;
let titleSel = 0, pauseSel = 0, rank = -1, hl = -1, initials = null;
let score = 0, lives = 3, won = false;
let player = null, enemies = [], cam = 0, wave = 0, locked = false, hitstop = 0, showBoxes = false, goT = 0, lastHit = null, lastHitT = 0;

function init() {
  if (dget(VERSION_SLOT) !== SAVE_VERSION) { // a new or older save: start clean
    for (let i = 0; i < 256; i++) dset(i, 0);
    dset(VERSION_SLOT, SAVE_VERSION);
  }
  // The street: the far city, the fence and the pavement, each a full picture that repeats sideways; the sky is a
  // gradient in scanline(). The camera scrolls them at 0.3, 0.6 and 1.
  for (const [l, name] of [[2, 'city'], [1, 'fence'], [0, 'ground']]) {
    const s = ART.scenes[name];
    bg(l, { mx: s.mx, my: s.my, mw: s.w, mh: s.h, x: 0, y: 0, wrap: true, show: true });
  }
  blend({ layers: ['overlay'], half: true }); // overlay colours from 192 up (ART.colors.GLASS) are see-through
  if (skipTitle) startGame(); else toTitle();
}

function toTitle() { state = 'title'; timer = 0; titleSel = 0; paused = false; scroll(0); play(SONG.title); }

function startGame() {
  score = 0; lives = 3; won = false; paused = false; timer = 0; state = 'play';
  cam = 0; wave = 0; locked = false; hitstop = 0; goT = 0; enemies = []; lastHit = null; lastHitT = 0;
  player = mkFighter('hero', 90, 180, HERO_HP);
  play(SONG.play);
}

function mkFighter(kind, x, y, hp) {
  return { kind, x, y, h: 0, vx: 0, vz: 0, face: 1, anim: 'idle', fi: 0, ft: 0, hp, hits: [], conn: false, connT: 99, queue: false,
    inv: 0, lie: 0, dying: false, ai: 'enter', cool: 40, token: false, tokenT: 0, seed: 0 };
}

// --- Animations and boxes ---

function setAnim(f, name) { f.anim = name; f.fi = 0; f.ft = 0; f.hits = []; f.conn = false; f.connT = 99; f.queue = false; }
const frameOf = (f) => { const a = ANIM[f.anim]; return a[Math.min(f.fi, a.length - 1)]; };
/** Advance a frame; true when the animation has run its course. */
function stepAnim(f) {
  const a = ANIM[f.anim];
  if (f.fi < a.length && ++f.ft >= a[f.fi][0]) { f.ft = 0; f.fi++; }
  return f.fi >= a.length;
}
/** A box in the world: x in the world, y on the screen (the height of a jump lifts it), mirrored for facing left. */
function worldBox(f, b) {
  const y = f.y - f.h;
  return f.face > 0 ? [f.x + b[0], y + b[1], f.x + b[2], y + b[3]] : [f.x - b[2], y + b[1], f.x - b[0], y + b[3]];
}
const overlaps = (a, b) => a[0] < b[2] && b[0] < a[2] && a[1] < b[3] && b[1] < a[3];
const canBeHit = (f) => f.anim !== 'down' && f.anim !== 'getup' && f.inv <= 0 && !f.dying;

// --- Hits ---

function checkHits(a, targets) {
  const fr = frameOf(a), mv = MOVE[a.anim];
  if (!fr[2] || !mv) return;
  const hb = worldBox(a, fr[2]);
  for (const t of targets) {
    if (a.hits.includes(t) || !canBeHit(t) || Math.abs(a.y - t.y) > LANE_TOL) continue;
    if (overlaps(hb, worldBox(t, frameOf(t)[1]))) landHit(a, t, mv);
  }
}

function landHit(a, t, mv) {
  a.hits.push(t); a.conn = true; a.connT = 0; hitstop = HITSTOP; t.hp -= mv.dmg;
  const dir = a.x <= t.x ? 1 : -1;
  t.face = -dir; t.token = false; t.queue = false;
  if (a === player) { score += 10; lastHit = t; lastHitT = 180; }
  if (t.hp <= 0 || mv.down) knockDown(t, dir);
  else { setAnim(t, 'hurt'); t.vx = dir * 6 / 16; }
  fx(SFX.hit);
}

function knockDown(f, dir) {
  setAnim(f, 'down'); f.vz = 3.4; f.vx = dir * 2.4; f.h = Math.max(f.h, 0.1); f.lie = 0;
  if (f.hp <= 0 && !f.dying) { f.dying = f.kind === 'thug'; if (f.kind === 'thug') { score += 100; fx(SFX.point); } }
}

/** Gravity: true on the frame a fighter lands. */
function fall(f) {
  if (f.h <= 0 && f.vz === 0) return false;
  f.h += f.vz; f.vz -= GRAV;
  if (f.h <= 0) { f.h = 0; f.vz = 0; return true; }
  return false;
}
function clampX(f) { f.x = Math.max(10, Math.min(LEVEL_W - 10, f.x)); }

/** The part of an animation shared by everyone: a hit stun, a fall and the getting up. True if it took the frame. */
function updateShared(f) {
  if (f.anim === 'hurt') {
    f.x += f.vx; clampX(f);
    if (stepAnim(f)) { f.vx = 0; setAnim(f, 'idle'); }
    return true;
  }
  if (f.anim === 'down') {
    if (f.h > 0 || f.vz !== 0) { f.x += f.vx; clampX(f); if (fall(f)) { f.vx = 0; f.lie = 40; } }
    else if (--f.lie <= 0) downEnded(f);
    return true;
  }
  if (f.anim === 'getup') { if (stepAnim(f)) setAnim(f, 'idle'); return true; }
  return false;
}

function downEnded(f) {
  if (f.kind === 'thug') { if (f.dying) f.gone = 1; else { setAnim(f, 'getup'); f.cool = 30; } return; }
  if (f.hp > 0) { setAnim(f, 'getup'); f.inv = 60; return; }
  if (--lives <= 0) { lives = 0; gameOver(false); return; }
  Object.assign(f, mkFighter('hero', cam + 128, 180, HERO_HP)); f.anim = 'getup'; f.inv = 120;
}

// --- The hero ---

function updateHero(p) {
  if (p.inv > 0) p.inv--;
  p.connT++;
  if (updateShared(p)) return;
  const dx = (btn(RIGHT) ? 1 : 0) - (btn(LEFT) ? 1 : 0), dy = (btn(DOWN) ? 1 : 0) - (btn(UP) ? 1 : 0);
  const a = p.anim;
  if (a === 'jump' || a === 'jkick') {                               // in the air: keep the walking speed
    p.x += dx * 1.4; p.y = Math.max(LANE_TOP, Math.min(LANE_BOT, p.y + dy * 0.9)); clampX(p);
    if (a === 'jump' && pressed(A)) setAnim(p, 'jkick');
    else if (a === 'jkick') stepAnim(p);
    if (fall(p)) setAnim(p, 'land');
    return;
  }
  if (a === 'punch1' || a === 'punch2' || a === 'hook') {
    if (pressed(A) && COMBO[a]) p.queue = true;
    const ended = stepAnim(p);
    if (COMBO[a] && p.queue && p.conn && p.connT <= 12 && (p.fi >= 2 || ended)) setAnim(p, COMBO[a]);
    else if (ended) setAnim(p, 'idle');
    return;
  }
  if (a === 'land') { if (stepAnim(p)) setAnim(p, 'idle'); return; }
  if (pressed(B)) { setAnim(p, 'jump'); p.vz = 5.2; p.h = 0.1; return; }
  if (pressed(A)) { setAnim(p, 'punch1'); return; }
  if (dx) p.face = dx;
  p.x += dx * 1.4; p.y = Math.max(LANE_TOP, Math.min(LANE_BOT, p.y + dy * 0.9)); clampX(p);
  const moving = dx || dy;
  if (moving && a !== 'walk') setAnim(p, 'walk'); else if (!moving && a !== 'idle') setAnim(p, 'idle');
  else stepAnim(p);
}

// --- The thug ---

function spawnWave(w) {
  for (let i = 0; i < w.n; i++) {
    const side = (i + wave) % 2 === 0 ? -1 : 1;                      // from the left edge, or from the right
    const t = mkFighter('thug', side < 0 ? cam - 24 - i * 10 : cam + 280 + i * 10, rndi(LANE_TOP + 4, LANE_BOT - 4), THUG_HP);
    t.face = -side; t.anim = 'walk'; t.cool = rndi(40, 90);
    enemies.push(t);
  }
}

const tokens = () => enemies.filter((e) => e.token).length;

function updateThug(t) {
  if (t.inv > 0) t.inv--;
  if (updateShared(t) || t.ai === 'dummy') return;                   // (a dummy is a punching bag for the tests)
  const p = player;
  if (t.anim === 'tpunch') {
    if (stepAnim(t)) { setAnim(t, 'walk'); t.token = false; t.cool = rndi(60, 120); }
    return;
  }
  if (t.cool > 0) t.cool--;
  let tx, ty;
  if (t.ai === 'enter') {                                            // walk in from off the screen
    tx = t.x < cam + 20 ? t.x + 10 : t.x > cam + 236 ? t.x - 10 : t.x; ty = t.y;
    if (t.x >= cam + 16 && t.x <= cam + 240) t.ai = 'fight';
    if (tx === t.x && ty === t.y) t.ai = 'fight';
  } else {
    const side = t.x >= p.x ? 1 : -1;
    if (!t.token && t.cool <= 0 && tokens() < 2 && p.hp > 0 && p.anim !== 'down') { t.token = true; t.tokenT = 0; }
    if (t.token && ++t.tokenT > 300) { t.token = false; t.cool = 60; }
    const gap = t.token ? 36 : 85;
    tx = p.x + side * gap; ty = p.y;
    if (tx < cam + 16 || tx > cam + 240) tx = p.x - side * gap;   // never wait off the screen: use the hero's other side
  }
  const mx = tx - t.x, my = ty - t.y;
  const walking = Math.abs(mx) > 2 || Math.abs(my) > 2;
  if (walking) { t.x += Math.sign(mx) * Math.min(0.8, Math.abs(mx)); t.y += Math.sign(my) * Math.min(0.6, Math.abs(my)); }
  t.y = Math.max(LANE_TOP, Math.min(LANE_BOT, t.y)); t.x = Math.max(cam - 60, Math.min(cam + 316, t.x));
  for (const o of enemies) if (o !== t && Math.abs(o.x - t.x) < 18 && Math.abs(o.y - t.y) < 8) t.x += t.x >= o.x ? 0.5 : -0.5;
  if (t.ai === 'fight') t.face = p.x >= t.x ? 1 : -1;
  else t.face = Math.sign(mx) || t.face;
  if (t.ai === 'fight' && t.token && Math.abs(p.y - t.y) <= 6 && Math.abs(p.x - t.x) >= 26 && Math.abs(p.x - t.x) <= 44) { setAnim(t, 'tpunch'); return; }
  if (walking && t.anim !== 'walk') setAnim(t, 'walk'); else if (!walking && t.anim !== 'idle') setAnim(t, 'idle');
}

// --- The level: the camera, the waves, the end ---

function updateCamera() {
  const next = LEVEL[wave];
  if (!locked) {
    const limit = next ? next.x : LEVEL_W - 256;
    cam = Math.min(Math.max(cam, player.x - 112), limit, LEVEL_W - 256);
    if (next && cam >= next.x) { locked = true; spawnWave(next); wave++; }
  } else if (enemies.length === 0) {
    locked = false;
    if (wave >= LEVEL.length) { clearStage(); return; }
    goT = 0;
  }
  player.x = Math.max(cam + 10, Math.min(cam + 246, player.x));
}

function clearStage() {
  score += player.hp * 10 + lives * 500; won = true; gameOver(true);
}

// --- Update ---

function update() {
  inputMask = readPad(); clock++;
  if (!paused) timer++; // a state's clock: it stands still while paused
  if (paused) updatePause();
  else if (state === 'title') updateTitle();
  else if (state === 'play') updatePlay();
  else if (state === 'over') updateOver();
  else if (state === 'initials') updateInitials();
  else if (state === 'records') updateRecords();
  prevMask = inputMask;
}

function updateTitle() {
  if (pressed(UP) || pressed(DOWN)) { titleSel ^= 1; fx(SFX.move); }
  if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (titleSel === 0) startGame(); else { state = 'records'; hl = -1; timer = 0; }
  }
}

function updatePlay() {
  if (pressed(START)) { paused = true; pauseSel = 0; fx(SFX.pause); return; }
  if (pressed(SELECT)) showBoxes = !showBoxes;
  if (lastHitT > 0) lastHitT--;
  if (hitstop > 0) {                                                 // both fighters freeze on a hit
    hitstop--; if (pressed(A) && COMBO[player.anim]) player.queue = true; // (a press during the freeze still counts)
    return;
  }
  updateHero(player);
  for (const e of enemies) updateThug(e);
  checkHits(player, enemies);
  for (const e of enemies) checkHits(e, [player]);
  enemies = enemies.filter((e) => !e.gone);
  if (state !== 'play') return;
  updateCamera();
  goT++;
}

function gameOver(clear) {
  state = 'over'; won = clear; timer = 0; play(-1); fx(clear ? SFX.record : SFX.over);
  rank = insertTop({ score, initials: lastInitials() });
}

function updateOver() {
  if (timer < 60 || !(pressed(A) || pressed(START))) return;
  fx(SFX.select);
  if (rank >= 0) { state = 'initials'; timer = 0; initials = { chars: lastInitials().split(''), pos: 0 }; fx(SFX.record); }
  else toTitle();
}

/** UP/DOWN pick a letter, LEFT/RIGHT (or A and B) move, START saves (as does A on the last letter). */
function updateInitials() {
  const ini = initials, k = LETTERS.indexOf(ini.chars[ini.pos]);
  if (pressed(UP)) { ini.chars[ini.pos] = LETTERS[(k + 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(DOWN)) { ini.chars[ini.pos] = LETTERS[(k + LETTERS.length - 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(LEFT) || pressed(B)) ini.pos = Math.max(0, ini.pos - 1);
  if (pressed(RIGHT)) ini.pos = Math.min(2, ini.pos + 1);
  const done = pressed(START) || (pressed(A) && ini.pos === 2);
  if (pressed(A) && ini.pos < 2) ini.pos++;
  if (!done || timer < 20) return;
  const v = packInitials(ini.chars.join(''));
  dset(INITIALS_SLOT, v); dset(TOP_SLOT + rank * ENTRY + 1, v);
  fx(SFX.select);
  state = 'records'; hl = rank; timer = 0;
}

function updateRecords() {
  if ((pressed(START) || pressed(A) || pressed(B)) && timer > 20) { fx(SFX.select); toTitle(); }
}

function updatePause() {
  if (pressed(UP)) { pauseSel = (pauseSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { pauseSel = (pauseSel + 1) % 3; fx(SFX.move); }
  if (pressed(B) || (pressed(START) && pauseSel === 0)) { paused = false; fx(SFX.pause); }
  else if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (pauseSel === 0) paused = false;
    else if (pauseSel === 1) startGame(); // restart
    else toTitle(); // quitting abandons the game: nothing is recorded
  }
}

// --- Draw ---

function scroll(c) { bgscroll(2, flr(c * 0.3), 0); bgscroll(1, flr(c * 0.6), 0); bgscroll(0, flr(c), 0); }

function draw() {
  cls();
  scroll(state === 'play' || state === 'over' ? cam : 0);
  if (state === 'play' || state === 'over') drawPlay();
  else if (state === 'title') drawTitle();
  else if (state === 'initials') drawInitials();
  else if (state === 'records') drawRecords();
  if (state === 'over') {
    panel(48, 80, 160, 64);
    ctxt(won ? 'STAGE CLEAR' : 'GAME OVER', 92, won ? GOLD : RED); ctxt(`SCORE ${score}`, 108, WHITE);
    if (timer > 60 && timer % 60 < 40) ctxt('START: CONTINUE', 126, DIM);
  }
  if (paused) drawPause();
}

function drawPlay() {
  const all = [player, ...enemies].sort((a, b) => a.y - b.y);        // nearer the bottom of the screen is in front
  for (const f of all) drawShadow(f);
  for (const f of all) drawFighter(f);
  if (showBoxes) for (const f of all) drawBoxes(f);
  drawHud();
}

function drawShadow(f) {
  const sx = flr(f.x - cam), w = Math.max(8, 16 - flr(f.h / 4));
  rectfill(sx - w, f.y - 2, w * 2, 4, SHADOW); rectfill(sx - w + 2, f.y - 3, w * 2 - 4, 6, SHADOW);
}

/**
 * THE ART LAYER. A fighter drawn as plain shapes from the frame table: the hurt box is the body, with a head and legs, and
 * a fist where the hit box is. Real frames replace this one function (the same feet, boxes and timings).
 */
function drawFighter(f) {
  if (f.inv > 0 && flr(clock / 3) % 2 === 0) return;                 // flashes while invulnerable
  if (f.dying && f.anim === 'down' && f.h === 0 && f.lie < 20 && flr(clock / 2) % 2 === 0) return;
  const hero = f.kind === 'hero', coat = hero ? 8 : 6, pants = hero ? 2 : 1, skin = 12, fist = f.hits.length ? GOLD : 9;
  const sx = flr(f.x - cam), by = flr(f.y - f.h), d = f.face;
  if (f.anim === 'down') {                                           // lying on the ground, or flying through the air
    const air = f.h > 0 || f.vz !== 0;
    if (air) { rectfill(sx - 30, by - 36, 60, 18, coat); circfill(sx - d * 34, by - 28, 9, skin); }
    else { rectfill(sx - 40, by - 14, 56, 14, coat); rectfill(sx + 14 * -d - 2, by - 12, 24, 10, pants); circfill(sx + d * 40 * -1, by - 8, 8, skin); }
    return;
  }
  const hurt = f.anim === 'hurt' && f.ft < 4;
  const walk = f.anim === 'walk' ? flr(clock / 6) % 2 : 0, lean = f.anim === 'hurt' ? -d * 4 : 0;
  const air = f.h > 0;
  if (air) { rectfill(sx - 10 + lean, by - 40, 8, 40, pants); rectfill(sx + 2 + lean, by - 34, 8, 30, pants); }
  else { rectfill(sx - 10 + lean, by - 40, 8, 40 - walk * 4, pants); rectfill(sx + 2 + lean, by - 40, 8, 36 + walk * 4, pants); }
  rectfill(sx - 14 + lean, by - 74, 28, 36, hurt ? WHITE : coat);                              // the torso
  circfill(sx + d * 2 + lean, by - 82, 9, skin);                                                // the head
  rectfill(sx + d * 6 + lean - 1, by - 84, 3, 3, SHADOW);                                       // an eye, on the side he faces
  const fr = frameOf(f), mv = MOVE[f.anim];
  if (mv) {                                                          // an attack: the fist cocked, then out at the hit box
    let fx0 = d * 16, fy0 = -62;
    if (fr[2]) { const b = fr[2]; fx0 = d * ((b[0] + b[2]) / 2); fy0 = (b[1] + b[3]) / 2; }
    else if (f.fi === 0) { fx0 = -d * 12; fy0 = -64; }
    const fx1 = sx + fx0, fy1 = by + fy0;
    line(sx + d * 8, by - 66, fx1, fy1, skin); line(sx + d * 8, by - 65, fx1, fy1 + 1, skin);
    rectfill(fx1 - 6, fy1 - 6, 12, 12, fr[2] ? fist : coat);
  } else {                                                           // guard: the fists up
    rectfill(sx + d * 14 + lean - 4, by - 70, 8, 8, skin);
  }
}

function drawBoxes(f) {
  const hb = worldBox(f, frameOf(f)[1]);
  rect(flr(hb[0] - cam), flr(hb[1]), hb[2] - hb[0], hb[3] - hb[1], GREEN);
  const ht = frameOf(f)[2];
  if (ht) { const b = worldBox(f, ht); rect(flr(b[0] - cam), flr(b[1]), b[2] - b[0], b[3] - b[1], RED); }
}

function bar(x, y, w, v, max, c) {
  rectfill(x, y, w, 6, SHADOW); rectfill(x + 1, y + 1, Math.max(0, flr((w - 2) * v / max)), 4, c); rect(x, y, w, 6, DIM);
}

