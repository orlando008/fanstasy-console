function addHero(pad, x, y) {
  const h = mkFighter('hero', x, y, HERO_HP);
  h.pad = pad; h.lives = 3; h.score = 0; players.push(h);
  return h;
}
const heroes = () => players.filter((h) => !h.out);                   // the ones still in the game

function mkFighter(kind, x, y, hp) {
  return { kind, x, y, h: 0, vx: 0, vz: 0, face: 1, anim: 'idle', fi: 0, ft: 0, hp, hits: [], conn: false, connT: 99, queue: false, queueUp: false,
    pad: 0, lives: 0, score: 0, out: false, flash: 0, tier: 3, maxhp: hp, type: kind === 'boss' ? 'bull' : '', v: 0, retreat: 0, vy: 0, back: false, weapon: null, grab: null, gt: 0, gcount: 0, held: null, thrown: null, hitBy: [], inv: 0, lie: 0, dying: false, ai: 'enter', cool: 40, token: false, tokenT: 0, seed: 0 };
}

// --- Animations and boxes ---

// The sound each animation starts with (a swing of the fist or the foot, a jump).
const CUE = { punch1: SFX.swing, punch2: SFX.swing, hook: SFX.swing, jkick: SFX.swing, tpunch: SFX.swing, tpunch2: SFX.swing, tpunch3: SFX.swing, sstab: SFX.swing, wlash: SFX.swing, hsmash: SFX.swing, bpunch: SFX.swing, bcharge: SFX.slam, rslash1: SFX.swing, rslash2: SFX.swing, rslash3: SFX.swing, kslam: SFX.swing, wthrow: SFX.swing, rleap: SFX.jump, jump: SFX.jump, special: SFX.swing, dash: SFX.swing, wpipe: SFX.swing, wknife: SFX.swing, uppercut: SFX.swing };
function setAnim(f, name) { if (CUE[name] !== undefined) fx(CUE[name]); f.anim = name; f.fi = 0; f.ft = 0; f.hits = []; f.conn = false; f.connT = 99; f.queue = false; f.queueUp = false; }
const BOSS_ANIM = BULL_ANIM;
// The Brute (a heavy thug): a wider, taller hurt box, and one slow club smash.
const BR = [-20, -100, 20, 0];
const BRUTE_ANIM = {
  idle: [[30, BR, null]], walk: [[30, BR, null]], hurt: [[16, BR, null]], getup: [[22, BR, null]], down: [[999, [-46, -22, 46, 0], null]],
  hsmash: [[28, BR, null], [5, BR, [10, -98, 68, -50]], [26, BR, null]],
};
const animOf = (f) => (f.kind === 'boss' ? { bull: BULL_ANIM, razor: RAZOR_ANIM, king: KING_ANIM }[f.type] : f.type === 'brute' ? BRUTE_ANIM : ANIM)[f.anim];
const frameOf = (f) => { const a = animOf(f); return a[Math.min(f.fi, a.length - 1)]; };
/** Advance a frame; true when the animation has run its course. */
function stepAnim(f) {
  const a = animOf(f);
  if (f.fi < a.length && ++f.ft >= a[f.fi][0]) { f.ft = 0; f.fi++; }
  return f.fi >= a.length;
}
/** A box in the world: x in the world, y on the screen (the height of a jump lifts it), mirrored for facing left. */
function worldBox(f, b) {
  const y = f.y - f.h;
  return f.face > 0 ? [f.x + b[0], y + b[1], f.x + b[2], y + b[3]] : [f.x - b[2], y + b[1], f.x - b[0], y + b[3]];
}
const overlaps = (a, b) => a[0] < b[2] && b[0] < a[2] && a[1] < b[3] && b[1] < a[3];
const canBeHit = (f) => f.anim !== 'down' && f.anim !== 'getup' && f.inv <= 0 && !f.dying && !((f.anim === 'special' || f.anim === 'dash') && f.fi < 2);

// --- Hits ---

function checkHits(a, targets) {
  const fr = frameOf(a), mv = MOVE[a.anim];
  if (!fr[2] || !mv) return;
  const hb = worldBox(a, fr[2]);
  for (const t of targets) {
    if (a.anim === 'dash' && a.hits.length) break;                    // the dash stops at the first thing it hits
    if (a.hits.includes(t) || !canBeHit(t) || Math.abs(a.y - t.y) > LANE_TOL) continue;
    if (overlaps(hb, worldBox(t, frameOf(t)[1]))) landHit(a, t, mv);
  }
}

/** Heroes can hit each other (friendly fire): 1 damage and a hit stun, never a knockdown, never below 1 health, no score. */
function landHit(a, t, mv) {
  const friendly = a.kind === 'hero' && t.kind === 'hero';
  const dmg = Math.round(mv.dmg * (a.kind === 'boss' ? BOSS[a.type].mult || 1 : 1));   // the last boss hits harder
  a.hits.push(t); a.conn = true; a.connT = 0; hitstop = HITSTOP; t.hp -= friendly ? 1 : dmg;
  if (friendly) t.hp = Math.max(1, t.hp);
  const dir = a.x <= t.x ? 1 : -1;
  t.face = -dir; t.token = false; t.queue = false;
  if (t.grab) release(t);                                            // a hero who is hit lets go
  if (t.weapon) dropWeapon(t);                                       // and drops his weapon
  if (a.kind === 'hero' && !friendly) { a.score += 10; lastHit = t; lastHitT = 180; }
  if (t.type === 'brute' && !mv.down && t.hp > 0) { t.flash = 6; fx(SFX.hit); return; }   // a Brute only flinches at a blow that does not knock down
  if (t.kind === 'boss') { bossHurt(t, dir, a); fx(SFX.hit); return; }   // armour: no hit stun
  if (!friendly && (t.hp <= 0 || mv.down || t.h > 0)) knockDown(t, dir, a, mv.lift);   // a hit in the air always knocks down (he must fall)
  else { setAnim(t, 'hurt'); t.vx = dir * 6 / 16; }
  fx(mv.down ? SFX.slam : SFX.hit);
}

function knockDown(f, dir, by, lift) {
  setAnim(f, 'down'); f.vz = lift || 3.4; f.vx = dir * (lift ? 0.6 : 2.4);   // a lift pops him up and lands him close
  f.h = Math.max(f.h, 0.1); f.lie = 0;
  if (f.hp <= 0 && !f.dying) {
    f.dying = f.kind !== 'hero';
    if (f.dying) { if (by && by.kind === 'hero') by.score += f.kind === 'boss' ? BOSS[f.type].points : ROLE[f.type].pts; fx(SFX.point); if (f.kind === 'boss') spawnItem(BOSS[f.type].drop, f.x, f.y); else if (f.type === 'knife') spawnItem('knife', f.x, f.y, 6); }
  }
}

/** Gravity: true on the frame a fighter lands. */
function fall(f) {
  if (f.h <= 0 && f.vz === 0) return false;
  f.h += f.vz; f.vz -= GRAV;
  if (f.h <= 0) { f.h = 0; f.vz = 0; return true; }
  return false;
}
function clampX(f) { f.x = Math.max(10, Math.min(LEVEL_W - 10, f.x)); }

/** The part of an animation shared by everyone: a hit stun, a fall and the getting up. True if it took the frame. */
function updateShared(f) {
  if (f.anim === 'hurt') {
    f.x += f.vx; clampX(f); fall(f);                                 // (hurt in the air: he comes down)
    if (stepAnim(f)) { f.vx = 0; setAnim(f, 'idle'); }
    return true;
  }
  if (f.anim === 'down') {
    if (f.h > 0 || f.vz !== 0) { f.x += f.vx; clampX(f); if (fall(f)) { f.vx = 0; f.lie = 40; f.thrown = null; fx(SFX.thud); } }
    else if (--f.lie <= 0) downEnded(f);
    return true;
  }
  if (f.anim === 'getup') { if (stepAnim(f)) setAnim(f, 'idle'); return true; }
  return false;
}

function downEnded(f) {
  if (f.kind !== 'hero') { if (f.dying) f.gone = 1; else { setAnim(f, 'getup'); f.cool = 30; f.inv = f.kind === 'boss' ? 30 : 0; } return; }
  if (f.hp > 0) { setAnim(f, 'getup'); f.inv = 60; return; }
  if (--f.lives <= 0) {                                              // out of lives: out of the game (the other goes on)
    f.lives = 0; f.out = true;
    if (!heroes().length) gameOver(false);
    return;
  }
  const keep = { pad: f.pad, lives: f.lives, score: f.score };
  Object.assign(f, mkFighter('hero', cam + 128 + (players.length > 1 ? (f.pad ? 30 : -30) : 0), 180, HERO_HP), keep); f.anim = 'getup'; f.inv = 120;
}

// --- The hero ---

function updateHero(p) {
  const bt = (b) => held(p.pad, b), pr = (b) => pressedBy(p.pad, b);
  if (p.inv > 0) p.inv--;
  p.connT++;
  if (updateShared(p)) return;
  const dx = (bt(RIGHT) ? 1 : 0) - (bt(LEFT) ? 1 : 0), dy = (bt(DOWN) ? 1 : 0) - (bt(UP) ? 1 : 0);
  const a = p.anim;
  if (a === 'jump' || a === 'jkick') {                               // in the air: keep the walking speed
    p.x += dx * 1.4; p.y = Math.max(LANE_TOP, Math.min(LANE_BOT, p.y + dy * 0.9)); clampX(p);
    if (a === 'jump' && pr(A)) setAnim(p, 'jkick');
    else if (a === 'jkick') stepAnim(p);
    if (fall(p)) setAnim(p, 'land');
    return;
  }
  if (a === 'punch1' || a === 'punch2' || a === 'hook' || a === 'uppercut') {
    if (pr(A) && COMBO[a]) { p.queue = true; p.queueUp = bt(UP); }     // UP held at the press of the third A: the uppercut, not the hook
    const ended = stepAnim(p);
    if (COMBO[a] && p.queue && p.conn && p.connT <= 12 && (p.fi >= 2 || ended)) setAnim(p, a === 'punch2' && p.queueUp ? 'uppercut' : COMBO[a]);
    else if (ended) setAnim(p, 'idle');
    return;
  }
  if (a === 'wpipe' || a === 'wknife' || a === 'pick') {
    if (stepAnim(p)) { setAnim(p, 'idle'); if (p.weapon && p.weapon.uses <= 0) { p.weapon = null; fx(SFX.smash); popup(p, 'BROKE', WHITE); } }
    return;
  }
  if (a === 'dash') {                                                // runs through the active frames, until it hits something
    if (p.fi === 1 && !p.hits.length) { p.x += p.face * DASH_SPEED; clampX(p); }
    if (stepAnim(p)) setAnim(p, 'idle');
    return;
  }
  if (a === 'wthrow') {                                              // the weapon leaves his hand as the second part begins
    if (stepAnim(p)) setAnim(p, 'idle'); else if (p.fi === 1 && p.ft === 0 && p.weapon) throwWeapon(p);
    return;
  }
  if (a === 'land' || a === 'throw' || a === 'suplex' || a === 'special') { if (stepAnim(p)) setAnim(p, 'idle'); return; }
  if (a === 'grab' || a === 'gpunch') { updateGrab(p, pr, dx); return; }
  if (pr(X)) {                                                       // the specials cost health
    if (dx && p.hp > DASH_COST) { p.hp -= DASH_COST; p.face = dx; setAnim(p, 'dash'); return; }   // LEFT or RIGHT + X: the dash, the way he holds
    if (p.hp > SPECIAL_COST) { p.hp -= SPECIAL_COST; setAnim(p, 'special'); return; }               // X alone, or UP or DOWN + X: the spin
  }
  if (pr(Y) && p.weapon) { setAnim(p, 'wthrow'); return; }             // Y throws the weapon he holds
  if (pr(B)) { setAnim(p, 'jump'); p.vz = 5.2; p.h = 0.1; return; }
  if (pr(A)) {
    const it = weaponAt(p);
    if (it) { pickUp(p, it); return; }                               // a weapon on the ground: A takes it (swapping the one in hand)
    if (p.weapon) { p.weapon.uses--; setAnim(p, ITEM[p.weapon.kind].weapon); return; }
    setAnim(p, 'punch1'); return;
  }
  if (dx) p.face = dx;
  const gt = dx && grabTarget(p, dx);                                // walking into a thug grabs him
  if (gt) { p.grab = gt; p.gt = 0; p.gcount = 0; p.back = Math.sign(gt.x - p.x) === gt.face; setAnim(p, 'grab'); gt.held = p; gt.token = false; setAnim(gt, 'held'); return; }   // (from behind, if his back is to him)
  p.x += dx * 1.4; p.y = Math.max(LANE_TOP, Math.min(LANE_BOT, p.y + dy * 0.9)); clampX(p);
  const moving = dx || dy;
  if (moving && a !== 'walk') setAnim(p, 'walk'); else if (!moving && a !== 'idle') setAnim(p, 'idle');
  else stepAnim(p);
}

// --- Items and props ---

function popup(f, text, c) { popups.push({ text, x: f.x, y: f.y - f.h - 100, t: 0, c }); }
function spawnItem(kind, x, y, uses) { items.push({ kind, x, y, h: 0.1, vz: 2.6, uses: uses ?? ITEM[kind].uses }); }
function dropWeapon(h) { spawnItem(h.weapon.kind, h.x - h.face * 12, h.y, h.weapon.uses); h.weapon = null; }
function weaponAt(p) {
  return items.find((i) => ITEM[i.kind].weapon && i.h <= 4 && Math.abs(i.x - p.x) <= 18 && Math.abs(i.y - p.y) <= 8);
}
function pickUp(p, it) {
  items = items.filter((i) => i !== it);
  if (p.weapon) spawnItem(p.weapon.kind, p.x - p.face * 12, p.y, p.weapon.uses);
  p.weapon = { kind: it.kind, uses: it.uses };
  setAnim(p, 'pick'); popup(p, ITEM[it.kind].name, WHITE); fx(SFX.pickup);
}
/** Food, money and a 1UP are taken by walking over them. */
function updateItems() {
  for (const i of items) if (i.h > 0 || i.vz !== 0) { i.h += i.vz; i.vz -= GRAV; if (i.h <= 0) { i.h = 0; i.vz = 0; } }
  for (const h of heroes()) {
    if (h.anim === 'down' || h.h > 0) continue;
    for (const i of items) {
      const d = ITEM[i.kind];
      if (d.weapon || i.h > 4 || Math.abs(i.x - h.x) > 16 || Math.abs(i.y - h.y) > 8) continue;
      items = items.filter((o) => o !== i);
      if (d.heal) { h.hp = Math.min(HERO_HP, h.hp + d.heal); popup(h, `+${d.heal}`, GREEN); fx(SFX.heal); }
      else if (d.pts) { h.score += d.pts; popup(h, `$${d.pts}`, GOLD); fx(SFX.pickup); }
      else { h.lives = Math.min(9, h.lives + d.life); popup(h, '1UP', CYAN); fx(SFX.record); }
    }
  }
  for (const q of props) if (q.flash > 0) q.flash--;
  for (const b of bits) { b.x += b.vx; b.y += b.vy; b.vy += 0.3; b.t++; }
  bits = bits.filter((b) => b.t < 26);
  for (const o of popups) o.t++;
  popups = popups.filter((o) => o.t < 50);
}
/** An attack's hit box against the crates, barrels and bins: two punches break one. */
function checkProps(a) {
  const fr = frameOf(a), mv = MOVE[a.anim];
  if (!fr[2] || !mv) return;
  const hb = worldBox(a, fr[2]);
  for (const q of props) {
    if (a.hits.includes(q) || Math.abs(a.y - q.y) > LANE_TOL) continue;
    if (hb[0] < q.x + q.box[2] && q.x + q.box[0] < hb[2]) { a.hits.push(q); hitProp(q, mv.dmg); }   // across only: a punch at head height still hits a crate in his lane
  }
}
function hitProp(q, dmg) {
  q.hp -= dmg; q.flash = 6; hitstop = Math.max(hitstop, 3); fx(SFX.hit);
  if (q.hp > 0) return;
  props = props.filter((o) => o !== q);
  for (let k = 0; k < 8; k++) bits.push({ x: q.x, y: q.y - 14, vx: (k - 3.5) * 0.8, vy: -2 - (k % 3), t: 0, c: q.kind === 'crate' ? BROWN : q.kind === 'barrel' ? BLUE : GREEN });
  spawnItem(q.item, q.x, q.y); fx(SFX.smash);
}

// --- The Chucker's bottles ---

const SHOT_H = [14, 26];                                             // a bottle flies 14 to 26 px above the floor: a hero above that (a jump) clears it
function fireShot(t) { shots.push({ x: t.x + t.face * 16, y: t.y, vx: t.face * 3.2, t: 0 }); fx(SFX.swing); }
function throwWeapon(p) {
  const w = p.weapon; p.weapon = null;                               // it flies along his lane, one use the lighter
  shots.push({ own: p, kind: w.kind, uses: w.uses - 1, x: p.x + p.face * 16, y: p.y, vx: p.face * (w.kind === 'knife' ? 5.2 : 4), t: 0, d: 0 });
}
/** A thrown weapon: it hits the first enemy in its lane (7: a pipe knocks him down, a knife stuns) or a crate, then drops where it was, if it has any use left. */
function weaponFlight(s) {
  const box = [s.x - 8, s.y - 60, s.x + 8, s.y - 46];
  s.d += Math.abs(s.vx);
  const e = enemies.find((o) => canBeHit(o) && o.anim !== 'held' && Math.abs(o.y - s.y) <= LANE_TOL && overlaps(box, worldBox(o, frameOf(o)[1])));
  const q = !e && props.find((o) => Math.abs(o.y - s.y) <= LANE_TOL && box[0] < o.x + o.box[2] && o.x + o.box[0] < box[2]);
  if (e) landHit(s.own, e, s.kind === 'knife' ? { dmg: 7, stun: 14 } : { dmg: 7, down: 1 }); else if (q) hitProp(q, 8);
  if (e || q || s.d > 230 || s.x > cam + 250 || s.x < cam + 6) { s.dead = 1; if (s.uses > 0) spawnItem(s.kind, Math.max(cam + 12, Math.min(cam + 244, s.x)), s.y, s.uses); }   // (the edge of the screen ends the flight too)
}
function updateShots() {
  for (const s of shots) { s.x += s.vx; s.t++; }
  for (const s of shots) {
    if (s.own) { weaponFlight(s); continue; }
    const box = [s.x - 5, s.y - SHOT_H[1], s.x + 5, s.y - SHOT_H[0]];
    for (const h of heroes()) {
      if (Math.abs(h.y - s.y) > LANE_TOL) continue;
      const fr = frameOf(h);
      const hb = fr[2] && worldBox(h, fr[2]);
      if (hb && box[0] < hb[2] && hb[0] < box[2]) { s.dead = 1; shatter(s); break; }        // any attack in its lane knocks it out of the air (whatever the height, as for a crate)
      if (canBeHit(h) && overlaps(box, worldBox(h, fr[1]))) {                               // otherwise it hits: 4 and a stun
        s.dead = 1; shatter(s); h.hp -= 4; hitstop = HITSTOP; fx(SFX.hit);
        if (h.grab) release(h); if (h.weapon) dropWeapon(h);
        const dir = Math.sign(s.vx); h.face = -dir;
        if (h.h > 0) knockDown(h, dir, null); else { setAnim(h, 'hurt'); h.vx = dir * 6 / 16; }
        break;
      }
    }
  }
  shots = shots.filter((s) => !s.dead && s.x > cam - 30 && s.x < cam + 290 && s.t < 200);
}
function shatter(s) { for (let k = 0; k < 6; k++) bits.push({ x: s.x, y: s.y - 20, vx: (k - 2.5) * 0.8, vy: -1.5 - (k % 3), t: 0, c: GREEN }); }

/** A thug the hero can grab by walking into him: on his feet, not attacking, close in front. */
function grabTarget(p, dir) {
  return enemies.find((e) => e.kind === 'thug' && e.type !== 'brute' && !e.dying && !e.held && e.h === 0 && (e.anim === 'idle' || e.anim === 'walk') && e.inv <= 0 &&
    Math.sign(e.x - p.x) === dir && Math.abs(e.x - p.x) <= GRAB_X && Math.abs(e.y - p.y) <= GRAB_Y);
}
function release(p) {
  const t = p.grab;
  if (t && t.anim === 'held') { setAnim(t, 'idle'); t.cool = 60; }
  if (t) t.held = null;
  p.grab = null; p.gcount = 0;
}
function updateGrab(p, pr, dx) {
  const t = p.grab;
  if (!t || t.anim !== 'held' || ++p.gt > GRAB_MAX) { release(p); setAnim(p, 'idle'); return; }   // he was hit away, or wriggles free
  t.x = p.x + p.face * 26; t.y = p.y; t.face = p.back ? p.face : -p.face;   // (held from behind, he looks the way the hero does)
  if (p.anim === 'gpunch') { if (stepAnim(p)) setAnim(p, 'grab'); return; }
  if (!pr(A)) return;
  if (p.back) { throwThug(p, t, -p.face, SUPLEX_DMG, 'suplex'); return; }   // from behind, A is a suplex over the head
  if (dx && dx !== p.face) { throwThug(p, t, -p.face); return; }     // the opposite direction and A: over the shoulder
  t.hp -= GRAB_DMG; p.score += 10; hitstop = HITSTOP; fx(SFX.hit); lastHit = t; lastHitT = 180;
  p.gcount++;
  if (t.hp <= 0 || p.gcount >= GRAB_HITS) throwThug(p, t, p.face);  // the third hit throws him
  else setAnim(p, 'gpunch');
}
/** The thug flies off in the direction dir, hurting whoever he lands on. */
function throwThug(p, t, dir, dmg = THROW_DMG, anim = 'throw') {
  const up = anim === 'suplex';                                      // a suplex lifts him (4.6) and lands him behind the hero
  p.grab = null; p.gcount = 0; t.held = null;
  t.hp -= dmg; p.score += 10; hitstop = HITSTOP; fx(SFX.slam); lastHit = t; lastHitT = 180;
  knockDown(t, dir, p, up ? 4.6 : 0); t.vx = dir * (up ? 2.2 : 3.6); t.thrown = p; t.hitBy = [];
  setAnim(p, anim);
}
/** A thrown thug in the air knocks down the thugs he hits, and hurts a hero (2 damage, a stun). */
function thrownHits() {
  for (const f of enemies) {
    if (!f.thrown || f.anim !== 'down' || f.h <= 0) continue;
    const body = worldBox(f, LYING), dir = f.vx >= 0 ? 1 : -1;
    for (const q of props) if (Math.abs(q.y - f.y) <= LANE_TOL && body[0] < q.x + q.box[2] && q.x + q.box[0] < body[2]) hitProp(q, PROP_HP);   // a thug thrown into a crate smashes it
    for (const o of [...enemies, ...heroes()]) {
      if (o === f || o === f.thrown || f.hitBy.includes(o) || !canBeHit(o) || Math.abs(o.y - f.y) > LANE_TOL || o.anim === 'held') continue;
      if (!overlaps(body, worldBox(o, frameOf(o)[1]))) continue;
      f.hitBy.push(o); hitstop = HITSTOP; fx(SFX.slam);
      if (o.kind === 'hero') { o.hp = Math.max(1, o.hp - 2); if (o.grab) release(o); if (o.weapon) dropWeapon(o); setAnim(o, 'hurt'); o.vx = dir * 6 / 16; }
      else if (o.kind === 'boss') { o.hp -= THROWN_DMG; f.thrown.score += 10; bossHurt(o, dir, f.thrown); }
      else { o.hp -= THROWN_DMG; f.thrown.score += 10; knockDown(o, dir, f.thrown); }
    }
  }
}

// --- The thug ---

function spawnWave(w) {
  const n = w.n + (heroes().length > 1 ? 1 : 0);                      // one more thug for two heroes
  for (let i = 0; i < n; i++) {
    const side = (i + wave) % 2 === 0 ? -1 : 1;                      // from the left edge, or from the right
    const k = w.k || 0, c = w.c || 0, l = w.l || 0;                    // the first k are Slashers, then c Chuckers, l Lashers and b Brutes (the extra thug for two heroes is a plain one)
    const type = i < k ? 'knife' : i < k + c ? 'chucker' : i < k + c + l ? 'lasher' : i < k + c + l + (w.b || 0) ? 'brute' : '';
    const t = mkFighter('thug', side < 0 ? cam - 24 - i * 10 : cam + 280 + i * 10, rndi(LANE_TOP + 4, LANE_BOT - 4), roleHp(type));
    t.v = stage; t.type = type;
    t.face = -side; t.anim = 'walk'; t.cool = rndi(40, 90);
    enemies.push(t);
  }
  if (w.boss) {                                                      // the stage's boss walks in from the right, with a warning and his own song
    const spec = BOSS[ST.boss], hp = Math.round(spec.hp * (1 + 0.4 * (heroes().length - 1)));
    const b = mkFighter('boss', cam + 300, 182, hp);
    b.type = ST.boss; b.face = -1; b.anim = 'walk'; b.cool = 70; b.ai = 'enter'; b.maxhp = hp;
    enemies.push(b); warnT = 150; play(spec.song);
  }
}

const tokens = () => enemies.filter((e) => e.token).length;
// The thugs, by stage (t.v = the stage): a quicker wind-up, a shorter wait, a faster walk; the Slasher is fast, fragile and lunges from range.
// The kinds of enemy (t.type): the distances to attack from (reach) and to wait at (gap: waiting, with his turn), the walk, the health
// (a part of the stage's thug), the points, the shirt, the attack. The Slasher lunges, the Chucker throws bottles, the Lasher's whip is long.
const ROLE = {
  '': { reach: [26, 44], gap: [85, 36], speed: 1, hp: 1, pts: 100 },
  knife: { reach: [40, 100], gap: [110, 70], speed: 1.5, hp: 0.6, pts: 150, coat: BROWN, anim: 'sstab' },
  chucker: { reach: [90, 210], gap: [170, 150], speed: 1, hp: 0.7, pts: 130, coat: DKGREEN, anim: 'cthrow' },
  lasher: { reach: [60, 112], gap: [100, 92], speed: 1.1, hp: 0.8, pts: 150, coat: CYAN, anim: 'wlash' },
  brute: { reach: [30, 62], gap: [95, 52], speed: 0.7, hp: 2.2, pts: 250, coat: SHADOW, anim: 'hsmash' },
};
const roleHp = (type) => Math.round(ST.thugHp * ROLE[type].hp);
const attackAnim = (t) => ROLE[t.type].anim || ['tpunch', 'tpunch2', 'tpunch3'][t.v];
const THUG_WAIT = [[60, 120], [50, 100], [40, 85]], THUG_SPEED = [0.8, 0.9, 1.0];
const thugWait = (t) => (t.type === 'knife' ? rndi(50, 90) : t.type === 'brute' ? rndi(100, 160) : t.type ? rndi(70, 120) : rndi(THUG_WAIT[t.v][0], THUG_WAIT[t.v][1]));
const maxTokens = () => (heroes().length > 1 ? 3 : 2);              // thugs that may attack at once
/** The hero a thug goes for: the nearest one who is still on his feet (any, if all are down). */
function target(t) {
  const hs = heroes(), up = hs.filter((h) => h.anim !== 'down');
  const list = up.length ? up : hs;
  return list.reduce((a, b) => (Math.abs(a.x - t.x) + 2 * Math.abs(a.y - t.y) <= Math.abs(b.x - t.x) + 2 * Math.abs(b.y - t.y) ? a : b));
}

function updateThug(t) {
  if (t.inv > 0) t.inv--;
  if (t.flash > 0) t.flash--;
  if (t.anim === 'held') return;                                     // the hero moves him
  if (updateShared(t) || t.ai === 'dummy') return;                   // (a dummy is a punching bag for the tests)
  if (!heroes().length) return;
  const p = target(t);
  const knife = t.type === 'knife', role = ROLE[t.type];
  if (t.anim === attackAnim(t)) {
    if (knife && t.fi === 1) { t.x += t.face * 3.5; t.x = Math.max(cam + 12, Math.min(cam + 244, t.x)); }   // the lunge
    const ended = stepAnim(t);
    if (t.anim === 'cthrow' && t.fi === 1 && t.ft === 0) fireShot(t);                                       // the bottle leaves his hand
    if (ended) { setAnim(t, 'walk'); t.token = false; t.cool = thugWait(t); if (knife) t.retreat = 14; }
    return;
  }
  if (t.retreat > 0) { t.retreat--; t.x = Math.max(cam + 16, Math.min(cam + 240, t.x - t.face * 2.5)); if (t.anim !== 'walk') setAnim(t, 'walk'); return; }   // the Slasher hops back
  if (t.cool > 0) t.cool--;
  let tx, ty;
  if (t.ai === 'enter') {                                            // walk in from off the screen
    tx = t.x < cam + 20 ? t.x + 10 : t.x > cam + 236 ? t.x - 10 : t.x; ty = t.y;
    if (t.x >= cam + 16 && t.x <= cam + 240) t.ai = 'fight';
    if (tx === t.x && ty === t.y) t.ai = 'fight';
  } else {
    const side = t.x >= p.x ? 1 : -1;
    if (!t.token && t.cool <= 0 && tokens() < maxTokens() && p.hp > 0 && p.anim !== 'down') { t.token = true; t.tokenT = 0; }
    if (t.token && ++t.tokenT > 300) { t.token = false; t.cool = 60; }
    const gap = role.gap[t.token ? 1 : 0];
    tx = p.x + side * gap; ty = p.y;
    if (!t.token) ty = Math.max(LANE_TOP, Math.min(LANE_BOT, p.y + (enemies.indexOf(t) % 3 - 1) * 16));   // those waiting spread across the lane
    if (tx < cam + 16 || tx > cam + 240) tx = p.x - side * gap;   // never wait off the screen: use the hero's other side
    tx = Math.max(cam + 20, Math.min(cam + 236, tx));              // (and if both sides are off it, at its edge)
  }
  const mx = tx - t.x, my = ty - t.y;
  const walking = Math.abs(mx) > 2 || Math.abs(my) > 2;
  const sp = THUG_SPEED[t.v] * role.speed;
  if (walking) { t.x += Math.sign(mx) * Math.min(sp, Math.abs(mx)); t.y += Math.sign(my) * Math.min(sp * 0.75, Math.abs(my)); }
  t.y = Math.max(LANE_TOP, Math.min(LANE_BOT, t.y)); t.x = Math.max(cam - 60, Math.min(cam + 316, t.x));
  if (t.ai === 'fight') t.face = p.x >= t.x ? 1 : -1;
  else t.face = Math.sign(mx) || t.face;
  const reach = role.reach;
  if (t.ai === 'fight' && t.token && Math.abs(p.y - t.y) <= 6 && Math.abs(p.x - t.x) >= reach[0] && Math.abs(p.x - t.x) <= reach[1]) { setAnim(t, attackAnim(t)); return; }
  if (walking && t.anim !== 'walk') setAnim(t, 'walk'); else if (!walking && t.anim !== 'idle') setAnim(t, 'idle');
}

/** Fighters of one side do not stand on each other: grounded thugs push apart, and so do the two heroes (a hero and a thug may close up). */
const SEP_X = 28, SEP_Y = 14;
function separate(list) {
  const on = list.filter((f) => f.h === 0 && f.anim !== 'down' && f.anim !== 'getup' && f.anim !== 'held' && f.ai !== 'dummy');
  for (let i = 0; i < on.length; i++) {
    for (let j = i + 1; j < on.length; j++) {
      const a = on[i], b = on[j], dx = b.x - a.x, dy = b.y - a.y;
      if (Math.abs(dx) >= SEP_X || Math.abs(dy) >= SEP_Y) continue;
      const sy = dy !== 0 ? Math.sign(dy) : (i % 2 ? 1 : -1), sx = dx !== 0 ? Math.sign(dx) : (j % 2 ? 1 : -1);
      a.y = Math.max(LANE_TOP, Math.min(LANE_BOT, a.y - sy * 0.6)); b.y = Math.max(LANE_TOP, Math.min(LANE_BOT, b.y + sy * 0.6));
      a.x -= sx * 0.5; b.x += sx * 0.5;
    }
  }
}

// --- The boss ---

/** A hit on the boss: he only flinches (a white flash), and goes down when a hit takes him under a third or two thirds of his health. */
function bossHurt(b, dir, by) {
  b.flash = 6;
  const tier = Math.max(0, Math.ceil(b.hp / (b.maxhp / 3)));
  if (b.hp <= 0 || tier < b.tier) { b.tier = tier; b.token = false; knockDown(b, dir, by); }
}
const clampBoss = (b) => { b.y = Math.max(LANE_TOP, Math.min(LANE_BOT, b.y)); };
const kingRage = (b) => b.type === 'king' && b.hp <= b.maxhp / 3;
const bossWait = (b, lo, hi) => Math.round(rndi(lo, hi) * (kingRage(b) ? 0.6 : 1));   // a raging boss waits less
function updateBull(b) {
  if (b.inv > 0) b.inv--;
  if (b.flash > 0) b.flash--;
  if (updateShared(b) || b.ai === 'dummy') return;                   // (a dummy is a punching bag for the tests)
  if (!heroes().length) return;
  const a = b.anim;
  if (a === 'bpunch') { if (stepAnim(b)) { setAnim(b, 'walk'); b.cool = bossWait(b, 40, 80); } return; }
  if (a === 'bstun') { if (stepAnim(b)) { setAnim(b, 'walk'); b.cool = 40; } return; }
  if (a === 'kslam') {                                               // the wave goes out along the floor on the first active frame
    if (stepAnim(b)) { setAnim(b, 'walk'); b.cool = bossWait(b, 50, 90); } else if (b.fi === 1 && b.ft === 0) fx(SFX.slam);
    return;
  }
  if (a === 'bcharge') {
    if (b.fi === 1) {                                                // running: until the time is up, or a wall
      b.x += b.face * CHARGE_SPEED;
      if (b.x <= cam + 26 || b.x >= cam + 230) { b.x = Math.max(cam + 26, Math.min(cam + 230, b.x)); setAnim(b, 'bstun'); fx(SFX.thud); return; }
    }
    if (stepAnim(b)) { setAnim(b, 'walk'); b.cool = bossWait(b, 70, 110); }
    return;
  }
  const p = target(b), dx = p.x - b.x, dy = p.y - b.y, adx = Math.abs(dx), ady = Math.abs(dy);
  if (b.ai === 'enter') {                                            // walks in from the right
    b.x -= 1.2; b.face = -1; if (b.x <= cam + 200) b.ai = 'fight';
    if (a !== 'walk') setAnim(b, 'walk');
    return;
  }
  if (b.cool > 0) b.cool--;
  b.face = dx >= 0 ? 1 : -1;
  if (b.cool <= 0 && ady <= 8 && adx >= 26 && adx <= 58) { setAnim(b, b.type === 'king' && rndi(0, 1) ? 'kslam' : 'bpunch'); return; }
  if (b.cool <= 0 && ady <= 10 && adx >= 110) { setAnim(b, 'bcharge'); return; }
  const sp = kingRage(b) ? 0.9 : 0.7;
  const tx = p.x - b.face * 44, ty = p.y;                            // walk to arm's length, in the hero's lane
  const mx = tx - b.x, my = ty - b.y, walking = Math.abs(mx) > 2 || Math.abs(my) > 2;
  if (walking) { b.x += Math.sign(mx) * Math.min(sp, Math.abs(mx)); b.y += Math.sign(my) * Math.min(sp * 0.7, Math.abs(my)); clampBoss(b); }
  b.x = Math.max(cam - 40, Math.min(cam + 300, b.x));
  if (walking && a !== 'walk') setAnim(b, 'walk'); else if (!walking && a !== 'idle') setAnim(b, 'idle');
}

/**
 * RAZOR, the docks' boss: fast (1.5 across, 1.0 into the screen), and always moving. Close in his lane he stabs three times (4, 4,
 * then 6 and a knockdown) and hops back; from far off he crouches (the warning), leaps over the hero and kicks down on the way (7,
 * knockdown), then lands with a gap in his guard. Like BULL: no hit stun, a knockdown only at the thirds of his health.
 */
function updateRazor(b) {
  if (b.inv > 0) b.inv--;
  if (b.flash > 0) b.flash--;
  if (updateShared(b) || b.ai === 'dummy') return;
  if (!heroes().length) return;
  const a = b.anim;
  if (a === 'rslash1' || a === 'rslash2' || a === 'rslash3') {
    b.x += b.face * (a === 'rslash3' ? 0.5 : 0.8);                   // each stab lunges a little
    if (stepAnim(b)) {
      if (a === 'rslash1') setAnim(b, 'rslash2'); else if (a === 'rslash2') setAnim(b, 'rslash3');
      else { setAnim(b, 'walk'); b.cool = rndi(45, 80); b.retreat = 14; }
    }
    return;
  }
  if (a === 'rcrouch') {                                             // then up and over: he lands behind the hero
    if (stepAnim(b)) { const p = target(b); setAnim(b, 'rleap'); b.vz = 5.8; b.h = 0.1; b.vx = (p.x + b.face * 34 - b.x) / 39; b.vy = (p.y - b.y) / 39; }   // 39 frames in the air, 56 px up
    return;
  }
  if (a === 'rleap' || a === 'rdive') {
    b.x += b.vx; b.y += b.vy; b.x = Math.max(cam + 16, Math.min(cam + 240, b.x));
    const landed = fall(b);
    if (a === 'rleap' && b.vz < 0) setAnim(b, 'rdive');              // coming down: the kick is out
    if (landed) { setAnim(b, 'rland'); b.vx = 0; b.vy = 0; fx(SFX.thud); }
    return;
  }
  if (a === 'rland') { if (stepAnim(b)) { setAnim(b, 'walk'); b.cool = rndi(50, 90); } return; }
  const p = target(b), dx = p.x - b.x, dy = p.y - b.y, adx = Math.abs(dx), ady = Math.abs(dy);
  if (b.ai === 'enter') { b.x -= 1.8; b.face = -1; if (b.x <= cam + 190) b.ai = 'fight'; if (a !== 'walk') setAnim(b, 'walk'); return; }
  if (b.cool > 0) b.cool--;
  if (b.retreat > 0) { b.retreat--; b.x = Math.max(cam + 20, Math.min(cam + 236, b.x - b.face * 2.5)); if (a !== 'walk') setAnim(b, 'walk'); return; }   // the hop back
  b.face = dx >= 0 ? 1 : -1;
  if (b.cool <= 0 && ady <= 8 && adx >= 30 && adx <= 60) { setAnim(b, 'rslash1'); return; }
  if (b.cool <= 0 && adx >= 100) { setAnim(b, 'rcrouch'); return; }
  const tx = p.x - b.face * 46, ty = p.y;
  const mx = tx - b.x, my = ty - b.y, walking = Math.abs(mx) > 2 || Math.abs(my) > 2;
  if (walking) { b.x += Math.sign(mx) * Math.min(1.5, Math.abs(mx)); b.y += Math.sign(my) * Math.min(1.0, Math.abs(my)); clampBoss(b); }
  b.x = Math.max(cam - 40, Math.min(cam + 300, b.x));
  if (walking && a !== 'walk') setAnim(b, 'walk'); else if (!walking && a !== 'idle') setAnim(b, 'idle');
}

// --- The level: the camera, the waves, the end ---

function updateCamera() {
  const next = LEVEL[wave];
  if (!locked) {
    const limit = next ? next.x : LEVEL_W - 256;
    const lead = Math.max(...heroes().map((h) => h.x));              // the screen follows the one who is furthest on
    cam = Math.min(Math.max(cam, lead - 112), limit, LEVEL_W - 256);
    if (next && cam >= next.x) { locked = true; spawnWave(next); wave++; }
  } else if (enemies.length === 0) {
    locked = false;
    if (wave >= LEVEL.length) { clearStage(); return; }
    goT = 0;
  }
  for (const h of heroes()) h.x = Math.max(cam + 10, Math.min(cam + 246, h.x));   // nobody leaves the screen
}

function clearStage() {
  bonusShown = players.map((h) => h.hp * 10 + h.lives * 500);
  players.forEach((h, k) => { h.score += bonusShown[k]; });
  if (stage + 1 < STAGES.length) { state = 'clear'; timer = 0; play(-1); fx(SFX.record); return; }   // on to the next stage
  won = true; gameOver(true);
}
function updateClear() {
  if (timer > 90 && (pressed(A) || pressed(START))) { fx(SFX.select); state = 'play'; loadStage(stage + 1); }
}

// --- Update ---

function update() {
  inputMask = [readPad(0), readPad(1)]; clock++;
  if (!paused) timer++; // a state's clock: it stands still while paused
  if (paused) updatePause();
  else if (state === 'title') updateTitle();
  else if (state === 'play') updatePlay();
  else if (state === 'clear') updateClear();
  else if (state === 'over') updateOver();
  else if (state === 'initials') updateInitials();
  else if (state === 'records') updateRecords();
  prevMask = inputMask;
}

function updateTitle() {
  if (pressed(UP)) { titleSel = (titleSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { titleSel = (titleSel + 1) % 3; fx(SFX.move); }
  if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (titleSel < 2) startGame(titleSel + 1); else { state = 'records'; hl = -1; timer = 0; }
  }
}

function updatePlay() {
  if (pressed(START)) { paused = true; pauseSel = 0; fx(SFX.pause); return; }
  if (players.length < 2 && pressedBy(1, A)) {                       // the second player joins any time
    const h = addHero(1, Math.max(cam + 30, players[0].x - 40), 190); h.inv = 120; setAnim(h, 'getup'); fx(SFX.select);
  }
  if (pressed(SELECT)) showBoxes = !showBoxes;
  if (lastHitT > 0) lastHitT--;
  if (warnT > 0) warnT--;
  if (bannerT > 0) bannerT--;
  if (hitstop > 0) {                                                 // both fighters freeze on a hit
    hitstop--;
    for (const h of players) if (pressedBy(h.pad, A) && COMBO[h.anim]) { h.queue = true; h.queueUp = held(h.pad, UP); }   // (a press during the freeze still counts)
    return;
  }
  for (const h of heroes()) updateHero(h);
  if (state !== 'play') return;                                      // (the last hero may have just gone out)
  for (const e of enemies) { if (e.kind === 'boss') (e.type === 'razor' ? updateRazor(e) : updateBull(e)); else updateThug(e); }
  for (const h of heroes()) checkProps(h);
  updateItems(); updateShots();
  for (const h of heroes()) { checkHits(h, enemies); checkHits(h, heroes().filter((o) => o !== h)); }
  for (const e of enemies) checkHits(e, heroes());
  thrownHits();
  separate(enemies); separate(heroes());
  enemies = enemies.filter((e) => !e.gone);
  if (state !== 'play') return;
  updateCamera();
  goT++;
}

function gameOver(clear) {
  state = 'over'; won = clear; timer = 0; play(-1); fx(clear ? SFX.record : SFX.over);
  pend = players.map((h) => ({ pad: h.pad, score: h.score })).sort((a, b) => b.score - a.score);   // each score for the top 10, best first
  nextEntry();
}
/** The next score that makes the top 10 (rank, and whose it is), or rank -1 when there is none left. */
function nextEntry() {
  rank = -1;
  while (pend.length && rank < 0) { const e = pend.shift(); rank = insertTop({ score: e.score, initials: lastInitials() }); if (rank >= 0) entryPad = e.pad; }
}

function updateOver() {
  if (timer < 60 || !(pressed(A) || pressed(START))) return;
  fx(SFX.select);
  if (rank >= 0) { state = 'initials'; timer = 0; initials = { chars: lastInitials().split(''), pos: 0 }; fx(SFX.record); }
  else toTitle();
}

/** UP/DOWN pick a letter, LEFT/RIGHT (or A and B) move, START saves (as does A on the last letter). */
function updateInitials() {
  const ini = initials, k = LETTERS.indexOf(ini.chars[ini.pos]);
  if (pressed(UP)) { ini.chars[ini.pos] = LETTERS[(k + 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(DOWN)) { ini.chars[ini.pos] = LETTERS[(k + LETTERS.length - 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(LEFT) || pressed(B)) ini.pos = Math.max(0, ini.pos - 1);
  if (pressed(RIGHT)) ini.pos = Math.min(2, ini.pos + 1);
  const done = pressed(START) || (pressed(A) && ini.pos === 2);
  if (pressed(A) && ini.pos < 2) ini.pos++;
  if (!done || timer < 20) return;
  const v = packInitials(ini.chars.join(''));
  dset(INITIALS_SLOT, v); dset(TOP_SLOT + rank * ENTRY + 1, v);
  fx(SFX.select);
  const saved = rank; nextEntry();
  if (rank >= 0) { initials = { chars: lastInitials().split(''), pos: 0 }; timer = 0; return; }   // the other player's score is next
  state = 'records'; hl = saved; timer = 0;
}

function updateRecords() {
  if ((pressed(START) || pressed(A) || pressed(B)) && timer > 20) { fx(SFX.select); toTitle(); }
}

function updatePause() {
  if (pressed(UP)) { pauseSel = (pauseSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { pauseSel = (pauseSel + 1) % 3; fx(SFX.move); }
  if (pressed(B) || (pressed(START) && pauseSel === 0)) { paused = false; fx(SFX.pause); }
  else if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (pauseSel === 0) paused = false;
    else if (pauseSel === 1) startGame(); // restart
    else toTitle(); // quitting abandons the game: nothing is recorded
  }
}

// --- Draw ---

function scroll(c) { bgscroll(2, flr(c * 0.3), 0); bgscroll(1, flr(c * 0.6), 0); bgscroll(0, flr(c), 0); }

function draw() {
  cls();
  scroll(state === 'play' || state === 'over' || state === 'clear' ? cam : 0);
  if (state === 'play' || state === 'over' || state === 'clear') drawPlay();
  else if (state === 'title') drawTitle();
  else if (state === 'initials') drawInitials();
  else if (state === 'records') drawRecords();
  if (state === 'clear') {
    panel(40, 64, 176, 104);
    ctxt(`STAGE ${stage + 1} CLEAR`, 76, GOLD);
    players.forEach((h, k) => ctxt(`P${h.pad + 1} BONUS ${bonusShown[k]}   SCORE ${h.score}`, 96 + k * 12, WHITE));
    ctxt(`NEXT: ${STAGES[stage + 1].name}`, 130, CYAN);
    if (timer > 90 && timer % 60 < 40) ctxt('START: CONTINUE', 150, DIM);
  }
  if (state === 'over') {
    panel(48, 80, 160, 64);
    ctxt(won ? 'ALL STAGES CLEAR' : 'GAME OVER', 92, won ? GOLD : RED);
    if (players.length > 1) ctxt(`P1 ${players[0].score}  P2 ${players[1].score}`, 108, WHITE); else ctxt(`SCORE ${players[0].score}`, 108, WHITE);
    if (timer > 60 && timer % 60 < 40) ctxt('START: CONTINUE', 126, DIM);
  }
  if (paused) drawPause();
}

function drawPlay() {
  const all = [...heroes(), ...enemies, ...props].sort((a, b) => a.y - b.y);   // nearer the bottom of the screen is in front
  for (const f of all) drawShadow(f);
  for (const i of items) drawItem(i);
  for (const s of shots) drawShot(s);
  for (const f of all) { if (f.prop) drawProp(f); else if (f.kind === 'boss') (f.type === 'razor' ? drawRazor(f) : drawBoss(f)); else drawFighter(f); }
  for (const b of bits) rectfill(flr(b.x - cam), flr(b.y), 4, 4, b.c);
  if (showBoxes) for (const f of all) drawBoxes(f);
  for (const o of popups) txt(o.text, flr(o.x - cam) - o.text.length * 4, flr(o.y - o.t * 0.4), o.t > 36 && o.t % 4 < 2 ? DIM : o.c);
  drawHud();
}

function drawShadow(f) {
  const sx = flr(f.x - cam), w = Math.max(8, 16 - flr(f.h / 4));
  rectfill(sx - w, f.y - 2, w * 2, 4, SHADOW); rectfill(sx - w + 2, f.y - 3, w * 2 - 4, 6, SHADOW);
}

/**
 * THE ART LAYER. A fighter drawn as plain shapes from the frame table: the hurt box is the body, with a head and legs, and
 * a fist where the hit box is. Real frames replace this one function (the same feet, boxes and timings).
 */
function drawFighter(f) {
  if (f.inv > 0 && flr(clock / 3) % 2 === 0) return;                 // flashes while invulnerable
  if (f.dying && f.anim === 'down' && f.h === 0 && f.lie < 20 && flr(clock / 2) % 2 === 0) return;
  const hero = f.kind === 'hero', coat = hero ? (f.pad ? 11 : 8) : ROLE[f.type].coat || ST.thugCoat, pants = hero ? 2 : 1, skin = 12, fist = f.hits.length ? GOLD : 9;
  const sx = flr(f.x - cam), by = flr(f.y - f.h), d = f.face;
  if (f.anim === 'down') {                                           // lying on the ground, or flying through the air
    const air = f.h > 0 || f.vz !== 0;
    if (air) { rectfill(sx - 30, by - 36, 60, 18, coat); circfill(sx - d * 34, by - 28, 9, skin); }
    else { rectfill(sx - 40, by - 14, 56, 14, coat); rectfill(sx + 14 * -d - 2, by - 12, 24, 10, pants); circfill(sx + d * 40 * -1, by - 8, 8, skin); }
    return;
  }
  const hurt = (f.anim === 'hurt' && f.ft < 4) || f.flash > 3 || (f.anim === 'held' && flr(clock / 6) % 2 === 0);
  const walk = f.anim === 'walk' ? flr(clock / 6) % 2 : 0, lean = f.anim === 'hurt' ? -d * 4 : 0;
  const air = f.h > 0;
  if (air) { rectfill(sx - 10 + lean, by - 40, 8, 40, pants); rectfill(sx + 2 + lean, by - 34, 8, 30, pants); }
  else { rectfill(sx - 10 + lean, by - 40, 8, 40 - walk * 4, pants); rectfill(sx + 2 + lean, by - 40, 8, 36 + walk * 4, pants); }
  rectfill(sx - 14 + lean, by - 74, 28, 36, hurt ? WHITE : coat);                              // the torso
  circfill(sx + d * 2 + lean, by - 82, 9, skin);                                                // the head
  if (f.type === 'brute') {                                                                      // a Brute: wide shoulders, thick legs, a big bald head, a gold belt
    rectfill(sx - 22 + lean, by - 78, 44, 40, hurt ? WHITE : coat); rectfill(sx - 22 + lean, by - 44, 44, 5, GOLD);
    rectfill(sx - 14 + lean, by - 40, 12, 40 - walk * 4, pants); rectfill(sx + 3 + lean, by - 40, 12, 36 + walk * 4, pants);
    circfill(sx + d * 2 + lean, by - 87, 11, skin);
  }
  rectfill(sx + d * 6 + lean - 1, by - 84, 3, 3, SHADOW);                                       // an eye, on the side he faces
  if (!hero) {                                                                                   // his stage's mark: a cap (docks), dark glasses (rooftop); a Slasher's yellow bandana
    if (f.type === 'knife') rectfill(sx - 8 + d * 2 + lean, by - 89, 18, 4, GOLD);
    else if (f.type === 'chucker') rectfill(sx - 8 + d * 2 + lean, by - 93, 17, 7, ORANGE);                  // a beanie
    else if (f.type === 'lasher') { rectfill(sx - d * 12 + lean - 3, by - 90, 6, 18, SHADOW); rectfill(sx - 7 + d * 2 + lean, by - 93, 15, 5, SHADOW); }   // long dark hair
    else if (f.v === 1) { rectfill(sx - 9 + d * 2 + lean, by - 92, 18, 5, NAVY); rectfill(sx + d * 8 + lean - 2, by - 88, 8, 2, NAVY); }
    else if (f.v === 2) rectfill(sx - 7 + d * 2 + lean, by - 85, 15, 4, SHADOW);
  }
  const fr = frameOf(f), mv = MOVE[f.anim];
  if (f.anim === 'special') {                                        // a spin: a fist out on each side while it is active
    if (fr[2]) { rectfill(sx - 58, by - 68, 14, 14, fist); rectfill(sx + 44, by - 68, 14, 14, fist); }
    else rectfill(sx + d * 14 + lean - 4, by - 70, 8, 8, skin);
  } else if (f.anim === 'grab' || f.anim === 'gpunch') {             // both hands on the thug
    rectfill(sx + d * (f.anim === 'gpunch' ? 30 : 22) - 5, by - 62, 10, 10, f.anim === 'gpunch' ? GOLD : skin);
  } else if (f.anim === 'dash') {                                    // the fist out, the body leaning into it, speed lines behind
    const b = fr[2] || [10, -66, 24, -60];
    rectfill(sx + d * ((b[0] + b[2]) / 2) - 7, by + (b[1] + b[3]) / 2 - 7, 14, 14, fr[2] ? GOLD : skin);
    if (fr[2] && !f.hits.length) { line(sx - d * 18, by - 70, sx - d * 46, by - 70, WHITE); line(sx - d * 14, by - 50, sx - d * 40, by - 50, WHITE); }
  } else if (f.anim === 'hsmash') {                                   // the Brute's club smash: both fists high for a long time, then down along the hit box
    const b = fr[2];
    if (b) { rectfill(sx + d * 52 - 9, by - 72, 18, 18, GOLD); line(sx + d * 14, by - 78, sx + d * 52, by - 64, skin); line(sx + d * 14, by - 77, sx + d * 52, by - 63, skin); }
    else { rectfill(sx - 4 + d * 6, by - 112, 18, 14, skin); rectfill(sx - 18 + d * 6, by - 112, 14, 14, skin); }
  } else if (f.anim === 'cthrow') {                                  // the Chucker: the bottle held high, then the arm thrown forward
    const wind = f.fi === 0;
    rectfill(sx + d * (wind ? 8 : 22) - 4, by - (wind ? 96 : 70), 8, 8, skin);
    if (wind) { rectfill(sx + d * 8 - 3, by - 110, 6, 12, GREEN); rectfill(sx + d * 8 - 1, by - 114, 2, 5, GREEN); }
  } else if (f.anim === 'wlash') {                                   // the Lasher: the whip drawn back, then a crack along the hit box with a spark at its tip
    const crack = f.fi === 1;
    rectfill(sx + d * 10 - 4, by - 68, 8, 8, skin);
    if (crack) { line(sx + d * 12, by - 66, sx + d * 60, by - 72, BROWN); line(sx + d * 60, by - 72, sx + d * 116, by - 64, BROWN); line(sx + d * 12, by - 65, sx + d * 60, by - 71, BROWN); rectfill(sx + d * 116 - 3, by - 68, 6, 6, WHITE); }
    else { line(sx + d * 12, by - 66, sx - d * 24, by - 84, BROWN); line(sx - d * 24, by - 84, sx - d * 40, by - 66, BROWN); }
  } else if (f.anim === 'sstab') {                                   // the Slasher's knife: held back while he crouches, then out along the hit box
    let tx = -d * 12, ty = -62;
    if (fr[2]) { const b = fr[2]; tx = d * b[2]; ty = (b[1] + b[3]) / 2; }
    line(sx + d * 8, by - 62, sx + tx, by + ty, WHITE); line(sx + d * 8, by - 63, sx + tx, by + ty - 1, WHITE); rectfill(sx + d * 8 - 4, by - 66, 8, 8, skin);
  } else if (f.anim === 'suplex') {                                  // both fists up, over his head
    rectfill(sx - 14, by - 124, 12, 12, skin); rectfill(sx + 2, by - 124, 12, 12, skin);
  } else if (f.anim === 'wpipe' || f.anim === 'wknife' || f.anim === 'wthrow' || f.anim === 'pick') {   // the weapon is the attack: a hand on it
    rectfill(sx + d * 12 - 4, by - 68, 8, 8, skin);
  } else if (mv) {                                                          // an attack: the fist cocked, then out at the hit box
    let fx0 = d * 16, fy0 = -62;
    const up = f.anim === 'uppercut';                                // the uppercut: the fist low, then up through the hit box
    if (fr[2]) { const b = fr[2]; fx0 = d * ((b[0] + b[2]) / 2); fy0 = up ? b[1] + 12 : (b[1] + b[3]) / 2; }
    else if (f.fi === 0) { fx0 = up ? d * 8 : -d * 12; fy0 = up ? -34 : -64; }
    else if (up) { fx0 = d * 14; fy0 = -50; }
    const fx1 = sx + fx0, fy1 = by + fy0;
    line(sx + d * 8, by - 66, fx1, fy1, skin); line(sx + d * 8, by - 65, fx1, fy1 + 1, skin);
    rectfill(fx1 - 6, fy1 - 6, 12, 12, fr[2] ? fist : coat);
  } else {                                                           // guard: the fists up
    rectfill(sx + d * 14 + lean - 4, by - 70, 8, 8, skin);
  }
  if (f.weapon) {
    drawWeapon(f, sx, by, fr);
    const tag = `${ITEM[f.weapon.kind].name} ${f.weapon.uses}`;
    txt(tag, Math.max(2, Math.min(254 - tag.length * 8, sx - tag.length * 4)), by - 108, f.weapon.kind === 'knife' ? WHITE : DIM);
  }
}

/** Each thing to pick up has its own colour and shape: red apple, orange chicken, gold money bag, cyan 1UP, steel pipe, white knife. */
function drawItem(i) {
  const sx = flr(i.x - cam), sy = flr(i.y - i.h);
  if (i.h === 0) { rectfill(sx - 9, sy - 2, 18, 4, SHADOW); }
  switch (i.kind) {
    case 'apple': circfill(sx, sy - 7, 6, RED); rectfill(sx - 1, sy - 16, 2, 5, BROWN); rectfill(sx + 1, sy - 15, 5, 3, GREEN); break;
    case 'chicken': circfill(sx - 3, sy - 9, 9, ORANGE); circfill(sx - 6, sy - 12, 3, GOLD); rectfill(sx + 5, sy - 12, 9, 4, WHITE); circfill(sx + 14, sy - 14, 3, WHITE); circfill(sx + 14, sy - 10, 3, WHITE); break;
    case 'money': circfill(sx, sy - 8, 8, GOLD); rectfill(sx - 3, sy - 19, 6, 6, GOLD); rectfill(sx - 5, sy - 15, 10, 2, BROWN); txt('$', sx - 4, sy - 13, NAVY); break;
    case 'oneup': rectfill(sx - 14, sy - 17, 28, 15, CYAN); rect(sx - 14, sy - 17, 28, 15, WHITE); print('1UP', sx - 12, sy - 14, NAVY); break;
    case 'pipe': rectfill(sx - 18, sy - 6, 36, 6, DIM); rectfill(sx - 18, sy - 6, 36, 2, WHITE); rectfill(sx - 20, sy - 7, 3, 8, DIM); rectfill(sx + 17, sy - 7, 3, 8, DIM); break;
    case 'knife': rectfill(sx - 4, sy - 5, 20, 4, WHITE); rectfill(sx + 14, sy - 4, 4, 2, WHITE); rectfill(sx - 16, sy - 6, 12, 6, BROWN); rectfill(sx - 5, sy - 7, 2, 8, DIM); break;
  }
}

function drawShot(s) {
  if (s.own) {                                                       // a weapon spinning through the air at chest height
    const sx = flr(s.x - cam), y = flr(s.y) - 53, a = flr(s.t / 2) % 2;
    rectfill(sx - 5, flr(s.y) - 1, 10, 3, SHADOW);
    if (s.kind === 'knife') { if (a) { rectfill(sx - 8, y - 1, 16, 3, WHITE); rectfill(sx - 12, y - 2, 5, 5, BROWN); } else { rectfill(sx - 1, y - 8, 3, 16, WHITE); rectfill(sx - 2, y + 7, 5, 5, BROWN); } }
    else if (a) { rectfill(sx - 14, y - 2, 28, 5, DIM); rectfill(sx - 14, y - 2, 28, 2, WHITE); } else { rectfill(sx - 2, y - 14, 5, 28, DIM); rectfill(sx - 2, y - 14, 2, 28, WHITE); }
    return;
  }
  const sx = flr(s.x - cam), y = flr(s.y) - 20, spin = flr(s.t / 3) % 2;
  rectfill(sx - 5, flr(s.y) - 1, 10, 3, SHADOW);
  if (spin) { rectfill(sx - 6, y - 3, 12, 6, GREEN); rectfill(sx + 5, y - 1, 4, 2, GREEN); rectfill(sx - 4, y - 2, 4, 1, WHITE); }
  else { rectfill(sx - 3, y - 6, 6, 12, GREEN); rectfill(sx - 1, y - 10, 2, 5, GREEN); rectfill(sx - 2, y - 4, 1, 5, WHITE); }
}

