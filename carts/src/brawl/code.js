/** A hit on the boss: he only flinches (a white flash), and goes down when a hit takes him under a third or two thirds of his health. */
function bossHurt(b, dir, by) {
  b.flash = 6;
  const tier = Math.max(0, Math.ceil(b.hp / (b.maxhp / 3)));
  if (b.hp <= 0 || tier < b.tier) { b.tier = tier; b.token = false; knockDown(b, dir, by); }
}
const clampBoss = (b) => { b.y = clamp(b.y, LANE_TOP, LANE_BOT); };
const kingRage = (b) => b.type === 'king' && b.hp <= b.maxhp / 3;
const bossWait = (b, lo, hi) => Math.round(rndi(lo, hi) * (kingRage(b) ? 0.6 : 1));   // a raging boss waits less
function updateBull(b) {
  if (b.inv > 0) b.inv--;
  if (b.flash > 0) b.flash--;
  if (updateShared(b) || b.ai === 'dummy') return;                   // (a dummy is a punching bag for the tests)
  if (!heroes().length) return;
  const a = b.anim;
  if (a === 'bpunch') { if (stepAnim(b)) { setAnim(b, 'walk'); b.cool = bossWait(b, 40, 80); } return; }
  if (a === 'bstun') { if (stepAnim(b)) { setAnim(b, 'walk'); b.cool = 40; } return; }
  if (a === 'kslam') {                                               // the wave goes out along the floor on the first active frame
    if (stepAnim(b)) { setAnim(b, 'walk'); b.cool = bossWait(b, 50, 90); } else if (b.fi === 1 && b.ft === 0) fx(SFX.slam);
    return;
  }
  if (a === 'bcharge') {
    if (b.fi === 1) {                                                // running: until the time is up, or a wall
      b.x += b.face * CHARGE_SPEED;
      if (b.x <= cam + 26 || b.x >= cam + 230) { b.x = clamp(b.x, cam + 26, cam + 230); setAnim(b, 'bstun'); fx(SFX.thud); return; }
    }
    if (stepAnim(b)) { setAnim(b, 'walk'); b.cool = bossWait(b, 70, 110); }
    return;
  }
  const p = target(b), dx = p.x - b.x, dy = p.y - b.y, adx = abs(dx), ady = abs(dy);
  if (b.ai === 'enter') {                                            // walks in from the right
    b.x -= 1.2; b.face = -1; if (b.x <= cam + 200) b.ai = 'fight';
    if (a !== 'walk') setAnim(b, 'walk');
    return;
  }
  if (b.cool > 0) b.cool--;
  b.face = dx >= 0 ? 1 : -1;
  if (b.cool <= 0 && ady <= 8 && adx >= 26 && adx <= 58) { setAnim(b, b.type === 'king' && rndi(0, 1) ? 'kslam' : 'bpunch'); return; }
  if (b.cool <= 0 && ady <= 10 && adx >= 110) { setAnim(b, 'bcharge'); return; }
  const sp = kingRage(b) ? 0.9 : 0.7;
  const tx = p.x - b.face * 44, ty = p.y;                            // walk to arm's length, in the hero's lane
  const mx = tx - b.x, my = ty - b.y, walking = abs(mx) > 2 || abs(my) > 2;
  if (walking) { b.x += sgn(mx) * Math.min(sp, abs(mx)); b.y += sgn(my) * Math.min(sp * 0.7, abs(my)); clampBoss(b); }
  b.x = clamp(b.x, cam - 40, cam + 300);
  if (walking && a !== 'walk') setAnim(b, 'walk'); else if (!walking && a !== 'idle') setAnim(b, 'idle');
}

/**
 * RAZOR, the docks' boss: fast (1.5 across, 1.0 into the screen), and always moving. Close in his lane he stabs three times (4, 4,
 * then 6 and a knockdown) and hops back; from far off he crouches (the warning), leaps over the hero and kicks down on the way (7,
 * knockdown), then lands with a gap in his guard. Like BULL: no hit stun, a knockdown only at the thirds of his health.
 */
function updateRazor(b) {
  if (b.inv > 0) b.inv--;
  if (b.flash > 0) b.flash--;
  if (updateShared(b) || b.ai === 'dummy') return;
  if (!heroes().length) return;
  const a = b.anim;
  if (a === 'rslash1' || a === 'rslash2' || a === 'rslash3') {
    b.x += b.face * (a === 'rslash3' ? 0.5 : 0.8);                   // each stab lunges a little
    if (stepAnim(b)) {
      if (a === 'rslash1') setAnim(b, 'rslash2'); else if (a === 'rslash2') setAnim(b, 'rslash3');
      else { setAnim(b, 'walk'); b.cool = rndi(45, 80); b.retreat = 14; }
    }
    return;
  }
  if (a === 'rcrouch') {                                             // then up and over: he lands behind the hero
    if (stepAnim(b)) { const p = target(b); setAnim(b, 'rleap'); b.vz = 5.8; b.h = 0.1; b.vx = (p.x + b.face * 34 - b.x) / 39; b.vy = (p.y - b.y) / 39; }   // 39 frames in the air, 56 px up
    return;
  }
  if (a === 'rleap' || a === 'rdive') {
    b.x += b.vx; b.y += b.vy; b.x = clamp(b.x, cam + 16, cam + 240);
    const landed = fall(b);
    if (a === 'rleap' && b.vz < 0) setAnim(b, 'rdive');              // coming down: the kick is out
    if (landed) { setAnim(b, 'rland'); b.vx = 0; b.vy = 0; fx(SFX.thud); }
    return;
  }
  if (a === 'rland') { if (stepAnim(b)) { setAnim(b, 'walk'); b.cool = rndi(50, 90); } return; }
  const p = target(b), dx = p.x - b.x, dy = p.y - b.y, adx = abs(dx), ady = abs(dy);
  if (b.ai === 'enter') { b.x -= 1.8; b.face = -1; if (b.x <= cam + 190) b.ai = 'fight'; if (a !== 'walk') setAnim(b, 'walk'); return; }
  if (b.cool > 0) b.cool--;
  if (b.retreat > 0) { b.retreat--; b.x = clamp(b.x - b.face * 2.5, cam + 20, cam + 236); if (a !== 'walk') setAnim(b, 'walk'); return; }   // the hop back
  b.face = dx >= 0 ? 1 : -1;
  if (b.cool <= 0 && ady <= 8 && adx >= 30 && adx <= 60) { setAnim(b, 'rslash1'); return; }
  if (b.cool <= 0 && adx >= 100) { setAnim(b, 'rcrouch'); return; }
  const tx = p.x - b.face * 46, ty = p.y;
  const mx = tx - b.x, my = ty - b.y, walking = abs(mx) > 2 || abs(my) > 2;
  if (walking) { b.x += sgn(mx) * Math.min(1.5, abs(mx)); b.y += sgn(my) * Math.min(1.0, abs(my)); clampBoss(b); }
  b.x = clamp(b.x, cam - 40, cam + 300);
  if (walking && a !== 'walk') setAnim(b, 'walk'); else if (!walking && a !== 'idle') setAnim(b, 'idle');
}

// --- The level: the camera, the waves, the end ---

function updateCamera() {
  const next = LEVEL[wave];
  if (!locked) {
    const limit = next ? next.x : LEVEL_W - 256;
    const lead = Math.max(...heroes().map((h) => h.x));              // the screen follows the one who is furthest on
    cam = Math.min(Math.max(cam, lead - 112), limit, LEVEL_W - 256);
    if (next && cam >= next.x) { locked = true; spawnWave(next); wave++; }
  } else if (enemies.length === 0) {
    locked = false;
    if (wave >= LEVEL.length) { clearStage(); return; }
    goT = 0;
  }
  for (const h of heroes()) h.x = clamp(h.x, cam + 10, cam + 246);   // nobody leaves the screen
  for (const h of players) if (h.out) h.x = clamp(h.x, cam + 20, cam + 236);   // and a tombstone stays on it, at its edge
}

function clearStage() {
  bonusShown = players.map((h) => h.hp * 10 + h.lives * 500);
  players.forEach((h, k) => { h.score += bonusShown[k]; });
  if (stage + 1 < STAGES.length) { state = 'clear'; timer = 0; play(-1); fx(SFX.record); return; }   // on to the next stage
  won = true; gameOver(true);
}
function updateClear() {
  if (timer > 90 && (pressed(A) || pressed(START))) { fx(SFX.select); state = 'play'; loadStage(stage + 1); }
}

// --- Update ---

function update() {
  inputMask = [readPad(0), readPad(1)]; clock++;
  if (!paused) timer++; // a state's clock: it stands still while paused
  if (paused) updatePause();
  else if (state === 'title') updateTitle();
  else if (state === 'play') updatePlay();
  else if (state === 'clear') updateClear();
  else if (state === 'over') updateOver();
  else if (state === 'initials') updateInitials();
  else if (state === 'records') updateRecords();
  prevMask = inputMask;
}

function updateTitle() {
  if (pressed(UP)) { titleSel = (titleSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { titleSel = (titleSel + 1) % 3; fx(SFX.move); }
  if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (titleSel < 2) startGame(titleSel + 1); else { state = 'records'; hl = -1; timer = 0; }
  }
}

function updatePlay() {
  if (pressed(START)) { paused = true; pauseSel = 0; fx(SFX.pause); return; }
  if (players.length < 2 && pressedBy(1, A)) {                       // the second player joins any time
    const h = addHero(1, Math.max(cam + 30, players[0].x - 40), 190); h.inv = 120; setAnim(h, 'getup'); fx(SFX.select);
  }
  if (pressed(SELECT)) showBoxes = !showBoxes;
  if (lastHitT > 0) lastHitT--;
  if (warnT > 0) warnT--;
  if (bannerT > 0) bannerT--;
  if (hitstop > 0) {                                                 // both fighters freeze on a hit
    hitstop--;
    for (const h of players) if (pressedBy(h.pad, A) && COMBO[h.anim]) { h.queue = true; h.queueUp = held(h.pad, UP); }   // (a press during the freeze still counts)
    return;
  }
  for (const h of heroes()) updateHero(h);
  if (state !== 'play') return;                                      // (the last hero may have just gone out)
  for (const e of enemies) { if (e.kind === 'boss') (e.type === 'razor' ? updateRazor(e) : updateBull(e)); else updateThug(e); }
  for (const h of heroes()) checkProps(h);
  updateItems(); updateShots();
  for (const h of heroes()) { checkHits(h, enemies); checkHits(h, heroes().filter((o) => o !== h)); }
  for (const e of enemies) checkHits(e, heroes());
  thrownHits();
  separate(enemies); separate(heroes());
  enemies = enemies.filter((e) => !e.gone);
  if (state !== 'play') return;
  updateCamera();
  goT++;
}

function gameOver(clear) {
  state = 'over'; won = clear; timer = 0; play(-1); fx(clear ? SFX.record : SFX.over);
  pend = players.map((h) => ({ pad: h.pad, score: h.score })).sort((a, b) => b.score - a.score);   // each score for the top 10, best first
  nextEntry();
}
/** The next score that makes the top 10 (rank, and whose it is), or rank -1 when there is none left. */
function nextEntry() {
  rank = -1;
  while (pend.length && rank < 0) { const e = pend.shift(); rank = insertTop({ score: e.score, initials: lastInitials() }); if (rank >= 0) entryPad = e.pad; }
}

function updateOver() {
  if (timer < 60 || !(pressed(A) || pressed(START))) return;
  fx(SFX.select);
  if (rank >= 0) { state = 'initials'; timer = 0; initials = { chars: lastInitials().split(''), pos: 0 }; fx(SFX.record); }
  else toTitle();
}

/** UP/DOWN pick a letter, LEFT/RIGHT (or A and B) move, START saves (as does A on the last letter). */
function updateInitials() {
  const ini = initials, k = LETTERS.indexOf(ini.chars[ini.pos]);
  if (pressed(UP)) { ini.chars[ini.pos] = LETTERS[(k + 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(DOWN)) { ini.chars[ini.pos] = LETTERS[(k + LETTERS.length - 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(LEFT) || pressed(B)) ini.pos = Math.max(0, ini.pos - 1);
  if (pressed(RIGHT)) ini.pos = Math.min(2, ini.pos + 1);
  const done = pressed(START) || (pressed(A) && ini.pos === 2);
  if (pressed(A) && ini.pos < 2) ini.pos++;
  if (!done || timer < 20) return;
  const v = packInitials(ini.chars.join(''));
  dset(INITIALS_SLOT, v); dset(TOP_SLOT + rank * ENTRY + 1, v);
  fx(SFX.select);
  const saved = rank; nextEntry();
  if (rank >= 0) { initials = { chars: lastInitials().split(''), pos: 0 }; timer = 0; return; }   // the other player's score is next
  state = 'records'; hl = saved; timer = 0;
}

function updateRecords() {
  if ((pressed(START) || pressed(A) || pressed(B)) && timer > 20) { fx(SFX.select); toTitle(); }
}

function updatePause() {
  if (pressed(UP)) { pauseSel = (pauseSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { pauseSel = (pauseSel + 1) % 3; fx(SFX.move); }
  if (pressed(B) || (pressed(START) && pauseSel === 0)) { paused = false; fx(SFX.pause); }
  else if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (pauseSel === 0) paused = false;
    else if (pauseSel === 1) startGame(); // restart
    else toTitle(); // quitting abandons the game: nothing is recorded
  }
}

