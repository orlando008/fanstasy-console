function draw() {
  cls();
  if (state === 'play' || state === 'over') drawPlay();
  else if (state === 'title') drawTitle();
  else if (state === 'initials') drawInitials();
  else if (state === 'records') drawRecords();
  if (state === 'over') { panel(48, 80, 160, 64); ctxt('FINISHED!', 92, GOLD); ctxt(fmtTime(raceT), 108, WHITE); if (timer > 60 && timer % 60 < 40) ctxt('START: CONTINUE', 126, DIM); }
  if (paused) drawPause();
}

const fmtTime = (f) => `${Math.floor(f / 3600)}:${String(Math.floor(f / 60) % 60).padStart(2, '0')}.${String(Math.floor((f % 60) * 5 / 3)).padStart(2, '0')}`;

/** The screen x of a yard's column. */
const colX = (y) => ((256 - COL_W * yards.length) >> 1) + y.slot * COL_W;

function drawPlay() {
  for (const y of yards) drawYard(y);
}

function drawYard(y) {
  const x0 = colX(y), ox = x0 + HALF, oy = 224 - y.cam; // world (0, 0) on the screen is (ox, oy + y.cam)
  const sx = (wx) => ox + wx, sy = (wy) => 224 + (wy - y.cam);
  rectfill(x0, VY, COL_W, VH, ART.colors.sky);
  clip(x0, VY, COL_W, VH);
  const gy = sy(0);
  line(x0, sy(-FINISH), x0 + COL_W, sy(-FINISH), y.hold > 0 ? ART.colors.goal : ART.colors.danger);
  for (const b of [y.W.ground, ...y.W.bodies]) drawBody(b, sx, sy, b === y.W.ground);
  if (y.cur) drawBody(y.cur, sx, sy, false);
  rectfill(x0, gy + 16, COL_W, 224 - gy, ART.colors.stoneDark);
  clip();
  rect(x0, VY, COL_W, VH, PANEL);
  txt(`P${y.slot + 1}`, x0 + 3, 4, WHITE);
  txt(`${Math.max(0, Math.round(-y.top))}/${FINISH}`, x0 + 22, 4, y.hold > 0 ? GOLD : CYAN);
  if (y.hold > 0) rectfill(x0 + 2, VY + 2, Math.round((COL_W - 4) * y.hold / HOLD), 3, ART.colors.goal);
}

/** A body: its blocks as filled squares with a dark edge, however they are turned. */
function drawBody(b, sx, sy, ground) {
  const fill = ground ? ART.colors.stone : ART.colors['p' + b.kind], edge = ground ? ART.colors.stoneDark : ART.colors.edge;
  for (let k = 0; k < b.n; k++) {
    const v = b.v[k], q = [sx(v[0]), sy(v[1]), sx(v[2]), sy(v[3]), sx(v[4]), sy(v[5]), sx(v[6]), sy(v[7])];
    fillQuad(q, fill);
    for (let e = 0; e < 4; e++) { const f = (e + 1) & 3; line(q[e * 2], q[e * 2 + 1], q[f * 2], q[f * 2 + 1], edge); }
  }
}

/** A filled quadrilateral, row by row. */
function fillQuad(q, c) {
  let lo = 1e9, hi = -1e9;
  for (let i = 1; i < 8; i += 2) { lo = Math.min(lo, q[i]); hi = Math.max(hi, q[i]); }
  for (let py = Math.ceil(lo - 0.5), end = Math.floor(hi - 0.5); py <= end; py++) {
    const yy = py + 0.5;
    let xl = 1e9, xr = -1e9;
    for (let e = 0; e < 4; e++) {
      const f = (e + 1) & 3, ax = q[e * 2], ay = q[e * 2 + 1], bx = q[f * 2], by = q[f * 2 + 1];
      if ((ay <= yy && by > yy) || (by <= yy && ay > yy)) { const x = ax + (yy - ay) / (by - ay) * (bx - ax); if (x < xl) xl = x; if (x > xr) xr = x; }
    }
    if (xr > xl) line(Math.round(xl), py, Math.max(Math.round(xl), Math.round(xr) - 1), py, c);
  }
}

