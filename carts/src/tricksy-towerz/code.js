const lastInitials = () => (dget(INITIALS_SLOT) ? unpackInitials(dget(INITIALS_SLOT)) : 'AAA');

// --- Input: edge-triggered presses for each of the four pads (btnp repeats; menus and pieces want one press) ---

const masks = [0, 0, 0, 0], prevMasks = [0, 0, 0, 0];
const BUTTONS = [UP, DOWN, LEFT, RIGHT, A, B, X, Y, L, R, START, SELECT];
function readPads() { for (let p = 0; p < 4; p++) { let m = 0; for (const b of BUTTONS) if (btn(b, p)) m |= 1 << b; prevMasks[p] = masks[p]; masks[p] = m; } }
