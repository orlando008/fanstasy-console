// Neon Drift (docs/carts/neon-drift.md)
// A diamond on the rim of a neon wormhole; lights ride the tunnel to the rim on the beat of a trance track, and the player glides the
// diamond round the rim to be under each one as it arrives. The music is the clock: a chart (rom/charts.bin, written by audio.py from the
// same notes as the song) says on which frame each light reaches the rim and where. The tunnel is one picture on BG2, zoomed by one ring
// step a beat and rolled by one affine matrix a frame; its rings' colours are set each frame from their radius on the screen.

// --- Colours: the default palette's overlay colours (the overlay's index 0 is transparent) ---

const SHADOW = 1, PANEL = 3, RED = 6, ORANGE = 9, DIM = 10, GREEN = 11, CYAN = 13, GOLD = 14, WHITE = 15;

