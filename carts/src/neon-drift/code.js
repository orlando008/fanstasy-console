/** Queue one of ART.sprites at (x, y); opts as for spr (fx, fy, prio ...). */
function sprite(s, x, y, opts = {}) { spr(s.tile, x, y, { size: s.size, pal: s.pal, prio: 3, ...opts }); }

// --- Sound (SPEC 5): songs on channels 0 to 5, effects take turns on 6 and 7 ---

const SFX = { move: 0, select: 1, pause: 2, locked: 3, up2: 4, up3: 5, up4: 6, fanfare: 7, fanfareLow: 8, record: 9, tick: 10, count: 11, go: 12, catch: 13 };
const SONG = { title: 0 };                                          // track i is song i + 1
const SFX_CH = [7, 6];
let fxNext = 0;
function fx(n) { sfx(n, SFX_CH[fxNext]); fxNext ^= 1; }
let playing = -1, songAt = 0;                                       // the song playing and the frame (clock) it started
function play(song) {
  if (song === playing) return;
  playing = song; songAt = clock; music(song);
}

// --- Save slots (spec section 13) ---

const VERSION_SLOT = 0, SAVE_VERSION = 1, LAG_SLOT = 1, OPEN_SLOT = 2, BEST_SLOT = 10;
const bestSlot = (track, level) => BEST_SLOT + (track * 3 + level) * 2;     // the score; the grade (0 none, 1 D to 5 S) and the best combo << 4

// --- Input: edge-triggered presses ---

let inputMask = 0, prevMask = 0;
const BUTTONS = [UP, DOWN, LEFT, RIGHT, A, B, X, Y, L, R, START, SELECT];
function readPad() { let m = 0; for (const b of BUTTONS) if (btn(b)) m |= 1 << b; return m; }
const pressed = (b) => (inputMask & (1 << b)) !== 0 && (prevMask & (1 << b)) === 0;
const held = (b) => (inputMask & (1 << b)) !== 0;

// --- The rules (spec section 5) ---

const CX = 128, CY = 112, RIM = 94, RHO = 1.6;                    // the vanishing point, the rim's radius, the ring step (a beat's zoom)
const LOOKAHEAD = 120, RESUME_LEAD = 90;                            // frames: how far ahead a light shows; the count-in after a pause
const VMAX = 3.2, ACC = 0.4, BRAKE = 0.8, DEC = 0.12;               // the diamond: top speed (angle units a frame, 256 a turn), speeding up, braking (the other way held), the drift's easing off (nothing held)
const WIN = [8, 16, 24], PTS = [100, 70, 40], JUDGE = ['PERFECT', 'GOOD', 'OK'], JUDGE_C = [GOLD, GREEN, CYAN];
const MULT_AT = [10, 20, 40];                                       // the combo for x2, x3, x4
const GRADES = ['D', 'C', 'B', 'A', 'S'], GRADE_C = [DIM, ORANGE, CYAN, GREEN, GOLD];
const LEVELS = ['CHILL', 'DRIVE', 'OVERDRIVE'];
const FOLLOWS = ['THE KICK', 'KICK AND OFFBEAT', 'THE ARPEGGIO'];
const TRACKS = ['EVENT HORIZON', 'STARLIGHT RUN', 'AURORA', 'PULSAR', 'SUPERNOVA'];
// Each track's colours (5-bit RGB): the rim's (near) and the hole's (far); and the space behind.
const LOOKS = [
  { near: [8, 28, 31], far: [20, 6, 28], back: [1, 0, 4] },
  { near: [31, 12, 24], far: [6, 10, 30], back: [2, 0, 5] },
  { near: [6, 31, 18], far: [4, 14, 26], back: [0, 2, 4] },
  { near: [31, 20, 4], far: [28, 4, 20], back: [3, 0, 2] },
  { near: [31, 30, 22], far: [30, 18, 4], back: [2, 1, 0] },
];

const wrap = (a) => ((a % 256) + 256) % 256;
const gap = (a, b) => ((((a - b) % 256) + 384) % 256) - 128;        // the signed shortest way round from b to a
const multiplier = () => (combo >= MULT_AT[2] ? 4 : combo >= MULT_AT[1] ? 3 : combo >= MULT_AT[0] ? 2 : 1);
const multOf = (c) => (c >= MULT_AT[2] ? 4 : c >= MULT_AT[1] ? 3 : c >= MULT_AT[0] ? 2 : 1);

/** A track's chart for a level, from the ROM: { speed, sections: [{ f, kind }], lights: [{ f, a, p, r }] } (r: 0 coming, 1-3 the judgement, 4 missed, 5 skipped). */
function loadChart(i, level) {
  const b = rom('charts'), off = b[1 + 2 * i] | (b[2 + 2 * i] << 8);
  let o = off + 2;
  const speed = b[off], sections = [];
  for (let k = 0; k < b[off + 1]; k++, o += 3) sections.push({ f: b[o] | (b[o + 1] << 8), kind: b[o + 2] });
  let lights = [];
  for (let lv = 0; lv < 3; lv++) {
    const n = b[o] | (b[o + 1] << 8); o += 2;
    const list = [];
    for (let k = 0; k < n; k++, o += 4) list.push({ f: b[o] | (b[o + 1] << 8), a: b[o + 2], p: b[o + 3], r: 0 });
    if (lv === level) lights = list;
  }
  return { speed, sections, lights };
}
const trackCount = () => rom('charts')[0];

/** The diamond, one frame: LEFT and RIGHT glide it round the rim (RIGHT adds to the angle: from the bottom, to the right); let go and it drifts on,
 * slowing gently; the other way brakes. */
function steer() {
  const dir = (held(RIGHT) ? 1 : 0) - (held(LEFT) ? 1 : 0);
  if (dir === 0) v = Math.abs(v) <= DEC ? 0 : v - Math.sign(v) * DEC;
  else if (v * dir < 0) v += dir * BRAKE;
  else v = clamp(v + dir * ACC, -VMAX, VMAX);
  dia = wrap(dia + v);
}

/** A light on the rim now: judged by how far round the diamond is from it. */
function arrive(l) {
  const d = Math.abs(gap(l.a, dia));
  const g = d <= WIN[0] ? 0 : d <= WIN[1] ? 1 : d <= WIN[2] ? 2 : 3;
  if (g === 3) { l.r = 4; counts[3]++; if (combo >= MULT_AT[0]) banner('COMBO LOST', RED); combo = 0; lastMult = 1; show('MISS', RED); return; }   // no sound: the screen says it
  l.r = g + 1; counts[g]++; combo++; bestCombo = Math.max(bestCombo, combo);
  const m = multiplier();
  score += PTS[g] * m;
  show(JUDGE[g], JUDGE_C[g]); fx(SFX.catch + (l.p % 12));
  const th = (dia + roll) * Math.PI / 128;
  bursts.push({ x: CX + RIM * Math.sin(th), y: CY + RIM * Math.cos(th), at: clock, g });
  if (m > lastMult) { banner('X' + m, [WHITE, CYAN, GREEN, GOLD][m - 1]); fx(m === 2 ? SFX.up2 : m === 3 ? SFX.up3 : SFX.up4); }
  lastMult = m;
  if (combo % 50 === 0) banner(`${combo} COMBO`, GOLD);
}
function banner(text, c) { bannerText = text; bannerColour = c; bannerAt = clock; }
function show(text, c) { judgeText = text; judgeColour = c; judgeAt = clock; }
const caught = () => counts[0] + counts[1] + counts[2];
const accuracy = () => { const n = caught() + counts[3]; return n ? caught() / n : 0; };
/** The grade from the share of the track's best possible score (S also needs no miss). */
const gradeOf = () => { const s = maxScore ? score / maxScore : 0; return s >= 0.9 && !counts[3] ? 4 : s >= 0.8 ? 3 : s >= 0.65 ? 2 : s >= 0.5 ? 1 : 0; };

// --- State ---

let skipTitle = false;                                              // tests set this to land straight in a track
let state = 'title', paused = false, timer = 0, clock = 0;
let titleSel = 0, pauseSel = 0, sel = 0, selLevel = 0, msg = '', msgAt = -999, opened = 0, savedLag = 0, cal = null;
let track = 0, level = 0, lights = [], sections = [], speed = 7, beat = 28, tm = 0, musicAt = 0, started = false, lag = 0;
let dia = 0, v = 0, roll = 0, rollV = 0, kick = 0, look = LOOKS[0], maxScore = 0, endAt = 0, newBest = false, songEnd = 0;
let score = 0, combo = 0, bestCombo = 0, lastMult = 1, counts = [0, 0, 0, 0], bursts = [], trail = [];
let judgeText = '', judgeColour = WHITE, judgeAt = -99, bannerText = '', bannerColour = WHITE, bannerAt = -99;
const st = () => tm - lag;                                          // the song time the player hears now
const openN = () => Math.max(1, dget(OPEN_SLOT));
const isOpen = (i) => i < openN();

function init() {
  if (dget(VERSION_SLOT) !== SAVE_VERSION) {                        // a new or older save: start clean
    for (let i = 0; i < 256; i++) dset(i, 0);
    dset(VERSION_SLOT, SAVE_VERSION);
  }
  lag = dget(LAG_SLOT) ? dget(LAG_SLOT) - 16 : 0;
  const tn = ART.scenes.tunnel, sp = ART.scenes.space, lg = ART.scenes.logo;
  bg(2, { mx: tn.mx, my: tn.my, mw: tn.w, mh: tn.h, x: CX, y: 256 - CY, wrap: false, show: true });
  bg(1, { mx: sp.mx, my: sp.my, mw: sp.w, mh: sp.h, x: 0, y: 0, wrap: false, show: true });
  bg(0, { mx: lg.mx, my: lg.my, mw: lg.w, mh: lg.h, x: 0, y: -40, wrap: false, show: false });
  if (skipTitle) startTrack(0, 1); else toTitle();
}

function toTitle() { state = 'title'; timer = 0; titleSel = 0; paused = false; look = LOOKS[0]; play(SONG.title); }
function toTracks(s = sel) {
  state = 'tracks'; timer = 0; paused = false; sel = s; play(SONG.title);
  if (opened) { sel = opened; msg = 'A NEW TRACK IS OPEN'; msgAt = clock; opened = 0; fx(SFX.up3); }
  look = LOOKS[sel];
}

/** A track from its start: the count-in (a bar), then the music when song time reaches 0. */
function startTrack(i, lv) {
  track = i; level = lv; look = LOOKS[i];
  const c = loadChart(i, lv); lights = c.lights; sections = c.sections; speed = c.speed; beat = 4 * speed;
  maxScore = 0; for (let k = 1; k <= lights.length; k++) maxScore += PTS[0] * multOf(k);
  songEnd = (lights.length ? lights[lights.length - 1].f : 0) + 4 * beat;
  dia = 0; v = 0; roll = 0; rollV = 0; trail = []; bursts = [];
  score = 0; combo = 0; bestCombo = 0; lastMult = 1; counts = [0, 0, 0, 0]; judgeAt = -99; bannerAt = -99; newBest = false;
  tm = -4 * beat; musicAt = 0; started = false; endAt = 0; paused = false; timer = 0; state = 'play'; play(-1);
}

// --- Update ---

function update() {
  inputMask = readPad(); clock++;
  if (!paused) timer++;
  if (paused) updatePause();
  else if (state === 'title') updateTitle();
  else if (state === 'tracks') updateTracks();
  else if (state === 'play') updatePlay();
  else if (state === 'calib') updateCalib();
  else if (state === 'results') updateResults();
  else if (state === 'records') updateRecords();
  prevMask = inputMask;
}

function updateTitle() {
  if (pressed(UP) || pressed(DOWN)) { titleSel ^= 1; fx(SFX.move); }
  if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (titleSel === 0) toTracks(); else { state = 'records'; timer = 0; }
  }
}

/** The track list: LEFT and RIGHT choose a track, UP and DOWN the level, A plays (the first time, the calibration comes first), SELECT the calibration, B the title. */
function updateTracks() {
  const n = trackCount(), before = sel;
  if (pressed(LEFT)) sel = (sel + n - 1) % n;
  if (pressed(RIGHT)) sel = (sel + 1) % n;
  if (before !== sel) { fx(SFX.move); msg = ''; look = LOOKS[sel]; }
  if (pressed(UP)) { selLevel = (selLevel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { selLevel = (selLevel + 1) % 3; fx(SFX.move); }
  if (pressed(B)) { fx(SFX.move); toTitle(); }
  else if (pressed(SELECT)) { fx(SFX.select); startCalib(false); }
  else if (pressed(A) || pressed(START)) {
    if (!isOpen(sel)) { msg = 'FINISH THE TRACK BEFORE IT'; msgAt = clock; fx(SFX.locked); return; }
    fx(SFX.select);
    if (!dget(LAG_SLOT)) startCalib(true); else startTrack(sel, selLevel);
  }
}

// --- The calibration (spec 5.6): a tick on a steady beat and a light coming to the diamond on it; press A in time. The median of
// how late the presses are is the offset in frames (-15 to 15), kept in save slot 1 as the value + 16. During it `lag` is 0.

const CAL_BEATS = 16, CAL_GAP = 32, CAL_FIRST = 120, CAL_NEED = 6;
function startCalib(then) {
  savedLag = lag; lag = 0; state = 'calib'; timer = 0; play(-1); paused = false; look = LOOKS[0];
  lights = []; for (let k = 0; k < CAL_BEATS; k++) lights.push({ f: CAL_FIRST + k * CAL_GAP, a: 0, p: 0, r: 0 });
  beat = CAL_GAP; tm = 0; dia = 0; v = 0; roll = 0; rollV = 0; bursts = []; trail = [];
  cal = { errs: [], then, stage: 'tap', off: 0 };
}
function updateCalib() {
  if (cal.stage === 'tap') {
    tm++;
    for (const l of lights) if (l.f === tm) fx(SFX.tick);
    if (pressed(A)) {
      let best = null;
      for (const l of lights) if (!l.r && Math.abs(l.f - tm) <= 16 && (!best || Math.abs(l.f - tm) < Math.abs(best.f - tm))) best = l;
      if (best) { best.r = 1; cal.errs.push(tm - best.f); bursts.push({ x: CX, y: CY + RIM, at: clock, g: 0 }); }
    }
    if (pressed(B)) endCalib(false);
    else if (tm > lights[lights.length - 1].f + 30 || cal.errs.length >= 14) {
      const e = cal.errs.slice(2).sort((x, y) => x - y);            // the first two presses are the player settling in
      if (e.length < CAL_NEED) cal.stage = 'fail'; else { cal.off = clamp(e[e.length >> 1], -15, 15); cal.stage = 'done'; }
    }
  } else {
    if (cal.stage === 'done') { if (pressed(LEFT)) cal.off = Math.max(-15, cal.off - 1); if (pressed(RIGHT)) cal.off = Math.min(15, cal.off + 1); }
    if (pressed(START)) { fx(SFX.select); startCalib(cal.then); }
    else if (pressed(B)) endCalib(false);
    else if (pressed(A) && cal.stage === 'done') endCalib(true);
  }
}
/** Leave the calibration: keep the offset (save it) or not; the first time, leaving it also stops it being offered again. */
function endCalib(save) {
  fx(SFX.select);
  if (save) { lag = cal.off; dset(LAG_SLOT, lag + 16); } else { lag = savedLag; if (!dget(LAG_SLOT)) dset(LAG_SLOT, 16); }
  const then = cal.then; cal = null;
  if (then) startTrack(sel, selLevel); else toTracks();
}

/** The section of the song at song time f. */
function sectionAt(f) { let s = sections[0]; for (const x of sections) if (x.f <= f) s = x; return s; }
const KIND_ROLL = [0.05, 0.1, 0.12, 0.22, 0.06, 0.16, 0.05];       // how fast the tunnel rolls in each kind of section (intro, groove, build, drop, break, rise, outro)
const HAS_KICK = [1, 1, 1, 1, 0, 0, 1];

/** One frame of a track: the clock, the music's start, the diamond, the lights that arrive, the roll, the end. */
function updatePlay() {
  if (pressed(START)) { paused = true; pauseSel = 0; fx(SFX.pause); music(-1); playing = -1; return; }
  const r = tm - musicAt;                                           // the count-in: a tick on each beat of the bar before, GO as the music starts
  if (r <= 0 && r >= -3 * beat && r % beat === 0) fx(r ? SFX.count : SFX.go);
  tm++;
  if (!started && tm >= musicAt) { started = true; playing = track + 1; music(track + 1, musicAt / (64 * speed)); }
  steer();
  const now = st();
  for (const l of lights) if (!l.r && l.f <= now) arrive(l);
  if (sections.length) {
    const s = sectionAt(Math.max(0, now)), k = sections.indexOf(s);
    rollV += ((k % 2 ? -1 : 1) * KIND_ROLL[s.kind] - rollV) * 0.02;
    roll += rollV;
    if (HAS_KICK[s.kind] && now >= 0 && now % beat === 0) kick = 1;
  }
  kick *= 0.85;
  trail.unshift(dia); if (trail.length > 8) trail.pop();
  if (!endAt && now > songEnd && lights.every((l) => l.r)) endAt = clock;
  if (endAt && clock > endAt + 60) finish();
}

function finish() {
  endAt = 0; state = 'results'; timer = 0;
  const g = gradeOf(), s = bestSlot(track, level);
  newBest = score > dget(s);
  if (newBest) { dset(s, score); dset(s + 1, (g + 1) | (bestCombo << 4)); }
  if (track + 1 < trackCount() && openN() < track + 2) { dset(OPEN_SLOT, track + 2); opened = track + 1; }   // a track played to the end opens the next
  fx(g >= 3 ? SFX.fanfare : SFX.fanfareLow);
}

function updateResults() {
  if (timer === 40 && newBest) fx(SFX.record);
  if (timer > 30 && (pressed(A) || pressed(START))) { fx(SFX.select); toTracks(track); }
}

function updateRecords() {
  if ((pressed(START) || pressed(A) || pressed(B)) && timer > 20) { fx(SFX.select); toTitle(); }
}

/** Resume starts the music again at the start of the pattern the track was in, after a count-in: lights whose time went by are skipped. */
function resume() {
  paused = false;
  const pat = Math.floor(Math.max(0, tm) / (64 * speed));
  musicAt = pat * 64 * speed; tm = musicAt - RESUME_LEAD; started = false; fx(SFX.count);
  for (const l of lights) if (!l.r && l.f < musicAt + 2 * beat) l.r = 5;
}

function updatePause() {
  if (pressed(UP)) { pauseSel = (pauseSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { pauseSel = (pauseSel + 1) % 3; fx(SFX.move); }
  if (pressed(B) || (pressed(START) && pauseSel === 0)) { fx(SFX.pause); resume(); }
  else if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (pauseSel === 0) resume();
    else if (pauseSel === 1) startTrack(track, level);
    else toTracks(track);
  }
}

// --- Draw ---

// The tunnel: the picture's rings are at RING0 / RHO^k (art.py); zoomed by s = RHO^phase, where phase is the part of the beat gone by, the
// rings move out by one ring step a beat and the picture is the same when the phase wraps. Band k (a ring and the rails inside it) has two
// CGRAM entries, a line and a glow, set here from the ring's radius on the screen: dark in the hole, bright at the rim.
const RING0 = 160, RINGS = 7, LINE0 = 17, GLOW0 = 24, HAZE0 = 36;
let tunnelBright = 1;
function drawTunnel(phase, rollAngle, bright) {
  const s = Math.pow(RHO, phase) * (1 + 0.03 * kick) * RIM / 100, th = rollAngle * Math.PI / 128, c = Math.cos(th) / s, n = Math.sin(th) / s;
  affine({ a: c, b: -n, c: n, d: c, cx: 256, cy: 256 });
  for (let k = 0; k < RINGS; k++) {
    const r = RING0 / Math.pow(RHO, k) * s;
    let b = r <= RIM ? 0.12 + 0.88 * Math.pow(clamp((r - 8) / (RIM - 8), 0, 1), 0.9) : 1 - Math.min(0.35, (r - RIM) / 300);
    b *= bright * (0.8 + 0.35 * kick);
    const t = clamp(r / RIM, 0, 1), col = [0, 1, 2].map((i) => lerp(look.far[i], look.near[i], t));
    color(LINE0 + k, clamp(col[0] * b, 0, 31), clamp(col[1] * b, 0, 31), clamp(col[2] * b, 0, 31));
    color(GLOW0 + k, clamp(col[0] * b * 0.32, 0, 31), clamp(col[1] * b * 0.32, 0, 31), clamp(col[2] * b * 0.32, 0, 31));
  }
  color(0, look.back[0], look.back[1], look.back[2]);
  for (let i = 0; i < 4; i++) { const k = (0.18 + 0.16 * i) * bright; color(HAZE0 + i, look.far[0] * k + look.back[0], look.far[1] * k + look.back[1], look.far[2] * k + look.back[2]); }   // the light at the end of the tunnel, in the track's far colour
}

/** Where a light at angle a, f frames before it reaches the rim, is on the screen: its radius shrinks a ring step each beat further away. */
function place(a, f) {
  const r = RIM * Math.pow(RHO, -f / beat), th = (a + roll) * Math.PI / 128;
  return { x: CX + r * Math.sin(th), y: CY + r * Math.cos(th), r };
}

function drawLights(now) {
  for (const l of lights) {
    const f = l.f - now;
    if (f > LOOKAHEAD || f < -12 || (l.r && l.r !== 4)) continue;
    const p = place(l.a, f); l.x = p.x; l.y = p.y;
    if (l.r === 4 && clock % 2) continue;                           // a missed light falls past, blinking
    const sp = p.r < 30 ? ART.sprites.light8 : p.r < 62 ? ART.sprites.light16 : ART.sprites.light32;
    sprite(sp, flr(p.x - sp.size / 2), flr(p.y - sp.size / 2), { prio: 2 });
  }
}

/** The diamond's sprite for its place on the rim: its long axis along the rim (9 turns drawn, the rest flipped). */
function drawDiamond() {
  const th = (dia + roll) * Math.PI / 128, x = CX + RIM * Math.sin(th), y = CY + RIM * Math.cos(th);
  let t = ((-th % Math.PI) + Math.PI) % Math.PI, flip = false;
  if (t > Math.PI / 2) { t = Math.PI - t; flip = true; }
  const k = Math.round(t / (Math.PI / 16));
  sprite(ART.sprites['gem' + k], flr(x - 16), flr(y - 16), { fx: flip, prio: 3 });
  sprite(ART.sprites.halo, flr(x - 16), flr(y - 16), { prio: 2 });
  for (let i = 3; i < trail.length; i += 2) {                       // the afterimage when it moves fast
    if (Math.abs(gap(trail[i], dia)) < 6) continue;
    const u = (trail[i] + roll) * Math.PI / 128;
    sprite(ART.sprites.light8, flr(CX + RIM * Math.sin(u) - 4), flr(CY + RIM * Math.cos(u) - 4), { pal: 5, prio: 2 });
  }
  return { x, y };
}

function drawBursts() {
  bursts = bursts.filter((b) => clock - b.at < 16);
  for (const b of bursts) {
    const a = clock - b.at;
    sprite(ART.sprites['burst' + Math.min(3, a >> 2)], flr(b.x - 16), flr(b.y - 16), { prio: 3 });
    if (b.g === 0) for (let k = 0; k < 6; k++) {
      const u = k * Math.PI / 3 + b.at, d = 6 + a * 1.6;
      sprite(ART.sprites.spark, flr(b.x + d * Math.cos(u) - 4), flr(b.y + d * Math.sin(u) - 4), { prio: 3 });
    }
  }
}

function draw() {
  cls();
  const inPlay = (state === 'play' || state === 'calib') && !paused;
  blend(inPlay ? { layers: ['overlay', 'spr'], op: 'add' } : { layers: ['overlay'], half: true });   // in play the glows add their light; in the menus the panels mix
  bg(0, { show: state === 'title' });
  if (state === 'play' || state === 'calib') {
    const now = state === 'calib' ? tm : st();
    drawTunnel(((now % beat) + beat) % beat / beat, roll, state === 'play' && !started ? 0.7 : 1);
    drawLights(now); drawDiamond(); drawBursts();
    if (state === 'play') drawHud(); else drawCalib();
  } else {
    const b = 28, f = clock - songAt;                               // the menus: the tunnel flows to the title song (speed 7, a beat of 28 frames)
    if (f % b === 0) kick = 1; kick *= 0.9;
    roll += 0.06;
    drawTunnel((f % b) / b, roll, state === 'results' ? 0.45 : 0.7);
    if (state === 'title') drawTitle();
    else if (state === 'tracks') drawTracks();
    else if (state === 'results') drawResults();
    else if (state === 'records') drawRecords();
  }
  if (paused) drawPause();
}

function drawHud() {
  txt(String(score).padStart(7, '0'), 8, 6, WHITE);
  const m = multiplier();
  txt('X' + m, 8, 16, [DIM, CYAN, GREEN, GOLD][m - 1]);
  if (combo >= 2) { const s = `${combo}`; txt(s, 248 - s.length * 8, 6, combo >= MULT_AT[0] ? GOLD : WHITE); txt('COMBO', 208, 16, DIM); }
  if (clock - judgeAt < 24) ctxt(judgeText, 100, judgeColour);
  if (clock - bannerAt < 50 && (clock - bannerAt) % 8 < 6) ctxt(bannerText, 84, bannerColour);
  const r = tm - musicAt;
  if (!started && r < 0) { const n = Math.ceil(-r / beat); if (n <= 3 && n >= 1) ctxt(String(n), 100, WHITE); }
  const p = clamp(st() / Math.max(1, songEnd), 0, 1);               // how far through the track
  rectfill(8, 216, 240, 2, SHADOW); rectfill(8, 216, flr(240 * p), 2, CYAN);
  txt(TRACKS[track], 8, 204, DIM);
  const lv = LEVELS[level]; txt(lv, 248 - lv.length * 8, 204, DIM);
}

