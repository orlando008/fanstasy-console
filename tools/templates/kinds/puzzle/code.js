// {{TITLE}}
// Scaffolded by tools/new-cart.js --kind puzzle: a match-3 game (swap two neighbouring gems, three or more in a row
// clear, the rest fall, new ones drop in, and chains score more) around the frame every cart needs: a title, play,
// pause, game over, a saved top 10 with initials, records, sound and music cues, a skipTitle hook and save slots.
// Replace the rules, the art (art.py) and the sound (audio.py); keep the structure. See docs/dev/playbook.md.
//
// The board logic is plain functions on an array of gem types (findRuns, hasMoves, makeTypes, popScore), kept apart from the
// gems' pictures and movement, so tests and bots can call them. The play state is a small machine (`phase`):
//   idle -> swap -> (no match: unswap -> idle) | (match: pop -> fall -> pop ... -> settle -> idle | win -> fall | over | shuffle -> fall)

// --- Colours: the default palette (DawnBringer 16). The overlay's index 0 is transparent. ---

const SHADOW = 1, PANEL = 3, RED = 6, DIM = 10, GREEN = 11, CYAN = 13, GOLD = 14, WHITE = 15;

// --- Art: made by art.py (tiles.txt, palette.txt, map.txt). The block below is rewritten each time it runs. ---

// ART (generated by art.py: do not edit)
const ART = { tiles: {}, sprites: {}, scenes: {}, colors: {} };
// END ART
/** Queue one of ART.sprites at (x, y), above the background; opts as for spr (fx, fy, pal ...). */
function sprite(s, x, y, opts = {}) { spr(s.tile, x, y, { size: s.size, pal: s.pal, prio: 3, ...opts }); }

// --- Sound (SPEC 5). The channel decides the voice: 0 and 1 pulse, 2 triangle, 3 saw, 4 noise, 5 sample. ---

const SFX = { move: 0, select: 1, pause: 2, swap: 3, bad: 4, match: 5, clear: 10, over: 11, shuffle: 12, record: 13 }; // match: 5 to 9, higher in a chain
const SONG = { title: 0, play: 1 };
const SFX_CH = 1; // effects share channel 1 (pulse); the songs leave it free
// Effects with noise (or saw or triangle) in them go on a channel with that voice (audio.py makes them).
const SFX_VOICE_CH = { [SFX.bad]: 4, [SFX.shuffle]: 4 };
function fx(n) { sfx(n, n in SFX_VOICE_CH ? SFX_VOICE_CH[n] : SFX_CH); }

// A song is only started if it is not already playing.
let playing = -1;
function play(song) {
  if (song === playing) return;
  playing = song; music(song);
}

// --- Save slots (SPEC 13) ---

const VERSION_SLOT = 0, SAVE_VERSION = 1, INITIALS_SLOT = 1;
const TOP_SLOT = 10, TOP_N = 10, ENTRY = 3; // the top 10, best first: score, initials, the level reached (slots 10 to 39)
const LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';

function readEntry(i) { const s = TOP_SLOT + i * ENTRY; return { score: dget(s), initials: unpackInitials(dget(s + 1)), level: dget(s + 2) }; }
function writeEntry(i, e) { const s = TOP_SLOT + i * ENTRY; dset(s, e.score); dset(s + 1, packInitials(e.initials)); dset(s + 2, e.level || 0); }
const topTen = () => Array.from({ length: TOP_N }, (_, i) => readEntry(i));

/** Put a score into the top 10 if it makes it. Returns its row, or -1. */
function insertTop(e) {
  if (!e.score) return -1;
  const list = topTen(), at = list.findIndex((x) => e.score > x.score);
  if (at < 0) return -1;
  list.splice(at, 0, e);
  for (let i = at; i < TOP_N; i++) writeEntry(i, list[i]);
  return at;
}
/** Three characters, 8 bits each. */
const packInitials = (str) => (str.charCodeAt(0) << 16) | (str.charCodeAt(1) << 8) | str.charCodeAt(2);
const unpackInitials = (v) => (v ? String.fromCharCode((v >> 16) & 255, (v >> 8) & 255, v & 255) : '---');
const lastInitials = () => (dget(INITIALS_SLOT) ? unpackInitials(dget(INITIALS_SLOT)) : 'AAA');

// --- Input: edge-triggered presses (btnp repeats; menus want one press) ---

let inputMask = 0, prevMask = 0;
const BUTTONS = [UP, DOWN, LEFT, RIGHT, A, B, X, Y, L, R, START, SELECT];
function readPad() { let m = 0; for (const b of BUTTONS) if (btn(b)) m |= 1 << b; return m; }
const pressed = (b) => (inputMask & (1 << b)) !== 0 && (prevMask & (1 << b)) === 0;

// --- The board: rules as plain functions on an array of gem types (0 to KINDS-1, -1 for empty), row by row ---

const COLS = 8, ROWS = 8, CELL = 16, BX = 64, BY = 64, KINDS = 6; // the board's size, its cells in px, its top left corner
const MOVES = 20, POP_FRAMES = 14, WIN_FRAMES = 100, FALL = 4; // moves a level, a match's flash, the level-clear banner, a gem's speed in px a frame

/** The runs of three or more equal gems, across or down: an array of arrays of cell numbers. */
function findRuns(t) {
  const runs = [];
  for (let line = 0; line < ROWS + COLS; line++) {
    const across = line < ROWS, len = across ? COLS : ROWS, at = (k) => (across ? line * COLS + k : k * COLS + (line - ROWS));
    for (let k = 0; k < len;) {
      const v = t[at(k)]; let e = k + 1;
      while (v >= 0 && e < len && t[at(e)] === v) e++;
      if (v >= 0 && e - k >= 3) runs.push(Array.from({ length: e - k }, (_, j) => at(k + j)));
      k = e;
    }
  }
  return runs;
}
/** The cells in any run (a cell where two runs cross counts once). */
const matched = (t) => [...new Set(findRuns(t).flat())];
const swapped = (t, a, b) => { const u = t.slice(); u[a] = t[b]; u[b] = t[a]; return u; };
/** Does any swap of two neighbours make a run? */
function hasMoves(t) {
  for (let i = 0; i < t.length; i++) {
    if (i % COLS < COLS - 1 && matched(swapped(t, i, i + 1)).length) return true;
    if (i < t.length - COLS && matched(swapped(t, i, i + COLS)).length) return true;
  }
  return false;
}
/** A full board with no run and at least one move. */
function makeTypes() {
  for (;;) {
    const t = Array(COLS * ROWS).fill(-1);
    for (let i = 0; i < t.length; i++) {
      let v;
      do v = rndi(0, KINDS - 1); while ((i % COLS >= 2 && t[i - 1] === v && t[i - 2] === v) || (i >= 2 * COLS && t[i - COLS] === v && t[i - 2 * COLS] === v));
      t[i] = v;
    }
    if (hasMoves(t)) return t;
  }
}
/** Points for one clear: 10 a gem, 30 more for each run of four or more, all times the chain (1 for the first clear, 2 for the one it caused ...). */
const popScore = (count, bigRuns, chain) => (10 * count + 30 * bigRuns) * chain;
/** The points a level asks for (earned in that level: the clear bonus does not count towards the next). */
const goalFor = (level) => 500 + 400 * level;

// --- The gems: a picture for each cell, sliding to its place ---

let grid = [];            // ROWS * COLS gems { t: type, x, y: pixel position of the picture } or null
let phase = 'idle';       // idle | swap | unswap | pop | fall | win
let cursor = 0, sel = -1; // the cursor's cell; the picked-up gem's cell, or -1
let sw = [0, 0];          // the two cells of the swap being shown
let popCells = [], popT = 0, winT = 0, chain = 0;
let score = 0, levelPts = 0, moves = MOVES, level = 1, goal = goalFor(1); // the total score; the points earned in this level; moves left; the level; its goal

const cellX = (i) => BX + (i % COLS) * CELL, cellY = (i) => BY + flr(i / COLS) * CELL;
const typesNow = () => grid.map((g) => (g ? g.t : -1));
/** A new board of gems, dropping in from above the screen (every column falls the same way). */
function dealBoard() {
  const t = makeTypes();
  grid = t.map((v, i) => ({ t: v, x: cellX(i), y: BY + (flr(i / COLS) - ROWS) * CELL }));
  phase = 'fall';
}
/** Move every gem a step towards its cell. Returns true while any is still on its way. */
function moveGems() {
  let moving = false;
  grid.forEach((g, i) => {
    if (!g) return;
    const tx = cellX(i), ty = cellY(i);
    g.x += Math.sign(tx - g.x) * Math.min(FALL, Math.abs(tx - g.x));
    g.y += Math.sign(ty - g.y) * Math.min(FALL, Math.abs(ty - g.y));
    if (g.x !== tx || g.y !== ty) moving = true;
  });
  return moving;
}
/** Gems fall to fill the gaps; new ones drop in above the board. */
function collapse() {
  for (let c = 0; c < COLS; c++) {
    let dst = ROWS - 1;
    for (let r = ROWS - 1; r >= 0; r--) {
      const g = grid[r * COLS + c];
      if (!g) continue;
      if (dst !== r) { grid[dst * COLS + c] = g; grid[r * COLS + c] = null; }
      dst--;
    }
    for (let r = dst; r >= 0; r--) grid[r * COLS + c] = { t: rndi(0, KINDS - 1), x: BX + c * CELL, y: BY + (r - dst - 1) * CELL };
  }
}

// --- State ---

let skipTitle = false; // tests set this to land straight in the game
let state = 'title', paused = false, timer = 0, clock = 0;
let titleSel = 0, pauseSel = 0, rank = -1, hl = -1, initials = null;

function init() {
  if (dget(VERSION_SLOT) !== SAVE_VERSION) { // a new or older save: start clean
    for (let i = 0; i < 256; i++) dset(i, 0);
    dset(VERSION_SLOT, SAVE_VERSION);
  }
  const b = ART.scenes.board; // the background: the board's picture in Map RAM, shown on layer 0
  bg(0, { mx: b.mx, my: b.my, mw: b.w, mh: b.h, show: true });
  if (skipTitle) startGame(); else toTitle();
}

function toTitle() { state = 'title'; timer = 0; titleSel = 0; paused = false; play(SONG.title); }

function startGame() {
  score = 0; levelPts = 0; level = 1; moves = MOVES; goal = goalFor(1); chain = 0; cursor = 3 * COLS + 3; sel = -1;
  paused = false; timer = 0; state = 'play';
  dealBoard();
  play(SONG.play);
}

// --- Update ---

function update() {
  inputMask = readPad(); clock++;
  if (!paused) timer++; // a state's clock: it stands still while paused
  if (paused) updatePause();
  else if (state === 'title') updateTitle();
  else if (state === 'play') updatePlay();
  else if (state === 'over') updateOver();
  else if (state === 'initials') updateInitials();
  else if (state === 'records') updateRecords();
  prevMask = inputMask;
}

function updateTitle() {
  if (pressed(UP) || pressed(DOWN)) { titleSel ^= 1; fx(SFX.move); }
  if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (titleSel === 0) startGame(); else { state = 'records'; hl = -1; timer = 0; }
  }
}

/** One frame of play: the pad in `idle`, otherwise the machine waits for the gems to settle, then takes its next step. */
function updatePlay() {
  if (pressed(START)) { paused = true; pauseSel = 0; fx(SFX.pause); return; }
  const moving = moveGems();
  if (phase === 'idle') idleInput();
  else if (phase === 'pop') { if (--popT <= 0) afterPop(); }
  else if (phase === 'win') { if (--winT <= 0) nextLevel(); }
  else if (!moving) {
    if (phase === 'swap') afterSwap();
    else if (phase === 'unswap') phase = 'idle';
    else if (phase === 'fall') afterFall();
  }
}

/** The cursor moves with the d-pad. A picks a gem up; then a direction swaps it with that neighbour (A or B puts it down). */
function idleInput() {
  const dx = (pressed(RIGHT) ? 1 : 0) - (pressed(LEFT) ? 1 : 0), dy = (pressed(DOWN) ? 1 : 0) - (pressed(UP) ? 1 : 0);
  const c = cursor % COLS, r = flr(cursor / COLS);
  if (sel < 0) {
    if (dx || dy) {
      const nc = mid(0, COLS - 1, c + dx), nr = mid(0, ROWS - 1, r + (dx ? 0 : dy));
      if (nr * COLS + nc !== cursor) { cursor = nr * COLS + nc; fx(SFX.move); }
    }
    if (pressed(A)) { sel = cursor; fx(SFX.select); }
  } else if (pressed(A) || pressed(B)) { sel = -1; fx(SFX.move); }
  else if (dx || dy) {
    const nc = c + dx, nr = r + (dx ? 0 : dy);
    if (nc >= 0 && nc < COLS && nr >= 0 && nr < ROWS) { cursor = nr * COLS + nc; trySwap(sel, cursor); }
  }
}

function trySwap(a, b) {
  const t = grid[a]; grid[a] = grid[b]; grid[b] = t;
  sw = [a, b]; sel = -1; phase = 'swap'; fx(SFX.swap);
}

/** The swap has been shown: keep it if it made a run (it costs a move), otherwise slide the gems back. */
function afterSwap() {
  if (matched(typesNow()).length) { moves--; chain = 1; startPop(); }
  else { const t = grid[sw[0]]; grid[sw[0]] = grid[sw[1]]; grid[sw[1]] = t; phase = 'unswap'; fx(SFX.bad); }
}

/** Score the runs and let the gems flash. */
function startPop() {
  const t = typesNow(), runs = findRuns(t);
  popCells = matched(t); popT = POP_FRAMES; phase = 'pop';
  const gain = popScore(popCells.length, runs.filter((r) => r.length >= 4).length, chain);
  score += gain; levelPts += gain;
  fx(SFX.match + Math.min(chain - 1, 4));
}
function afterPop() {
  for (const i of popCells) grid[i] = null;
  popCells = [];
  collapse();
  phase = 'fall';
}
/** The gems have landed: a chain goes on if they made a run; otherwise the turn is over. */
function afterFall() {
  if (matched(typesNow()).length) { chain++; startPop(); return; }
  chain = 0;
  settle();
}
/** The turn is over: the level is won, or the game lost, or the board is stuck (reshuffled), or the player goes on. */
function settle() {
  if (levelPts >= goal) { const bonus = moves * 50; score += bonus; winT = WIN_FRAMES; phase = 'win'; fx(SFX.clear); }
  else if (moves <= 0) gameOver();
  else if (!hasMoves(typesNow())) { dealBoard(); fx(SFX.shuffle); }
  else phase = 'idle';
}
function nextLevel() {
  level++; levelPts = 0; moves = MOVES; goal = goalFor(level); sel = -1;
  dealBoard();
}

function gameOver() {
  state = 'over'; timer = 0; play(-1); fx(SFX.over); phase = 'idle'; sel = -1;
  rank = insertTop({ score, initials: lastInitials(), level });
}

function updateOver() {
  if (timer < 60 || !(pressed(A) || pressed(START))) return;
  fx(SFX.select);
  if (rank >= 0) { state = 'initials'; timer = 0; initials = { chars: lastInitials().split(''), pos: 0 }; fx(SFX.record); }
  else toTitle();
}

/** UP/DOWN pick a letter, LEFT/RIGHT (or A and B) move, START saves (as does A on the last letter). */
function updateInitials() {
  const ini = initials, k = LETTERS.indexOf(ini.chars[ini.pos]);
  if (pressed(UP)) { ini.chars[ini.pos] = LETTERS[(k + 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(DOWN)) { ini.chars[ini.pos] = LETTERS[(k + LETTERS.length - 1) % LETTERS.length]; fx(SFX.move); }
  if (pressed(LEFT) || pressed(B)) ini.pos = Math.max(0, ini.pos - 1);
  if (pressed(RIGHT)) ini.pos = Math.min(2, ini.pos + 1);
  const done = pressed(START) || (pressed(A) && ini.pos === 2);
  if (pressed(A) && ini.pos < 2) ini.pos++;
  if (!done || timer < 20) return;
  const v = packInitials(ini.chars.join(''));
  dset(INITIALS_SLOT, v); dset(TOP_SLOT + rank * ENTRY + 1, v);
  fx(SFX.select);
  state = 'records'; hl = rank; timer = 0;
}

function updateRecords() {
  if ((pressed(START) || pressed(A) || pressed(B)) && timer > 20) { fx(SFX.select); toTitle(); }
}

function updatePause() {
  if (pressed(UP)) { pauseSel = (pauseSel + 2) % 3; fx(SFX.move); }
  if (pressed(DOWN)) { pauseSel = (pauseSel + 1) % 3; fx(SFX.move); }
  if (pressed(B) || (pressed(START) && pauseSel === 0)) { paused = false; fx(SFX.pause); }
  else if (pressed(A) || pressed(START)) {
    fx(SFX.select);
    if (pauseSel === 0) paused = false;
    else if (pauseSel === 1) startGame(); // restart
    else toTitle(); // quitting abandons the game: nothing is recorded
  }
}

// --- Draw ---

function draw() {
  cls();
  if (state === 'play' || state === 'over') drawPlay();
  else if (state === 'title') drawTitle();
  else if (state === 'initials') drawInitials();
  else if (state === 'records') drawRecords();
  if (state === 'over') { panel(48, 80, 160, 64); ctxt('GAME OVER', 92, RED); ctxt(`SCORE ${score}`, 108, WHITE); if (timer > 60 && timer % 60 < 40) ctxt('START: CONTINUE', 126, DIM); }
  if (paused) drawPause();
}

function drawPlay() {
  grid.forEach((g, i) => {
    if (!g || g.y <= -CELL) return;
    if (phase === 'pop' && popCells.includes(i) && (popT >> 1) & 1) return; // the matched gems flash
    sprite(ART.sprites[`gem${g.t}`], g.x, g.y);
  });
  if (state === 'play' && phase === 'idle') {
    if (sel >= 0) sprite(ART.sprites.cursor, cellX(sel), cellY(sel), { pal: 7 });
    sprite(ART.sprites.cursor, cellX(cursor), cellY(cursor), { pal: 6 });
  }
  txt(`SCORE ${score}`, 8, 8, WHITE);
  txt(`LEVEL ${level}`, 8, 20, GOLD);
  txt(`GOAL ${levelPts}/${goal}`, 136, 8, WHITE);
  txt(`MOVES ${moves}`, 168, 20, moves <= 3 ? RED : GREEN);
  const bar = mid(0, 1, levelPts / goal); // progress to the goal
  rectfill(8, 36, 240, 6, SHADOW); rectfill(8, 36, flr(240 * bar), 6, bar >= 1 ? GOLD : CYAN);
  if (chain > 1 && phase !== 'idle') ctxt(`CHAIN x${chain}`, 202, GOLD);
  if (phase === 'win') { panel(40, 86, 176, 48); ctxt(`LEVEL ${level} CLEAR!`, 96, GOLD); ctxt(`BONUS ${moves * 50}`, 112, WHITE); }
}

function drawTitle() {
  ctxt('{{TITLE_UPPER}}', 50, GOLD);
  ['PLAY', 'RECORDS'].forEach((s, i) => txt(`${i === titleSel ? '> ' : '  '}${s}`, 96, 100 + i * 14, i === titleSel ? WHITE : DIM));
}

function drawRecords() {
  panel(24, 16, 208, 192);
  ctxt('TOP 10', 24, GOLD);
  topTen().forEach((e, i) => {
    const y = 48 + i * 14, on = i === hl;
    if (on && timer % 40 < 30) rectfill(28, y - 2, 200, 12, PANEL);
    txt(String(i + 1).padStart(2), 40, y, i === 0 ? GOLD : DIM);
    txt(e.score ? e.initials : '---', 72, y, on ? GOLD : WHITE);
    txt(e.score ? `L${e.level}` : '', 112, y, DIM);
    txt(e.score ? String(e.score).padStart(8) : '', 140, y, i === 0 ? GOLD : WHITE);
  });
  if (timer % 60 < 40) ctxt('START: BACK', 192, DIM);
}

function drawInitials() {
  const ini = initials;
  panel(24, 40, 208, 144);
  ctxt(rank === 0 ? 'NEW HIGH SCORE!' : `TOP 10: #${rank + 1}`, 52, GOLD);
  ctxt(String(score), 68, WHITE);
  ctxt('ENTER YOUR INITIALS', 90, DIM);
  for (let i = 0; i < 3; i++) {
    const on = i === ini.pos, x = 84 + i * 32;
    rect(x - 2, 106, 28, 20, on ? GOLD : PANEL);
    txt(ini.chars[i], x + 10, 112, on ? GOLD : WHITE);
  }
  if (timer % 60 < 40) ctxt('START: SAVE', 160, WHITE);
}

function drawPause() {
  panel(64, 80, 128, 64);
  ctxt('PAUSED', 88, GOLD);
  ['RESUME', 'RESTART', 'QUIT TO TITLE'].forEach((s, i) => txt(`${i === pauseSel ? '>' : ' '} ${s}`, 76, 104 + i * 10, i === pauseSel ? WHITE : DIM));
}

function panel(x, y, w, h) { rectfill(x, y, w, h, SHADOW); rect(x, y, w, h, PANEL); }
function txt(s, x, y, c) { print(s, x + 1, y + 1, SHADOW); print(s, x, y, c); }
const ctxt = (s, y, c) => txt(s, 128 - s.length * 4, y, c);
