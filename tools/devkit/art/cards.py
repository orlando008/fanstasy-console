def _pips(im, suit, rank, P, size, ink):
    """The pips: laid out as a real deck on a large card; one big pip in the middle of a medium or small card (the
    index says the rank) and of a large ace."""
    w, h = im.w, im.h
    if size != 'large' or rank == 1:
        n = {'large': 15, 'medium': 11 if rank == 1 else 9, 'small': 7}[size]
        rows = pip(suit, n)
        x, y = ((7, 12) if size == 'small' else ((w - n) // 2, (h - n) // 2))
        _rows(im, rows, x, y, ink)
        if n >= 11:                                  # a big pip: a darker line along its lower right
            for j, r in enumerate(rows):
                for i, ch in enumerate(r):
                    if ch == '#' and (i + 1 >= n or r[i + 1] != '#' or j + 1 >= n or rows[j + 1][i] != '#'): im.pset(x + i, y + j, P.ink[0])
        return
    n, cx, dx = (5 if rank >= 9 else 7), w // 2, 5      # the 9 and 10 have smaller pips, so the middle ones clear the sides
    y0, y1 = 6 + (7 - n) // 2, h - 7 - n - (7 - n) // 2
    for col, row in LAYOUT[rank]:
        rows = pip(suit, n)
        if row > 0.5: rows = _rot(rows)
        _rows(im, rows, cx + col * dx - n // 2, int(round(y0 + (y1 - y0) * row)), ink)


def _letter(im, label, P, ink, size):
    """A court card at medium and small size: its letter, in a gold frame on a medium card, over a gold bar on a small."""
    t = Img(8, 8); t.text(label, 0, 0, 1)
    if size == 'medium': fx, fy, fw, fh, lx, ly = 7, 9, 10, 14, 8, 12
    else: fx, fy, fw, fh, lx, ly = None, None, 0, 0, 7, 10
    if fx is not None:
        im.rect(fx, fy, fw, fh, P.gold[0], fill=False)
        im.rect(fx + 1, fy + 1, fw - 2, fh - 2, P.gold[1], fill=False)
    else:
        for x in range(7, 14): im.pset(x, 19, P.gold[1]); im.pset(x, 20, P.gold[0])
    for y in range(8):
        for x in range(8):
            if t.px[y][x]: im.pset(lx + x, ly + y, ink)


def court(rank, P):
    """The top half of a king (13), queen (12) or jack (11) at 32 x 48, 16 x 21: a crown or a cap, a face, the robe in
    the suit's ink with gold trim, and what each holds (a sword, a flower, a halberd)."""
    d = Canvas(16, 21)
    skin, hair, gold, ink, acc = P.skin, P.hair, P.gold, P.ink, P.back
    # the robe: shoulders and chest, a gold band, a collar in the back's colour
    d.fill(poly([(0, 21), (0, 15), (3, 12), (13, 12), (16, 15), (16, 21)]), ink[1], part='robe')
    d.fill(poly([(6.5, 12), (9.5, 12), (9.5, 21), (6.5, 21)]), gold[1], part='band')
    d.fill(poly([(4, 11.5), (12, 11.5), (10, 14), (6, 14)]), acc[2], part='collar')
    # the head
    hy = 7.5 if rank != 11 else 7.8
    if rank == 12: d.fill(oval(8, hy + 1.5, 5, 5.2), hair, part='hairback')
    d.fill(oval(8, hy, 3.2, 3.6), skin[1], part='face')
    d.shadow('face', skin[0], light=(-1, -1), depth=1)
    if rank == 13:
        d.fill(poly([(4.6, 8.5), (11.4, 8.5), (10, 12.5), (8, 13.4), (6, 12.5)]), hair, part='beard')
        d.fill(poly([(4, 4.6), (4, 1), (5.7, 2.8), (8, 0.2), (10.3, 2.8), (12, 1), (12, 4.6)]), gold[1], part='crown')
        d.fill(poly([(4, 3.6), (12, 3.6), (12, 4.8), (4, 4.8)]), gold[0], part='rim')
        d.fill(brush([(14, 20), (14, 4)], 1.6, 1.0), P.paper[1], part='blade')
        d.fill(poly([(12, 13), (16, 13), (16, 14.2), (12, 14.2)]), gold[0], part='hilt')
    elif rank == 12:
        d.fill(poly([(5, 4.4), (5.8, 2), (7, 3.4), (8, 1.4), (9, 3.4), (10.2, 2), (11, 4.4)]), gold[1], part='crown')
        d.fill(brush([(2.5, 20), (2.5, 11), (2.2, 8)], 0.9, 0.7), acc[0], part='stem')
        d.fill(oval(2.3, 7.4, 1.8, 1.8), ink[1], part='flower')
        d.dot(2, 7, gold[1])
    else:
        d.fill(poly([(4.2, 5), (5, 2.2), (8, 1.2), (11.4, 2.4), (12.2, 5)]), acc[1], part='cap')
        d.fill(brush([(10.5, 2.4), (14, 0.4)], 1.2, 0.5), ink[1], part='feather')
        d.fill(oval(4.4, 9, 1.0, 2.2), hair, part='hairl'); d.fill(oval(11.6, 9, 1.0, 2.2), hair, part='hairr')
        d.fill(brush([(1.6, 21), (1.6, 3)], 1.0, 0.8), gold[0], part='pole')
        d.fill(poly([(0, 3), (3.6, 1.6), (3.6, 6), (0, 5.4)]), P.paper[1], part='axe')
    d.dot(7, int(hy), P.edge); d.dot(9, int(hy), P.edge)
    if rank != 13: d.dot(8, int(hy) + 2, skin[0])
    return d.render(outline=P.edge, tidy=1)


def _court_large(im, suit, rank, P, ink):
    w, h = im.w, im.h
    fx, fy, fw, fh = 8, 3, 16, h - 6
    top = court(rank, P)
    im.rect(fx, fy, fw, fh, P.gold[0], fill=False)
    half = fh // 2
    for y in range(min(top.h, half - 1)):
        for x in range(min(top.w - 2, fw - 2)):
            v = top.px[y + max(0, top.h - (half - 1))][x + 1]
            if v: im.pset(fx + 1 + x, fy + 1 + y, v)
    bottom = Img(fw - 2, half - 1)
    for y in range(half - 1):
        for x in range(fw - 2): bottom.px[y][x] = im.px[fy + 1 + y][fx + 1 + x]
    for y in range(half - 1):
        for x in range(fw - 2):
            v = bottom.px[half - 2 - y][fw - 3 - x]
            if v: im.pset(fx + 1 + x, fy + fh - 2 - (half - 2) + y, v)
    for x in range(fx + 1, fx + fw - 1): im.pset(x, fy + half, P.gold[0])


def joker(im, P, size):
    """A joker: a jester's hat of three points with gold bells; at the large size its name down the left."""
    w, h = im.w, im.h
    if size == 'large':
        d = Canvas(20, 22)
        d.fill(poly([(2, 13), (0.5, 2), (7, 9), (10, 0.5), (13, 9), (19.5, 2), (18, 13)]), P.ink[1], part='hat')
        d.fill(poly([(7, 9), (10, 0.5), (13, 9), (11, 12), (9, 12)]), P.back[1], part='mid')
        d.fill(oval(10, 15.5, 4, 4.2), P.skin[1], part='face'); d.shadow('face', P.skin[0], light=(-1, -1), depth=1)
        d.fill(poly([(3, 13), (17, 13), (17, 14.5), (3, 14.5)]), P.gold[0], part='brim')
        for (x, y) in ((1, 2), (10, 1), (19, 2)): d.fill(oval(x, y, 1.6, 1.6), P.gold[1])
        d.dot(8, 15, P.edge); d.dot(12, 15, P.edge); d.ink([(8, 18), (10, 19), (12, 18)], P.edge)
        pic = d.render(outline=P.edge, tidy=1)
        im.blit(pic, 9, 12)
        g = [_G[ch] for ch in 'JOKER']
        for k, rows in enumerate(g):
            _rows(im, rows, 2, 3 + k * 6, P.ink[1])
            _rows(im, _rot(rows), w - 5, h - 8 - k * 6, P.ink[1])
    else:
        n = 11 if size == 'medium' else 9
        star = Img(n, n)
        c = (n - 1) / 2
        import math
        pts = [(c + (c if k % 2 == 0 else c * 0.42) * math.sin(k * math.pi / 5), c - (c if k % 2 == 0 else c * 0.42) * math.cos(k * math.pi / 5)) for k in range(10)]
        star.poly(pts, P.gold[1])
        star.outline(P.edge)
        im.blit(star, *((6, 11) if size == 'small' else ((w - n) // 2, (h - n) // 2)))
        _rows(im, glyph('J'), 2, 2, P.ink[1]); _rows(im, _G['*'], 2, 8, P.ink[1])
        if size == 'medium': _rows(im, _rot(glyph('J')), w - 5, h - 7, P.ink[1]); _rows(im, _G['*'], w - 5, h - 13, P.ink[1])


def face(suit, rank, P, size, ink=None):
    """The face of a standard card (suit 0 to 3, rank 1 to 13; suit 4 a joker) at a size."""
    w, h = SIZES[size]
    im = body(w, h, P)
    ink = P.ink[1] if ink is None else ink
    if suit == 4: joker(im, P, size); return im
    label = RANKS[rank - 1] if 1 <= rank <= 13 else str(rank)
    _index(im, label, suit, P, size, ink)
    if rank >= 11 and rank <= 13:
        if size == 'large': _court_large(im, suit, rank, P, ink)
        else: _letter(im, label, P, ink, size)
    elif 1 <= rank <= 10 and suit < 4: _pips(im, suit, rank, P, size, ink)
    return im


# --- the kit's entry point ---
def _code(use):
    src = open(os.path.join(HERE, 'cards.js'), encoding='utf8').read()
    parts, order, need = {}, [], {}
    for m in re.finditer(r'^//@ (\w+):([^\n]*)\n(.*?)(?=^//@ |\Z)', src, re.S | re.M):
        parts[m.group(1)] = m.group(3).rstrip() + '\n'; order.append(m.group(1)); need[m.group(1)] = m.group(2).split()
    want = set(SECTIONS) if use == 'all' or 'all' in use else set(use) | {'core', 'draw'}
    bad = want - set(parts)
    if bad: raise ValueError('art.cards(use=...): no section %s (there are %s)' % (', '.join(sorted(bad)), ', '.join(order)))
    while True:
        more = {n for w in want for n in need[w]} - want
        if not more: break
        want |= more
    return ''.join(parts[n] for n in order if n in want)


def cards(art, sizes=('large',), slots=None, pals=(4, 5), colours='classic', back='2c4c9c', jokers=True, deck=None,
          inks=None, use=(), region='spr', paper='f4f0e4'):
    """Playing cards for this cart: their palettes, faces in the ROM, slots on the tile sheet and the CARDS block of
    code.js (see this module's header). Returns {'pals': {ink: Roles}, 'faces': {size: [Img, ...]}, 'entries': n}."""
    sizes = [sizes] if isinstance(sizes, str) else list(sizes)
    for z in sizes:
        if z not in SIZES: raise ValueError('art.cards: size %r (sizes are %s)' % (z, ', '.join(SIZES)))
    slots = dict(slots or {})
    inks = list(inks or INKS.get(colours) or [])
    if not inks: raise ValueError("art.cards: colours is 'classic' or 'four' (or give inks= for a custom deck)")
    if deck is None:
        uniq = list(dict.fromkeys(inks))
        need = len(uniq)
    else:
        uniq = list(dict.fromkeys(inks)); need = len(uniq)
    pals = list(pals)
    if len(pals) < need: raise ValueError('art.cards: %d ink colours need %d sprite palettes, pals=%s' % (need, need, pals))
    roles = {}
    for k, hexink in enumerate(uniq):
        roles[hexink] = art.sprite_palette(pals[k], {
            'edge': '201c2c', 'paper': ramp(paper, 3, at=2), 'ink': ramp(hexink, 2, at=1), 'gold': ramp('dcb040', 2, at=1),
            'back': ramp(back, 3, at=1), 'skin': ramp('eab890', 2, at=1), 'hair': '6a4028'})
    # the faces, in id order, then the back and the flip's six frames
    if deck is None:
        ids = [(s, r) for s in range(4) for r in range(1, 14)] + ([(4, 0), (4, 0)] if jokers else [])
        ink_of = lambda i, s: inks[s] if s < 4 else inks[1 if i == 53 else 0]
    else:
        ids = [(c.get('suit', 0), c.get('rank', 0)) for c in deck]
        ink_of = lambda i, s: inks[deck[i].get('ink', s % len(inks))]
    faces, blobs, subs = {}, {}, {}
    roles_by_sub = {P.sub: P for P in roles.values()}
    first = roles[uniq[0]]
    for z in sizes:
        w, h = SIZES[z]
        out, pal_of = [], []
        for i, (s, r) in enumerate(ids):
            P = roles[ink_of(i, s)]
            if deck is None: im = face(s, r, P, z)
            else:
                c = deck[i]
                im = body(w, h, P)
                if not c.get('plain'):
                    if 1 <= r <= 13 and s < 4: im = face(s, r, P, z)
                    else:                    # a rank the standard deck has not (0, 14 ...): its number and one big pip
                        _index(im, str(r), min(s, 3), P, z, P.ink[1])
                        _pips(im, min(s, 3), 1, P, z, P.ink[1])
                if c.get('face'): c['face'](im, P, z, c)
            out.append(im); pal_of.append(P.sub)
        bk = card_back(w, h, first)
        blank = body(w, h, first)
        frames = [bk] + [squash(bk, k, first, False) for k in (0.75, 0.5, 0.25)] + [squash(blank, k, first, True) for k in (0.25, 0.5, 0.75)]
        out += frames; pal_of += [first.sub] * len(frames)
        b = bytearray()
        for im, p in zip(out, pal_of):
            b.append(p)
            for y in range(h):
                for x in range(0, w, 2): b.append(im.px[y][x] | (im.px[y][x + 1] << 4))
        blobs[z] = b; faces[z] = out; subs[z] = [roles_by_sub[p] for p in pal_of]
        art.rom['cards_' + z] = bytes(b)
    if sum(len(b) for b in art.rom.values()) > 131072: raise MemoryError('the cards and the rest of the ROM come to %d bytes of 131,072: use fewer sizes' % sum(len(b) for b in art.rom.values()))
    # the slots
    data = {}
    for z in sizes:
        tw, th, parts = SLOT[z]
        n = slots.get(z, 8)
        tiles = []
        for _ in range(n):
            t = art._find(tw, th, region, True)
            for j in range(th):
                for i in range(tw): art.used.add(t + j * 16 + i)
            tiles.append(t)
        w, h = SIZES[z]
        data[z] = {'w': w, 'h': h, 'bytes': 1 + w * h // 2, 'rom': 'cards_' + z, 'slots': tiles, 'parts': parts,
                   'shows': [-1] * n, 'used': [-1] * n}
    js = lambda v: json.dumps(v, separators=(',', ':'))
    info = 'null' if deck is None else js([[a, b] for a, b in ids])
    names = 'null' if deck is None else js([c.get('name', str(i)) for i, c in enumerate(deck)])
    copies = 'null' if deck is None else js([c.get('copies', 1) for c in deck])
    head = ('const CARDS = { size: %s, back: %d, info: %s, names: %s, copies: %s, missed: 0, loads: 0,\n  sizes: { %s } };\n'
            % (js(sizes[0]), len(ids), info, names, copies, ',\n    '.join('%s: %s' % (z, js(data[z])) for z in sizes)))
    art.blocks = getattr(art, 'blocks', {})
    art.blocks['CARDS'] = head + _code(use)
    art.notes.append('cards: %s, %s slots (%d tiles), %d entries a size, %s bytes of ROM' % (
        ', '.join(sizes), ', '.join('%d %s' % (len(data[z]['slots']), z) for z in sizes),
        sum(len(data[z]['slots']) * SLOT[z][0] * SLOT[z][1] for z in sizes), len(ids) + 7, '+'.join(str(len(blobs[z])) for z in sizes)))
    art.card_faces = faces
    return {'pals': roles, 'faces': faces, 'subs': subs, 'entries': len(ids) + 7}


def card_sheet(made, path, size=None, scale=3):
    """A PNG of every face of a size (and the back and the flip's frames), to look at with the Read tool:
    card_sheet(cards, 'out/cards.png'), cards being what art.cards returned."""
    from preview import Sheet
    size = size or next(iter(made['faces']))
    sheet = Sheet(scale=scale)
    by_sub = {P.sub: P for P in made['pals'].values()}
    faces = made['faces'][size]
    names = ([('%s%s' % (r, 'SHDC'[s])) for s in range(4) for r in RANKS] + ['JOKER', 'JOKER']) if len(faces) == 61 else [str(i) for i in range(len(faces) - 7)]
    names += ['BACK', 'F1', 'F2', 'F3', 'F4', 'F5', 'F6']
    for k, (im, nm) in enumerate(zip(faces, names)):
        if k and k % 13 == 0 and k <= 52: sheet.row()
        if k == len(faces) - 7: sheet.row()
        sheet.add(nm, im, made['subs'][size][k] if 'subs' in made else by_sub[min(by_sub)])
    sheet.save(path)
    return path


def inject_block(code_path, name, block, after=ART_END):
    """Replace the text between `// <NAME> (generated by art.py: do not edit)` and `// END <NAME>` in code.js; the lines
    are added after the `after` line (the END ART line) if the file has none yet."""
    begin, end = '// %s (generated by art.py: do not edit)' % name, '// END %s' % name
    text = open(code_path, encoding='utf8').read()
    if text.count(begin) == 0 and text.count(end) == 0:
        if text.count(after) != 1: raise ValueError('%s: add a "%s" line and a "%s" line where the %s block should go' % (code_path, begin, end, name))
        i = text.index(after) + len(after)
        text = text[:i] + '\n\n' + begin + '\n' + end + text[i:]
    if text.count(begin) != 1 or text.count(end) != 1: raise ValueError('%s needs exactly one "%s" line and one "%s" line' % (code_path, begin, end))
    a = text.index(begin) + len(begin); b = text.index(end)
    new = text[:a] + '\n' + block + text[b:]
    if new != open(code_path, encoding='utf8').read(): open(code_path, 'w', encoding='utf8', newline='\n').write(new)


