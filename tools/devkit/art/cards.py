"""The card kit: playing cards for a cart, drawn in code, and the code that deals and draws them.

    cards = art.cards(sizes=('large', 'small'), slots={'large': 10, 'small': 24}, pals=(4, 5),
                      use=('sort', 'poker', 'anim'))        # in art.py, before art.write(...)

What it makes:
  * Every face, the back and seven frames of a card turning over, at each size asked for, in the cart's ROM
    (rom/cards_<size>.bin): 'large' 32 x 48 (index in the corners, the pips laid out as a real deck, drawn kings, queens
    and jacks, a joker in a jester's hat), 'medium' 24 x 32 and 'small' 16 x 24 (an index and a big pip; a letter for a
    court card). Faces are not tiles: 54 large faces would take 1,296 of the sheet's 1,024. A card on screen is copied
    from the ROM into a sprite slot (sset) when it is first drawn, and stays while it is drawn: give each size as many
    slots as faces it shows at once (`slots=`). A large slot is 24 tiles, a medium 16, a small 8. Cards face down share
    one slot.
  * The sprite palettes: classic red and black needs two (`pals=(black, red)`), colours='four' four (spades, hearts,
    diamonds, clubs: black, red, blue, green), which read better on small cards. A custom deck takes one a colour of ink.
    Each palette is the card's paper, edge, ink, gold, skin, hair and the back's colour (`back=`), 14 colours.
  * The CARDS block of code.js: `const CARDS = {...}` and the functions of tools/devkit/art/cards.js that `use` asks for
    (always 'core' and 'draw'; 'sort', 'poker', 'blackjack', 'runs', 'anim', or 'all'). The block sits between
    `// CARDS (generated by art.py: do not edit)` and `// END CARDS`; the lines are added after `// END ART` the first time.

A custom deck (Uno-like, a trading-card game): deck=[{'name': 'RED 7', 'suit': 0, 'rank': 7, 'copies': 2, 'ink': 0,
'face': fn}, ...] with inks=['d03030', ...] (one palette each, pals= as many). Each card has a suit and a rank for the
code (cardSuit, cardRank: runs, sets and sorting work on them), a name (cardName) and copies (newDeck). Its face is the
card's paper and edge with, unless face= draws it all, its rank and suit's pip as on the standard deck (ranks 1 to 13
show A to K, others their number; suits 0 to 3 the standard pips); face(img, P, size, card) draws on top (P: the
card's palette roles; size: 'large', 'medium' or 'small').

ROM: large 769 bytes a face, medium 385, small 193 (61 entries for the standard deck: 47 KB, 23 KB, 12 KB of the
128 KB). They compress well in a .nova.png (mostly paper). `card_sheet(cards, path)` saves a PNG of every face to look at.
"""
