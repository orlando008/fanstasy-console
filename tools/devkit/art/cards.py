def _rows(img, rows, x, y, c):
    for j, r in enumerate(rows):
        for i, ch in enumerate(r):
            if ch == '#': img.pset(x + i, y + j, c)


def _rot(rows): return [r[::-1] for r in rows[::-1]]


def glyph(text):
    """The rows of a rank or word in the 3 x 5 glyphs (letters a pixel apart)."""
    parts = [_G[text]] if text in _G else [_G[ch] for ch in text]
    return [''.join(p[j] + ('.' if k < len(parts) - 1 else '') for k, p in enumerate(parts)) for j in range(5)]


def _big_pip(suit, n):
    """A pip n px square (n odd, 9 and up), from the suit's shape sampled 4 x 4 a pixel."""
    def inside(u, v):                       # u, v in 0..1
        lobe = lambda cx, cy, r: (u - cx) ** 2 + (v - cy) ** 2 <= r * r
        if suit == 1:   return lobe(0.29, 0.32, 0.25) or lobe(0.71, 0.32, 0.25) or (v >= 0.3 and abs(u - 0.5) <= (1.0 - v) * 0.92 and v <= 0.98)
        if suit == 2:   return abs(u - 0.5) / 0.42 + abs(v - 0.5) / 0.5 <= 1
        if suit == 0:   return lobe(0.29, 0.6, 0.23) or lobe(0.71, 0.6, 0.23) or (v <= 0.62 and abs(u - 0.5) <= v * 0.8 and v >= 0.02) or (v >= 0.6 and abs(u - 0.5) <= 0.05 + (v - 0.6) * 0.5)
        return lobe(0.5, 0.25, 0.21) or lobe(0.25, 0.56, 0.21) or lobe(0.75, 0.56, 0.21) or (v >= 0.45 and abs(u - 0.5) <= 0.05 + max(0, v - 0.72) * 0.9 and v <= 0.98)
    rows = []
    for y in range(n):
        r = ''
        for x in range(n):
            k = sum(inside((x + (i + 0.5) / 4) / n, (y + (j + 0.5) / 4) / n) for i in range(4) for j in range(4))
            r += '#' if k >= 8 else '.'
        rows.append(r)
    return rows


def pip(suit, n):
    """A suit's pip, n px: 5 and 7 drawn by hand, bigger ones from the shape."""
    return _PIP[n][suit] if n in _PIP else _big_pip(suit, n)


# --- the parts of a card ---
def body(w, h, P):
    """A blank card: paper with an edge, the corners rounded, a shade along the bottom and right."""
    im = Img(w, h)
    im.rect(0, 0, w, h, P.edge)
    im.rect(1, 1, w - 2, h - 2, P.paper[2])
    for x in range(2, w - 1): im.pset(x, h - 2, P.paper[1])
    for y in range(2, h - 1): im.pset(w - 2, y, P.paper[1])
    for (x, y) in ((0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)): im.pset(x, y, 0)
    for (x, y) in ((1, 1), (w - 2, 1), (1, h - 2), (w - 2, h - 2)): im.pset(x, y, P.edge)
    return im


def card_back(w, h, P):
    """The back: a border of paper round a lattice in the back's colour, with a diamond in the middle."""
    im = body(w, h, P)
    b = 2 if w >= 24 else 1
    x0, y0, x1, y1 = 1 + b, 1 + b, w - 2 - b, h - 2 - b
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            u, v = x - x0, y - y0
            c = P.back[1]
            if (u + v) % 4 == 0 or (u - v) % 4 == 0: c = P.back[0]
            if x in (x0, x1) or y in (y0, y1): c = P.back[0]
            im.pset(x, y, c)
    cx, cy, r = (x0 + x1) / 2, (y0 + y1) / 2, max(2, min(x1 - x0, y1 - y0) // 4)
    for y in range(y0 + 1, y1):
        for x in range(x0 + 1, x1):
            d = abs(x - cx) + abs(y - cy) * 0.8
            if d <= r: im.pset(x, y, P.back[2] if d <= r - 1.2 else P.back[0])
    return im


def squash(img, k, P, blank):
    """img narrowed to k of its width (a frame of a card turning over), centred; blank: the narrowed face is plain paper."""
    w, h = img.w, img.h
    nw = max(2, int(round(w * k)))
    out = Img(w, h)
    x0 = (w - nw) // 2
    for y in range(h):
        for i in range(nw):
            out.px[y][x0 + i] = img.px[y][min(w - 1, int((i + 0.5) * w / nw))]
    return out


def _index(im, label, suit, P, size, ink):
    """The corner index: the rank over a small pip, top left, and turned round at the bottom right (large and medium)."""
    w, h = im.w, im.h
    g = glyph(label)
    gw = len(g[0])
    x, y = (1 if gw > 3 else 2), 2
    _rows(im, g, x, y, ink)
    p = _PIP[5][suit] if suit < 4 else _G['*']
    px = max(1, x + (gw - len(p[0])) // 2)
    _rows(im, p, px, y + 6, ink)
    if size in ('large', 'medium'):
        _rows(im, _rot(g), w - x - gw, h - y - 5, ink)
        _rows(im, _rot(p), w - px - len(p[0]), h - (y + 6) - len(p), ink)


