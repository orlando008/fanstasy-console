"""Art toolkit for NOVA-16 carts: draw tiles, sprites and scenes in code, and write the files tools/pack.js reads
(tiles.txt, palette.txt, map.txt) plus a manifest (art.json) and the tile numbers for code.js. The art counterpart of
the song toolkit in tools/devkit/music/kit.py: a game keeps an art.py next to its code.js, and the output is
reproducible, so tools/verify.js can check that the committed files are what the script makes.

    import os, sys; sys.path.insert(0, '<repo>/tools/devkit/art')     # art.py in carts/src/<name>/ does this for you
    from kit import *
    art = Art()
    art.region('bg', 1, 255); art.region('spr', 256, 1023)
    ground = art.palette(1, {'dark': '442434', 'mid': '854c30', 'light': 'd27d2c'})       # BG palette 1: entries 17..
    hero = art.sprite_palette(0, {'skin': 'd2aa99', 'shirt': '597dce'})                   # sprite palette 0: entries 129..
    art.sprite('hero', Img.from_rows(['..11....', ...]), pal=0)                          # 8, 16 or 32 px, square
    art.scene('field', Img.make(256, 224, lambda x, y: ground.mid), pal=ground, at=(0, 0), solid=True)
    art.write(sys.argv[1])        # tiles.txt, palette.txt, map.txt, art.json in that folder; and the ART block in its code.js

What you get, and what it checks for you (each of these was a bug in a real game):
  * Pixel values are palette *indices* 0 to 15; 0 is transparent (tiles and sprites), never "black". Colours go by role
    name (`ground.mid`), so art code does not contain bare numbers.
  * A tile or sprite using a colour its palette does not define is an error (it would show a default colour).
  * Tile 0 stays empty (the console reserves it). Named tiles share storage when identical; scene tiles also when
    one is another flipped (the map carries the flip bits), which is what makes a big picture fit.
  * Sprites sit where the console expects them: a 16 px sprite at tile n uses n, n+1, n+16, n+17, a 32 px one the 4 x 4
    block from n, so a sprite is placed only at an aligned spot with all its tiles free.
  * `solid=True` on a scene refuses a transparent cell: a hole in ground or sky (a tile left empty showing the
    backdrop) is caught when you build, not by looking at the game.
  * The budget: tiles used against 1,024, and per named region; a full region is an error that names it.
  * BG palette 0 shares CGRAM entries 1 to 15 with the overlay's default colours (print, rectfill ...): defining it is
    allowed and reported, since the overlay's text colours change with it. Prefer BG palettes 1 to 7, or give the overlay
    its own colours with art.color(index, hex).

Files: art.py owns tiles.txt, palette.txt, map.txt and art.json of its cart (do not edit them by hand); the ART block in
code.js (between `// ART (generated by art.py: do not edit)` and `// END ART`) is rewritten each time.
"""
import json, math, os, re, sys

SHEET_W, SHEET_H, TILES_X, TILE_COUNT = 128, 512, 16, 1024
MAP_W, MAP_H = 256, 128
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
ART_BEGIN, ART_END = '// ART (generated by art.py: do not edit)', '// END ART'


def hsh(n):
    """A small integer hash: deterministic 'noise' for textures (hsh(x * 31 + y * 17) % 5 == 0 ...)."""
    n &= 0xffffffff
    n = (n ^ (n >> 15)) * 0x2c1b3c6d & 0xffffffff
    n = (n ^ (n >> 12)) * 0x297a2d39 & 0xffffffff
    return n ^ (n >> 15)

BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
def dither(x, y, level):
    """Ordered dither: True for a share level/16 of the pixels (level 0 to 16), in a fixed pattern. For gradients."""
    return BAYER[y & 3][x & 3] < level


def _glyphs():
    text = open(os.path.join(ROOT, 'src', 'console', 'font.js'), encoding='utf8').read()
    g = re.findall(r"^\s*'([0-9a-f]{16})',", text, re.M)
    assert len(g) == 95, len(g)
    return g
_GLYPHS = None


class Img:
    """A picture of palette indices 0 to 15 (0 is transparent). Drawing methods change it and return it, so they chain;
    flip_h, flip_v, rot90 and crop return a new picture."""
    def __init__(s, w, h, fill=0):
        s.w, s.h = w, h
        s.px = [[fill] * w for _ in range(h)]

    @classmethod
    def make(cls, w, h, f):
        """A picture from a function of (x, y) returning an index (0 to 15)."""
        im = cls(w, h)
        for y in range(h):
            for x in range(w):
                im.px[y][x] = f(x, y)
        im._check()
        return im

    @classmethod
    def from_rows(cls, rows, key=None, mirror=None, odd=False):
        """A picture from rows of text: '.' or ' ' is 0, a hex digit its index. `key` maps other characters to indices
        (e.g. key={'#': 3}). mirror='x' takes the rows as the left half and makes the whole, symmetric picture (odd=True
        shares the last column as the centre); mirror='y' the top half."""
        if mirror:
            from shade import mirrored
            return mirrored(cls.from_rows(rows, key), odd=odd, axis=mirror)
        key = key or {}
        w = max(len(r) for r in rows)
        im = cls(w, len(rows))
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch in '. ': continue
                im.px[y][x] = key[ch] if ch in key else int(ch, 16)
        im._check()
        return im

    def _check(s):
        for row in s.px:
            for v in row:
                if not (isinstance(v, int) and 0 <= v <= 15): raise ValueError('pixel value %r: palette indices are 0 to 15' % (v,))

    def copy(s):
        im = Img(s.w, s.h); im.px = [r[:] for r in s.px]; return im
    def get(s, x, y): return s.px[y][x] if 0 <= x < s.w and 0 <= y < s.h else 0
    def key(s): return tuple(tuple(r) for r in s.px)
    def is_empty(s): return not any(any(r) for r in s.px)
    def colors(s): return {v for r in s.px for v in r if v}
    def rows(s): return [''.join('.' if v == 0 else '%x' % v for v in r) for r in s.px]
    def __eq__(s, o): return isinstance(o, Img) and s.key() == o.key()
    __hash__ = None

    # --- drawing (clipped to the picture) ---
    def pset(s, x, y, c):
        if not (isinstance(c, int) and 0 <= c <= 15): raise ValueError('colour %r: palette indices are 0 to 15' % (c,))
        x, y = int(x), int(y)
        if 0 <= x < s.w and 0 <= y < s.h: s.px[y][x] = c
        return s
    def line(s, x0, y0, x1, y1, c):
        x0, y0, x1, y1 = int(x0), int(y0), int(x1), int(y1)
        dx, dy, sx, sy = abs(x1 - x0), -abs(y1 - y0), 1 if x0 < x1 else -1, 1 if y0 < y1 else -1
        err = dx + dy
        while True:
            s.pset(x0, y0, c)
            if x0 == x1 and y0 == y1: break
            e2 = 2 * err
            if e2 >= dy: err += dy; x0 += sx
            if e2 <= dx: err += dx; y0 += sy
        return s
    def rect(s, x, y, w, h, c, fill=True):
        for j in range(h):
            for i in range(w):
                if fill or i in (0, w - 1) or j in (0, h - 1): s.pset(x + i, y + j, c)
        return s
    def disc(s, cx, cy, r, c):
        """A filled circle; the centre may be fractional (3.5, 3.5 is the middle of an 8 x 8 tile)."""
        for y in range(s.h):
            for x in range(s.w):
                if math.hypot(x - cx, y - cy) <= r: s.pset(x, y, c)
        return s
    def ring(s, cx, cy, r0, r1, c):
        for y in range(s.h):
            for x in range(s.w):
                if r0 <= math.hypot(x - cx, y - cy) <= r1: s.pset(x, y, c)
        return s
    def poly(s, points, c):
        """A filled polygon (even-odd rule, tested at pixel centres)."""
        for y in range(s.h):
            for x in range(s.w):
                px_, py_, inside = x + 0.5, y + 0.5, False
                for k in range(len(points)):
                    (xa, ya), (xb, yb) = points[k], points[(k + 1) % len(points)]
                    if (ya > py_) != (yb > py_) and px_ < (xb - xa) * (py_ - ya) / (yb - ya) + xa: inside = not inside
                if inside: s.pset(x, y, c)
        return s
    def fill(s, x, y, c):
        """Flood fill (4-way) from (x, y) with colour c."""
        if not (0 <= x < s.w and 0 <= y < s.h): return s
        old = s.px[y][x]
        if old == c: return s
        todo = [(x, y)]
        while todo:
            i, j = todo.pop()
            if 0 <= i < s.w and 0 <= j < s.h and s.px[j][i] == old:
                s.px[j][i] = c; todo += [(i + 1, j), (i - 1, j), (i, j + 1), (i, j - 1)]
        return s
    def outline(s, c):
        """Surround every opaque shape with colour c (on transparent pixels next to it, up, down, left and right)."""
        add = [(x, y) for y in range(s.h) for x in range(s.w) if s.px[y][x] == 0 and any(s.get(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))]
        for x, y in add: s.px[y][x] = c
        return s
    def replace(s, a, b):
        s.px = [[b if v == a else v for v in r] for r in s.px]; return s
    def blit(s, src, x, y):
        """Draw another picture here at (x, y); its transparent pixels leave this one as it is."""
        for j in range(src.h):
            for i in range(src.w):
                if src.px[j][i]: s.pset(x + i, y + j, src.px[j][i])
        return s
    def text(s, string, x, y, c):
        """Text in the console's own 8 x 8 font (ASCII 32 to 126). Returns the width in pixels."""
        global _GLYPHS
        if _GLYPHS is None: _GLYPHS = _glyphs()
        for k, ch in enumerate(string):
            code = ord(ch) - 32
            if not 0 <= code < 95: continue
            for j in range(8):
                row = int(_GLYPHS[code][j * 2:j * 2 + 2], 16)
                for i in range(8):
                    if (row >> i) & 1: s.pset(x + k * 8 + i, y + j, c)
        return 8 * len(string)

    # --- new pictures ---
    def flip_h(s):
        im = Img(s.w, s.h); im.px = [r[::-1] for r in s.px]; return im
    def flip_v(s):
        im = Img(s.w, s.h); im.px = [r[:] for r in s.px[::-1]]; return im
    def rot90(s):
        """Turned a quarter clockwise."""
        im = Img(s.h, s.w)
        for y in range(s.h):
            for x in range(s.w): im.px[x][s.h - 1 - y] = s.px[y][x]
        return im
    def crop(s, x, y, w, h):
        im = Img(w, h)
        for j in range(h):
            for i in range(w): im.px[j][i] = s.get(x + i, y + j)
        return im
    def __repr__(s): return 'Img %dx%d\n%s' % (s.w, s.h, '\n'.join(s.rows()))


class RampIdx(tuple):
    """A ramp's palette indices, dark to light, knowing its palette (`kind`, `pal`): what pal.skin returns."""
    def __new__(cls, items, kind=None, pal=None):
        t = super().__new__(cls, items); t.kind, t.pal = kind, pal; return t


class Roles:
    """The colours of one sub-palette by role name: `roles.mid` is its index (1 to 15). A ramp given to the palette
    (a list of colours, dark to light, as ramp() makes) is roles name0, name1 ... and `roles.name` is the tuple of their
    indices, dark to light."""
    def __init__(s, kind, sub, base, index, hexes, ramps=None):
        s.kind, s.sub, s.base, s._index, s.hexes = kind, sub, base, dict(index), dict(hexes)
        s.ramps = {n: RampIdx(v, kind, sub) for n, v in (ramps or {}).items()}
    def __getattr__(s, name):
        if name.startswith('_') or name in ('ramps', 'hexes', 'kind', 'sub', 'base'): raise AttributeError(name)
        if name in s.ramps: return s.ramps[name]
        try: return s._index[name]
        except KeyError: raise AttributeError('palette %s %d has no colour %r (it has %s)' % (s.kind, s.sub, name, ', '.join(list(s.ramps) + [n for n in s._index if not s._in_ramp(n)]))) from None
    __getitem__ = __getattr__
    def _in_ramp(s, role): return any(role in ('%s%d' % (r, k) for k in range(len(v))) for r, v in s.ramps.items())
    def names(s): return dict(s._index)
    def cgram(s, name): return s.base + s._index[name]
    def hex_of(s, index):
        """The colour ('rrggbb') of an index of this palette."""
        for name, i in s._index.items():
            if i == index: return s.hexes[name]
        raise KeyError('palette %s %d has no index %d' % (s.kind, s.sub, index))
    def ramp_of(s, index):
        """The ramp an index belongs to, as (its indices, its position in them), or None."""
        for r in s.ramps.values():
            if index in r: return r, r.index(index)
        return None
    def step(s, index, k):
        """The index k steps lighter (k > 0) or darker along its ramp, stopping at the ends; an index in no ramp is
        returned as it is (0, transparent, stays 0)."""
        found = s.ramp_of(index)
        if not found: return index
        r, at = found
        return r[max(0, min(len(r) - 1, at + k))]


def _hex(v):
    if isinstance(v, (tuple, list)): v = '%02x%02x%02x' % tuple(v)
    v = str(v).lstrip('#').lower()
    if not re.fullmatch(r'[0-9a-f]{6}', v): raise ValueError('colour %r: use rrggbb' % v)
    return v


class Art:
    def __init__(s):
        s.sheet = [bytearray(SHEET_W) for _ in range(SHEET_H)]
        s.used = {0}                 # tile numbers in use; tile 0 is the console's empty tile
        s.regions = {}               # name -> (first, last) tile numbers
        s.tiles = {}                 # named tiles: name -> number
        s.sprites = {}               # name -> {tile, size, pal}
        s.scenes = {}                # name -> {mx, my, w, h, pal}
        s.big = {}                   # big sprites: name -> {w, h, parts: [[dx, dy, tile, size, pal, flip], ...]}
        s.gradients = {}             # per-line colours: name -> {entry, y0, lines: [RGB555, ...]}
        s.exact = {}                 # tile picture -> number (for sharing identical tiles)
        s.palettes = {}              # (kind, sub) -> Roles
        s.cgram = {}                 # CGRAM entry -> rrggbb
        s.colors = {}                # named CGRAM entries (for the overlay): name -> index
        s.map = [[0] * MAP_W for _ in range(MAP_H)]
        s.shared = 0                 # tiles saved by sharing
        s.notes = []

    # --- regions and the allocator ---
    def region(s, name, first, last):
        """Reserve tile numbers first..last for tiles and sprites made with region=name (so, for instance, BG tiles stay
        below 256 and sprites above). A region that fills up is an error that names it."""
        if not (1 <= first <= last < TILE_COUNT): raise ValueError('region %s: tiles %d to %d' % (name, first, last))
        s.regions[name] = (first, last)

    def _span(s, region):
        if region is None: return (1, TILE_COUNT - 1)
        if region not in s.regions: raise KeyError('no region %r (art.region(name, first, last))' % region)
        return s.regions[region]

    def _find(s, w, h, region, align):
        first, last = s._span(region)
        for n in range(first, last + 1):
            col, row = n % TILES_X, n // TILES_X
            if col + w > TILES_X: continue
            if align and (col % w or row % h): continue
            cells = [n + j * TILES_X + i for j in range(h) for i in range(w)]
            if cells[-1] > last or any(c in s.used or c < first for c in cells): continue
            return n
        raise MemoryError('out of tiles in region %s (%d to %d): %d used of the region%s' % (
            region or 'all', first, last, sum(1 for t in s.used if first <= t <= last), ' (a %dx%d tile block needs an aligned free spot)' % (w, h) if w > 1 else ''))

    def _put(s, n, img):
        bx, by = (n % TILES_X) * 8, (n // TILES_X) * 8
        for y in range(8):
            for x in range(8): s.sheet[by + y][bx + x] = img.px[y][x]
        s.used.add(n)

    def _tile_at(s, n):
        bx, by = (n % TILES_X) * 8, (n // TILES_X) * 8
        im = Img(8, 8)
        for y in range(8):
            for x in range(8): im.px[y][x] = s.sheet[by + y][bx + x]
        return im

    # --- colours ---
    def backdrop(s, hexcolor):
        """CGRAM entry 0: what shows where no layer draws."""
        s.cgram[0] = _hex(hexcolor)

    def color(s, index, hexcolor, name=None):
        """One CGRAM entry by number (1 to 255), for overlay colours; `name` puts it in the manifest's `colors`."""
        if not 0 <= index <= 255: raise ValueError('CGRAM entries are 0 to 255')
        s.cgram[index] = _hex(hexcolor)
        if name: s.colors[name] = index
        return index

    def _palette(s, kind, sub, colors, at=None):
        base = 16 * sub if kind == 'bg' else 128 + 16 * sub
        if kind == 'bg' and not 0 <= sub <= 7 or kind == 'spr' and not 0 <= sub <= 7: raise ValueError('%s palette %d: 0 to 7' % (kind, sub))
        if (kind, sub) in s.palettes: raise ValueError('%s palette %d is already defined' % (kind, sub))
        at = dict(at or {})
        # A ramp (a list of colours, dark to light) becomes the roles name0, name1 ...; at={'name': i} pins its first.
        flat, ramps = {}, {}
        for name, v in colors.items():
            if isinstance(v, (list, tuple)) and v and not isinstance(v[0], int):
                for k, c in enumerate(v): flat['%s%d' % (name, k)] = c
                if name in at: at.update({'%s%d' % (name, k): at.pop(name) + k for k in range(len(v))})
                ramps[name] = len(v)
            else: flat[name] = v
        if len(flat) > 15: raise ValueError('%s palette %d: %d colours, and a sub-palette holds 15 (0 is transparent)' % (kind, sub, len(flat)))
        colors = flat
        index, hexes, nxt = {}, {}, 1
        for name, v in colors.items():
            i = at.get(name)
            if i is None:
                while nxt in index.values(): nxt += 1
                i = nxt; nxt += 1
            if not 1 <= i <= 15: raise ValueError('palette %s %d: %r needs index 1 to 15 (0 is transparent), got %d' % (kind, sub, name, i))
            if i in index.values(): raise ValueError('palette %s %d: index %d used twice' % (kind, sub, i))
            index[name] = i; hexes[name] = _hex(v)
            s.cgram[base + i] = hexes[name]
        if kind == 'bg' and sub == 0: s.notes.append('BG palette 0 is defined: it shares CGRAM entries 1 to 15 with the overlay\'s default text colours, which change with it')
        r = Roles(kind, sub, base, index, hexes, {n: tuple(index['%s%d' % (n, k)] for k in range(c)) for n, c in ramps.items()})
        s.palettes[(kind, sub)] = r
        return r

    def palette(s, sub, colors, at=None):
        """BG sub-palette `sub` (0 to 7), entries 16*sub+1.. from a dict of role -> 'rrggbb' in order (or pinned with
        at={'role': index}); a role may be a ramp (a list of colours, dark to light, e.g. ramp('4a8a2e', 5)). Entry 0 of
        every sub-palette is transparent. Returns the roles."""
        return s._palette('bg', sub, colors, at)

    def sprite_palette(s, sub, colors, at=None):
        """Sprite sub-palette `sub` (0 to 7, the `pal` of spr()), CGRAM entries 128+16*sub+1.."""
        return s._palette('spr', sub, colors, at)

    def _roles(s, kind, pal):
        if pal is None: return None
        if isinstance(pal, Roles):
            if pal.kind != kind: raise ValueError('a %s palette was given where a %s palette is needed (scenes and tiles use art.palette, sprites art.sprite_palette)' % (pal.kind, kind))
            return pal
        return s.palettes.get((kind, pal))

    def _check_colors(s, img, roles, what):
        if roles is None: return
        bad = sorted(img.colors() - set(roles.names().values()))
        if bad: raise ValueError('%s uses colour(s) %s that %s palette %d does not define (it defines %s)' % (what, bad, roles.kind, roles.sub, sorted(roles.names().values())))

    # --- tiles ---
    def tile(s, name, img, pal=None, region=None, at=None):
        """A named 8 x 8 tile, shared with an identical one made before. `pal` (a palette from art.palette, or its number)
        checks the colours. at=n pins the tile number. Returns the tile number."""
        if name in s.tiles: raise ValueError('tile %r already exists' % name)
        if (img.w, img.h) != (8, 8): raise ValueError('tile %r is %dx%d: tiles are 8x8 (use scene() or sprite() for more)' % (name, img.w, img.h))
        s._check_colors(img, s._roles('bg', pal), 'tile %r' % name)
        if img.is_empty(): s.tiles[name] = 0; return 0
        k = img.key()
        if at is not None:
            if at in s.used:
                if s._tile_at(at) != img: raise ValueError('tile %r: number %d is already used by a different tile' % (name, at))
                s.shared += 1
            else:
                if not 1 <= at < TILE_COUNT: raise ValueError('tile numbers are 1 to 1023')
                s._put(at, img); s.exact.setdefault(k, at)
            n = at
        elif k in s.exact:
            n = s.exact[k]; s.shared += 1
        else:
            n = s._find(1, 1, region, False); s._put(n, img); s.exact[k] = n
        s.tiles[name] = n
        return n

    def _intern(s, cell, region):
        """A scene tile: the number, and the flips, of an existing tile this one equals (flipped or not), or a new tile."""
        for fx, fy, c in ((0, 0, cell), (1, 0, cell.flip_h()), (0, 1, cell.flip_v()), (1, 1, cell.flip_h().flip_v())):
            n = s.exact.get(c.key())
            if n is not None:
                s.shared += 1
                return n, fx, fy
        n = s._find(1, 1, region, False); s._put(n, cell); s.exact[cell.key()] = n
        return n, 0, 0

    def entry(s, tile, pal=0, fx=0, fy=0, prio=0):
        """A Map RAM entry: tile number, sub-palette, flips, priority."""
        return (tile & 1023) | (pal & 7) << 10 | (fx & 1) << 13 | (fy & 1) << 14 | (prio & 1) << 15

    def scene(s, name, img, pal=0, at=(0, 0), region=None, solid=False, prio=0, overwrite=False):
        """A picture of any size (multiples of 8) cut into tiles and written to Map RAM at tile position `at` = (column,
        row). Identical tiles, and flipped ones, are stored once. `pal` is the BG sub-palette (a palette from art.palette,
        or its number): it sets the palette bits of every entry and checks the colours. solid=True refuses transparent
        cells (a hole). Returns the entries as a grid."""
        if name in s.scenes: raise ValueError('scene %r already exists' % name)
        if img.w % 8 or img.h % 8: raise ValueError('scene %r is %dx%d: a multiple of 8 each way' % (name, img.w, img.h))
        roles = s._roles('bg', pal)
        sub = pal.sub if isinstance(pal, Roles) else (pal or 0)
        s._check_colors(img, roles, 'scene %r' % name)
        mx, my, w, h = at[0], at[1], img.w // 8, img.h // 8
        if not (0 <= mx and mx + w <= MAP_W and 0 <= my and my + h <= MAP_H): raise ValueError('scene %r at %s is outside Map RAM (%dx%d tiles)' % (name, at, MAP_W, MAP_H))
        holes, grid = [], []
        for ty in range(h):
            row = []
            for tx in range(w):
                cell = img.crop(tx * 8, ty * 8, 8, 8)
                if cell.is_empty():
                    e = 0
                    if solid: holes.append((tx, ty))
                else:
                    n, fx, fy = s._intern(cell, region)
                    e = s.entry(n, sub, fx, fy, prio)
                if s.map[my + ty][mx + tx] and e and not overwrite: raise ValueError('scene %r overlaps another at map cell (%d, %d); overwrite=True to allow' % (name, mx + tx, my + ty))
                if e or overwrite: s.map[my + ty][mx + tx] = e
                row.append(e)
            grid.append(row)
        if holes: raise ValueError('scene %r is not solid: %d empty cell(s), the first at tile (%d, %d) (pixel %d, %d)' % (name, len(holes), holes[0][0], holes[0][1], holes[0][0] * 8, holes[0][1] * 8))
        s.scenes[name] = {'mx': mx, 'my': my, 'w': w, 'h': h, 'pal': sub}
        return grid

    # --- sprites ---
    def sprite(s, name, img, pal=0, region=None, at=None):
        """A sprite of 8, 16 or 32 px (square), in the tile layout spr() expects, at an aligned free spot (or at=n).
        `pal` is the sprite sub-palette 0 to 7 (a palette from art.sprite_palette, or its number). Returns the number of its
        first tile: spr(n, x, y, { size, pal })."""
        if name in s.sprites: raise ValueError('sprite %r already exists' % name)
        if img.w != img.h or img.w not in (8, 16, 32): raise ValueError('sprite %r is %dx%d: sprites are 8x8, 16x16 or 32x32' % (name, img.w, img.h))
        roles = s._roles('spr', pal)
        sub = pal.sub if isinstance(pal, Roles) else pal
        s._check_colors(img, roles, 'sprite %r' % name)
        t = img.w // 8
        if at is None: n = s._find(t, t, region, True)
        else:
            n = at
            if n % TILES_X + t > TILES_X or n + (t - 1) * (TILES_X + 1) >= TILE_COUNT: raise ValueError('sprite %r at %d does not fit the sheet' % (name, n))
            if any(n + j * TILES_X + i in s.used for j in range(t) for i in range(t)): raise ValueError('sprite %r at %d overlaps tiles already used' % (name, n))
        for j in range(t):
            for i in range(t): s._put(n + j * TILES_X + i, img.crop(i * 8, j * 8, 8, 8))
        s.sprites[name] = {'tile': n, 'size': img.w, 'pal': sub}
        return n

    def variant(s, name, of, swap=None, pal=None, region=None):
        """A recoloured copy of sprite `of` as a sprite of its own: swap={'shirt': 'coat'} replaces roles (or ramps) of
        the sprite's palette by others of the same palette, and/or pal= puts the same pixels in another sprite palette
        whose roles have the same indices (often enough: a palette made with the same role names). Returns its first tile."""
        src = s.sprites.get(of)
        if src is None: raise KeyError('variant %r: no sprite %r' % (name, of))
        n, size = src['tile'], src['size']
        img = Img(size, size)
        for j in range(size // 8):
            for i in range(size // 8): img.blit(s._tile_at(n + j * TILES_X + i), i * 8, j * 8)
        roles = s.palettes.get(('spr', src['pal']))
        if swap:
            if roles is None: raise ValueError('variant %r: sprite %r has no palette made with sprite_palette() to swap roles in' % (name, of))
            m = {}
            for a, b in swap.items():
                ra, rb = getattr(roles, a), getattr(roles, b)
                if isinstance(ra, tuple) != isinstance(rb, tuple) or (isinstance(ra, tuple) and len(ra) != len(rb)): raise ValueError('variant %r: %s and %s must both be colours or ramps of one length' % (name, a, b))
                m[ra] = rb
            from shade import recolour
            img = recolour(img, m)
        return s.sprite(name, img, pal=src['pal'] if pal is None else pal, region=region)

    def big_sprite(s, name, img, pal=None, region=None, piece='auto'):
        """A sprite of any size, drawn as several hardware sprites: `img` is a picture (in sprite palette `pal`), or a
        dict {palette: picture} of the same size (what Sculpt.render() gives for parts in several palettes), the higher
        palette numbers drawn over the lower. It is cut into 32 px pieces where they are full enough and 16 px ones elsewhere (piece=32 or 16
        forces one size), empty pieces are skipped, and a piece equal to another one, or to it flipped, reuses its
        tiles. In code.js: bigSprite(ART.big.name, x, y, { fx, fy, prio, pal }). Returns the entry."""
        if name in s.big: raise ValueError('big sprite %r already exists' % name)
        layers = img if isinstance(img, dict) else {pal if not isinstance(pal, Roles) else pal.sub: img}
        if any(p is None for p in layers): raise ValueError('big sprite %r: give pal= (a sprite palette) for a single picture' % name)
        sizes = {(im.w, im.h) for im in layers.values()}
        if len(sizes) != 1: raise ValueError('big sprite %r: the pictures for its palettes must be the same size, got %s' % (name, sorted(sizes)))
        W, H = sizes.pop()
        parts, made = [], {}
        def place(cell, sub, dx, dy, size):
            key = cell.key()
            for flip, c in ((0, cell), (1, cell.flip_h()), (2, cell.flip_v()), (3, cell.flip_h().flip_v())):
                hit = made.get((sub, size, c.key()))
                if hit is not None:
                    parts.append([dx, dy, hit, size, sub, flip]); s.shared += 1; return
            n = s.sprite('%s#%d' % (name, len(made)), cell, pal=sub, region=region)
            del s.sprites['%s#%d' % (name, len(made))]
            made[(sub, size, key)] = n
            parts.append([dx, dy, n, size, sub, 0])
        for sub, im in sorted(layers.items()):
            roles = s._roles('spr', sub)
            s._check_colors(im, roles, 'big sprite %r (palette %d)' % (name, sub))
            for by in range(0, H, 32):
                for bx in range(0, W, 32):
                    block = im.crop(bx, by, 32, 32)
                    if block.is_empty(): continue
                    quads = [(qx, qy) for qy in (0, 16) for qx in (0, 16) if not block.crop(qx, qy, 16, 16).is_empty()]
                    if piece == 32 or (piece == 'auto' and len(quads) == 4):
                        place(block, sub, bx, by, 32)
                    else:
                        for qx, qy in quads: place(block.crop(qx, qy, 16, 16), sub, bx + qx, by + qy, 16)
        # Among sprites of one priority the first drawn is on top, so the last palette's parts (drawn over the others)
        # go first.
        order = {sub: k for k, sub in enumerate(sorted(layers))}
        parts.sort(key=lambda p: -order[p[4]])
        s.big[name] = {'w': W, 'h': H, 'parts': parts}
        return s.big[name]

    def gradient(s, name, stops, y0=0, y1=223, entry=0):
        """Per-line colours for CGRAM `entry` (0, the backdrop, by default) from line y0 to y1: `stops` is a list of
        colours spread evenly over those lines (a ramp works) or of (line, colour) pairs, mixed in OKLab. In scanline():
        gradientLine(ART.gradients.name, y). The SNES drew its skies this way (HDMA)."""
        from colour import mix
        pts = [(st[0], st[1]) if isinstance(st, (tuple, list)) and len(st) == 2 and isinstance(st[0], int) else None for st in stops]
        if any(p is None for p in pts):
            pts = [(y0 + round(k * (y1 - y0) / max(1, len(stops) - 1)), c) for k, c in enumerate(stops)]
        lines = []
        for y in range(y0, y1 + 1):
            k = 0
            while k < len(pts) - 2 and y > pts[k + 1][0]: k += 1
            (ya, ca), (yb, cb) = pts[k], pts[min(k + 1, len(pts) - 1)]
            t = 0 if yb == ya else min(1.0, max(0.0, (y - ya) / (yb - ya)))
            h = mix(ca, cb, t)
            r, g, b = (int(h[i:i + 2], 16) >> 3 for i in (0, 2, 4))
            lines.append(r | g << 5 | b << 10)
        s.gradients[name] = {'entry': entry, 'y0': y0, 'lines': lines}
        return s.gradients[name]

    def frames(s, name, imgs, pal=0, region=None):
        """An animation: sprites named name0, name1 ... Returns their first tiles."""
        return [s.sprite('%s%d' % (name, i), im, pal, region) for i, im in enumerate(imgs)]

    # --- report and files ---
    def report(s):
        lines = []
        count = lambda a, b: sum(1 for t in s.used if a <= t <= b and t != 0)
        lines.append('tiles: %d of %d used (%d saved by sharing identical and flipped tiles)' % (count(1, TILE_COUNT - 1), TILE_COUNT - 1, s.shared))
        for name, (a, b) in sorted(s.regions.items(), key=lambda kv: kv[1]):
            lines.append('  region %-6s tiles %4d to %4d: %d of %d used' % (name, a, b, count(a, b), b - a + 1))
        lines.append('sprites: %d; scenes: %d; named tiles: %d; palettes: %s; CGRAM entries set: %d' % (
            len(s.sprites), len(s.scenes), len(s.tiles), ', '.join('%s%d' % k for k in sorted(s.palettes)) or 'none', len(s.cgram)))
        lines += ['note: ' + n for n in s.notes]
        return '\n'.join(lines)

    def manifest(s):
        m = {'version': 1,
             'tiles': dict(sorted(s.tiles.items())), 'sprites': dict(sorted(s.sprites.items())), 'scenes': dict(sorted(s.scenes.items())),
             'colors': dict(sorted(s.colors.items())),
             'palettes': {'%s%d' % k: {'base': r.base, 'colors': r.names()} for k, r in sorted(s.palettes.items())},
             'used': len(s.used) - 1}
        if s.big: m['big'] = dict(sorted(s.big.items()))
        if s.gradients: m['gradients'] = sorted(s.gradients)
        return m

    def tiles_txt(s):
        last = max(s.used)
        rows = (last // TILES_X + 1) * 8
        lines = ['# generated by art.py: do not edit']
        for y in range(rows):
            lines.append(''.join('.' if v == 0 else '%x' % v for v in s.sheet[y]).rstrip('.'))
        return '\n'.join(lines) + ('\n' if rows < SHEET_H else '')

    def palette_txt(s):
        return '# generated by art.py: do not edit\n' + ''.join('%d %s\n' % (i, c) for i, c in sorted(s.cgram.items()))

    def map_txt(s):
        last = max((y for y in range(MAP_H) if any(s.map[y])), default=-1)
        if last < 0: return None
        lines = []
        for y in range(last + 1):
            row = s.map[y]; end = max((x for x in range(MAP_W) if row[x]), default=-1)
            lines.append(''.join('%04x' % row[x] for x in range(end + 1)))
        return '\n'.join(lines) + '\n'

    def constants(s):
        """The JavaScript for code.js: const ART = { tiles, sprites, scenes, colors }."""
        j = lambda v: json.dumps(v, separators=(', ', ': '), sort_keys=True)
        extra = ''
        if s.big: extra += '\n  big: %s,' % j(dict(sorted(s.big.items())))
        if s.gradients: extra += '\n  gradients: %s,' % json.dumps(dict(sorted(s.gradients.items())), separators=(',', ':'), sort_keys=True)
        out = 'const ART = {\n  tiles: %s,\n  sprites: %s,\n  scenes: %s,\n  colors: %s,%s\n};' % (j(dict(sorted(s.tiles.items()))), j(dict(sorted(s.sprites.items()))), j(dict(sorted(s.scenes.items()))), j(dict(sorted(s.colors.items()))), extra)
        if s.big:
            out += BIG_JS
        if s.gradients:
            out += GRADIENT_JS
        return out

    def write(s, outdir, quiet=False):
        """Write tiles.txt, palette.txt, map.txt (removed if the map is empty) and art.json into `outdir`, and rewrite the ART
        block of outdir/code.js if there is one. Prints the report."""
        if s.sheet[0][0:8] != bytearray(8) or any(s.sheet[y][0:8] != bytearray(8) for y in range(8)): raise AssertionError('tile 0 must stay empty')
        os.makedirs(outdir, exist_ok=True)
        def put(name, text):
            p = os.path.join(outdir, name)
            if text is None:
                if os.path.exists(p): os.remove(p)
            else: open(p, 'w', encoding='utf8', newline='\n').write(text)
        put('tiles.txt', s.tiles_txt()); put('palette.txt', s.palette_txt()); put('map.txt', s.map_txt())
        put('art.json', json.dumps(s.manifest(), indent=1, sort_keys=True) + '\n')
        code = os.path.join(outdir, 'code.js')
        if os.path.exists(code): inject(code, s.constants())
        if not quiet: print(s.report())


BIG_JS = """
/** Draw one of ART.big at (x, y), its top left: opts { fx, fy (flip the whole sprite), prio (default 3), pal (every
 * part in this sprite palette, e.g. a hit flash) }. Each part is one spr() (generated by art.py). */
function bigSprite(b, x, y, opts = {}) {
  const fx = !!opts.fx, fy = !!opts.fy, prio = opts.prio ?? 3;
  for (const [dx, dy, t, size, pal, f] of b.parts) {
    spr(t, x + (fx ? b.w - dx - size : dx), y + (fy ? b.h - dy - size : dy),
      { size, pal: opts.pal ?? pal, fx: fx !== !!(f & 1), fy: fy !== !!(f & 2), prio });
  }
}"""

GRADIENT_JS = """
/** In scanline(y): set the CGRAM entry of a gradient from ART.gradients to its colour for line y (generated by art.py). */
function gradientLine(g, y) {
  const v = g.lines[y - g.y0];
  if (v !== undefined) color(g.entry, v & 31, (v >> 5) & 31, v >> 10);
}"""


def inject(code_path, block):
    """Replace what is between the `// ART (generated by art.py: do not edit)` and `// END ART` lines of a code.js by `block`."""
    text = open(code_path, encoding='utf8').read()
    if text.count(ART_BEGIN) != 1 or text.count(ART_END) != 1: raise ValueError('%s needs exactly one "%s" line and one "%s" line' % (code_path, ART_BEGIN, ART_END))
    a = text.index(ART_BEGIN) + len(ART_BEGIN); b = text.index(ART_END)
    if b < a: raise ValueError('the END ART line comes before the ART line')
    new = text[:a] + '\n' + block + '\n' + text[b:]
    if new != text: open(code_path, 'w', encoding='utf8', newline='\n').write(new)


